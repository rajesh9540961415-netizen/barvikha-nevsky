import { timingSafeEqual } from "node:crypto";

/**
 * Проверка ключа у адреса приёма финансовых данных.
 *
 * ⚠️ **Ключ отдельный, не `EXPORT_KEY`.** Тот открывает ЧТЕНИЕ смены; этот
 * открывает ЗАПИСЬ в финансовый учёт. Цена утечки разная: утёкший ключ отчёта
 * показывает чужие заработки, утёкший ключ записи позволяет подложить в учёт
 * выдуманные платежи — а по ним считается прибыль и планируются выплаты.
 * Один ключ на оба означал бы, что первая утечка отдаёт сразу обе двери.
 *
 * ⚠️ **Почему не общий файл с приложением смены.** Там уже есть свой
 * `src/lib/apiKey.ts`, и заманчиво было сделать один на оба приложения. Но
 * общий файл пришлось бы держать копией и проверять `npm run copies` — а сам
 * он ради этого стал бы настраиваемым: имя переменной и имя заголовка
 * параметрами. Настраиваемая проверка ключа — ровно то место, где однажды
 * передадут не то имя и дверь окажется открытой. Здесь имя одно и вписано
 * прямо в код.
 *
 * Ключ передаётся заголовком `X-Finance-Key`, а не в адресе: адреса оседают
 * в журналах сервера и в истории команд, и ключ утёк бы туда вместе с ними.
 */

/** Сравнение за постоянное время: обычное `===` выдаёт длину совпадения. */
function ключиСовпали(данный: string, нужный: string): boolean {
  const a = Buffer.from(данный);
  const b = Buffer.from(нужный);
  // timingSafeEqual падает на разной длине, поэтому длину проверяем отдельно.
  // Сама по себе она секрета не выдаёт.
  return a.length === b.length && timingSafeEqual(a, b);
}

/**
 * Вернуть готовый отказ, если ключ не подошёл, или `null`, если всё в порядке.
 *
 * Не задан `FINANCE_KEY` — адрес не работает вовсе. Принимать записи в учёт
 * без защиты нельзя даже разово: адрес угадывается с первой попытки.
 */
export function отказПоФинансовомуКлючу(request: Request): Response | null {
  const нужный = process.env.FINANCE_KEY;

  if (!нужный) {
    return Response.json(
      {
        ok: false,
        причина:
          "не задана переменная FINANCE_KEY — приём финансовых данных выключен. " +
          "Задать её в панели Amvera, тем же значением, что и у скрипта на Маке",
      },
      { status: 503 },
    );
  }

  // Короткий ключ подбирается, а «выключено» и «слабо защищено» — разные
  // состояния, и второе опаснее, потому что выглядит как первое.
  if (нужный.length < 24) {
    return Response.json(
      { ok: false, причина: "FINANCE_KEY короче 24 символов — так нельзя" },
      { status: 503 },
    );
  }

  const данный = request.headers.get("X-Finance-Key");
  if (!данный || !ключиСовпали(данный, нужный)) {
    return Response.json({ ok: false, причина: "неверный ключ" }, { status: 401 });
  }

  return null;
}
