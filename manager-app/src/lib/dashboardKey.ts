import { timingSafeEqual } from "node:crypto";

/**
 * Проверка ключа у служебной двери «Обзора».
 *
 * ⚠️ **Ключ четвёртый, отдельный от трёх прежних.** `EXPORT_KEY` открывает
 * чтение смены, `FINANCE_KEY` — запись в финансовый учёт, `TIPS_FIX_KEY` —
 * правку записанных чаевых, этот — заливку дневных итогов для «Обзора».
 * Цена утечки у каждого своя, и один ключ на всех означал бы, что первая же
 * утечка отдаёт сразу четыре двери.
 *
 * ⚠️ **Зачем дверь.** Числа «Обзора» считаются на Маке из фискальных чеков:
 * до сервера папка `data/ofd` не доезжает, Amvera собирает бэк-офис отдельным
 * корнем. Напрямую в базу с Мака тоже не достучаться — порт 5432 перехватывает
 * VPN incy, а выключать его нельзя (решение владельца 28.08.2026). Остаётся
 * HTTPS: скрипт присылает готовые дневные итоги, сервер кладёт их в базу.
 *
 * ⚠️ **Что через эту дверь потерять нельзя.** Она пишет только в
 * `dashboard_days` — слепок, который в любой момент собирается заново из
 * чеков. Ни чаевых, ни финансовых операций она не касается: у служебной
 * двери должна быть ровно одна возможность, а не «доступ к базе».
 *
 * Проверка повторяет `tipsFixKey.ts` строка в строку и НАРОЧНО не вынесена
 * в общий настраиваемый файл: настраиваемая проверка ключа — ровно то место,
 * где однажды передадут не то имя переменной и дверь окажется открытой.
 *
 * Ключ идёт заголовком `X-Dashboard-Key`, а не в адресе: адреса оседают
 * в журналах сервера и в истории команд.
 */

/** Сравнение за постоянное время: обычное `===` выдаёт длину совпадения. */
function ключиСовпали(данный: string, нужный: string): boolean {
  const a = Buffer.from(данный);
  const b = Buffer.from(нужный);
  return a.length === b.length && timingSafeEqual(a, b);
}

/** Отказ, если ключ не подошёл, или `null`, если всё в порядке. */
export function отказПоКлючуОбзора(request: Request): Response | null {
  const нужный = process.env.DASHBOARD_KEY;

  if (!нужный) {
    return Response.json(
      {
        ok: false,
        причина:
          "не задана переменная DASHBOARD_KEY — заливка «Обзора» выключена. " +
          "Задать её в панели Amvera у приложения nevsky-office, тем же " +
          "значением, что и у скрипта на Маке",
      },
      { status: 503 },
    );
  }

  if (нужный.length < 24) {
    return Response.json(
      { ok: false, причина: "DASHBOARD_KEY короче 24 символов — так нельзя" },
      { status: 503 },
    );
  }

  const данный = request.headers.get("X-Dashboard-Key");
  if (!данный || !ключиСовпали(данный, нужный)) {
    return Response.json({ ok: false, причина: "неверный ключ" }, { status: 401 });
  }

  return null;
}
