/**
 * Вознаграждение собственнику — что и когда выводилось, и за какой месяц.
 *
 * Задача владельца 11.09.2026: «месяц, за который мы заплатили, общая сумма,
 * с каких юридических лиц какие суммы были выведены».
 *
 * 🔴 **Две даты, и путать их дороже всего.** Дата платежа — факт из выписки.
 * Месяц, за который вознаграждение, — знание владельца, в банке его нет.
 * За июль 2026 платили пятью платежами с 22 июля по 8 сентября, и часть
 * одного сентябрьского платежа тоже относится к июлю. По дате платежа такую
 * картину не собрать.
 *
 * ⚠️ Месяц не назван — это «ещё не разбирали», а не «ни за какой». Такие
 * выплаты стоят отдельной строкой и в месяцы не размазываются: догадка,
 * выданная за факт, здесь стоит миллионы.
 */

