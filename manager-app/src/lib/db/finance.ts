  обновлено: number;
  ужеБыло: number;
  дней: number;
  /** Сколько строк выручки по юрлицам записано. */
  выручки: number;
  /** Сколько строк остатков по счетам записано. */
  остатков: number;
  /** Сколько наличных строк стёрто заменой. Ноль, если замены не просили. */
  убрано: number;
