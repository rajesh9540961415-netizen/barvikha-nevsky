export type Table = {
  id: number;
  title: string;
  seats: number | null;
  x: number;
  y: number;
  width: number;
  height: number;
  shape: string;
};

export type Hall = {
  id: number;
  title: string;
  tables: Table[];
};

export type Scheme = {
  scheme: string;
  halls: Hall[];
};

export type Employee = {
  id: number;
  /** Полное имя из Quick Resto. */
  name: string;
  /** Короткое имя для кнопки: «Анна К.» */
  short: string;
  /**
   * Человек убран из списка выбора: стажёра оформили в кассе или он ушёл.
   *
   * Только у вписанных руками; у людей из Quick Resto роль этой пометки
   * играет их собственный признак `blocked` — заблокированные до нас
   * просто не доезжают.
   *
   * ⚠️ Убранный человек остаётся полноценным человеком везде, кроме экрана
   * сбора смены: его имя по-прежнему находится по номеру, его прошлые смены
   * и деньги на месте. Пометка про экран, а не про существование.
   */
  hidden?: boolean;
  /**
   * «Это тот же человек, что №…». Только у вписанных руками.
   *
   * Стоит, когда стажёра оформили в кассе и у него появился второй номер.
   * Записи остаются на своих номерах — переписывать денежные документы
   * задним числом нельзя, — а склейка говорит, что человек один.
   */
  mergedInto?: number;
};

/**
 * Что именно записали.
 *
 * cash и terminal — чаевые от гостя, добровольные.
 * service — сервисный сбор: 10 % от чека, начисляется автоматически
 * большим компаниям. Выдаётся официантам в тот же день, как и чаевые,
 * но делится иначе — кассир от него доли не получает.
 */
/**
 * Что именно записали.
 *
 * Первые четыре — деньги, полученные официантом. `staff` стоит особняком:
 * это не доход, а **вычет** — сколько человек проел за смену. Расходы
 * на питание пробиваются в Quick Resto на столе STAFF, и администратор
 * в конце смены вычитает их из причитающейся выплаты.
 */
export type Kind = "cash" | "terminal" | "service" | "qr" | "staff";

/**
 * Чьи это деньги: зала, хостес или кальянного бара.
 *
 * Вид денег отвечает «чем оставили», контур — «какому котлу». Это разные
 * вопросы: наличные бывают и у официанта, и у кальянщика, а считаются они
 * по-разному.
 *
 * Зал делится: 20 % администратору, доля кассиру, порог 1300 ₽. Хостес
 * и кальянный бар не делятся ни с кем и порога не знают — решение владельца
 * 18.08.2026, см. plans/2026-08-18-hostes-i-kalyannyy-bar.md.
 *
 * У записей, сделанных до 18.08.2026, поля нет — все они зальные.
 */
export type Contour = "hall" | "hostess" | "hookah";

/**
 * Поступление по персональному QR — пришло, но ещё не разнесено по людям.
 *
 * Приходит не из зала: гость платит по QR на чеке, кассир этих денег не видит.
 * Сбер сообщает о них уведомлением в Telegram и называет не человека,
 * а котёл — «Официант 5». Кто обслуживал, знает только смена, поэтому
 * сумму разносит кассир.
 */
export type QrTip = {
  /** Идентификатор сообщения в Telegram — он же защита от повторов. */
  messageId: number;
  /** Когда пришло, ISO. */
  receivedAt: string;
  businessDay: string;
  amount: number;
  /** Котёл Сбера: «Официант 5», «Хостес». */
  team: string;
};

/**
 * Состав смены и роли.
 *
 * Живёт здесь, а не в crew.ts, чтобы серверный слой базы мог ссылаться
 * на этот тип, не втягивая за собой браузерный код.
 */
export type Shift = {
  crew: number[];
  operator: number | null;
  admin: number | null;
  /**
   * Второй администратор, если смену делили надвое.
   *
   * С августа 2026 администраторы работают по очереди: один до пересменки,
   * второй после. Доля администратора при этом делится ПОПОЛАМ, без привязки
   * к часам — так это считали на бумаге (5 августа: 2 812 и 2 812).
   *
   * Пополам, а не по времени, намеренно: делить по часам значит отмечать
   * момент пересменки, а это лишний вопрос кассиру посреди вечера. Первая же
   * забытая отметка испортила бы расчёт молча.
   *
   * Пусто в обычную смену — тогда всё как раньше, вся доля одному.
   */
  admin2: number | null;
  cashier: number | null;
  /**
   * Хостес этого вечера. Отдельно от `crew` намеренно.
   *
   * В зальный состав они не входят: сумма кассира делится на число
   * официантов, и попади хостес в `crew`, доля каждого официанта молча
   * уменьшилась бы. Их деньги не делятся ни с кем.
   */
  hostess: number[];
  /** Кальянщики на смене. Номера со сдвигом +1 000 000 — касса другая. */
  hookah: number[];
  /**
   * Имена всех, кто назван в этой смене: номер → имя.
   *
   * Зачем дублировать справочник. Состав хранит только номера, а имя ищется
   * по кассе Quick Resto и по дописанным вручную. Убрали человека из
   * дописанных — и смена остаётся с номером без имени: деньги есть,
   * получатель безымянный. В августе 2026 так потерялось 44 998,72 ₽ по
   * девяти сменам, и заметно это стало только сверкой с чужой таблицей.
   *
   * Записи о чаевых от этого защищены давно — они хранят `waiterName` внутри
   * себя. Состав смены теперь тоже: это денежный документ, он должен
   * читаться сам по себе и через год.
   *
   * Пусто у смен до 19.08.2026.
   */
  names?: Record<string, string>;
};

/** Одна запись о полученных деньгах. */
export type Entry = {
  id: string;
  /**
   * Зал и стол. Пусто у QR-чаевых: гость платит по чеку, а не за столом,
   * и привязки к месту в зале у такого поступления нет.
   */
  hallId: number | null;
  hallTitle: string | null;
  tableId: number | null;
  tableTitle: string | null;
  waiterId: number;
  waiterName: string;
  /**
   * Сколько **дошло** до официанта — после комиссии Сбера.
   *
   * Именно эта сумма участвует во всём: в пороге 1300 ₽, в доле
   * администратора и кассира, в итогах смены и в отчёте. Брать долю
   * с денег, которых человек не получил, нельзя.
   */
  amount: number;
  /**
   * Сколько **оставил гость** — до комиссии.
   *
   * У наличных и сервисного сбора совпадает с `amount`: они идут мимо Сбера.
   * Хранится отдельно, чтобы было видно, куда делась разница, и чтобы
   * сходилось с выгрузкой Сбера, когда дойдём до склейки.
   */
  gross: number;
  /**
   * Ставка комиссии, применённая **в момент записи**: 0.08 у терминала.
   *
   * Хранится в самой записи, а не берётся из настроек при чтении: если Сбер
   * поменяет тариф, прошлые смены должны остаться такими, какими были.
   */
  commissionRate: number;
  kind: Kind;
  /**
   * Какому котлу деньги: залу, хостес или кальянному бару.
   *
   * Проставляется В МОМЕНТ ЗАПИСИ, а не выводится из сегодняшней роли
   * человека: сегодня она хостес, завтра официант, а денежный документ
   * обязан читаться сам по себе и через год. По той же причине рядом
   * хранится ставка комиссии.
   *
   * Пусто у записей до 18.08.2026 — тогда контур был один, зальный.
   */
  contour?: Contour;
  /** Кто внёс запись — администратор или кассир на смене. */
  operatorId: number;
  operatorName: string;
  /** Момент ввода, ISO. */
  createdAt: string;
  /** Бизнес-день, к которому относится запись: YYYY-MM-DD. */
  businessDay: string;
  /**
   * Когда запись отменили, ISO. Пусто у живых записей.
   *
   * Отменённые не входят ни в суммы, ни в отчёт — они видны только
   * в истории. Отмена не стирает строку: иначе проверить себя нельзя.
   */
  deletedAt?: string | null;
  /** Кто отменил. */
  deletedByName?: string | null;
  /**
   * Метка «эти строки — одни чаевые, поделённые между официантами».
   *
   * Большой стол обслуживают вдвоём, гость оставляет чаевые за стол целиком,
   * и запись ложится в базу по строке на каждого — каждому своя доля.
   * Общая метка связывает их: история показывает такие строки одним событием,
   * а отмена убирает группу целиком.
   *
   * Пусто у обычной записи одному официанту.
   */
  splitGroup?: string | null;
  /**
   * Ключ события, которое эта запись заменила. Пусто у первоначальных.
   *
   * Правка не переписывает запись: старая помечается отменённой, новая встаёт
   * рядом и ссылается на неё этим полем. Через год должно быть видно не только
   * «сколько», но и «что было до того, как поправили».
   */
  corrects?: string | null;
  /**
   * Откуда пришла запись: из приложения смены или из бэк-офиса.
   *
   * Смена правит только свою смену и только в ту же ночь, бэк-офис — любой
   * период. По этому полю видно, вмешивались ли в смену задним числом.
   */
  source?: "shift" | "office";
  /** Зачем поправили. В смене не спрашивается, в бэк-офисе обязательно. */
  note?: string | null;
  /** Зачем отменили. */
  deletedNote?: string | null;
};
