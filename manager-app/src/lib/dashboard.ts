import снимок from "@/data/dashboard.json";

/**
 * Первый экран: считаем показатели за выбранный период.
 *
 * Числа лежат готовыми в `data/dashboard.json` — его собирает на Маке
 * `scripts/dashboard_snapshot.py`. Считать здесь на лету нечего и не из чего:
 * Amvera собирает бэк-офис отдельным корнем, и папка `data/ofd` с чеками
 * до сервера не доезжает.
 *
 * ⚠️ Сутки в слепке — с 11:00 до 10:59, как во всём проекте. Поэтому «день»
 * здесь торговый: субботняя ночь после полуночи лежит в субботе.
 */

export type День = {
  выручка: number;
  чеков: number;
  нал: number;
  безнал: number;
  возвраты: number;
  возвратов: number;
  направления: Record<string, number>;
  часы: number[];
  чаевые?: number;
};

type Слепок = { собрано: string; дни: Record<string, День> };
const ДАННЫЕ = снимок as unknown as Слепок;

export const НАПРАВЛЕНИЯ = ["бар", "кухня", "кальяны", "аренда"] as const;
export const ПОДПИСЬ_НАПРАВЛЕНИЯ: Record<string, string> = {
  бар: "Бар",
  кухня: "Кухня",
  кальяны: "Кальяны",
  аренда: "Аренда VIP",
};

export type Период = {
  ключ: string;
  подпись: string;
  /** Сколько дней назад начинается, считая от последнего дня с данными. */
  дней: number;
};

/**
 * Наборы периодов. «Вчера» — один день, остальное — окна подряд.
 *
 * Окна, а не календарные месяцы, нарочно: заведение работает без выходных,
 * и «последние 30 дней» отвечают на вопрос владельца «как идут дела сейчас»
 * честнее, чем огрызок текущего месяца, который в первых числах пуст.
 */
export const ПЕРИОДЫ: Период[] = [
  { ключ: "1", подпись: "Вчера", дней: 1 },
  { ключ: "7", подпись: "7 дней", дней: 7 },
  { ключ: "30", подпись: "30 дней", дней: 30 },
  { ключ: "90", подпись: "90 дней", дней: 90 },
  { ключ: "365", подпись: "Год", дней: 365 },
];

export type Показатели = {
  выручка: number;
  чеков: number;
  среднийЧек: number;
  нал: number;
  безнал: number;
  долянала: number;
  возвраты: number;
  возвратов: number;
  доляВозвратов: number;
  чаевые: number;
  днейСЧаевыми: number;
  направления: { имя: string; сумма: number; доля: number }[];
  часы: number[];
  дниНедели: number[];
  дней: number;
  с: string;
  по: string;
};

function сдвинуть(день: string, наДней: number): string {
  const d = new Date(день + "T12:00:00Z");
  d.setUTCDate(d.getUTCDate() + наДней);
  return d.toISOString().slice(0, 10);
}

/** Последний день, за который вообще есть чеки. От него и пляшем. */
export function последнийДень(): string {
  const все = Object.keys(ДАННЫЕ.дни);
  return все.length ? все.sort()[все.length - 1] : new Date().toISOString().slice(0, 10);
}

export function собрано(): string {
  return ДАННЫЕ.собрано;
}

/**
 * Сложить дни из окна [с; по] включительно.
 *
 * Пустых дней в слепке нет вовсе — заведение работает не каждый день, и день
 * без чеков просто отсутствует. Поэтому считаем по тому, что есть, а число
 * дней берём как длину окна: делить выручку на «дни с чеками» значило бы
 * показывать выручку в день выше, чем она была.
 */
export function заПериод(с: string, по: string): Показатели {
  let выручка = 0, чеков = 0, нал = 0, безнал = 0;
  let возвраты = 0, возвратов = 0, чаевые = 0, днейСЧаевыми = 0;
  const напр: Record<string, number> = {};
  const часы = new Array(24).fill(0);
  const дниНедели = new Array(7).fill(0);

  for (const [день, д] of Object.entries(ДАННЫЕ.дни)) {
    if (день < с || день > по) continue;
    выручка += д.выручка;
    чеков += д.чеков;
    нал += д.нал;
    безнал += д.безнал;
    возвраты += д.возвраты;
    возвратов += д.возвратов;
    if (typeof д.чаевые === "number") {
      чаевые += д.чаевые;
      днейСЧаевыми += 1;
    }
    for (const н of НАПРАВЛЕНИЯ) напр[н] = (напр[н] ?? 0) + (д.направления[н] ?? 0);
    for (let ч = 0; ч < 24; ч++) часы[ч] += д.часы[ч] ?? 0;
    // Понедельник первым: неделя у заведения начинается с тихого понедельника
    // и кончается субботой, а не наоборот.
    const вд = (new Date(день + "T12:00:00Z").getUTCDay() + 6) % 7;
    дниНедели[вд] += д.выручка;
  }

  const суммаНаправлений = Object.values(напр).reduce((a, b) => a + b, 0);
  const дней = Math.round(
    (Date.parse(по + "T12:00:00Z") - Date.parse(с + "T12:00:00Z")) / 86400000) + 1;

  return {
    выручка, чеков,
    среднийЧек: чеков ? выручка / чеков : 0,
    нал, безнал,
    долянала: выручка ? (нал / выручка) * 100 : 0,
    возвраты, возвратов,
    доляВозвратов: выручка ? (возвраты / выручка) * 100 : 0,
    чаевые, днейСЧаевыми,
    направления: НАПРАВЛЕНИЯ.map((н) => ({
      имя: ПОДПИСЬ_НАПРАВЛЕНИЯ[н],
      сумма: напр[н] ?? 0,
      доля: суммаНаправлений ? ((напр[н] ?? 0) / суммаНаправлений) * 100 : 0,
    })).sort((a, b) => b.сумма - a.сумма),
    часы, дниНедели, дней, с, по,
  };
}

/** Окно той же длины ровно год назад — для сравнения «к прошлому году». */
export function годНазад(с: string, по: string): Показатели {
  return заПериод(сдвинуть(с, -365), сдвинуть(по, -365));
}

export function окно(дней: number, последний = последнийДень()) {
  return { с: сдвинуть(последний, -(дней - 1)), по: последний };
}

/**
 * Насколько выросло, в процентах. `null` — когда сравнивать не с чем.
 *
 * Отдельный случай нужен потому, что до июня 2025 касса работала неполно,
 * и «рост в 800 %» к пустому прошлому году — не новость, а шум.
 */
export function рост(сейчас: number, было: number): number | null {
  if (!было) return null;
  return ((сейчас - было) / было) * 100;
}
