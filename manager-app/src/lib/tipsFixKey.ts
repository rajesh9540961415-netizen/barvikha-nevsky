import { timingSafeEqual } from "node:crypto";

/**
 * Проверка ключа у служебной двери правок чаевых.
 *
 * ⚠️ **Ключ третий, отдельный от двух прежних.** `EXPORT_KEY` открывает чтение
 * смены, `FINANCE_KEY` — запись в финансовый учёт, этот — правку уже
 * записанных чаевых. Цена утечки у каждого своя, и один ключ на всех означал
 * бы, что первая же утечка отдаёт сразу три двери.
 *
 * ⚠️ **Зачем дверь вообще.** Сверка августа 06.09.2026 дала 105 правок
 * получателя и 36 записей кальянного бара. Через экран это 500–600 действий
 * мышью подряд по живой базе — работа, где промах неизбежен, а заметить его
 * нечем. Дверь не пишет в базу сама: она вызывает те же `correctEvent`,
 * `cancelEvent` и `добавитьЗапись`, что и экран, со всеми их проверками
 * и следом. Меняется только то, кем подписана правка.
 *
 * Проверка повторяет `financeKey.ts` строка в строку и НАРОЧНО не вынесена
 * в общий настраиваемый файл: настраиваемая проверка ключа — ровно то место,
 * где однажды передадут не то имя переменной и дверь окажется открытой.
 *
 * Ключ идёт заголовком `X-Tips-Fix-Key`, а не в адресе: адреса оседают
 * в журналах сервера и в истории команд.
 */

/** Сравнение за постоянное время: обычное `===` выдаёт длину совпадения. */
function ключиСовпали(данный: string, нужный: string): boolean {
  const a = Buffer.from(данный);
  const b = Buffer.from(нужный);
  return a.length === b.length && timingSafeEqual(a, b);
}

/** Отказ, если ключ не подошёл, или `null`, если всё в порядке. */
export function отказПоКлючуПравок(request: Request): Response | null {
  const нужный = process.env.TIPS_FIX_KEY;

  if (!нужный) {
    return Response.json(
      {
        ok: false,
        причина:
          "не задана переменная TIPS_FIX_KEY — служебные правки выключены. " +
          "Задать её в панели Amvera у приложения nevsky-office, тем же " +
          "значением, что и у скрипта на Маке",
      },
      { status: 503 },
    );
  }

  if (нужный.length < 24) {
    return Response.json(
      { ok: false, причина: "TIPS_FIX_KEY короче 24 символов — так нельзя" },
      { status: 503 },
    );
  }

  const данный = request.headers.get("X-Tips-Fix-Key");
  if (!данный || !ключиСовпали(данный, нужный)) {
    return Response.json({ ok: false, причина: "неверный ключ" }, { status: 401 });
  }

  return null;
}
