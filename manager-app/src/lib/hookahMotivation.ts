import правила from "@/data/hookah-motivation.json";

/**
 * Мотивация кальянного бара: категории, ставки и счёт по готовым продажам.
 *
 * Ставки владельца 06.09.2026, рубли за штуку, мотивация ОБЩАЯ НА СМЕНУ.
 *
 * 🔴 **Категорию здесь БОЛЬШЕ НЕ УГАДЫВАЕМ.** До 08.09.2026 в этом файле жил
 * разбор названий по словам: «содержит PERFUME», «начинается с ЧМ». Он давал
 * неверный ответ на трёх позициях сразу и требовал заплатки на каждое новое
 * название меню. Теперь категорию ставит МЕНЮ КАССЫ, а решение «сколько
 * за это платить» принимается ОДИН раз — в `scripts/hookah_push.py`, — и
 * приезжает сюда готовым.
 *
 * Причина не в красоте. 08.09.2026 счёт мотивации разошёлся с отчётом
 * администратора, и корнем оказалось то, что одно и то же правило жило
 * в двух местах и разошлось. Здесь третье место было бы четвёртым шансом
 * разойтись — на живых деньгах людей.
 *
 * ⚠️ **Почему решение нельзя принять здесь.** Доплата за «ЧМ» положена только
 * в комплекте с электронной чашей (владелец 08.09.2026: «400 рублей мы платим
 * за комплект, который стоит 6500»). Комплект виден по СОСТАВУ ЧЕКА, а в базу
 * приезжают уже сложенные продажи дня. Значит здесь этого не решить в принципе.
 *
 * ⚠️ **Ставки — в базе, категории — в файле.** Ставка это решение владельца
 * на каждый день, она правится прямо на экране. Список категорий приходит
 * из меню кассы и меняется вместе с меню.
 *
 * ⚠️ **Файл `hookah-motivation.json` — копия.** Хозяин в приложении смены,
 * сюда приезжает через `npm run copies`.
 */

type ПравилоКатегории = { наша: string; ставка: number; только_в_комплекте?: boolean };

const КАТЕГОРИИ_МЕНЮ = Object.fromEntries(
  Object.entries(правила.категории_меню as Record<string, unknown>)
    .filter(([ключ]) => !ключ.startsWith("_")),
) as Record<string, ПравилоКатегории>;

export const БЕЗ_МОТИВАЦИИ = "без мотивации";

/**
 * Наши категории в том порядке, в каком их называет владелец, без повторов.
 *
 * Категорий меню девять, а наших семь: «ЧМ ЧАША» и «ЧМ DEUS PERFUME» — это
 * одно и то же «Чемпионат мира», просто в меню они заведены порознь.
 */
export const КАТЕГОРИИ: string[] = [
  ...new Set(
    Object.values(КАТЕГОРИИ_МЕНЮ)
      .map((п) => п.наша)
      .filter((н) => н !== БЕЗ_МОТИВАЦИИ),
  ),
];

export const СТАВКИ_ПО_УМОЛЧАНИЮ: Record<string, number> = Object.fromEntries(
  Object.values(КАТЕГОРИИ_МЕНЮ)
    .filter((п) => п.наша !== БЕЗ_МОТИВАЦИИ)
    .map((п) => [п.наша, п.ставка]),
);

/**
 * Продажа, приехавшая с Мака: позиция уже отнесена к категории и уже
 * очищена от того, за что не платят.
 *
 * `qty` — количество, за которое положена доплата, а не проданное. Для
 * электронной чаши внутри комплекта это ноль: её оплатили через «ЧМ».
 */
export type ПродажаПозиции = {
  position: string;
  category: string;
  qty: number;
  amount: number;
};

/** Та же продажа, но с днём: так она лежит в базе и так приезжает с Мака. */
export type ПродажаДня = ПродажаПозиции & { day: string };

export type ИтогКатегории = {
  категория: string;
  штук: number;
  ставка: number;
  мотивация: number;
  позиции: { позиция: string; штук: number }[];
};

/**
 * Складывает готовые продажи по категориям и умножает на ставки.
 *
 * ⚠️ Возвраты вычтены раньше, на Маке: в `qty` уже нетто. Кальян, от которого
 * гость отказался, доплаты не приносит (владелец 06.09.2026).
 *
 * 💡 Позиции внутри категории показываем нарочно. Владелец 08.09.2026:
 * сумму, которую нельзя разложить обратно на конкретные кальяны, проверить
 * нечем — и именно раскладка по позициям вскрыла три ошибки счёта за день.
 */
export function посчитать(
  продажи: ПродажаПозиции[],
  ставки: Record<string, number>,
): { поКатегориям: ИтогКатегории[]; всего: number; штукВсего: number } {
  const штукПоКатегории = new Map<string, number>();
  const позицииПоКатегории = new Map<string, Map<string, number>>();

  for (const п of продажи) {
    if (!п.category || п.category === БЕЗ_МОТИВАЦИИ || !п.qty) continue;
    штукПоКатегории.set(п.category, (штукПоКатегории.get(п.category) ?? 0) + п.qty);
    const внутри = позицииПоКатегории.get(п.category) ?? new Map<string, number>();
    внутри.set(п.position, (внутри.get(п.position) ?? 0) + п.qty);
    позицииПоКатегории.set(п.category, внутри);
  }

  // ⚠️ Категория, которой нет в списке, всё равно попадает в итог: она
  // означает, что меню изменилось, а файл правил — нет. Промолчать значило бы
  // недоплатить, а это худшее, чем может кончиться расхождение.
  const все = [...new Set([...КАТЕГОРИИ, ...штукПоКатегории.keys()])];

  const поКатегориям: ИтогКатегории[] = все.map((к) => {
    const штук = штукПоКатегории.get(к) ?? 0;
    const ставка = ставки[к] ?? СТАВКИ_ПО_УМОЛЧАНИЮ[к] ?? 0;
    return {
      категория: к,
      штук,
      ставка,
      мотивация: штук * ставка,
      позиции: [...(позицииПоКатегории.get(к) ?? new Map())]
        .map(([позиция, штук]) => ({ позиция, штук }))
        .sort((а, б) => б.штук - а.штук),
    };
  });

  return {
    поКатегориям,
    всего: поКатегориям.reduce((с, к) => с + к.мотивация, 0),
    штукВсего: поКатегориям.reduce((с, к) => с + к.штук, 0),
  };
}
