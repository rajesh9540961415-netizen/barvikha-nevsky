import type { Employee, Entry, Shift } from "./types";

/**
 * Состав смены людьми, а не номерами.
 *
 * Зачем отдельной функцией, да ещё и общей на оба приложения. Раскладка
 * денег перебирает СОСТАВ, а не записи: кого нет в составе — того нет
 * и в деньгах. Значит из состава нельзя потерять никого, даже человека,
 * которого больше нет в справочнике.
 *
 * ⚠️ 19.08.2026 ровно это и случилось, и стоило 12 900,96 ₽. Елизавету
 * Пархоменко вписали руками (номер −6), она отработала 13 и 16 августа,
 * а потом её строку из списка дописанных удалили. Записи остались, номер
 * в составе остался, а имени по номеру больше не находилось — и выгрузка
 * молча выбросила её из состава вместе со всеми деньгами. Бэк-офис в тот же
 * день показывал их на месте: он подставлял имя из самой записи. Два экрана,
 * две разные суммы за один вечер, и в отчёт уходила меньшая.
 *
 * 💡 Главное здесь — не имя, а то, что человек ОСТАЁТСЯ в составе. Имя можно
 * не найти вовсе, и тогда в отчёт поедет «№−6» — некрасиво, но видно глазами
 * и лечится за минуту. Выброшенный человек не виден никак: доля кассира тихо
 * делится на меньшее число людей, остальные получают чуть больше положенного,
 * а его собственные деньги не получает никто.
 *
 * Имя ищем в трёх местах подряд, от надёжного к последнему:
 *   1. справочник — касса Quick Resto и дописанные вручную;
 *   2. имена, сохранённые вместе со сменой (`shift.names`) — смена это
 *      денежный документ, и в нём записано, кто работал В ТОТ вечер;
 *   3. имя, лежащее в самой записи о деньгах.
 *
 * Третье слабее второго: его писали в тот вечер и с тех пор человека могли
 * переименовать. Но оно есть всегда, а пустого имени в отчёте быть не должно.
 */
export function crewPeople(
  shift: Shift,
  // Не `Entry[]`: у записи бэк-офиса автор может быть не заполнен, и целый
  // тип сюда не подходит. Нужны ровно два поля — просим только их.
  entries: Pick<Entry, "waiterId" | "waiterName">[],
  everyone: Employee[],
): Employee[] {
  // ⚠️ Один номер в составе может лежать ДВАЖДЫ, и тогда человек считается
  // дважды: раскладка перебирает состав и на каждом заходе складывает ЕГО ЖЕ
  // записи. 20.08.2026 так вышло на 11 августа — Алексей Горбунов встал двумя
  // строками с одинаковыми суммами, смена выросла с 31 947,08 до 36 107,92,
  // а доля кассира разделилась на пятерых вместо четверых.
  //
  // 💡 Раньше этого не случалось не потому, что состав был чист, а потому что
  // прежний отбор шёл ПО СПРАВОЧНИКУ (`все.filter(p => crew.includes(p.id))`)
  // и повторы отбрасывал сам собой, ничего о них не зная. Заменив отбор
  // перебором состава, я вместе с потерей людей убрал и эту защиту —
  // случайную, никем не описанную и потому невидимую.
  //
  // Правило на будущее: **меняя способ обхода, проверь, что молча делал
  // прежний.** Побочные свойства не задокументированы ровно потому, что
  // о них никто не думал, — и исчезают они так же молча.
  const уникальные = [...new Set(shift.crew)];

  return уникальные.map((id) => {
    const known = everyone.find((p) => p.id === id);
    if (known) return known;

    const name =
      shift.names?.[String(id)] ??
      entries.find((e) => e.waiterId === id)?.waiterName ??
      `№${id}`;

    // Короткое имя не сокращаем: сокращение — дело справочника, а здесь
    // мы и так подставляем что нашли. «Елизавета Пархоменко» в узкой
    // колонке лучше, чем «№−6» на своём месте.
    return { id, name, short: name };
  });
}
