/**
 * Служебная дверь «Обзора»: приём дневных итогов с Мака.
 *
 * Числа считаются на компьютере владельца из фискальных чеков — до сервера
 * папка `data/ofd` не доезжает, Amvera собирает бэк-офис отдельным корнем.
 * Напрямую в базу с Мака тоже не достучаться: порт 5432 перехватывает
 * VPN incy, выключать который нельзя. Остаётся HTTPS.
 *
 * Присылает `scripts/dashboard_push.py`. Тело:
 *
 *   {"дни": [{"день":"2026-09-06","выручка":123.45,"чеков":12,
 *             "нал":100,"безнал":23.45,"возвраты":0,"возвратов":0,
 *             "направления":{"бар":100,"кухня":23.45},
 *             "часы":[0,0,…24 числа…],"чаевые":32830.72}]}
 *
 * ⚠️ **Проверяем каждый день целиком, до записи.** Дверь пишет слепок, по
 * которому владелец смотрит на выручку: кривое число здесь не уронит экран,
 * а тихо соврёт. Поэтому день с плохим полем не пропускаем, а отвечаем
 * отказом на всю пачку и не пишем ничего — половина залитого хуже, чем
 * ничего, потому что выглядит как целое.
 *
 * ⚠️ **Дверь умеет ровно одно** — писать в `dashboard_days`. Ни чаевых,
 * ни финансовых операций она не касается.
 */

export const dynamic = "force-dynamic";

const ДЕНЬ = /^\d{4}-\d{2}-\d{2}$/;

function число(v: unknown, где: string, ошибки: string[]): number {
  if (typeof v !== "number" || !Number.isFinite(v)) {
    ошибки.push(`${где}: ожидалось число, пришло ${JSON.stringify(v)}`);
    return 0;
  }
  return v;
}

function разобрать(сырое: unknown, ошибки: string[]): ДеньОбзора | null {
  if (typeof сырое !== "object" || сырое === null) {
    ошибки.push("день должен быть объектом");
    return null;
  }
  const д = сырое as Record<string, unknown>;
  const день = String(д.день ?? "");
  if (!ДЕНЬ.test(день)) {
    ошибки.push(`«${день}» — не дата вида ГГГГ-ММ-ДД`);
    return null;
  }

  const часы = Array.isArray(д.часы) ? д.часы : [];
  if (часы.length !== 24) {
    ошибки.push(`${день}: часов должно быть 24, пришло ${часы.length}`);
    return null;
  }

  const направления: Record<string, number> = {};
  const сыроеН = (д.направления ?? {}) as Record<string, unknown>;
  for (const [имя, знач] of Object.entries(сыроеН)) {
    направления[имя] = число(знач, `${день}, направление «${имя}»`, ошибки);
  }

  return {
    день,
    выручка: число(д.выручка, `${день}, выручка`, ошибки),
    чеков: число(д.чеков, `${день}, чеков`, ошибки),
    нал: число(д.нал, `${день}, нал`, ошибки),
    безнал: число(д.безнал, `${день}, безнал`, ошибки),
    возвраты: число(д.возвраты, `${день}, возвраты`, ошибки),
    возвратов: число(д.возвратов, `${день}, возвратов`, ошибки),
    направления,
    часы: часы.map((в, i) => число(в, `${день}, час ${i}`, ошибки)),
    чаевые: д.чаевые === null || д.чаевые === undefined
      ? null
      : число(д.чаевые, `${день}, чаевые`, ошибки),
  };
}

/**
 * Чтение: те же числа, что показывает «Сводка», в виде JSON.
 *
 * Заведено 07.09.2026 по замечанию владельца — «ты же делал себе дверь,
 * ты не можешь сам через неё проверить». И правда: дверь была только
 * на запись, а сверить посчитанное было нечем. Бэк-офис за паролем,
 * пароль ассистент не вводит никогда, боевая база с Мака недоступна —
 * значит без этого чтения проверка сводилась к «посмотрите сами».
 *
 * ⚠️ Отдаёт ТОЛЬКО итоги: выручку, затраты по статьям, прибыль. Ни одной
 * операции, ни одного контрагента, ни одной фамилии. Дверь для сверки
 * чисел, а не выгрузка учёта наружу.
 *
 *   GET /api/dashboard?с=2026-08-08&по=2026-09-06
 */
export async function GET(request: Request) {
  const отказ = отказПоКлючуОбзора(request);
  if (отказ) return отказ;

  const адрес = new URL(request.url);
  const { первый, последний, обновлено } = await состояние();
  const по = ДЕНЬ.test(адрес.searchParams.get("по") ?? "")
    ? адрес.searchParams.get("по")! : последний;
  const с = ДЕНЬ.test(адрес.searchParams.get("с") ?? "")
    ? адрес.searchParams.get("с")! : по;

  if (!с || !по) {
    return Response.json(
      { ok: false, причина: "в базе нет ни одного дня — сначала залейте числа" },
      { status: 409 },
    );
  }

  const показатели = await заПериод(с, по);
  const затраты = await затратыЗаПериодПоКлючу(с, по);
  const прибыль = показатели.выручка - затраты.затраты;

  return Response.json({
    ok: true,
    период: { с, по, дней: показатели.дней, днейСЧеками: показатели.днейСЧеками },
    данные: { первый, последний, обновлено },
    выручка: {
      всего: показатели.выручка,
      чеков: показатели.чеков,
      среднийЧек: Math.round(показатели.среднийЧек),
      нал: показатели.нал,
      безнал: показатели.безнал,
      долянала: Number(показатели.долянала.toFixed(1)),
      направления: показатели.направления,
    },
    возвраты: {
      сумма: показатели.возвраты,
      чеков: показатели.возвратов,
      доля: Number(показатели.доляВозвратов.toFixed(1)),
    },
    чаевые: { сумма: показатели.чаевые, смен: показатели.днейСЧаевыми },
    затраты,
    прибыль: {
      сумма: прибыль,
      маржа: показатели.выручка
        ? Number(((прибыль / показатели.выручка) * 100).toFixed(1)) : 0,
    },
  });
}

export async function POST(request: Request) {
  const отказ = отказПоКлючуОбзора(request);
  if (отказ) return отказ;

  let тело: unknown;
  try {
    тело = await request.json();
  } catch {
    return Response.json({ ok: false, причина: "тело не разобралось как JSON" }, { status: 400 });
  }

  const сырые = (тело as { дни?: unknown })?.дни;
  if (!Array.isArray(сырые)) {
    return Response.json(
      { ok: false, причина: "в теле нет списка «дни»" },
      { status: 400 },
    );
  }
  if (сырые.length === 0) {
    return Response.json({ ok: true, записано: 0, замечание: "список пуст" });
  }

  const ошибки: string[] = [];
  const дни = сырые
    .map((с) => разобрать(с, ошибки))
    .filter((д): д is ДеньОбзора => д !== null);

  if (ошибки.length > 0) {
    return Response.json(
      {
        ok: false,
        причина: "не записано ничего: в присланном есть плохие поля",
        // Первые десять: список на тысячу строк никто не прочтёт, а причина
        // почти всегда одна и та же и видна по первым.
        ошибки: ошибки.slice(0, 10),
        всегоОшибок: ошибки.length,
      },
      { status: 400 },
    );
  }

  try {
    const записано = await залить(дни);
    return Response.json({
      ok: true,
      записано,
      с: дни[0].день,
      по: дни[дни.length - 1].день,
    });
  } catch (е) {
    return Response.json(
      { ok: false, причина: `база не приняла: ${(е as Error).message}` },
      { status: 500 },
    );
  }
}
