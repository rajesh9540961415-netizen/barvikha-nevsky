/**
 * Служебная дверь экрана «Вознаграждение босса»: приём выплат собственнику.
 *
 * Присылает `scripts/boss_push.py`. Тело:
 *
 *   {"выплаты": [{"день":"2026-09-08","документ":"1053",
 *                 "весь_платёж":1650000,"доля":1500000,
 *                 "юрлицо":"ip_shalaeva","за_месяц":"2026-08",
 *                 "комментарий":null}]}
 *
 * 🔴 Строка — это ДОЛЯ платежа, приходящаяся на один месяц. Делёный платёж
 * приходит двумя строками с одним «весь_платёж» и разными «доля»: 08.09.2026
 * из 1 650 000 ₽ к июлю относятся 150 000, остальное к августу.
 *
 * ⚠️ Ключ тот же, что у финансов, — по тому же доводу, что и у `/api/zaimy`:
 * это те же движения из той же выписки, цена утечки одна, а лишняя переменная
 * в панели Amvera означала бы ещё одну возможность забыть её задать.
 *
 * ⚠️ Пачка с плохой выплатой отвергается целиком: половина залитого хуже,
 * чем ничего, потому что выглядит как целое.
 */

export const dynamic = "force-dynamic";

const ДЕНЬ = /^\d{4}-\d{2}-\d{2}$/;
const МЕСЯЦ = /^\d{4}-\d{2}$/;

type Готовое = {
  день: string;
  документ: string;
  весьПлатёж: number;
  доля: number;
  юрлицо: string;
  заМесяц: string | null;
  комментарий: string | null;
};

function строкаИлиПусто(v: unknown): string | null {
  if (typeof v !== "string") return null;
  const т = v.trim();
  return т ? т : null;
}

function разобрать(сырое: unknown, ошибки: string[]): Готовое | null {
  if (typeof сырое !== "object" || сырое === null) {
    ошибки.push("выплата должна быть объектом");
    return null;
  }
  const в = сырое as Record<string, unknown>;

  const день = String(в.день ?? "");
  if (!ДЕНЬ.test(день)) {
    ошибки.push(`«${день}» — не дата вида ГГГГ-ММ-ДД`);
    return null;
  }

  const весьПлатёж = в["весь_платёж"];
  const доля = в.доля;
  for (const [имя, з] of [["весь_платёж", весьПлатёж], ["доля", доля]] as const) {
    if (typeof з !== "number" || !Number.isFinite(з) || з <= 0) {
      ошибки.push(`${день}: «${имя}» должно быть положительным числом`);
      return null;
    }
  }
  // ⚠️ Доля больше платежа — это ошибка счёта на той стороне, и пропустить
  // её нельзя: месяц молча вырастет, а сверить будет нечем.
  if ((доля as number) > (весьПлатёж as number) + 0.01) {
    ошибки.push(`${день}: доля ${доля} больше всего платежа ${весьПлатёж}`);
    return null;
  }

  const юрлицо = строкаИлиПусто(в.юрлицо);
  if (!юрлицо) {
    // Без юрлица выплата бессмысленна: владелец просила раскладку именно
    // по ним, и строка без него тихо испортила бы итог по каждому.
    ошибки.push(`${день}: не указано юрлицо`);
    return null;
  }

  const заМесяц = строкаИлиПусто(в["за_месяц"]);
  if (заМесяц !== null && !МЕСЯЦ.test(заМесяц)) {
    ошибки.push(`${день}: «${заМесяц}» — не месяц вида ГГГГ-ММ`);
    return null;
  }

  return {
    день,
    документ: String(в.документ ?? ""),
    весьПлатёж: весьПлатёж as number,
    доля: доля as number,
    юрлицо,
    заМесяц,
    комментарий: строкаИлиПусто(в.комментарий),
  };
}

export async function POST(request: Request) {
  const отказ = отказПоФинансовомуКлючу(request);
  if (отказ) return отказ;

  let тело: unknown;
  try {
    тело = await request.json();
  } catch {
    return Response.json({ ok: false, причина: "тело не разобралось как JSON" },
                         { status: 400 });
  }

  const сырые = (тело as { выплаты?: unknown })?.выплаты;
  if (!Array.isArray(сырые)) {
    return Response.json({ ok: false, причина: "ожидался список «выплаты»" },
                         { status: 400 });
  }

  const ошибки: string[] = [];
  const готовые = сырые.map((с) => разобрать(с, ошибки))
                       .filter((в): в is Готовое => в !== null);

  if (ошибки.length) {
    return Response.json({ ok: false, причина: "пачка отвергнута целиком", ошибки },
                         { status: 400 });
  }

  try {
    const записано = await залитьВыплаты(готовые);
    return Response.json({ ok: true, записано });
  } catch (e) {
    const err = e as { message?: string };
    return Response.json(
      { ok: false, причина: `база не ответила: ${err.message ?? "неизвестно"}` },
      { status: 500 },
    );
  }
}
