/**
 * Служебная дверь экрана «Москва»: приём заимствований между площадками.
 *
 * Движения считаются на компьютере владельца: выписка лежит в `data/`, до
 * сервера она не доезжает — Amvera собирает бэк-офис отдельным корнем.
 * Напрямую в базу с Мака тоже не достучаться, порт 5432 перехватывает
 * VPN incy, выключать который нельзя. Остаётся HTTPS.
 *
 * Присылает `scripts/zaimy_push.py`. Тело:
 *
 *   {"движения": [{"день":"2026-08-14","документ":"995","сумма":1524000,
 *                  "направление":"out","комментарий":null,
 *                  "не_заём":false,"почему":null}]}
 *
 * ⚠️ **Ключ тот же, что у финансов — `X-Finance-Key`, и это осознанно.**
 * У каждой двери здесь свой ключ, и довод за это хороший: утечка одного
 * не отдаёт остальные. Но заимствования — те же финансовые движения из той
 * же выписки, и цена утечки у них одна. Пятый ключ означал бы ещё одну
 * переменную в панели Amvera, которую надо не забыть задать, — а забытая
 * переменная роняет заливку молча. Понадобится развести — разведём.
 *
 * ⚠️ **Проверяем всю пачку до записи.** Дверь пишет числа, по которым
 * владелец смотрит на долг между площадками: кривое движение не уронит
 * экран, а тихо соврёт. Поэтому пачка с плохим движением отвергается
 * целиком и не пишется вовсе — половина залитого хуже, чем ничего,
 * потому что выглядит как целое.
 */

export const dynamic = "force-dynamic";

const ДЕНЬ = /^\d{4}-\d{2}-\d{2}$/;

type Готовое = {
  день: string;
  документ: string;
  сумма: number;
  направление: "out" | "in";
  комментарий: string | null;
  неЗаём: boolean;
  почему: string | null;
};

function строкаИлиПусто(v: unknown): string | null {
  if (typeof v !== "string") return null;
  const т = v.trim();
  return т ? т : null;
}

function разобрать(сырое: unknown, ошибки: string[]): Готовое | null {
  if (typeof сырое !== "object" || сырое === null) {
    ошибки.push("движение должно быть объектом");
    return null;
  }
  const д = сырое as Record<string, unknown>;

  const день = String(д.день ?? "");
  if (!ДЕНЬ.test(день)) {
    ошибки.push(`«${день}» — не дата вида ГГГГ-ММ-ДД`);
    return null;
  }

  const сумма = д.сумма;
  if (typeof сумма !== "number" || !Number.isFinite(сумма) || сумма <= 0) {
    // Сумма всегда положительная: куда двигались деньги, говорит направление.
    // Отрицательная сумма означала бы, что где-то по дороге знак посчитали
    // дважды, и долг вышел бы не тот.
    ошибки.push(`${день}: сумма должна быть положительным числом, пришло ${JSON.stringify(сумма)}`);
    return null;
  }

  const направление = String(д.направление ?? "");
  if (направление !== "out" && направление !== "in") {
    ошибки.push(`${день}: направление должно быть «out» или «in», пришло «${направление}»`);
    return null;
  }

  return {
    день,
    документ: String(д.документ ?? ""),
    сумма,
    направление,
    комментарий: строкаИлиПусто(д.комментарий),
    неЗаём: д["не_заём"] === true,
    почему: строкаИлиПусто(д.почему),
  };
}

export async function POST(request: Request) {
  const отказ = отказПоФинансовомуКлючу(request);
  if (отказ) return отказ;

  let тело: unknown;
  try {
    тело = await request.json();
  } catch {
    return Response.json({ ok: false, причина: "тело не разобралось как JSON" },
                         { status: 400 });
  }

  const сырые = (тело as { движения?: unknown })?.движения;
  if (!Array.isArray(сырые)) {
    return Response.json({ ok: false, причина: "ожидался список «движения»" },
                         { status: 400 });
  }

  const ошибки: string[] = [];
  const готовые = сырые.map((с) => разобрать(с, ошибки)).filter((д): д is Готовое => д !== null);

  if (ошибки.length) {
    return Response.json({ ok: false, причина: "пачка отвергнута целиком", ошибки },
                         { status: 400 });
  }

  try {
    const записано = await залитьДвижения(готовые);
    return Response.json({ ok: true, записано });
  } catch (e) {
    const err = e as { message?: string };
    return Response.json(
      { ok: false, причина: `база не ответила: ${err.message ?? "неизвестно"}` },
      { status: 500 },
    );
  }
}
