/**
 * Сторож чёрного экрана после выкладки.
 *
 * 🔴 **Что лечим.** 11.09.2026 владелец полдня не могла открыть бэк-офис:
 * страница открывалась пустой и чёрной. Сервер был жив, файлы отдавались,
 * на соседнем компьютере всё рисовалось. Дело было в браузере: у новой
 * сборки другие имена файлов, а Safari держался за старые — те, которых
 * на сервере уже нет. Он получал 404, молча бросал загрузку, и приложению
 * было нечем нарисоваться. Лечилось стиранием данных сайта руками.
 *
 * 💡 **Как ловим.** Неудачная загрузка файла поднимает событие `error`
 * на самом теге `script` или `link`. Оно не всплывает как обычные события,
 * поэтому слушаем в режиме перехвата (`true` третьим доводом). Плюс
 * `unhandledrejection` — так о себе заявляет сорвавшаяся подгрузка куска
 * приложения при переходе между разделами.
 *
 * ⚠️ **Почему прямо в HTML, а не отдельным компонентом.** Компонент — это
 * тот же файл приложения. Не загрузился он — не загрузится и сторож, и мы
 * останемся ровно с тем же чёрным экраном. Здесь код едет внутри самой
 * страницы и работает, даже когда не приехало больше ничего.
 *
 * ⚠️ **Почему адрес с меткой, а не простая перезагрузка.** Перезагрузка
 * может снова взять страницу из того же кэша, который и сломался, — и мы
 * получим тот же чёрный экран, только дважды. Метка `свежесть` делает адрес
 * новым, и браузеру приходится спросить сервер. Метку убираем из адресной
 * строки сразу после загрузки, чтобы она не попадала в закладки.
 *
 * 🔴 **Одна попытка в пять минут, и это главная защита.** Если бы сторож
 * перезагружал страницу на каждую ошибку, по-настоящему сломанная выкладка
 * дала бы вечный круг перезагрузок — то есть хуже, чем чёрный экран:
 * из него хотя бы видно, что что-то не так. Отметка о попытке лежит
 * в `sessionStorage` и нарочно НЕ стирается при удачной загрузке: событие
 * `load` приходит и на сломанной странице тоже.
 */
const СТОРОЖ_ЧЁРНОГО_ЭКРАНА = `
(function () {
  var КЛЮЧ = "перезагрузка-после-выкладки";
  var МЕТКА = "svezhest";
  var ПАУЗА = 300000;

  function наше(адрес) {
    return typeof адрес === "string" && адрес.indexOf("/_next/") !== -1;
  }

  function перезагрузить() {
    var было = 0;
    try { было = Number(sessionStorage.getItem(КЛЮЧ)) || 0; } catch (e) {}
    if (Date.now() - было < ПАУЗА) return;
    try { sessionStorage.setItem(КЛЮЧ, String(Date.now())); } catch (e) {}
    var адрес = location.href.split("#")[0];
    адрес += (адрес.indexOf("?") === -1 ? "?" : "&") + МЕТКА + "=" + Date.now();
    location.replace(адрес);
  }

  window.addEventListener("error", function (соб) {
    var цель = соб && соб.target;
    if (!цель || !цель.tagName) return;
    if (цель.tagName !== "SCRIPT" && цель.tagName !== "LINK") return;
    if (наше(цель.src || цель.href)) перезагрузить();
  }, true);

  window.addEventListener("unhandledrejection", function (соб) {
    var беда = соб && соб.reason;
    var текст = беда ? String(беда.name || "") + " " + String(беда.message || беда) : "";
    if (/ChunkLoadError|Loading chunk|dynamically imported module|Importing a module script/i.test(текст)) {
      перезагрузить();
    }
  });

  function убратьМетку() {
    if (location.search.indexOf(МЕТКА + "=") === -1) return;
    var поиск = location.search.replace(new RegExp("[?&]" + МЕТКА + "=\\\\d+"), "");
    if (поиск === "?") поиск = "";
    try {
      history.replaceState(null, "", location.pathname + поиск + location.hash);
    } catch (e) {}
  }

  window.addEventListener("load", function () {
    убратьМетку();
    setTimeout(убратьМетку, 1500);
  });
})();
`;

// Шрифт не подгружаем со стороны: бэк-офис открывают на компьютере, где
// системный шрифт и так хорош, а лишняя внешняя зависимость — лишний способ
// не собраться в неудачный момент.
export default function RootLayout({
  children,
}: Readonly<{ children: React.ReactNode }>) {
  return (
    <html lang="ru" className="h-full antialiased">
      <head>
        <script dangerouslySetInnerHTML={{ __html: СТОРОЖ_ЧЁРНОГО_ЭКРАНА }} />
      </head>
      <body className="min-h-full">{children}</body>
    </html>
  );
}
