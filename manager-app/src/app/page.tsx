import { redirect } from "next/navigation";
import { requireManager } from "@/lib/db/managers";

export const dynamic = "force-dynamic";

/**
 * Корень бэк-офиса. Пока — перенаправление, потом здесь встанет дашборд.
 *
 * До 16.08.2026 тут лежал список смен, и при входе первыми вываливались
 * чаевые. Владелец: нужно наоборот — сначала общая картина, потом финансы,
 * потом чаевые, потом сотрудники. Дашборда ещё нет, поэтому владельца
 * встречают «Финансы».
 *
 * ⚠️ Разное перенаправление по роли, и это не украшение. `требоватьВладельца`
 * отправляет управляющего на «/» — отправь мы отсюда всех подряд на «/finance»,
 * управляющий закружился бы между двумя страницами навсегда.
 */
export default async function Home() {
  const manager = await requireManager();
  redirect(manager.role === "owner" ? "/finance" : "/tips");
}
