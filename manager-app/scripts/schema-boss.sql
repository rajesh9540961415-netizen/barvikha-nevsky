-- Вознаграждение собственнику — для экрана «Вознаграждение босса».
--
-- Заведено 11.09.2026 по задаче владельца: «отдельная страничка, где нужно
-- описать вывод в порядке: месяц, за который мы заплатили, общая сумма,
-- с каких юридических лиц какие суммы были выведены».
--
-- 🔴 Здесь ДВЕ разные даты, и путать их дороже всего остального.
--   `day` — когда деньги ушли со счёта. Это факт из выписки.
--   `for_month` — за какой месяц вознаграждение. Это ЗНАНИЕ ВЛАДЕЛЬЦА,
--     в банковских данных его нет вовсе.
-- За июль 2026 платили пятью платежами с 22 июля по 8 сентября, а часть
-- одного сентябрьского платежа относится к июлю. По дате платежа такую
-- картину не собрать никак.
--
-- ⚠️ `for_month` пустой — это «владелец ещё не называла месяц», а не «ни за
-- какой». Из 110 выплат на 11.09.2026 месяц известен у восьми: их владелец
-- разобрала в тот день, разбирая переводы на московский счёт. Показывать
-- пустое как ноль или как «прочее» нельзя — это разные новости.
--
-- Наполняет таблицу scripts/boss_push.py с Мака через дверь /api/boss:
-- напрямую в базу с компьютера владельца не достучаться, порт 5432
-- перехватывает VPN incy, а выключать его нельзя.

create table if not exists owner_payouts (
  -- Дата платежа по выписке.
  day         date          not null,
  doc_no      text          not null default '',
  -- Полная сумма платежа по выписке. Не меняется при делении по месяцам:
  -- по ней платёж находится в банке и сверяется с выпиской.
  full_amount numeric(14,2) not null,

  -- Юрлицо, с чьего счёта ушли деньги: ip_khisamov, ip_borzova, ip_shalaeva.
  -- Владелец просила раскладку именно по ним: деятельность шла через разные
  -- ИП подряд, и «сколько всего вывели» без этого разреза ни о чём не говорит.
  entity      text          not null,

  -- За какой месяц вознаграждение, в виде ГГГГ-ММ. Null — месяц не назван.
  --
  -- 🔴 Часть ключа, и это не мелочь: ОДИН платёж может относиться к двум
  -- месяцам. 08.09.2026 из 1 650 000 ₽ к июлю относятся 150 000, остальное
  -- к августу (владелец 11.09.2026). Одна строка на платёж такую выплату
  -- показать не может: либо июль занижен на 150 000, либо август завышен.
  for_month   text          not null default '',

  -- Сколько из платежа приходится на этот месяц. Для неделёного платежа
  -- равно full_amount.
  part_amount numeric(14,2)  not null,

  -- Пояснение владельца к выплате. Пусто — не разбирали.
  comment     text,

  updated_at  timestamptz   not null default now(),

  -- Дата + документ + сумма + месяц. Месяц в ключе затем, чтобы делёный
  -- платёж лёг двумя строками и обе сохранились.
  -- ⚠️ coalesce в ключе не поставить, поэтому неназванный месяц пишем
  -- пустой строкой, а не null: null в первичном ключе не живёт.
  primary key (day, doc_no, full_amount, for_month)
);
