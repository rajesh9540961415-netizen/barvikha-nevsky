-- Дневные итоги для экрана «Обзор».
--
-- Заведено 07.09.2026. Отдельным файлом, а не строками в schema.sql,
-- по двум причинам:
--
--   1. В schema.sql на тот момент лежала незафиксированная тема мотивации
--      кальянного бара, и трогать этот файл значило утащить её за собой.
--   2. Таблица служебная: это не деньги смены, а слепок фискальных чеков,
--      который можно в любой момент собрать заново из data/ofd. Потерять
--      её не страшно, и держать рядом с таблицами, где живут настоящие
--      чаевые, — значит уравнять в правах несравнимое.
--
-- ⚠️ Почему таблица вообще нужна. Amvera собирает бэк-офис отдельным корнем:
-- папка data/ofd с чеками до сервера не доезжает, и посчитать выручку на
-- месте он не может. До 07.09.2026 числа лежали файлом внутри сборки —
-- и обновлялись только вместе с выкладкой. Владелец: «делай живое
-- обновление через базу».
--
-- Наполняет её scripts/dashboard_push.py с Мака через служебную дверь
-- /api/dashboard: напрямую в базу с компьютера владельца не достучаться,
-- порт 5432 перехватывает VPN incy, а выключать его нельзя.

create table if not exists dashboard_days (
  -- Торговый день, с 11:00 до 10:59. Не календарный: субботняя ночь после
  -- полуночи принадлежит субботе, а суббота — главный день недели.
  business_day  date          primary key,
  revenue       numeric(14,2) not null default 0,
  checks        integer       not null default 0,
  cash          numeric(14,2) not null default 0,
  cashless      numeric(14,2) not null default 0,
  refunds       numeric(14,2) not null default 0,
  refund_count  integer       not null default 0,
  -- {"бар": 123.45, "кухня": …} — суммы позиций по направлениям.
  directions    jsonb         not null default '{}'::jsonb,
  -- 24 числа, выручка по часам суток. Час настоящий, часовой: ради него
  -- всё и затевалось, пик приходится на полночь.
  hours         jsonb         not null default '[]'::jsonb,
  -- Чаевые смены. null — не «ноль», а «смены в приложении нет»: чаевые
  -- ведутся с августа 2026, и на длинных периодах их просто не было.
  tips          numeric(14,2),
  updated_at    timestamptz   not null default now()
);
