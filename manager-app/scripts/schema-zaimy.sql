-- Заимствования между площадками — для экрана «Москва».
--
-- Заведено 11.09.2026 по задаче владельца: «сделаем отдельную страничку
-- по заимствованиям между площадками — что уходило с питерской на московскую
-- и что приходило обратно, с комментариями, за что именно ушли деньги».
--
-- 🔴 Это ЗАЁМ, а не расход и не вывод — решение владельца 15.08.2026.
-- Счёт оформлен на то же ИП, поэтому обычная разметка считает такой перевод
-- внутренним, и он исчезает из отчёта совсем: не расход, не вывод. А это
-- деньги, ушедшие из невского бизнеса в другое заведение.
--
-- ⚠️ Видно только то, что прошло через НЕВСКИЕ счета: выписку по московскому
-- счёту владелец сознательно не берёт (решение 15.08.2026). Возврат, сделанный
-- внутри Москвы, сюда не попадёт, и отсутствие возврата не доказывает долг.
-- Страница обязана говорить об этом вслух.
--
-- Наполняет таблицу scripts/zaimy_push.py с Мака через служебную дверь
-- /api/zaimy: напрямую в базу с компьютера владельца не достучаться,
-- порт 5432 перехватывает VPN incy, а выключать его нельзя.

create table if not exists interbranch_moves (
  -- Дата платежа по выписке.
  day          date          not null,
  -- Номер документа в выписке. Строкой: в выписке он приходит строкой,
  -- и у части движений его нет вовсе.
  doc_no       text          not null default '',
  -- Сумма всегда положительная; куда двигались деньги, говорит direction.
  amount       numeric(14,2) not null,
  -- 'out' — Питер → Москва (выдали заём), 'in' — Москва → Питер (вернули).
  --
  -- ⚠️ Отбирать движения без проверки направления нельзя: 14.08.2026 возврат
  -- на 24 000 ₽ лежит в выписке среди тех же «заимствований» и отличается
  -- только этим полем. Отбор по одному счёту даёт его как расход — на этом
  -- уже ошиблись 17.08.2026 и завысили отток.
  direction    text          not null check (direction in ('out', 'in')),

  -- За что ушли деньги. Пишет владелец — через переписку, не руками в базе:
  -- страница только показывает (решение владельца 11.09.2026).
  -- Пусто — «ещё не разбирали», а не «не за что».
  comment      text,

  -- Разобрано и оказалось НЕ займом — как 182 260 ₽ от 09.07.2026:
  -- московский счёт оплатил четыре наших счёта, мы ему возместили, сумма
  -- сошлась в ноль. Такие строки уходят из долга и показываются отдельно.
  --
  -- ⚠️ Источник правды об этом — `rules.reclassify` в data/dds/registry.json,
  -- здесь лежит слепок. Отличать разобранное по тексту комментария нельзя:
  -- он заполнен и у тех, и у других.
  settled      boolean       not null default false,
  settled_why  text,

  updated_at   timestamptz   not null default now(),

  -- Тройка «дата + документ + сумма» — тот же ключ, которым закрываются
  -- движения в registry.json. Один ключ на оба места: разойдись они,
  -- разобранное перестало бы находиться, и долг вырос бы на ровном месте.
  primary key (day, doc_no, amount)
);
