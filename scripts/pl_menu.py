def hookah_names():
    s = set()
    for f in glob.glob("data/ofd/чеки-бар-2026-0[78].json"):
        for ч in json.load(open(f)):
            for n,_,_ in ч.get("позиции", []):
                s.add(n.strip().lower())
    return s

