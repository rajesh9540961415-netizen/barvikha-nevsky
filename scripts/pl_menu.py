def бар_по_виду(n: str) -> bool:
    ln = n.lower()
    if re.search(r"\(\s*\d+\s*(ml|мл)\s*\)", ln): return True      # (50 ml), (150мл)
    if re.search(r"\d[\d,\. ]*\s*л\)", ln): return True            # (… 0 5 л)
    if re.search(r"\b\d[\d,\. ]*\s*л\b", ln): return True          # 0 33 л
    if re.search(r"\b\d[\d,\. ]*\s*(мл|ml)\b", ln): return True    # 0 75, 250 мл
    if re.search(r"\b0\s*[,\.]?\s*\d{2}\b", ln): return True       # 0 75 без «л»
    if re.search(r"^[A-Z0-9 &'`\.\-\+!\?]{4,}$", n.strip()): return True  # КОКТЕЙЛИ КАПСОМ
    if any(w in ln for w in ЧАИ): return True
    return any(w in ln for w in НАПИТКИ_СЛОВА)

def категория(n: str) -> str:
    ln = n.strip().lower()
    if ln in HOOKAH: return "кальяны"
    if any(w in ln for w in КАЛЬЯН_СЛОВА): return "кальяны"
    if any(w in ln for w in КАЛЬЯН_МАРКИ): return "кальяны"
    if any(ln.startswith(m) for m in МИКСЫ): return "кальяны"
    if "аренда" in ln: return "аренда"
    if бар_по_виду(n): return "бар"
    return "кухня"

