#!/usr/bin/env python3
"""Вписывает выручку в отчёт по чаевым — из обеих касс Quick Resto.

Выручка нужна отчёту ради строки «% чаевых от выручки». Без неё та показывает
0,0 %, и весь смысл сравнения пропадает: чаевые сами по себе ни о чём не
говорят, важна их доля от того, что заведение заработало.

🔴 **ОБЛАКО БАРА — СЕТЕВОЕ, и читать его целиком НЕЛЬЗЯ.** В `gt464` кроме
Невского живут Митино, Красная площадь и Москва-Сити (заведены 13.08.2026).
Здесь отбора по залу не было до 22.08.2026, и выручка за 21.08 выходила
1 463 145 ₽ вместо 1 096 395 — на 366 750 ₽ чужих денег.

⚠️ **Ошибка пряталась вдвойне.** В `qr_sales.py` отбор поставили ещё утром
22.08, и утренняя финсводка стала верной — а этот файл остался прежним.
Один и тот же вопрос считался двумя путями, и разошлись они молча: процент
чаевых занижался, блок «ДОХОД» финсвода завышался. **Нашлось только тем,
что две цифры одного дня легли рядом на экран.**

💡 Отбор кричит вслух о каждом выброшенном зале — молчаливый отбор однажды
выбросит наш собственный, если его переименуют в кассе.

⚠️ **Касс две, и складывать надо обе.** С 7 июля 2026 в заведении работают
два юрлица со своими облаками Quick Resto: ООО «МАВ» и ИП Шалаева. Выручка
заведения — это сумма. Взять одну кассу значит занизить выручку почти вдвое
и получить вдвое завышенный процент чаевых.

День берётся по дате ОТКРЫТИЯ смены — так же, как в приложении смены и в
ручной таблице. Бизнес-день в Quick Resto начинается в 11:00, приложение
настроено так же, поэтому дни в обоих источниках означают одно и то же.

Запуск:
    python3 scripts/report_revenue.py              # месяц вчерашнего дня
    python3 scripts/report_revenue.py 2026-08      # конкретный месяц

Доступы берёт из `.env`: QR_MAV_* и QR_SHALAEVA_*.
"""

from __future__ import annotations

import sys
from collections import defaultdict
from datetime import date, timedelta
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from openpyxl import load_workbook  # noqa: E402

from qr_sales import (  # noqa: E402
    CLOUDS, business_day, fetch_shifts, наша_смена, read_env, зал_смены,
)
from report_path import describe, report_dir  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
МЕСЯЦЫ = ("январь февраль март апрель май июнь июль "
          "август сентябрь октябрь ноябрь декабрь").split()


def выручка_по_дням(месяц: str) -> tuple[dict[date, float], dict[str, float]]:
    """Сумма по обеим кассам за месяц. Возвращает (по дням, итоги по кассам)."""
    по_дням: dict[date, float] = defaultdict(float)
    по_кассам: dict[str, float] = {}

    for cloud, (_, название) in CLOUDS.items():
        cfg = read_env(cloud)
        всего = 0.0
        чужие: dict[str, float] = defaultdict(float)
        for s in fetch_shifts(cfg):
            d = business_day(s)
            # Открытые смены не берём: суммы в них ещё меняются, и вчерашний
            # день попал бы в отчёт недосчитанным.
            if not d or s.get("status") != "CLOSED":
                continue
            if d.strftime("%Y-%m") != месяц:
                continue
            if not наша_смена(s):
                чужие[зал_смены(s)] += ((s.get("totalCash") or 0) - (s.get("totalReturnCash") or 0)
                               + (s.get("totalCard") or 0) - (s.get("totalReturnCard") or 0))
                continue
            нал = (s.get("totalCash") or 0) - (s.get("totalReturnCash") or 0)
            безнал = (s.get("totalCard") or 0) - (s.get("totalReturnCard") or 0)
            по_дням[d] += нал + безнал
            всего += нал + безнал
        по_кассам[название] = всего
        print(f"  {название:<14} {всего:>14,.0f} ₽".replace(",", " "))
        for зал, деньги in sorted(чужие.items(), key=lambda x: -x[1]):
            print(f"    ⚠ не наш зал «{зал}»: {деньги:,.0f} ₽ — "
                  f"в выручку не берём".replace(",", " "))

    return по_дням, по_кассам


def разбивка(месяц: str) -> dict[str, dict[str, float]]:
    """Выручка по юрлицам и видам оплаты, для блока «ДОХОД» «Фин. свода».

    ⚠️ Зачем понадобилась — 14.08.2026. Владелец сверяла выручку в «Фин. своде»
    руками и не сходилась. Ошибки не было: с 07.07.2026 за строками «Нал»
    и «Без нал» стоит СУММА ДВУХ ЮРЛИЦ, а глазами такое не проверить —
    сверяя с любой одной кассой, не попасть никогда.

    💡 Берём «Выручку», а не «Сумму продаж». Разница — возвраты, и она велика:
    за 13.08 продажи по безналу 368 645 ₽, выручка 308 865 ₽. Совпадение
    с колонкой Quick Resto «Выручка» проверено до рубля по скриншоту владельца.

    ⚠️ Открытые смены не берём: суммы в них ещё меняются.
    """
    итог: dict[str, dict[str, float]] = {}
    for cloud, (_, название) in CLOUDS.items():
        cfg = read_env(cloud)
        нал = безнал = 0.0
        for s in fetch_shifts(cfg):
            d = business_day(s)
            if not d or s.get("status") != "CLOSED":
                continue
            if d.strftime("%Y-%m") != месяц:
                continue
            # ⚠️ Тот же отбор, что и в выручке выше. Две функции читают одно
            # облако — забыть его здесь значит развести «ДОХОД» финсвода
            # с процентом чаевых, считая при этом одно и то же.
            if not наша_смена(s):
                continue
            нал += (s.get("totalCash") or 0) - (s.get("totalReturnCash") or 0)
            безнал += (s.get("totalCard") or 0) - (s.get("totalReturnCard") or 0)
        if нал or безнал:
            итог[название] = {"нал": round(нал, 2), "безнал": round(безнал, 2)}
    return итог


def показать_разбивку(месяцы: list[str]) -> None:
    """Печатает строки так, как они лягут в блок «ДОХОД»."""
    for месяц in месяцы:
        данные = разбивка(месяц)
        if not данные:
            print(f"\n{месяц}: закрытых смен нет")
            continue
        print(f"\n  ВЫРУЧКА ЗА {месяц} — для блока «ДОХОД» «Фин. свода»")
        print("  " + "─" * 52)
        всего_нал = всего_безнал = 0.0
        for название, д in данные.items():
            print(f"  {название} нал{'':<6}{д['нал']:>18,.2f} ₽".replace(",", " "))
            print(f"  {название} безнал{'':<3}{д['безнал']:>18,.2f} ₽".replace(",", " "))
            всего_нал += д["нал"]
            всего_безнал += д["безнал"]
        print("  " + "─" * 52)
        print(f"  {'ИТОГО нал':<20}{всего_нал:>18,.2f} ₽".replace(",", " "))
        print(f"  {'ИТОГО без нал':<20}{всего_безнал:>18,.2f} ₽".replace(",", " "))
        print(f"  {'ИТОГО выручка':<20}{всего_нал + всего_безнал:>18,.2f} ₽".replace(",", " "))


def main() -> None:
    # Показ разбивки — отдельный режим: он ничего не записывает, только считает.
    if "--разбивка" in sys.argv:
        месяцы = [a for a in sys.argv[1:] if not a.startswith("--")]
        вчера = date.today() - timedelta(days=1)
        показать_разбивку(месяцы or [вчера.strftime("%Y-%m")])
        return

    месяц = sys.argv[1] if len(sys.argv) > 1 else (
        date.today() - timedelta(days=1)).strftime("%Y-%m")
    год, мес = (int(x) for x in месяц.split("-"))

    имя = f"Чаевые-дубль-{МЕСЯЦЫ[мес - 1]}-{год}.xlsx"
    найдено = [p for p in (report_dir() / имя, ROOT / имя) if p.exists()]
    if not найдено:
        sys.exit(
            f"Не нашёл отчёт «{имя}».\n"
            f"  Создать: python3 scripts/report_new.py {месяц}"
        )
    отчёт = найдено[0]

    print(f"Выручка за {МЕСЯЦЫ[мес - 1]} {год}:")
    по_дням, по_кассам = выручка_по_дням(месяц)
    if not по_дням:
        sys.exit("✗ Ни одной закрытой смены за этот месяц. В отчёт писать нечего.")

    wb = load_workbook(отчёт)
    ws = wb[wb.sheetnames[0]]

    строка = next(
        (r for r in range(1, 40) if ws.cell(r, 1).value == "Выручка"), None
    )
    if строка is None:
        sys.exit("В отчёте нет строки «Выручка». Отчёт собран старым шаблоном.")

    записано = 0
    for д, сумма in sorted(по_дням.items()):
        нужно = д.strftime("%d.%m.%Y")
        столбец = next(
            (c for c in range(2, ws.max_column + 1)
             if str(ws.cell(1, c).value or "").strip() == нужно),
            None,
        )
        if столбец is None:
            print(f"  ⚠ в отчёте нет столбца {нужно} — пропускаю")
            continue
        ws.cell(строка, столбец, round(сумма, 2))
        записано += 1

    wb.save(отчёт)

    итого = sum(по_кассам.values())
    print(f"  {'ВСЕГО':<14} {итого:>14,.0f} ₽".replace(",", " "))
    print(f"\nЗаписано дней: {записано}")
    print(f"Отчёт: {отчёт.name}")
    print(f"Папка: {describe(отчёт.parent)}")
    print("\nПроцент чаевых от выручки таблица посчитает сама при открытии.")


if __name__ == "__main__":
    main()
