#
# Поэтому у кальянщиков свой диапазон: настоящий номер плюс миллион. Тем же
# приёмом уже разведены вписанные вручную — у них номер отрицательный.
# Вернуть настоящий номер всегда можно вычитанием, он никуда не делся.
HOOKAH_OFFSET = 1_000_000

# Кто заведён в кассе, но в ЭТОМ контуре не работает и получателем чаевых
# быть не должен. Ключ — настоящий номер в своей кассе, без прибавки.
#
# ⚠️ Зачем это вообще нужно. Заведение работает через два юрлица, и учётка
# в кассе следует за РАБОТОДАТЕЛЕМ: завести сотрудника одного юрлица в кассе
# другого нельзя — это цифровой след и доказательство связи компаний
# (решение владельца 22.08.2026). Поэтому человек зала, оформленный
# на ИП Шалаеву, законно живёт в кассе БАРА — и оттуда приезжает в список
# кальянщиков, хотя в баре не работает ни дня.
#
# 💡 Учётку при этом убирать нельзя: под ней открывают смены, она рабочая.
# Значит развести оформление и работу приходится здесь, на нашей стороне.
#
# ⚠️ Это заплатка, и она знает, что заплатка. Настоящее решение —
# plans/2026-08-22-chelovek-ne-nomer.md: человек перестаёт быть номером
# в кассе, роль берётся из состава смены, а не из того, где он оформлен.
# Когда план сделан — этот список удаляется целиком.
# Наш зал. Облако ИП Шалаевой обслуживает НЕ ТОЛЬКО нас: 22.08.2026 в нём
# нашлись четыре зала — Невский, Митино, Красная площадь, Москва-Сити.
# Сотрудники чужих залов приезжали к нам в список кальянщиков и могли быть
# выбраны получателями наших чаевых.
#
# 💡 Правило намеренно мягкое: отсекаем только тех, у кого привязка ЕСТЬ
# и она к чужому залу. У кого привязки нет — берём, как раньше: сегодня
# именно так заведены все, кто реально работает на Невском, и строгий отбор
# «только Невский» оставил бы нас без людей.
#
# ⚠️ Когда владелец проставит привязки своим людям, правило продолжит
# работать без правок — они попадут под «свой зал». После этого можно будет
# ужесточить до строгого отбора, и вот тогда — только по факту, а не заранее.
НАШ_ЗАЛ = "Барвиха Lounge Невский"


def не_наш_зал(e, строго):
    """Почему запись не наша. None — берём.

    ⚠️ Два правила, и разница между ними принципиальная.

    Касса ЗАЛА (`fk381`) — наша собственная: кто в ней есть, тот наш,
    отсеивать некого. Привязка к залу там проставлена лишь у двоих из 23,
    и строгий отбор оставил бы смену без официантов.

    Касса БАРА (`gt464`) — ОБЩАЯ на сеть: 22.08.2026 в ней нашлись четыре
    зала — Невский, Митино, Красная площадь, Москва-Сити. Там отсутствие
    привязки НЕ означает «наш»: владелец 22.08 подтвердила, что ни один
    человек из этого облака в баре на Невском не работает. Поэтому берём
    только тех, у кого явно стоит наш зал.

    💡 Именной список кальянщиков от этого становится пустым — и это правда,
    а не поломка. Весь август барские чаевые шли в общий котёл «Весь бар»
    именно потому, что выбирать было не из кого: в списке стояли посторонние.

    ⚠️ Без аннотации типа нарочно: системному Python на этом Маке 3.9,
    а запись «str | None» появилась только в 3.10 — на ней скрипт падает.
    """
    залы = [s.get("name") for s in (e.get("allowedTablesSchemes") or []) if s.get("name")]
    if НАШ_ЗАЛ in залы:
        return None
    if залы:
        return f"зал «{', '.join(sorted(set(залы)))}», не наш"
    if строго:
        return "зал не указан, а облако общее на сеть — своим не считаем"
    return None


