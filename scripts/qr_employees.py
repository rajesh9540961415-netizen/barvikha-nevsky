def read_env():
    cfg = {}
    for line in ENV.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            key, value = line.split("=", 1)
            cfg[key.strip()] = value.strip()
    return cfg


def fetch(cfg, prefix):
    """Список сотрудников одной кассы.

    Ключи ищем сначала свои (QR_MAV_URL), потом общие (QR_URL): общие
    остались с тех пор, когда касса была одна.
    """
    def key(suffix):
        value = cfg.get(f"{prefix}_{suffix}") or cfg.get(f"QR_{suffix}")
        if not value:
            raise SystemExit(f"В .env не заполнено: {prefix}_{suffix}")
        return value

    token = base64.b64encode(
        f"{key('LOGIN')}:{key('PASSWORD')}".encode()
    ).decode()
    query = urllib.parse.urlencode(
        {"moduleName": "personnel.employee", "className": EMPLOYEE_CLASS}
    )
    req = urllib.request.Request(
        f"{key('URL').rstrip('/')}{API_PREFIX}/api/list?{query}",
        headers={
            "Authorization": "Basic " + token,
            "Content-Type": "application/json",
            "Connection": "keep-alive",
        },
    )
    return json.loads(достучаться(req, таймаут=90).decode("utf-8"))


def people_from(raw, offset=0, prefix=None, строго=False):
    """Список людей одной кассы. Исключённые не молчат, а называются вслух."""
    исключены = НЕ_ПОЛУЧАТЕЛИ.get(prefix or "", {})
    убрали = []
    people = []
    for e in raw:
        if e.get("id") in исключены:
            убрали.append((e.get("id"), исключены[e["id"]]))
            continue
        чужой = не_наш_зал(e, строго)
        if чужой:
            имя_ч = (e.get("fullName") or "").strip() or f"№{e.get('id')}"
            убрали.append((e.get("id"), f"{имя_ч} — {чужой}"))
            continue
        # systemEmployee — тип учётки, а не флаг: Custom у живых людей,
        # SuperUser и FrontOffice у служебных входов.
        if e.get("blocked") or e.get("systemEmployee") != "Custom":
            continue
        first = (e.get("firstName") or "").strip()
        last = (e.get("lastName") or "").strip()
        full = (e.get("fullName") or f"{first} {last}").strip()
        if not full:
            continue
        people.append(
            {
                "id": e.get("id") + offset,
                "name": full,
                # Короткое имя для кнопки: «Анна К.»
                "short": f"{first} {last[:1]}." if first and last else full,
            }
        )
    people.sort(key=lambda p: p["name"])
    # Кричим вслух: молчаливое исключение однажды уберёт нужного человека,
    # и искать будут долго.
    for номер, почему in убрали:
        print(f"  ⚠ не берём в этот контур: №{номер} — {почему}")
    return people


ВНЕ_КАССЫ = ROOT / "data" / "кальянщики-вне-кассы.json"


def дописать_вне_кассы(people):
    """Кальянщики, которых в кассе нет и не будет.

    🔴 Владелец 08.09.2026: «я не могу завести их в кассу — они не оформлены».
    А отмечать их в смене надо: мотивация бара делится поровну между теми,
    кто вышел, и без имён делить не на кого.

    ⚠️ Дописываем ЗДЕСЬ, а не правим hookah.json руками: этот файл скрипт
    перезаписывает при каждом обновлении справочника, и всякая ручная правка
    в нём жила бы до следующего утра.
    """
    if not ВНЕ_КАССЫ.exists():
        return people
    свои = json.loads(ВНЕ_КАССЫ.read_text(encoding="utf-8")).get("люди") or []
    номера = {ч["id"] for ч in people}
    добавлены = [ч for ч in свои if ч["id"] not in номера]
    if добавлены:
        print(f"  + вне кассы: {', '.join(ч['name'] for ч in добавлены)}")
    return sorted(people + добавлены, key=lambda ч: ч["name"])


def warn_about(people):
    """Странное не выбрасываем молча, а показываем.

    Одинаковых людей и тестовые записи чинят в самой кассе — решение,
    кого удалять, за владельцем. Скрипт, который «умно» отфильтровал бы
    их сам, однажды выкинет живого человека и не скажет об этом.
    """
    warnings = []
    for name, count in Counter(p["name"] for p in people).items():
        if count > 1:
            warnings.append(f"дважды заведён: {name} ({count} записи)")
    for p in people:
        parts = p["name"].lower().split()
        if len(set(parts)) < len(parts) or "иванов" in p["name"].lower():
            warnings.append(f"похоже на тестовую запись: {p['name']}")
    return warnings


def main():
    cfg = read_env()
    for cloud in CLOUDS:
        raw = fetch(cfg, cloud["prefix"])
        people = people_from(raw, cloud["offset"], cloud["prefix"],
                             cloud.get("строго", False))
        if cloud["prefix"] == "QR_SHALAEVA":
            people = дописать_вне_кассы(people)
        # ⚠️ Пусто бывает двух разных видов, и путать их нельзя.
        #
        # Касса не ответила или ответила пустотой — это сбой связи, и молча
        # затирать справочник нулём нельзя: приложение осталось бы без людей.
        # Останавливаемся с криком.
        #
        # А вот «касса ответила, но все до одного отсеяны отбором» — это
        # законный результат, а не сбой. 22.08.2026 так и вышло с кассой бара:
        # в общем на сеть облаке не оказалось ни одного человека нашего зала.
        # Пустой именной список правдив, и записать его надо: иначе в приложении
        # навсегда останутся посторонние из других заведений.
        if not raw:
            sys.exit(f"{cloud['title']}: Quick Resto не вернул ни одного сотрудника.\n"
                     "  Похоже на обрыв связи. Справочник не тронут.")
        if not people:
            print(f"\n⚠️  {cloud['title']}: своих не осталось — отбор отсеял всех, "
                  f"кого вернула касса ({len(raw)} записей).")
            print("    Это правда, а не сбой: записываю пустой список.")

        body = json.dumps(people, ensure_ascii=False, indent=2) + "\n"
        for path in cloud["files"]:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(body, encoding="utf-8")

        print(f"\n{cloud['title']}: {len(people)} человек")
        for p in people:
            print(f"  {p['short']:24} ({p['name']})")
        for w in warn_about(people):
            print(f"  ⚠️  {w}")
        print("  записано в: " + ", ".join(
            str(p.relative_to(ROOT)) for p in cloud["files"]
        ))


if __name__ == "__main__":
    main()
