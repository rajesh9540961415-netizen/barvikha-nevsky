def строки_банка(месяц):
    """Платежи месяца из размеченной выписки."""
    for r in csv.DictReader(open(DDS / "bank_classified.csv", encoding="utf-8")):
        if r["date"].startswith(месяц):
            yield r


def это_карта(r) -> bool:
    """Покупка по бизнес-карте, а не платёж со счёта.

    У ИП Хисамова карта своя, и её покупки в июльском листе стоят внутри его
    блока, а не в блоке карты ООО. Поэтому проверяем и юрлицо.
    """
    п = r["purpose"].upper()
    return r["entity"] == "mav" and ("PURCHASE" in п or "ТУ СБЕРБАНКА" in п)


def имя_по_карте(purpose: str):
    """Как назвать покупку по карте и в какую статью её отнести."""
    п = purpose.upper()
    for ключ, (имя, статья) in КАРТА.items():
        if ключ in п:
            return имя, статья
    # Незнакомая точка: достаём имя между «в ТУ» и «по карте» — его видно
    # в своде целиком, а не обрезанным по первому пробелу.
    м = re.search(r"в ТУ (?:Сбербанка )?(.+?)\s+по карте", purpose, re.IGNORECASE)
    return (м.group(1).strip() if м else purpose[:40]), "Прочие расходы"


def выручка(месяц):
    """Наличная и безналичная выручка обеих касс."""
    итог = {}
    for имя, файл in (("ООО «МАВ»", "qr_sales_mav.csv"),
                      ("ИП Шалаева", "qr_sales_shalaeva.csv")):
        нал = безнал = 0.0
        for r in csv.DictReader(open(DDS / файл, encoding="utf-8")):
            if r["date"].startswith(месяц):
                нал += float(r["cash"] or 0)
                безнал += float(r["cashless"] or 0)
        итог[имя] = (нал, безнал)
    return итог


def эквайринг(месяц):
    """Комиссия, удержанная банком прямо из зачисления, по юрлицам.

    В выписке её нет отдельной строкой — она спрятана в тексте зачисления
    («Комиссия 571.31»), поэтому вычитается из суммы платежа и в расход
    попадает только так.
    """
    итог = defaultdict(float)
    for r in строки_банка(месяц):
        if r["direction"] != "in" or "эквайринг" not in r["purpose"].lower():
            continue
        # Регулярка взята из fin_articles.acquiring: в назначении встречается
        # и «Комиссия 144.27.» с точкой-концом предложения, и несколько
        # комиссий в одной строке.
        for м in re.finditer(r"Комиссия\s+([\d\s ]+[.,]\d+|[\d\s ]+)", r["purpose"]):
            число = м.group(1).replace(" ", "").replace(" ", "").replace(",", ".")
            итог[r["entity"]] += float(число)
    return итог


def это_возврат_гостю(r) -> bool:
    """Банк удержал со счёта возвраты, сделанные гостям по эквайрингу.

    ⚠️ В расход это НЕ идёт — гостю вернули его же деньги, то есть выручка
    уменьшилась. Проверено на мае: единственная такая строка, 3 250 ₽,
    и ровно на неё мой первый расчёт расходился с листом владельца.
    """
    п = r["purpose"].lower()
    return "завершение расчетов с тст" in п and "возврат покупки" in п


def это_возврат_покупки(r) -> bool:
    """Магазин вернул деньги на бизнес-карту.

    ⚠️ В доход это НЕ идёт: в выверенных листах карта показана «нетто»,
    уже за вычетом возвратов. Проверено на июне — там 191 + 1 + 3 728
    + 2 764 + 1 = 6 685 ₽, и ровно на эту сумму мой первый расчёт
    расходился с листом владельца.
    """
    п = r["purpose"].lower()
    return "возврат покупки" in п or "отмена покупки" in п


def прочий_доход(месяц):
    """Всё, что пришло не от гостей: проценты, бонусы, возмещения.

    Правило снято с трёх выверенных листов: майский состоял из одних бонусов
    банка, июльский — из процентов и бонусов, июньский включал ещё
    возмещение за коммунальные услуги от соседа по зданию (314 608,93 ₽).
    Поэтому берём ВСЕ внешние поступления, кроме выручки эквайринга
    и возвратов по карте, и добавляем проценты на остаток — они приходят
    на депозит и потому помечены как перевод между своими счетами.
    """
    сумма = 0.0
    состав = []
    for r in строки_банка(месяц):
        if r["direction"] != "in":
            continue
        п = r["purpose"].lower()
        if "эквайринг" in п or это_возврат_покупки(r):
            continue
        # ⚠️ Пополнение счёта ИП самим предпринимателем — его же деньги,
        # не доход: зеркало правила «вывод собственнику не расход». 22.10.2026
        # в сентябрь так попали 495 000 ₽ — Хисамов докинул на налог.
        if "пополнение расчетного счета ип владельцем" in п:
            continue
        если_наше = r["class"] == "external" or "процент" in п
        if если_наше:
            сумма += float(r["amount"])
            состав.append(f"{r['purpose'][:45]} — {float(r['amount']):,.2f}")
    return сумма, состав


def наличные(месяц):
    """Расходы наличными из таблицы выручки, по столбцам."""
    итог = defaultdict(float)
    статья_столбца = {}
    for r in csv.DictReader(open(DDS / "cash_expenses.csv", encoding="utf-8")):
        if r["date"].startswith(месяц):
            итог[r["column"]] += float(r["amount"])
            статья_столбца[r["column"]] = r["category"]
    return итог, статья_столбца


def платежи_юрлица(месяц, юрлицо):
    """Внешние платежи со счёта, сгруппированные как в своде: контрагент + скобки."""
    итог = defaultdict(float)
    статьи = {}
    for r in строки_банка(месяц):
        if (r["entity"] != юрлицо or r["direction"] != "out"
                or r["class"] != "external" or это_карта(r)
                or это_возврат_гостю(r)):
            continue
        имя = имя_строки(r)
        статья = статья_строки(r)
        # Ключ группировки включает статью: без неё зарплата по реестрам
        # и комиссии банка слипались в одну строку «ПАО Сбербанк» — суммы
        # разных статей под одним именем, и статья у неё выходила наугад.
        итог[(имя, статья)] += float(r["amount"])
        статьи[(имя, статья)] = статья
    return {и: с for и, с in итог.items()}, статьи


def имя_строки(r) -> str:
    """Как назвать платёж в своде.

    Банк — контрагент особый: под именем «ПАО Сбербанк» приходят и зарплатные
    реестры, и абонентская плата, и мелкие комиссии. В выверенных листах они
    стоят отдельными строками с говорящими именами, так и делаем.
    """
    п = r["purpose"]
    низ = п.lower()
    контрагент = (r["counterparty"] or "—").strip()
    if "сбербанк" in контрагент.lower() or "сбербанк" in низ[:30]:
        if "megafon" in низ:
            return "Связь (МегаФон) (по карте ИП)"
        if "заработная плата по реестру" in низ:
            return "Зарплата Сбер"
        if "сберБизнес прайм" in п or "сбербизнес прайм" in низ:
            return "Обслуживание счёта (СберБизнес Прайм)"
        if "комиссия" in низ or "плата за" in низ:
            return "Прочие комиссии банка"
    # brackets() возвращает СПИСОК подсказок — склеиваем в строку,
    # иначе в свод попадёт питоновский список прямо в имени контрагента.
    скобки = ", ".join(brackets(п))
    return f"{контрагент} ({скобки})" if скобки else контрагент


НЕ_ОПОЗНАНО = "⚠️ не опознано"


def статья_строки(r) -> str:
    """Статья расхода — считает её `fin_articles`, та же, что уходит в бэк-офис.

    ⚠️ Неопознанное НЕ приписываем к «Прочим расходам». Так было в первой
    редакции, и 11.09.2026 это чуть не спрятало настоящую ошибку: четыре
    платежа по ИП Шалаевой с назначением «Для зачисления на счет … Заработная
    плата» (76 752,64 ₽) разметка не опознаёт, и свод тихо сложил их
    в «Прочие расходы». В ДДС их нет вовсе, и расхождение выглядело бы
    недостачей неизвестно чего. Пусть лучше в своде стоит заметная строка.
    """
    статья, _откуда = article(r, словарь())
    return статья or НЕ_ОПОЗНАНО


def карта_месяца(месяц):
    """Покупки по бизнес-карте ООО за вычетом возвратов, по торговым точкам."""
    итог = defaultdict(float)
    статьи = {}
    for r in строки_банка(месяц):
        if r["class"] != "external" or not это_карта(r):
            continue
        имя, статья = имя_по_карте(r["purpose"])
        if r["direction"] == "out":
            итог[имя] += float(r["amount"])
            статьи[имя] = статья
        elif это_возврат_покупки(r):
            итог[имя] -= float(r["amount"])
            статьи.setdefault(имя, статья)
    return {и: с for и, с in итог.items() if abs(с) > 0.001}, статьи


def main():
    аргументы = sys.argv[1:]
    проверка = "--проверка" in аргументы
    месяцы = [a for a in аргументы if re.fullmatch(r"\d{4}-\d{2}", a)]
    if not месяцы:
        сегодня = date.today()
        год, мес = (сегодня.year, сегодня.month - 1) if сегодня.month > 1 else (сегодня.year - 1, 12)
        месяцы = [f"{год}-{мес:02d}"]

    for месяц in месяцы:
        собрать(месяц, проверка)


def собрать(месяц, только_проверка):
    год, номер = месяц.split("-")
    название = f"{МЕСЯЦЫ[int(номер) - 1]} {год}"

    в = выручка(месяц)
    экв = эквайринг(месяц)
    другое, состав_другого = прочий_доход(месяц)

    # Порядок строк дохода как на июльском листе: сперва обе наличные,
    # потом обе безналичные, внутри — ООО впереди ИП.
    доход = []
    for юр, (нал, _) in в.items():
        if нал:
            доход.append((f"{юр} нал", нал, f"Наличная выручка кассы {юр} Quick Resto за месяц."))
    for юр, (_, безнал) in в.items():
        if безнал:
            доход.append((f"{юр} безнал", безнал, f"Безналичная выручка кассы {юр} Quick Resto за месяц."))
    # ⚠️ Ноль здесь — не факт, а пустая строка: скрипт этих поступлений
    # не считает, данных о них в разборе нет вовсе (в июне 2026 владелец
    # вписала сюда 3 900 ₽ руками). Поэтому и комментарий говорит «проверьте»,
    # а не «не было»: прежняя формулировка утверждала то, чего никто не
    # проверял, и в первый же месяц с реализацией лист соврал бы уверенно.
    доход.append(("Прочее нал", 0.0,
                  "Скрипт это не считает — проверьте по таблице выручки "
                  "и впишите руками, если за месяц продавали имущество. "
                  "Август 2026 подтверждён владельцем: не было."))
    доход.append(("Другое (проценты на остаток счёта, операции не по основной деятельности)",
                  другое, "Проценты на остаток, бонусы банка, возвраты покупок по карте. "
                          + "; ".join(состав_другого[:3])))
    итого_доход = sum(с for _, с, _ in доход)

    блоки = []
    for юрлицо, заголовок, пояснение in ЮРЛИЦА:
        суммы, _статьи = платежи_юрлица(месяц, юрлицо)
        строки = [(статья, имя, сумма) for (имя, статья), сумма in суммы.items()]
        строки.sort(key=lambda x: -x[2])
        if экв.get(юрлицо):
            строки.append(("Комиссия", "Комиссия банка за эквайринг (чистая)", экв[юрлицо]))
        if строки:
            блоки.append((заголовок, пояснение, строки, f"Итого {заголовок}:"))
        if юрлицо == "mav":
            суммы_к, статьи_к = карта_месяца(месяц)
            строки_к = sorted(((статьи_к[и], и, с) for и, с in суммы_к.items()), key=lambda x: -x[2])
            if строки_к:
                блоки.append(("Списания с бизнес-карты ООО",
                              "Покупки по бизнес-карте ООО «МАВ».", строки_к, "Итого по карте:"))

    нал_суммы, нал_статьи = наличные(месяц)
    строки_нал = []
    вывод_нал = 0.0
    for столбец, сумма in sorted(нал_суммы.items(), key=lambda x: -x[1]):
        статья = нал_статьи[столбец]
        if статья == ВЫВОД:
            вывод_нал += сумма
            continue
        строки_нал.append((статья, столбец, сумма))

    итого_безнал = sum(с for _, _, строки, _ in блоки for _, _, с in строки)
    итого_нал = sum(с for _, _, с in строки_нал)
    итого_расход = итого_безнал + итого_нал
    прибыль = итого_доход - итого_расход

    структура = defaultdict(float)
    for _, _, строки, _ in блоки:
        for статья, _, сумма in строки:
            структура[статья or "Прочие расходы"] += сумма
    for статья, _, сумма in строки_нал:
        структура[статья] += сумма

    print(f"=== {название}")
    print(f"   доход        {итого_доход:>15,.2f}")
    print(f"   безнал       {итого_безнал:>15,.2f}")
    print(f"   наличные     {итого_нал:>15,.2f}")
    print(f"   ИТОГО расход {итого_расход:>15,.2f}")
    print(f"   прибыль      {прибыль:>15,.2f}   рентабельность продаж {прибыль / итого_доход:.1%}")
    if вывод_нал:
        print(f"   вывод собственнику наличными {вывод_нал:,.2f} — в расход не включён")
    сумма_структуры = sum(структура.values())
    сходится = abs(сумма_структуры - итого_расход) < 0.01
    print(f"   структура расходов {сумма_структуры:,.2f} — "
          + ("сходится с расходом" if сходится else "⚠️ НЕ СХОДИТСЯ"))

    if только_проверка:
        сверить(название, итого_доход, итого_безнал, итого_нал, итого_расход, прибыль)
        return

    записать(название, доход, итого_доход, блоки, строки_нал, итого_нал,
             итого_безнал, итого_расход, прибыль, структура, вывод_нал, месяц)


def сверить(название, доход, безнал, нал, расход, прибыль):
    """Сравнивает расчёт с готовым листом — так проверена сама методика."""
    файл = образец()
    if not файл.exists():
        print("   сверять не с чем: нет файла свода")
        return
    книга = openpyxl.load_workbook(файл, data_only=True)
    if название not in книга.sheetnames:
        print(f"   в своде нет листа «{название}»")
        return
    лист = книга[название]
    эталон = {}
    for строка in лист.iter_rows(values_only=True):
        ключ = строка[0]
        if isinstance(ключ, str) and isinstance(строка[2], (int, float)):
            эталон[ключ.strip()] = float(строка[2])
    пары = (("Итого доход:", доход), ("ИТОГО БЕЗНАЛ:", безнал),
            ("Итого нал:", нал), ("ИТОГО РАСХОД:", расход),
            ("ЧИСТАЯ ПРИБЫЛЬ:", прибыль))
    print("   сверка с листом владельца:")
    for имя, наше in пары:
        если_есть = эталон.get(имя)
        if если_есть is None:
            print(f"      {имя:20} в листе нет")
            continue
        разница = наше - если_есть
        знак = "✓" if abs(разница) < 0.01 else f"⚠️ расходится на {разница:,.2f}"
        print(f"      {имя:20} наше {наше:>15,.2f}   лист {если_есть:>15,.2f}   {знак}")


def записать(название, доход, итого_доход, блоки, строки_нал, итого_нал,
             итого_безнал, итого_расход, прибыль, структура, вывод_нал, месяц):
    источник = образец()
    имя_месяца = название.split()[0].lower()
    цель = СВОДЫ / f"Фин-свод-май-{имя_месяца}-2026.xlsx"
    if not цель.exists():
        shutil.copy(источник, цель)
    книга = openpyxl.load_workbook(цель)
    if название in книга.sheetnames:
        # ⚠️ Лист уже есть — значит его, возможно, правили руками. Перед тем
        # как затереть, кладём копию файла в «Резервные копии»: правка
        # владельца ценнее любой пересборки, а пропажу её никто не заметит.
        копии = ROOT / "Резервные копии"
        копии.mkdir(exist_ok=True)
        отметка = date.today().isoformat()
        копия = копии / f"{цель.stem} — до пересборки {название} {отметка}.xlsx"
        if not копия.exists():
            shutil.copy(цель, копия)
            print(f"   прежняя версия сохранена: {копия.name}")
        del книга[название]
    лист = книга.create_sheet(название)

    жирный = Font(bold=True)
    формат = "#,##0.00"

    def клетка(строка, колонка, значение, полужирно=False, число=False):
        # Копейки округляем при записи: сложение дробей даёт хвосты вида
        # 4 168 970.609999999, и в ячейке это выглядит как ошибка счёта.
        if isinstance(значение, float):
            значение = round(значение, 2)
        к = лист.cell(row=строка, column=колонка, value=значение)
        if полужирно:
            к.font = жирный
        if число:
            к.number_format = формат
        return к

    н = 1
    клетка(н, 1, f"ФИН. СВОД — {название}", полужирно=True)
    клетка(н, 5, "КОММЕНТАРИЙ: откуда взята сумма", полужирно=True)
    н += 1
    клетка(н, 1, "Только фактические суммы месяца: что реально пришло и ушло.")
    н += 1
    клетка(н, 1, "Слева от контрагента — статья, в которую сумма попадает в структуре расходов.")
    н += 2
    клетка(н, 1, "ДОХОД", полужирно=True)
    строка_структуры = н + 1
    for имя, сумма, комментарий in доход:
        н += 1
        клетка(н, 2, имя)
        клетка(н, 3, сумма, число=True)
        клетка(н, 5, комментарий)
    н += 1
    клетка(н, 1, "Итого доход:", полужирно=True)
    клетка(н, 3, итого_доход, полужирно=True, число=True)
    клетка(н, 5, "Сумма строк выше.")

    # Структура расходов — справа, в порядке ARTICLES, как на прежних листах.
    клетка(строка_структуры, 7, "СТРУКТУРА РАСХОДОВ", полужирно=True)
    ряд = строка_структуры
    for статья in ARTICLES:
        if статья == ВЫВОД:
            continue
        ряд += 1
        клетка(ряд, 7, статья)
        клетка(ряд, 8, структура.get(статья, 0.0), число=True)
    for статья in sorted(структура):
        if статья not in ARTICLES:
            ряд += 1
            клетка(ряд, 7, статья)
            клетка(ряд, 8, структура[статья], число=True)
            клетка(ряд, 9, "статьи нет в списке порядка")
    ряд += 1
    клетка(ряд, 7, "ИТОГО по статьям", полужирно=True)
    клетка(ряд, 8, sum(структура.values()), полужирно=True, число=True)

    н += 2
    клетка(н, 1, "РАСХОД", полужирно=True)
    for заголовок, пояснение, строки, подпись in блоки:
        н += 1
        клетка(н, 1, заголовок, полужирно=True)
        клетка(н, 5, пояснение)
        сумма_блока = 0.0
        for статья, имя, сумма in строки:
            н += 1
            клетка(н, 1, статья)
            клетка(н, 2, имя)
            клетка(н, 3, сумма, число=True)
            сумма_блока += сумма
        н += 1
        клетка(н, 1, подпись, полужирно=True)
        клетка(н, 3, сумма_блока, полужирно=True, число=True)
        н += 1

    клетка(н, 1, "ИТОГО БЕЗНАЛ:", полужирно=True)
    клетка(н, 3, итого_безнал, полужирно=True, число=True)
    клетка(н, 5, "Сумма всех безналичных блоков выше.")
    н += 2

    клетка(н, 1, "Наличные", полужирно=True)
    клетка(н, 5, "Столбцы таблицы «Выручка Невский 2026» за месяц.")
    for статья, имя, сумма in строки_нал:
        н += 1
        клетка(н, 1, статья)
        клетка(н, 2, имя)
        клетка(н, 3, сумма, число=True)
    н += 1
    клетка(н, 1, "Итого нал:", полужирно=True)
    клетка(н, 3, итого_нал, полужирно=True, число=True)

    н += 2
    клетка(н, 1, "ИТОГО РАСХОД:", полужирно=True)
    клетка(н, 3, итого_расход, полужирно=True, число=True)
    н += 1
    клетка(н, 1, "ЧИСТАЯ ПРИБЫЛЬ:", полужирно=True)
    клетка(н, 3, прибыль, полужирно=True, число=True)
    клетка(н, 5, "Доход минус расход.")
    н += 1
    клетка(н, 1, "Рентабельность продаж (прибыль ÷ выручка)")
    клетка(н, 3, прибыль / итого_доход if итого_доход else 0)
    клетка(н, 5, "Сколько прибыли в каждом рубле выручки.")
    н += 1
    клетка(н, 1, "Рентабельность затрат (прибыль ÷ расход)")
    клетка(н, 3, прибыль / итого_расход if итого_расход else 0)

    if вывод_нал:
        н += 2
        клетка(н, 1, f"Вывод собственнику за месяц: {вывод_нал:,.0f} ₽ — "
                     "в расход не включён, как и на прежних листах.", полужирно=True)

    лист.column_dimensions["A"].width = 28
    лист.column_dimensions["B"].width = 46
    лист.column_dimensions["C"].width = 16
    лист.column_dimensions["E"].width = 60
    лист.column_dimensions["G"].width = 26
    лист.column_dimensions["H"].width = 15
    for ряд_клеток in лист.iter_rows(min_col=5, max_col=5):
        for к in ряд_клеток:
            к.alignment = Alignment(wrap_text=False, vertical="top")

    книга.save(цель)
    print(f"   записано: {цель.name}, лист «{название}»")


