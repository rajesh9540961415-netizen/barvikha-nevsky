def месяцы_бара() -> list[str]:
    """С июля 2026 по текущий: касса бара открылась 07.07.2026."""
    из_ = date(2026, 7, 1)
    сегодня = date.today()
    вых = []
    while из_ <= сегодня:
        вых.append(из_.strftime("%Y-%m"))
        из_ = date(из_.year + (из_.month == 12), из_.month % 12 + 1, 1)
    return вых


def чеки_бара() -> list[dict]:
    """Чеки кассы ИП Шалаевой: ПО КЛЮЧУ, а ручные выгрузки — в дополнение.

    С 23.08.2026 основной источник — API (`чеки_бара_ключом`). Ручные выгрузки
    `чеки-Шалаева-*.csv` остались и продолжают читаться: в них история
    с 1 августа, снятая до того, как пришёл ключ, и выбрасывать её нельзя,
    пока не убедимся, что API отдаёт то же самое за те же дни.

    ⚠️ Файл НЕ ПЕРЕБИВАЕТ ключ: если чек есть в обоих, берём версию из API.
    У неё состав позиций приходит полем, а не собирается из строк выгрузки.

    Читает ВСЕ файлы `чеки-Шалаева-*.csv` в data/ofd/ и складывает: выгрузки
    приходят кусками по мере того, как их берут руками, и периоды перекрываются.
    Повторы отсеиваются по номеру документа.

    ⚠️ Формат выгрузки — строка на ПОЗИЦИЮ, а не на чек: один чек размазан
    по нескольким строкам, и собирать его надо по колонке «Номер чека».

    ⚠️ Суммы возвратов в выгрузке отрицательные, а в данных API — нет.
    Приводим к API: разбору важен состав, а знак он берёт из вида документа.
    """
    из_файлов = {}
    for файл in sorted(КЭШ.glob("чеки-Шалаева-*.csv")):
        with файл.open(encoding="utf-8-sig", newline="") as f:
            строки = csv.reader(f, delimiter="\t")
            next(строки, None)                      # заголовок отчёта
            шапка = next(строки, None)
            if not шапка:
                continue
            К = {имя: i for i, имя in enumerate(шапка)}

            def поле(r, имя, по_умолчанию=""):
                i = К.get(имя)
                return r[i] if i is not None and i < len(r) else по_умолчанию

            for r in строки:
                ключ = поле(r, "Номер чека")
                if not ключ:
                    continue
                вид = ВИДЫ.get(поле(r, "Тип документа. Признак расчета (1054)").strip())
                if not вид:
                    continue
                ч = из_файлов.get(ключ)
                if ч is None:
                    нал = abs(число(поле(r, "Сумма по чеку (БСО) наличными (1031)")))
                    безнал = abs(число(поле(r, "Сумма по чеку (БСО) безналичными (1081)")))
                    ч = из_файлов[ключ] = {
                        "номер": int(число(ключ.rsplit("_", 1)[-1])),
                        "фпд": поле(r, "ФПД (1077)"),
                        "время": поле(r, "Дата, время (1012)")[:19],
                        "вид": вид, "нал": нал, "безнал": безнал,
                        "сумма": round(нал + безнал, 2),
                        "смена": int(число(поле(r, "Номер смены (1038)"))),
                        "кассир": поле(r, "Кассир (1021)"),
                        "позиции": [],
                    }
                ч["позиции"].append([
                    поле(r, "Наименование предмета расчета (1030)"),
                    abs(число(поле(r, "Количество предмета расчета (1023)"))),
                    abs(число(поле(r, "Стоимость предмета расчета с учетом скидок и наценок (1043)"))),
                ])
    итог = {}
    try:
        for ч in чеки_бара_ключом(месяцы_бара()):
            итог[str(ч["номер"])] = ч
    except SystemExit as e:
        # Ключа нет или ОФД не ответил — работаем на одних выгрузках, но вслух.
        if not ТИХО:
            print(f"  ⚠️  чеки бара по ключу не пришли ({e}) — только ручные выгрузки")

    из_ключа = len(итог)
    только_из_файлов = 0
    for ч in из_файлов.values():
        н = str(ч["номер"])
        if н not in итог:
            итог[н] = ч
            только_из_файлов += 1
    if not ТИХО and из_ключа:
        print(f"  чеки бара: по ключу {из_ключа}, только из ручных выгрузок "
              f"{только_из_файлов}")
    return sorted(итог.values(), key=lambda ч: ч["время"])


def число(s: str) -> float:
    s = (s or "0").replace("\xa0", "").replace(" ", "").replace(",", ".")
    try:
        return float(s)
    except ValueError:
        return 0.0


