def набор(чек) -> Counter:
    """Позиции чека как «блюдо → количество» — для поиска исходного чека."""
    с = Counter()
    for поз in чек["позиции"]:
        с[поз[0]] += поз[1]
    return с


def разобрать(чеки: list[dict], окно_минут: int):
    """Для каждого возврата ищем перебивку ПО БЛЮДАМ, а не по сумме.

    ⚠️ Почему по блюдам. Дробление счёта — идеальное прикрытие: погашенный
    чек перебивают тремя мелкими, и совпадения суммы нет ни с одним. Поиск
    по сумме такой случай считает дырой. Разница огромна: на августе
    2026 по суммам выходит 46 счетов и 370 077 ₽, по блюдам — единицы.

    Считаем НЕ ВЕРНУВШУЮСЯ СТОИМОСТЬ, а не «счёт целиком»: если из погашенного
    счёта перебили две позиции из трёх, дырой является третья, а не весь счёт.

    Порядок для каждого возврата:
      1. Списать исходный чек — тот же набор позиций, ближайший раньше.
      2. Собрать пул позиций из приходов в окне ±N минут.
      3. Жадно закрыть блюда возврата из этого пула, вычёркивая взятое,
         чтобы одна порция не досталась двум возвратам.
      4. Что не закрылось — то и не вернулось, по цене из чека.
    """
    приходы = [ч for ч in чеки if ч["вид"] == ПРИХОД]
    возвраты = [ч for ч in чеки if ч["вид"] == ВОЗВРАТ_ПРИХОДА]
    # ⚠️ Порядок — по НОМЕРУ фискального документа, не по времени. Время в ОФД
    # с точностью до минуты, и в одной минуте свободно лежат четыре чека.
    приходы.sort(key=lambda ч: int(ч["номер"]))
    номера = [int(ч["номер"]) for ч in приходы]
    времена = [datetime.fromisoformat(ч["время"]) for ч in приходы]

    # Свободные порции каждого прихода: блюдо → сколько ещё можно взять.
    свободно = [набор(ч) for ч in приходы]
    списан = [False] * len(приходы)
    окно = timedelta(minutes=окно_минут)
    неперебитые = []

    for в in sorted(возвраты, key=lambda ч: int(ч["номер"])):
        t = datetime.fromisoformat(в["время"])
        н = int(в["номер"])
        мой = набор(в)

        # 1. Исходный чек — тот же набор, ближайший раньше ПО НОМЕРУ. Списываем.
        #
        # ⚠️ Здесь стояло `времена[i] > t`, и это давало ложные дыры. Пример,
        # 17.08.2026, четыре чека в одной минуте 19:27:
        #
        #     19:25  №3664  ПРИХОД   Кальян на Ананасе PERFUME
        #     19:27  №3665  ВОЗВРАТ  Кальян на Ананасе PERFUME
        #     19:27  №3666  ПРИХОД   Кальян на Ананасе PERFUME
        #     19:27  №3667  ВОЗВРАТ  Кальян на Ананасе PERFUME
        #     19:27  №3668  ПРИХОД   Кальян на Ананасе PERFUME
        #
        # Три прихода против двух возвратов — терять нечего. Но перебор идёт
        # с конца, и по времени «не позже 19:27» первым подходил №3668, то есть
        # сама перебивка. Она списывалась как исходник, настоящей перебивки
        # не оставалось, и возврат объявлялся дырой.
        #
        # 💡 Номер документа — строгая последовательность без ничьих: №3668
        # физически не мог быть раньше №3665. Правка убрала 46 ложных счетов
        # из 196 за 2026 год (988 653 ₽ → 751 984 ₽).
        for i in range(len(приходы) - 1, -1, -1):
            if списан[i] or номера[i] > н:
                continue
            if набор(приходы[i]) == мой:
                списан[i] = True
                свободно[i] = Counter()
                break

        # 2–3. Жадно закрываем блюда из окна.
        осталось = Counter(мой)
        for i, ч in enumerate(приходы):
            if списан[i] or not осталось:
                continue
            if abs(времена[i] - t) > окно:
                continue
            общие = осталось & свободно[i]
            if not общие:
                continue
            осталось -= общие
            свободно[i] -= общие

        # 4. Что не закрылось — по цене из самого возврата.
        if осталось:
            цены = {}
            for p in в["позиции"]:
                имя, кол, сум = p[0], p[1], (p[2] if len(p) > 2 else 0)
                if кол:
                    цены[имя] = сум / кол
            не_вернулось = round(
                sum(цены.get(и, 0) * к for и, к in осталось.items()), 2)
            if не_вернулось > 0:
                копия = dict(в)
                копия["не_вернулось"] = не_вернулось
                копия["чего_не_нашли"] = [[и, к] for и, к in осталось.items()]
                неперебитые.append(копия)

    return возвраты, неперебитые


def деньги(v) -> str:
    return f"{v:,.0f}".replace(",", " ")


def за_день(день: date, окно: int = 60, заново: bool = False) -> dict:
    """Кассовая дисциплина за ОДИН торговый день, по обеим кассам.

    Отдаёт словарь: касса → {возвратов, сумма_возвратов, неперебитые, есть_данные}.
    Для утренней сводки: короткий блок, который видно с телефона.

    ⚠️ Разбор идёт по ВСЕМУ месяцу, а фильтр по дню накладывается на РЕЗУЛЬТАТ.
    Считать «день в отрыве» нельзя: сутки заведения кончаются в 10:59, и
    перебивка ночного гашения запросто ложится на календарно другую дату.

    ⚠️ Отсутствие данных и отсутствие нарушений — РАЗНЫЕ вещи, и различать их
    обязан вызывающий: у бара выгрузка ручная, и за вчера её может не быть
    вовсе. Молчаливый ноль в такой день соврал бы в самую спокойную сторону.
    """
    global ТИХО
    ТИХО, был = True, ТИХО
    месяц = день.strftime("%Y-%m")
    итог = {}
    for касса, о in КАССЫ.items():
        # Месяц тянем ОДИН раз: и на фильтр по дню, и на разбор. Первая
        # редакция звала источник дважды — лишний поход в API на каждый вызов.
        все = (чеки_за([месяц], заново) if о["источник"] == "api" else чеки_бара())
        чеки = [ч for ч in все if торговый_день(datetime.fromisoformat(ч["время"])) == день]
        # Разбор ведём по всему месяцу, иначе перебивка за границей дня потеряется.
        _, неперебитые = разобрать(все, окно)
        неперебитые = [ч for ч in неперебитые
                       if торговый_день(datetime.fromisoformat(ч["время"])) == день]
        возвраты = [ч for ч in чеки if ч["вид"] == ВОЗВРАТ_ПРИХОДА]
        итог[касса] = {
            "титул": о["титул"],
            "есть_данные": bool(чеки),
            "возвратов": len(возвраты),
            "сумма_возвратов": round(sum(ч["сумма"] for ч in возвраты), 2),
            "неперебитые": неперебитые,
            "не_вернулось": round(sum(ч["не_вернулось"] for ч in неперебитые), 2),
        }
    ТИХО = был
    return итог


def блок_за_день(день: date, окно: int = 60) -> list[str]:
    """Тот же расчёт, но готовыми строками — для утренней сводки и телеграма."""
    итог = за_день(день, окно)
    строки = [f"КАССОВАЯ ДИСЦИПЛИНА за {день.strftime('%d.%m')}"]
    всего = 0.0
    for касса, д in итог.items():
        if not д["есть_данные"]:
            строки.append(f"   {касса:<4} ⚠️  данных нет — выгрузка ОФД по этой кассе "
                          f"не загружена, а не «нарушений ноль»")
            continue
        хвост = ("всё пробито заново" if not д["неперебитые"]
                 else f"🔴 НЕ ПРОБИТО ЗАНОВО {len(д['неперебитые'])} на {деньги(д['не_вернулось'])} ₽")
        строки.append(f"   {касса:<4} возвратов {д['возвратов']:>3} "
                      f"на {деньги(д['сумма_возвратов']):>9} ₽   {хвост}")
        всего += д["не_вернулось"]
        for ч in sorted(д["неперебитые"], key=lambda x: x["время"]):
            что = "; ".join(f"{и} ×{к:g}" for и, к in ч["чего_не_нашли"])
            строки.append(f"        {ч['время'][11:16]}  {деньги(ч['не_вернулось']):>7} ₽  {что[:52]}")
    if всего == 0 and all(д["есть_данные"] for д in итог.values()):
        строки.append("   ✅ всё погашенное пробито заново")
    return строки


