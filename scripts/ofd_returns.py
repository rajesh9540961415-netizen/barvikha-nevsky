"""Возвраты без перебивки — по данным API Первого ОФД.

Погашенный счёт, который не пробили заново, — единственный канал, где разбор
16.08.2026 нашёл настоящую дыру. Раньше это считалось по выгрузке, скачанной
руками, и скрипты не сохранились. Теперь данные берутся из API, и счёт можно
повторить в любой день одной командой.

⚠️ МЕТОД. Списан с plans/2026-08-16-analiz-froda.md, раздел «Как повторить
расчёт», вместе с четырьмя ошибками первого захода — они стоили разницы
между «5,5 млн не вернулось» и «1,44 млн»:

  1. Окно ищется СИММЕТРИЧНО, вперёд и назад. Перебивают часто наоборот:
     сначала пробивают правильный чек, потом гасят ошибочный.
  2. Границы окна НЕСТРОГИЕ: время в ОФД с точностью до минуты, а медиана
     перебивки — одна минута. Строгое «позже возврата» выбрасывало почти всё.
  3. Исходный чек сначала находится и СПИСЫВАЕТСЯ. Иначе возврат находит
     сам себя, и всё «сходится» на 100 % бессмысленно.
  4. Один чек не может закрыть два возврата: найденное убирается из пула.

⚠️ ШИРИНА ОКНА — не мелочь, а сам ответ. Владелец 21.08.2026: норма — ЧАС.
При ±30 минутах выходило 1 444 575 ₽, при ±60 — 896 254 ₽.

Запуск:
    python3 scripts/ofd_returns.py                    весь 2026 год
    python3 scripts/ofd_returns.py 2026-08            один месяц
    python3 scripts/ofd_returns.py --окно 30          другая ширина окна
    python3 scripts/ofd_returns.py --заново           не брать из кэша

Кэш — data/ofd/чеки-YYYY-MM.json: API отдаёт максимум 30 дней за запрос,
а месяцы прошлого не меняются. Ключ нигде не печатается.
"""

from __future__ import annotations

import json
import sys
import urllib.parse
from collections import Counter, defaultdict
from datetime import date, datetime, timedelta
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from ofd_check import (  # noqa: E402
    FS_CURRENT, FS_PREVIOUS, KKM_REG_ID, запрос, читать_ключ,
)

ROOT = Path(__file__).resolve().parent.parent
КЭШ = ROOT / "data" / "ofd"
ОРГ = "9729385147.772901001"

ПРИХОД, ВОЗВРАТ_ПРИХОДА = 1, 2
# Сутки заведения идут с 11:00 до 10:59 следующего дня — так их считает
# и приложение смены (BUSINESS_DAY_START_HOUR в mini-app/src/lib/businessDay.ts).
#
# ⚠️ Здесь стояло 6 утра, и это была отсебятина: заведение работает за полночь,
# смена открывается в одиннадцать, и чек в три часа ночи принадлежит вчерашнему
# вечеру. Владелец 22.08.2026: «смена открывается в 11 утра, соответственно
# сутки нужно правильно закончить — в 10:59».
#
# 💡 За 2026 год между шестью и одиннадцатью утра всего 13 чеков из 24 тысяч,
# то есть на сегодняшний счёт разница почти не влияет. Но две части проекта
# не должны датировать один вечер по-разному: однажды это сойдётся в отчёте,
# и разбираться будут долго.
СМЕНА_НАЧИНАЕТСЯ = 11


def торговый_день(момент: datetime) -> date:
    return (момент - timedelta(hours=СМЕНА_НАЧИНАЕТСЯ)).date()


def скачать_месяц(месяц: str, токен: str) -> list[dict]:
    """Чеки одного месяца: из кэша или из API.

    Накопителей два — текущий и прежний. Спрашиваем оба и складываем:
    в месяце замены часть чеков лежит под одним номером, часть под другим,
    и запрос по одному молча потерял бы половину месяца.
    """
    год, м = map(int, месяц.split("-"))
    начало = date(год, м, 1)
    конец = date(год + (м == 12), м % 12 + 1, 1)
    чеки = []
    # ⚠️ API не пускает промежуток больше 30 суток, а месяц с хвостом
    # до утра следующего дня в него не влезает: 31 день + 6 часов, и в ответ
    # прилетает «error.invalid.period». Поэтому режем пополам.
    отрезки = [(начало, начало + timedelta(days=15)),
               (начало + timedelta(days=15), конец + timedelta(hours=0))]
    for накопитель in (FS_CURRENT, FS_PREVIOUS):
      for от, до in отрезки:
        params = urllib.parse.urlencode({
            "kkmRegId": KKM_REG_ID,
            "fsFactoryNumber": накопитель,
            "fromDate": f"{от}T00:00:00",
            "toDate": f"{до}T{СМЕНА_НАЧИНАЕТСЯ:02d}:00:00",
        })
        ответ = запрос(
            f"/api/rent/v2/organisations/{urllib.parse.quote(ОРГ)}/documents?{params}",
            токен)
        # ⚠️ Документы лежат в «documents», а не в «page», как у прочих
        # методов этого же API. Перепутать — получить молчаливый ноль.
        for d in ответ.get("documents") or []:
            if not (d.get("transactionType") or "").startswith("Кассовый"):
                continue
            t = d.get("ticket") or {}
            чеки.append({
                "номер": d.get("fiscalDocumentNumber"),
                "фпд": d.get("fiscalSign"),
                "время": d.get("transactionDate")[:19],
                "вид": t.get("operationType"),
                "сумма": round(float(t.get("totalSum") or 0), 2),
                "нал": round(float(t.get("cashTotalSum") or 0), 2),
                "безнал": round(float(t.get("ecashTotalSum") or 0), 2),
                "смена": d.get("shiftNum"),
                "кассир": (t.get("operator") or {}).get("operatorName") or "",
                # Позиция везёт и сумму: незакрытое надо оценить по цене
                # из самого чека, а не по средней.
                "позиции": [[p.get("name", ""), float(p.get("quantity") or 0),
                             float(p.get("sum") or 0)]
                            for p in (t.get("items") or [])],
            })
    # Один и тот же чек мог приехать дважды — ключ фискального документа.
    по_номеру = {(ч["номер"], ч["время"]): ч for ч in чеки}
    return sorted(по_номеру.values(), key=lambda ч: ч["время"])


def чеки_за(месяцы: list[str], заново: bool) -> list[dict]:
    КЭШ.mkdir(parents=True, exist_ok=True)
    токен = None
    всё = []
    for месяц in месяцы:
        файл = КЭШ / f"чеки-{месяц}.json"
        свежий = месяц >= date.today().strftime("%Y-%m")
        if файл.exists() and not заново and not свежий:
            всё += json.loads(файл.read_text(encoding="utf-8"))
            continue
        if токен is None:
            токен = запрос("/api/auth", тело={"apiKey": читать_ключ()})["token"]
        порция = скачать_месяц(месяц, токен)
        файл.write_text(json.dumps(порция, ensure_ascii=False), encoding="utf-8")
        print(f"  {месяц}: скачано чеков {len(порция)}")
        всё += порция
    return всё


def набор(чек) -> Counter:
    """Позиции чека как «блюдо → количество» — для поиска исходного чека."""
    с = Counter()
    for поз in чек["позиции"]:
        с[поз[0]] += поз[1]
    return с


def разобрать(чеки: list[dict], окно_минут: int):
    """Для каждого возврата ищем перебивку ПО БЛЮДАМ, а не по сумме.

    ⚠️ Почему по блюдам. Дробление счёта — идеальное прикрытие: погашенный
    чек перебивают тремя мелкими, и совпадения суммы нет ни с одним. Поиск
    по сумме такой случай считает дырой. Разница огромна: на августе
    2026 по суммам выходит 46 счетов и 370 077 ₽, по блюдам — единицы.

    Считаем НЕ ВЕРНУВШУЮСЯ СТОИМОСТЬ, а не «счёт целиком»: если из погашенного
    счёта перебили две позиции из трёх, дырой является третья, а не весь счёт.

    Порядок для каждого возврата:
      1. Списать исходный чек — тот же набор позиций, ближайший раньше.
      2. Собрать пул позиций из приходов в окне ±N минут.
      3. Жадно закрыть блюда возврата из этого пула, вычёркивая взятое,
         чтобы одна порция не досталась двум возвратам.
      4. Что не закрылось — то и не вернулось, по цене из чека.
    """
    приходы = [ч for ч in чеки if ч["вид"] == ПРИХОД]
    возвраты = [ч for ч in чеки if ч["вид"] == ВОЗВРАТ_ПРИХОДА]
    приходы.sort(key=lambda ч: ч["время"])
    времена = [datetime.fromisoformat(ч["время"]) for ч in приходы]

    # Свободные порции каждого прихода: блюдо → сколько ещё можно взять.
    свободно = [набор(ч) for ч in приходы]
    списан = [False] * len(приходы)
    окно = timedelta(minutes=окно_минут)
    неперебитые = []

    for в in sorted(возвраты, key=lambda ч: ч["время"]):
        t = datetime.fromisoformat(в["время"])
        мой = набор(в)

        # 1. Исходный чек — тот же набор, ближайший раньше. Списываем целиком.
        for i in range(len(приходы) - 1, -1, -1):
            if списан[i] or времена[i] > t:
                continue
            if набор(приходы[i]) == мой:
                списан[i] = True
                свободно[i] = Counter()
                break

        # 2–3. Жадно закрываем блюда из окна.
        осталось = Counter(мой)
        for i, ч in enumerate(приходы):
            if списан[i] or not осталось:
                continue
            if abs(времена[i] - t) > окно:
                continue
            общие = осталось & свободно[i]
            if not общие:
                continue
            осталось -= общие
            свободно[i] -= общие

        # 4. Что не закрылось — по цене из самого возврата.
        if осталось:
            цены = {}
            for p in в["позиции"]:
                имя, кол, сум = p[0], p[1], (p[2] if len(p) > 2 else 0)
                if кол:
                    цены[имя] = сум / кол
            не_вернулось = round(
                sum(цены.get(и, 0) * к for и, к in осталось.items()), 2)
            if не_вернулось > 0:
                копия = dict(в)
                копия["не_вернулось"] = не_вернулось
                копия["чего_не_нашли"] = [[и, к] for и, к in осталось.items()]
                неперебитые.append(копия)

    return возвраты, неперебитые


def деньги(v) -> str:
    return f"{v:,.0f}".replace(",", " ")


def главное():
    args = [a for a in sys.argv[1:]]
    заново = "--заново" in args
    окно = 60
    if "--окно" in args:
        окно = int(args[args.index("--окно") + 1])
        args = args[:args.index("--окно")] + args[args.index("--окно") + 2:]
    месяцы = [a for a in args if len(a) == 7 and a[4] == "-"]
    if not месяцы:
        сегодня = date.today()
        месяцы = [f"2026-{m:02d}" for m in range(1, сегодня.month + 1)]

    print(f"=== ЧЕКИ ({', '.join(месяцы[:3])}{'…' if len(месяцы) > 3 else ''}) ===")
    чеки = чеки_за(месяцы, заново)
    print(f"  всего чеков: {len(чеки)}")

    возвраты, неперебитые = разобрать(чеки, окно)
    # ⚠️ Считаем НЕ ВЕРНУВШУЮСЯ ЧАСТЬ, а не сумму чека целиком. 21.08.2026
    # я сложил здесь «сумму» — и итог вырос с 1,44 млн до 2,43 млн, хотя
    # поштучно всё совпадало с прежним разбором до рубля. Две величины
    # рядом, обе правдоподобные: у счёта на 5 000 ₽ не вернуться могло 800.
    сумма = sum(ч["не_вернулось"] for ч in неперебитые)
    доля = 100 * (len(возвраты) - len(неперебитые)) / len(возвраты) if возвраты else 0

    print(f"\n=== ВОЗВРАТЫ, окно ±{окно} минут ===")
    print(f"  возвратов всего: {len(возвраты)} на {деньги(sum(ч['сумма'] for ч in возвраты))} ₽")
    print(f"  перебито заново: {len(возвраты) - len(неперебитые)} ({доля:.1f} %)")
    целиком = sum(ч["сумма"] for ч in неперебитые)
    print(f"  🔴 НЕ ПЕРЕБИТО:  {len(неперебитые)} счетов, "
          f"не вернулось {деньги(сумма)} ₽")
    print(f"     (сами счета на {деньги(целиком)} ₽ — часть их позиций "
          f"перебита, часть нет)")

    по_месяцам = defaultdict(lambda: [0, 0.0])
    по_кассирам = defaultdict(lambda: [0, 0.0])
    for ч in неперебитые:
        м = ч["время"][:7]
        по_месяцам[м][0] += 1
        по_месяцам[м][1] += ч["не_вернулось"]
        к = ч["кассир"] or "без имени"
        по_кассирам[к][0] += 1
        по_кассирам[к][1] += ч["не_вернулось"]

    print("\n  по месяцам:")
    for м in sorted(по_месяцам):
        n, s = по_месяцам[м]
        print(f"    {м}  {n:>4} шт.  {деньги(s):>12} ₽")
    print("\n  по учётным записям кассы:")
    for к, (n, s) in sorted(по_кассирам.items(), key=lambda x: -x[1][1]):
        print(f"    {к:<26} {n:>4} шт.  {деньги(s):>12} ₽")

    print(f"\n  наличными из них: "
          f"{деньги(sum(ч['нал'] for ч in неперебитые))} ₽, безналом: "
          f"{деньги(sum(ч['безнал'] for ч in неперебитые))} ₽")

    (КЭШ / "неперебитые.json").write_text(
        json.dumps(неперебитые, ensure_ascii=False, indent=1), encoding="utf-8")
    print(f"\nСписок целиком: data/ofd/неперебитые.json")


if __name__ == "__main__":
    главное()
