def column(day: int) -> str:
    """Буква столбца для дня месяца: 1 → B, 26 → AA."""
    n = FIRST_DAY_COLUMN + day - 1
    letters = ""
    while n:
        n, rest = divmod(n - 1, 26)
        letters = chr(ord("A") + rest) + letters
    return letters


def read_month(month: str):
    """Собирает наш месяц из выгрузок смен."""
    безымянные = []              # смены, где деньги есть, а имени нет
    tips = defaultdict(dict)     # официант → день → начислено
    service = defaultdict(dict)  # официант → день → сервисный сбор
    admin = defaultdict(dict)
    cashier = defaultdict(dict)
    days = []

    for path in sorted(EXPORTS.glob(f"смена-{month}-*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        day = int(data["businessDay"].split("-")[2])
        days.append(day)
        for w in data["waiters"]:
            # «Начислено» в их таблице — это наше accrued: сумма после долей
            # администратору и кассиру. Проверено сверкой 18.08.2026.
            if w["accrued"]:
                tips[w["name"]][day] = round(w["accrued"], 2)
            if w["service"]:
                service[w["name"]][day] = round(w["service"], 2)
        # ⚠️ Администраторов в смене может быть ДВОЕ — смену делят надвое,
        # и доля делится пополам (решение владельца 18.08.2026). Поле `admin`
        # держит только первого; список `admins` — всех.
        #
        # Читали здесь `admin`, и доля второго молча не доезжала до таблицы УК.
        # 21.08.2026 так нашлись 2 813,08 ₽ Елизаветы Недорезовой за 5 августа:
        # в отчёте они стояли, в листе УК их не было, и заметить это можно было
        # только сложив итог месяца двумя путями. Пропажа не разовая — она
        # повторялась бы каждую поделённую смену.
        роли = [("admin", кто, admin)
                for кто in (data.get("admins") or [data.get("admin")])]
        роли.append(("cashier", data.get("cashier"), cashier))

        for роль, кто, куда in роли:
            if not кто or not кто.get("amount"):
                continue
            имя = кто.get("name") or БЕЗ_ИМЕНИ.get((data["businessDay"], роль))
            if имя:
                # Складываем, а не присваиваем: один человек может получить
                # за день долю дважды, и второе присваивание стёрло бы первое.
                куда[имя][day] = round(куда[имя].get(day, 0) + кто["amount"], 2)
            else:
                безымянные.append((data["businessDay"], роль, round(кто["amount"], 2)))

    return days, tips, service, admin, cashier, безымянные


def block_rows(people: dict, start: int, end: int, title: str):
    """Раскладывает людей по строкам блока. Не влезли — останавливаемся."""
    места = end - start + 1
    if len(people) > места:
        sys.exit(
            f"В блоке «{title}» {места} строк, а людей {len(people)}.\n"
            "Строки в их таблице добавляет дирекция франшизы — по их же\n"
            "инструкции. Впишу кого попало — деньги лягут не тому человеку."
        )
    # По убыванию заработка: самые заметные строки сверху, как в нашем отчёте.
    порядок = sorted(people, key=lambda n: -sum(people[n].values()))
    return {name: start + i for i, name in enumerate(порядок)}



def предыдущий_лист(листы, месяцы, year: int, month_num: int):
    """От какого листа заводить новый месяц.

    Сначала ищем лист УК за прошлый месяц: в нём их разметка и их формулы,
    а нам нужна именно она — строки блоков жёстко привязаны к номерам.
    Если его нет, берём наш прошлый дубль: он такой же по устройству.

    Возвращает имя листа или None, если заводить не от чего.
    """
    пред_год, пред_месяц = (year - 1, 12) if month_num == 1 else (year, month_num - 1)
    имя = f"{месяцы[пред_месяц]} {пред_год}"
    # Пробуем в порядке предпочтения: их лист (с пробелом и без), потом наш.
    for кандидат in (f"{имя} ", имя, f"{имя} — из приложения"):
        if кандидат in листы:
            return кандидат
    return None


def выбрать_образец(api, листы: dict, имя_месяца: str) -> str:
    """Из близнецов месяца берём ЗАПОЛНЯЕМЫЙ, а не первый попавшийся.

    🔴 У УК на один месяц заводится по нескольку листов с одинаковым именем,
    различающихся только пробелами в конце: на сентябрь 2026 их три —
    «Сентябрь 2026», «Сентябрь 2026 » и «Сентябрь 2026  ». Живой из них один,
    остальные пустые заготовки.

    Здесь стояло простое `f"{месяц} {год} "` — имя с ОДНИМ пробелом. В августе
    им оказался заполняемый лист, и всё работало. В сентябре с одним пробелом
    оказалась пустая заготовка, а живой был с двумя, — и мы месяц копировали
    пустышку. Владелец 08.09.2026: «ты не переносишь данные в файл УК».

    Поэтому выбираем не по имени, а по СОДЕРЖИМОМУ: среди листов, чьё имя
    без пробелов совпадает с месяцем, берём тот, где больше заполненных строк.
    Заготовка пуста по определению, живой лист — нет.

    ⚠️ Выбор говорится вслух вместе с отвергнутыми. Молчаливый выбор между
    похожими листами — это ровно та ошибка, которую мы здесь и чиним.
    """
    свои = " — из приложения"
    кандидаты = [и for и in листы
                 if и.strip() == имя_месяца and not и.endswith(свои)]
    if not кандидаты:
        return имя_месяца + " "
    if len(кандидаты) == 1:
        return кандидаты[0]

    веса = {}
    for и in кандидаты:
        try:
            строки = api.spreadsheets().values().get(
                spreadsheetId=SHEET, range=f"'{и}'!A1:H60").execute().get("values", [])
        except Exception:
            строки = []
        веса[и] = sum(1 for р in строки if any(str(к).strip() for к in р))

    лучший = max(кандидаты, key=lambda и: веса[и])
    прочие = ", ".join(f"{и!r} ({веса[и]} строк)" for и in кандидаты if и != лучший)
    print(f"⚠️ Листов месяца несколько. Беру {лучший!r} — в нём {веса[лучший]} "
          f"заполненных строк. Отвергнуты: {прочие}")
    return лучший


