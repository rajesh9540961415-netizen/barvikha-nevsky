def _как_у_ук(имя: str) -> str:
    """«Акмаль Беков» → «Беков Акмаль».

    У нас везде «Имя Фамилия», в листе УК — наоборот, и блок стоит в ИХ
    таблице, рядом с их же строками. Решение владельца 10.09.2026:
    «пиши как у них».

    ⚠️ Переворачиваем только имя ровно из двух слов. «Никита Алексеевич
    Тарасов» переворачивать нечем — какое из трёх слов фамилия, программа
    не знает, а угадавшая однажды угадает неверно в другой раз. Такие
    и вписанные руками («Максим, стажёр») оставляем как есть.
    """
    части = имя.split()
    return f"{части[1]} {части[0]}" if len(части) == 2 else имя


def _кальянщики_листа(доли_дня: dict) -> list[tuple[str, str]]:
    """Строки людей: (имя как в выгрузке, имя как писать в лист).

    Порядок — по фамилии, по алфавиту. У УК в листе порядок свой, ничем
    не объяснимый; повторять его значит держать девять имён списком
    в коде и править их руками при каждом приёме.

    ⚠️ Кто отработал, но в справочнике бара его нет, — тоже строкой,
    в конце. Пропусти мы его, доля просто исчезла бы из листа, и заметить
    это было бы нечем: итоговая строка считается отдельно и сошлась бы.
    """
    справочник = json.loads(СПРАВОЧНИК_БАРА.read_text(encoding="utf-8"))
    свои = [ч["name"] for ч in справочник]
    чужие = sorted(имя for имя in доли_дня if имя not in свои)
    if чужие:
        print(f"  ⚠️ В баре работали не из справочника: {', '.join(чужие)}")
    return [(имя, _как_у_ук(имя))
            for имя in sorted(свои, key=_как_у_ук) + чужие]


def _доли_кальянщиков(месяц: str, рубли_дня: dict) -> tuple[dict, list]:
    """Мотивация дня, поделённая между теми, кто в этот день вышел.

    Состав берём из выгрузок смен — поле `hookahCrew`, появилось 10.09.2026.
    Считаем ровно так же, как экран мотивации в приложении: котёл делится
    на число ОТМЕЧЕННЫХ, до десятых рубля (решение владельца 08.09.2026,
    подтверждено 10.09.2026; недостачу в пару рублей закрывают из кассы).

    ⚠️ Делим на отмеченных, а не на всех девятерых. Забыли отметить
    вышедшего — доля остальных выйдет БОЛЬШЕ настоящей, а забытый останется
    ни с чем. Ошибка идёт в плюс и по самой цифре не видна: 9 400 на троих
    выглядит так же правдоподобно, как на четверых. Ловится она только
    глазами, по именам в этом самом блоке, — ради этого он и нужен.

    Отдаёт (имя → день → доля, дни без состава).
    """
    доли: dict[str, dict[str, float]] = {}
    без_состава = []
    for путь in sorted(EXPORTS.glob(f"смена-{месяц}-*.json")):
        д = json.loads(путь.read_text(encoding="utf-8"))
        день = д["businessDay"]
        котёл = рубли_дня.get(день, 0)
        if not котёл:
            continue
        # За дни, где приложение подставляло состав из вчерашней смены,
        # главнее чат: см. пояснение к СОСТАВ_ИЗ_ЧАТА. Дальше — выгрузка,
        # она запись самого вечера.
        состав = СОСТАВ_ИЗ_ЧАТА.get(день) or [
            ч["name"] for ч in д.get("hookahCrew") or []
        ]
        if not состав:
            # Пусто — значит, в тот вечер бар не отмечали: до 08.09.2026
            # раздела «Кальянный бар» в составе смены ещё не было. Это
            # «не вели», а не «никто не работал»; молчать об этом нельзя.
            без_состава.append(день)
            continue
        доля = round(котёл / len(состав), 1)
        for имя in состав:
            доли.setdefault(имя, {})[день] = доля
    return доли, без_состава


def сетка_и_группы(месяц: str):
    """Наш отчёт → (сетка, группы, оформление).

    ⚠️ Читаем формулы, а НЕ посчитанные значения. Отчёт собирает openpyxl,
    а она формулы пишет, но не считает: посчитанного значения в файле нет
    вовсе. Excel считает при открытии, поэтому у владельца на экране всё
    на месте — а программа, читающая файл, видит пустоту. 19.08.2026 из-за
    этого в лист УК уехали пустые «Общий чай всего», «Начислено»
    и «Расхождение», и владелец это заметила первой.

    Формулы уезжают формулами: Google Таблицы считают SUMIF и ROUND сами,
    разметка листа та же, ссылки не съезжают. Лист становится живым,
    а не снимком.

    Группа — (первая строка, последняя), нумерация листа с единицы.
    Оформление — (номер строки, цвет заливки, жирная ли) по столбцу подписи.
    """
    import openpyxl
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from report_path import report_dir

    месяцы_имена = ["", "январь", "февраль", "март", "апрель", "май", "июнь",
                    "июль", "август", "сентябрь", "октябрь", "ноябрь", "декабрь"]
    файл = report_dir() / f"Чаевые-дубль-{месяцы_имена[int(месяц[5:7])]}-{месяц[:4]}.xlsx"
    if not файл.exists():
        sys.exit(
            f"Нет нашего отчёта: {файл}\n"
            "Сначала соберите его: python3 scripts/report_pull.py --month"
        )
    ws = openpyxl.load_workbook(файл, data_only=False).active

    сетка, уровни, оформление = [], [], []
    for r in range(1, ws.max_row + 1):
        ряд = []
        for c in range(1, ws.max_column + 1):
            v = ws.cell(r, c).value
            if isinstance(v, datetime.datetime):
                v = v.strftime("%d.%m.%Y")
            elif isinstance(v, datetime.date):
                v = v.strftime("%d.%m.%Y")
            # Ноль в денежной клетке значит «человека в этот день не было»,
            # а читается как настоящая сумма. Решение владельца: пусто.
            elif v in (0, 0.0) and c > 1 and not isinstance(v, str):
                v = ""
            # ⚠️ Разделитель аргументов в формуле. У их таблицы русская
            # локаль: SUMIF(что; по чему; что сложить) — через точку с
            # запятой. Запятая из Excel даёт «#ERROR!» в каждой клетке,
            # и лист выглядит сломанным целиком. Десятичных запятых внутри
            # формул нет: Питон пишет дробные через точку.
            if isinstance(v, str) and v.startswith("="):
                v = v.replace(",", ";")
            ряд.append("" if v is None else v)
        сетка.append(ряд)

        d = ws.row_dimensions.get(r)
        уровни.append(getattr(d, "outlineLevel", 0) if d else 0)

        клетка = ws.cell(r, 1)
        цвет = None
        f = клетка.fill
        if f is not None and f.fgColor is not None and f.fgColor.rgb:
            rgb = str(f.fgColor.rgb)
            if rgb not in ("00000000", "None"):
                цвет = rgb[-6:]
        оформление.append((r, цвет, bool(клетка.font and клетка.font.bold)))

    группы, начало_гр = [], None
    for i, ур in enumerate(уровни, start=1):
        if ур >= 2 and начало_гр is None:
            начало_гр = i
        elif ур < 2 and начало_гр is not None:
            группы.append((начало_гр, i - 1))
            начало_гр = None
    if начало_гр is not None:
        группы.append((начало_гр, len(уровни)))
    return сетка, группы, оформление


