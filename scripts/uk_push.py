    for блок, люди in данные.items():
        print(f"— {блок}:")
        for имя in sorted(люди, key=lambda n: -sum(люди[n].values())):
            дни = люди[имя]
            всего = sum(дни.values())
            print(f"    {имя:<28} дней {len(дни):>2}  всего {всего:>12,.2f} ₽"
                  .replace(",", " "))

    итог = sum(sum(d.values()) for d in tips.values())
    итог_сбор = sum(sum(d.values()) for d in service.values())
    итог_адм = sum(sum(d.values()) for d in admin.values())
    итог_кас = sum(sum(d.values()) for d in cashier.values())
    print(f"\nИтого за месяц: официантам {итог:,.2f} (сбор {итог_сбор:,.2f} уже внутри), "
          f"администраторам {итог_адм:,.2f}, кассирам {итог_кас:,.2f}".replace(",", " "))
    print(f"Всего людям: {итог + итог_адм + итог_кас:,.2f} ₽ — столько и должно "
          f"стоять в их строке «Общий чай всего персонала»".replace(",", " "))

    if not args.записать:
        print("\nЭто был холостой прогон. Чтобы записать — добавьте --записать")
        return

    # ── Лист в НАШЕМ формате
    #
    # ⚠️ Решение владельца 19.08.2026: лист повторяет наш отчёт целиком,
    # а строки видов денег спрятаны в свёрнутые группы. Код для этого написали
    # тогда же (`сетка_и_группы` внизу файла) — и не подключили: `main()`
    # продолжала заполнять дубль ИХ листа, по клетке на человека. Владелец
    # увидела это 21.08.2026: «вместо основной сводки — сводка по официантам,
    # причём без формул, просто цифры».
    #
    # 💡 Урок: написанное и неподключённое — то же, что ненаписанное, и хуже:
    # в файле лежит подробное объяснение того, чего программа не делает.
    сетка, группы, оформление = сетка_и_группы(args.month)
    ширина = max(len(р) for р in сетка)

    хвост, хвост_оформление = блок_мотивации(args.month, ширина)
    if хвост:
        сдвиг = len(сетка)
        сетка += хвост
        оформление += [(сдвиг + н, ц, ж) for н, ц, ж in хвост_оформление]

    # 🔴 **Пишем прямо в лист УК — решение владельца 08.09.2026.**
    #
    # До этого мы писали в свой дубль «— из приложения»: решение от 18.08.2026
    # звучало «заполненный руками лист не трогаем, старый удалит человек,
    # когда сверит». Три недели спустя человек так и заполнял его руками,
    # а мы рядом свой. Владелец: «пиши прямо в тот лист». Ради этого всё
    # и затевалось — снять работу с человека целиком.
    #
    # ⚠️ Что при этом теряется, и это надо знать: лист вычищается ПОЛНОСТЬЮ
    # и рисуется заново из нашей сетки. Формулы становятся простыми числами
    # (владелец 18.08: «нужны цифры, причём без формул»), а всё, чего в нашей
