def сетка_и_группы(месяц: str):
    """Наш отчёт → (сетка, группы, оформление).

    ⚠️ Читаем формулы, а НЕ посчитанные значения. Отчёт собирает openpyxl,
    а она формулы пишет, но не считает: посчитанного значения в файле нет
    вовсе. Excel считает при открытии, поэтому у владельца на экране всё
    на месте — а программа, читающая файл, видит пустоту. 19.08.2026 из-за
    этого в лист УК уехали пустые «Общий чай всего», «Начислено»
    и «Расхождение», и владелец это заметила первой.

    Формулы уезжают формулами: Google Таблицы считают SUMIF и ROUND сами,
    разметка листа та же, ссылки не съезжают. Лист становится живым,
    а не снимком.

    Группа — (первая строка, последняя), нумерация листа с единицы.
    Оформление — (номер строки, цвет заливки, жирная ли) по столбцу подписи.
    """
    import openpyxl
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    from report_path import report_dir

    месяцы_имена = ["", "январь", "февраль", "март", "апрель", "май", "июнь",
                    "июль", "август", "сентябрь", "октябрь", "ноябрь", "декабрь"]
    файл = report_dir() / f"Чаевые-дубль-{месяцы_имена[int(месяц[5:7])]}-{месяц[:4]}.xlsx"
    if not файл.exists():
        sys.exit(
            f"Нет нашего отчёта: {файл}\n"
            "Сначала соберите его: python3 scripts/report_pull.py --month"
        )
    ws = openpyxl.load_workbook(файл, data_only=False).active

    сетка, уровни, оформление = [], [], []
    for r in range(1, ws.max_row + 1):
        ряд = []
        for c in range(1, ws.max_column + 1):
            v = ws.cell(r, c).value
            if isinstance(v, datetime.datetime):
                v = v.strftime("%d.%m.%Y")
            elif isinstance(v, datetime.date):
                v = v.strftime("%d.%m.%Y")
            # Ноль в денежной клетке значит «человека в этот день не было»,
            # а читается как настоящая сумма. Решение владельца: пусто.
            elif v in (0, 0.0) and c > 1 and not isinstance(v, str):
                v = ""
            # ⚠️ Разделитель аргументов в формуле. У их таблицы русская
            # локаль: SUMIF(что; по чему; что сложить) — через точку с
            # запятой. Запятая из Excel даёт «#ERROR!» в каждой клетке,
            # и лист выглядит сломанным целиком. Десятичных запятых внутри
            # формул нет: Питон пишет дробные через точку.
            if isinstance(v, str) and v.startswith("="):
                v = v.replace(",", ";")
            ряд.append("" if v is None else v)
        сетка.append(ряд)

        d = ws.row_dimensions.get(r)
        уровни.append(getattr(d, "outlineLevel", 0) if d else 0)

        клетка = ws.cell(r, 1)
        цвет = None
        f = клетка.fill
        if f is not None and f.fgColor is not None and f.fgColor.rgb:
            rgb = str(f.fgColor.rgb)
            if rgb not in ("00000000", "None"):
                цвет = rgb[-6:]
        оформление.append((r, цвет, bool(клетка.font and клетка.font.bold)))

    группы, начало_гр = [], None
    for i, ур in enumerate(уровни, start=1):
        if ур >= 2 and начало_гр is None:
            начало_гр = i
        elif ур < 2 and начало_гр is not None:
            группы.append((начало_гр, i - 1))
            начало_гр = None
    if начало_гр is not None:
        группы.append((начало_гр, len(уровни)))
    return сетка, группы, оформление


