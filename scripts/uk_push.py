def блок_мотивации(месяц: str, ширина: int) -> tuple[list, list]:
    """Мотивация кальянного бара строками в конец листа УК.

    Владелец 08.09.2026: «давай в этот файл внизу добавим ещё данные
    по мотивации».

    Отдаёт (строки, оформление_подписей). Считает не сам: зовёт
    `hookah_push`, где это решается единственный раз. Доплата за «ЧМ»
    положена только в комплекте с электронной чашей, и разбирается это
    по составу чека — повторять такое во втором месте нельзя.

    ⚠️ Сбой здесь НЕ роняет лист. Чеков бара за месяц может не быть вовсе
    (например, УК смотрит старый месяц) — тогда блока просто не будет,
    а таблица чаевых уедет как обычно: она важнее.

    Столбцы те же, что у всей сетки: подпись, потом дни месяца по порядку.
    """
    sys.path.insert(0, str(Path(__file__).resolve().parent))
    try:
        from hookah_push import правила, строки_для_базы
        ставки, _комплект, _вне = правила()
        строки_бд = строки_для_базы(месяц)
    except SystemExit as е:
        print(f"  ⚠️ Мотивация не посчиталась, блока не будет: {е}")
        return [], []
    if not строки_бд:
        print("  ⚠️ Продаж кальянов за месяц нет — блока мотивации не будет")
        return [], []

    ставка_типа = {п["наша"]: п["ставка"] for к, п in ставки.items()}
    дни = sorted({с["day"] for с in строки_бд})
    первый = min(дни)
    номер_дня = {д: int(д[8:10]) for д in дни}

    # Считаем только рубли: штуки и разбивку по типам блок больше не
    # показывает (см. ниже). Продажи по типам смотрят на странице
    # `/motivaciya` в бэк-офисе, там они живые и с раскладкой по дням.
    рубли_дня: dict[str, float] = {}
    for с in строки_бд:
        т, д, к = с["category"], с["day"], с["qty"]
        рубли_дня[д] = рубли_дня.get(д, 0) + к * ставка_типа.get(т, 0)

    def ряд(подпись: str, по_дням: dict, знаков: int = 0) -> list:
        р = [подпись] + [""] * (ширина - 1)
        for д, з in по_дням.items():
            место = номер_дня[д]
            if место < ширина:
                р[место] = round(з, знаков) if знаков else int(round(з))
        return р

    всего = sum(рубли_дня.values())

    # Формат владельца 08.09.2026 (прислала снимком их листа), доделан
    # 10.09.2026: верхней строкой общая сумма за смену, ниже — она же,
    # разделённая между теми, кто в эту смену работал, по строке на человека.
    #
    # ⚠️ Разбивка по типам кальянов отсюда УБРАНА 10.09.2026 по указанию
    # владельца. Она стояла заглушкой: имён взять было неоткуда, состав бара
    # до отчёта не доезжал. Теперь доезжает, и на её месте люди — ради них
    # блок и затевался. Продажи по типам никуда не делись, они на странице
    # `/motivaciya` в бэк-офисе.
    доли_дня, без_состава = _доли_кальянщиков(месяц, рубли_дня)

    строки = [
        [""] * ширина,
        ряд("КАЛЬЯННЫЙ БАР Мотивация", рубли_дня),
    ]
    # Люди — все, кто есть в справочнике бара, а не только вышедшие в этом
    # месяце: решение владельца 10.09.2026, «всех девятерых». У них в листе
    # так же — человек без смен виден пустой строкой, и сразу понятно, что
    # его не забыли, а он не работал.
    for имя_отчёта, имя_листа in _кальянщики_листа(доли_дня):
        строки.append(ряд(имя_листа, доли_дня.get(имя_отчёта, {}), знаков=1))

    # Подписи блока: заголовок жирный, остальные обычные — как в отчёте.
    оформление = [(2, None, True)] + [(i, None, False) for i in range(3, len(строки) + 1)]
    print(f"  ✓ Мотивация кальянного бара: {всего:,.0f} ₽ за {len(дни)} дн., "
          f"людей {len(строки) - 2}".replace(",", " "))
    if без_состава:
        дни_словами = ", ".join(д[8:10] for д in без_состава)
        print(f"  ⚠️ Состава бара нет за {len(без_состава)} дн. ({дни_словами}) — "
              f"в этих столбцах строка мотивации будет, а имён нет. "
              f"Приложение начало записывать состав 08.09.2026.")
    return строки, оформление


