def column(day: int) -> str:
    """Буква столбца для дня месяца: 1 → B, 26 → AA."""
    n = FIRST_DAY_COLUMN + day - 1
    letters = ""
    while n:
        n, rest = divmod(n - 1, 26)
        letters = chr(ord("A") + rest) + letters
    return letters


def read_month(month: str):
    """Собирает наш месяц из выгрузок смен."""
    безымянные = []              # смены, где деньги есть, а имени нет
    tips = defaultdict(dict)     # официант → день → начислено
    service = defaultdict(dict)  # официант → день → сервисный сбор
    admin = defaultdict(dict)
    cashier = defaultdict(dict)
    days = []

    for path in sorted(EXPORTS.glob(f"смена-{month}-*.json")):
        data = json.loads(path.read_text(encoding="utf-8"))
        day = int(data["businessDay"].split("-")[2])
        days.append(day)
        for w in data["waiters"]:
            # «Начислено» в их таблице — это наше accrued: сумма после долей
            # администратору и кассиру. Проверено сверкой 18.08.2026.
            if w["accrued"]:
                tips[w["name"]][day] = round(w["accrued"], 2)
            if w["service"]:
                service[w["name"]][day] = round(w["service"], 2)
        for роль, куда in (("admin", admin), ("cashier", cashier)):
            кто = data[роль]
            if not кто["amount"]:
                continue
            имя = кто["name"] or БЕЗ_ИМЕНИ.get((data["businessDay"], роль))
            if имя:
                куда[имя][day] = round(кто["amount"], 2)
            else:
                безымянные.append((data["businessDay"], роль, round(кто["amount"], 2)))

    return days, tips, service, admin, cashier, безымянные


def block_rows(people: dict, start: int, end: int, title: str):
    """Раскладывает людей по строкам блока. Не влезли — останавливаемся."""
    места = end - start + 1
    if len(people) > места:
        sys.exit(
            f"В блоке «{title}» {места} строк, а людей {len(people)}.\n"
            "Строки в их таблице добавляет дирекция франшизы — по их же\n"
            "инструкции. Впишу кого попало — деньги лягут не тому человеку."
        )
    # По убыванию заработка: самые заметные строки сверху, как в нашем отчёте.
    порядок = sorted(people, key=lambda n: -sum(people[n].values()))
    return {name: start + i for i, name in enumerate(порядок)}


def main():
    parser = argparse.ArgumentParser(description="Наш месяц → таблица УК.")
    parser.add_argument("month", help="месяц вида 2026-08")
    parser.add_argument("--записать", action="store_true",
                        help="создать дубль листа и заполнить (без него — вхолостую)")
    parser.add_argument("--лист", help="имя листа-образца; по умолчанию «<Месяц> <год> » ")
    parser.add_argument("--поверх", action="store_true",
                        help="лист «— из приложения» уже есть: очистить наши блоки и заполнить заново")
    args = parser.parse_args()

    if not KEY.exists():
        sys.exit(f"Нет ключа служебного аккаунта: {KEY}")

    from google.oauth2 import service_account
    from googleapiclient.discovery import build

    creds = service_account.Credentials.from_service_account_file(str(KEY), scopes=SCOPES)
    api = build("sheets", "v4", credentials=creds, cache_discovery=False)

    year, month_num = int(args.month[:4]), int(args.month[5:7])
    месяцы = ["", "Январь", "Февраль", "Март", "Апрель", "Май", "Июнь",
              "Июль", "Август", "Сентябрь", "Октябрь", "Ноябрь", "Декабрь"]
    образец = args.лист or f"{месяцы[month_num]} {year} "

    meta = api.spreadsheets().get(
        spreadsheetId=SHEET, fields="sheets.properties(sheetId,title,index)").execute()
    листы = {s["properties"]["title"]: s["properties"] for s in meta["sheets"]}

    if образец not in листы:
        похожие = [t for t in листы if t.strip() == образец.strip()]
        sys.exit(f"Листа {образец!r} нет. Похожие по имени: {похожие}")

    источник = листы[образец]
    print(f"Образец: {образец!r} (номер листа {источник['sheetId']})")

    days, tips, service, admin, cashier, безымянные = read_month(args.month)
    if not days:
        sys.exit(f"Нет выгрузок смен за {args.month} в {EXPORTS}")

    # Молча пропустить деньги без имени нельзя: они настоящие, просто
    # приложение забыло, чьи. Пропуск заметен только сверкой итога месяца,
    # то есть не заметен никогда.
    if безымянные:
        всего = sum(с for _, _, с in безымянные)
        print("⚠️  ДЕНЬГИ БЕЗ ИМЕНИ — в лист они НЕ ПОПАДУТ:")
        for день, роль, сумма in безымянные:
            подпись = "администратор" if роль == "admin" else "кассир"
            print(f"      {день}  {подпись:<14} {сумма:>10,.2f} ₽".replace(",", " "))
        print(f"      ─────────────────────────────────────")
        print(f"      итого {всего:>26,.2f} ₽".replace(",", " "))
        print("      Кто это — решает владелец. Вписать в словарь БЕЗ_ИМЕНИ "
              "вверху файла.\n")
    print(f"Смен в выгрузках: {len(days)} — с {min(days):02d} по {max(days):02d} число\n")

    # ⚠️ Блок «Сервисный сбор» НЕ заполняем, и это не забывчивость.
    #
    # Наше «начислено» — это уже вся выплата человеку: чаевые ПЛЮС сервисный
    # сбор, минус доли администратору и кассиру. Их формула «Общий чай всего
    # персонала» складывает блок чаевых и блок сбора. Заполнив оба, мы задваиваем
    # сбор: 18.08.2026 первый прогон дал 63 596 ₽ за 1 августа вместо 61 606 —
    # ровно на сбор того дня. Управляющий этот блок руками тоже не заполнял.
    #
    # Разложить «начислено» обратно на чай и сбор нельзя честно: доли берутся
    # с общей суммы, а не с каждой части. Понадобится разбивка — считать её
    # надо в приложении, а не делить задним числом на глазок.
    строки = {
        "официанты_чаевые": block_rows(tips, *BLOCKS["официанты_чаевые"], title="официанты"),
        "администраторы": block_rows(admin, *BLOCKS["администраторы"], title="администраторы"),
        "кассиры": block_rows(cashier, *BLOCKS["кассиры"], title="кассиры"),
    }
    данные = {
        "официанты_чаевые": tips,
        "администраторы": admin,
        "кассиры": cashier,
    }

    for блок, места in строки.items():
        print(f"— {блок}:")
        for имя, строка in места.items():
            дни = данные[блок][имя]
            всего = sum(дни.values())
            print(f"    строка {строка:>3}  {имя:<28} дней {len(дни):>2}  всего {всего:>12,.2f} ₽"
                  .replace(",", " "))

    итог = sum(sum(d.values()) for d in tips.values())
    итог_сбор = sum(sum(d.values()) for d in service.values())
    итог_адм = sum(sum(d.values()) for d in admin.values())
    итог_кас = sum(sum(d.values()) for d in cashier.values())
    print(f"\nИтого за месяц: официантам {итог:,.2f} (сбор {итог_сбор:,.2f} уже внутри), "
          f"администраторам {итог_адм:,.2f}, кассирам {итог_кас:,.2f}".replace(",", " "))
    print(f"Всего людям: {итог + итог_адм + итог_кас:,.2f} ₽ — столько и должно "
          f"стоять в их строке «Общий чай всего персонала»".replace(",", " "))

    if not args.записать:
        print("\nЭто был холостой прогон. Чтобы записать — добавьте --записать")
        return

    # ── Дубль листа
    имя_дубля = f"{месяцы[month_num]} {year} — из приложения"
    if имя_дубля in листы and not args.поверх:
        sys.exit(f"Лист {имя_дубля!r} уже есть. Заполнить заново — ключ --поверх.")

    if имя_дубля in листы:
        новый = листы[имя_дубля]
        print(f"\n✓ Пишу поверх листа {имя_дубля!r} (номер {новый['sheetId']})")
    else:
        ответ = api.spreadsheets().batchUpdate(spreadsheetId=SHEET, body={"requests": [{
            "duplicateSheet": {
                "sourceSheetId": источник["sheetId"],
                "insertSheetIndex": источник["index"] + 1,
                "newSheetName": имя_дубля,
            }
        }]}).execute()
        новый = ответ["replies"][0]["duplicateSheet"]["properties"]
        print(f"\n✓ Создан лист {имя_дубля!r} (номер {новый['sheetId']})")

    # ── Чистим только те блоки, которые заполняем сами.
    #
    # Хостес и кальянный бар не трогаем: до 19.08.2026 приложение их не вело,
    # и заменить их нечем. Стереть чужую работу, не имея что положить взамен,
    # — это не «наш формат», а потеря данных.
    наши_блоки = ["официанты_чаевые", "официанты_сбор", "администраторы", "кассиры"]
    # блок сбора чистим (в дубле там могла остаться рука), но не заполняем
    чистить = [f"'{имя_дубля}'!A{BLOCKS[b][0]}:AF{BLOCKS[b][1]}" for b in наши_блоки]
    api.spreadsheets().values().batchClear(
        spreadsheetId=SHEET, body={"ranges": чистить}).execute()
    print(f"✓ Очищены блоки: {len(чистить)}")

    # ── Пишем наше
    записи = []
    for блок, места in строки.items():
        for имя, строка in места.items():
            записи.append({"range": f"'{имя_дубля}'!A{строка}", "values": [[имя]]})
            for день, сумма in sorted(данные[блок][имя].items()):
                записи.append({
                    "range": f"'{имя_дубля}'!{column(день)}{строка}",
                    "values": [[сумма]],
                })

    api.spreadsheets().values().batchUpdate(spreadsheetId=SHEET, body={
        "valueInputOption": "RAW", "data": записи}).execute()
    print(f"✓ Записано клеток: {len(записи)}")
    print(f"\nОткрыть: https://docs.google.com/spreadsheets/d/{SHEET}/edit#gid={новый['sheetId']}")


if __name__ == "__main__":
    main()
