    в_дубль = getattr(args, "в_дубль", False)

    # 🔴 Закрытый месяц в листе УК НЕ переписываем без прямого слова.
    # Владелец 08.09.2026: «август не трогай» — его лист заполнен управляющим
    # руками, и наша запись стёрла бы месяц чужой работы. Текущий месяц
    # переписывать можно и нужно: он и так наш, его никто не ведёт руками.
    #
    # ⚠️ Замок нужен именно потому, что команда безобидна на вид:
    # `uk_push.py 2026-08 --записать` отличается от ежедневной одной цифрой.
    if not в_дубль and args.month != date.today().strftime("%Y-%m"):
        if not args.закрытый_месяц:
            sys.exit(
                f"✗ {args.month} — не текущий месяц, а лист УК за него, "
                f"скорее всего, заполнен руками.\n"
                f"  Записать поверх: добавьте --закрытый-месяц.\n"
                f"  Записать в свой дубль, ничего чужого не трогая: --в-дубль."
            )
    имя_листа = (f"{месяцы[month_num]} {year} — из приложения"
                 if в_дубль else образец)

    # ⚠️ Копия ДО первой записи в месяце — один раз, не каждое утро.
    # Чужой документ переписывать без запасного экземпляра нельзя: ошибка
    # в нашей сетке иначе стирает чужую работу без возврата.
    if not в_дубль:
        запас = f"{месяцы[month_num]} {year} — как было до приложения"
        if запас not in листы:
            api.spreadsheets().batchUpdate(spreadsheetId=SHEET, body={"requests": [{
                "duplicateSheet": {
                    "sourceSheetId": листы[образец]["sheetId"],
                    "newSheetName": запас,
                    "insertSheetIndex": листы[образец]["index"] + 1}}]}).execute()
            print(f"✓ Копия их листа сохранена: {запас!r}")
        else:
            print(f"  копия их листа уже есть: {запас!r}")

    # ⚠️ Лист НЕ пересоздаём, а вычищаем и заполняем заново — чтобы у него
    # не менялся адрес. Удалить и создать проще, но каждое утро выходил бы
    # новый `gid`, и сохранённая кем-нибудь ссылка назавтра вела бы в пустоту.
    # Чистить приходится втроём: значения, оформление и группы строк —
    # группы живут отдельно от клеток и при простой очистке остаются висеть,
    # а новые легли бы поверх старых.
    if имя_листа in листы:
        лист_id = листы[имя_листа]["sheetId"]
        подробно = api.spreadsheets().get(
            spreadsheetId=SHEET, ranges=[f"'{имя_листа}'!A1"],
            fields="sheets(properties(sheetId),rowGroups)").execute()["sheets"][0]
        прежние = подробно.get("rowGroups") or []
        очистка = [{"deleteDimensionGroup": {"range": {
            "sheetId": лист_id, "dimension": "ROWS",
            "startIndex": г["range"]["startIndex"],
            "endIndex": г["range"]["endIndex"]}}} for г in прежние]
        # 🔴 Сперва РАЗЪЕДИНИТЬ клетки, потом писать. В листе УК их 16, каждая
        # растянута на 38 столбцов: запись в объединённую строку заполняет
        # только первую клетку, остальные молча теряются. 08.09.2026 первый
        # заход в их лист так и вышел — часть чисел наших, часть их старых,
