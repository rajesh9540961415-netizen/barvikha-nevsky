def Д(v):
    """Деньги без копеек, разряды пробелом."""
    return f"{round(v):,.0f}".replace(",", " ")


def млн(v):
    """Крупные суммы — в миллионах: «21,9 млн» читается, «21 913 406» нет."""
    return f"{v / 1e6:.1f}".replace(".", ",") + " млн"


def П(доля):
    """Процент по-русски: с пробелом перед знаком и настоящим минусом."""
    знак = "−" if доля < 0 else "+"
    return f"{знак}{abs(доля) * 100:.0f} %"


def чеков_словом(n):
    """«131 чек», «132 чека», «135 чеков» — иначе отчёт читается как машинный."""
    если = n % 100
    if 11 <= если <= 14:
        return "чеков"
    return {1: "чек", 2: "чека", 3: "чека", 4: "чека"}.get(n % 10, "чеков")


def торговый_день(t: datetime) -> date:
    return (t - timedelta(days=1)).date() if t.hour < СУТКИ_С else t.date()


