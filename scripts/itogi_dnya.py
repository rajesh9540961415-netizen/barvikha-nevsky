def блок_денег(день):
    остатки = DATA / "bank_balances.csv"
    реестр = DATA / "registry.json"
    if not (остатки.exists() and реестр.exists()):
        return ["⚠️ <b>Деньги:</b> нет выписок или реестра счетов"]
    имена, закрытые = {}, set()
    for e in json.loads(реестр.read_text(encoding="utf-8"))["entities"]:
        for a in e["accounts"]:
            if a.get("number"):
                имена[a["number"]] = (e["short"], a.get("role", ""))
                if a.get("закрыт") or a.get("в_учёте_до"):
                    закрытые.add(a["number"])
    последние = {}
    for b in csv.DictReader(остатки.open(encoding="utf-8")):
        if b["date"] > день.isoformat():
            continue
        if b["account"] not in последние or b["date"] > последние[b["account"]]["date"]:
            последние[b["account"]] = b
    по_юрлицу = defaultdict(lambda: {"счёт": 0.0, "резерв": 0.0})
    оборот = 0.0
    for номер, b in последние.items():
        if номер in закрытые:
            continue
        короткое, роль = имена.get(номер, ("?", ""))
        короткое = ЮРЛИЦА.get(короткое, короткое)
        сумма = float(b["closing"])
        if роль == "tax_reserve":
            по_юрлицу[короткое]["резерв"] += сумма
        else:
            по_юрлицу[короткое]["счёт"] += сумма
            оборот += сумма
    строки = ["💰 <b>Деньги на счетах</b>"]
    for имя, ч in sorted(по_юрлицу.items(), key=lambda x: -x[1]["счёт"]):
        хвост = f", резерв на налоги {Д(ч['резерв'])} ₽" if ч["резерв"] else ""
        строки.append(f"• {имя} — {Д(ч['счёт'])} ₽{хвост}")
    строки.append(f"Оборотных всего {Д(оборот)} ₽")

    расход = defaultdict(float)
    вывод = defaultdict(float)
    месяц = день.strftime("%Y-%m")
    for r in csv.DictReader((DATA / "bank_classified.csv").open(encoding="utf-8")):
        if r["date"][:7] != месяц or r["direction"] != "out" or r["date"] > день.isoformat():
            continue
        короткое = ЮРЛИЦА.get(r["entity"], r["entity"])
        if r["class"] == "external":
            расход[короткое] += float(r["amount"])
        elif r["class"] == "withdrawal":
            вывод[короткое] += float(r["amount"])
    if расход:
        части = " · ".join(f"{и} {Д(с)}" for и, с in
                           sorted(расход.items(), key=lambda x: -x[1]))
        строки.append(f"<b>Расходы месяца {Д(sum(расход.values()))} ₽:</b> {части}")
    if вывод:
        кто = sorted(вывод.items(), key=lambda x: -x[1])
        хвост = (f" — весь с одного счёта: {кто[0][0]}" if len(кто) == 1 else
                 ": " + " · ".join(f"{и} {Д(с)}" for и, с in кто))
        строки.append(f"<b>Вывод {Д(sum(вывод.values()))} ₽</b>{хвост}")
    return строки


