def блок_листа(день):
    """Вердикт по бумажному листу смены — его пишет утренняя задача.

    Машина рукописный лист не разбирает: сверяет человек, а сюда кладёт строку.
    Нет строки — так и пишем, а не выдумываем «сошлось».
    """
    файл = ROOT / "data" / "вердикт-листа.json"
    if файл.exists():
        try:
            данные = json.loads(файл.read_text(encoding="utf-8"))
            запись = данные.get(день.isoformat())
            if isinstance(запись, str):          # старый вид файла
                return [запись]
            if запись:
                значок = "✅" if запись.get("сошлось") else "⚠️"
                return [f"{значок} {запись['строка']}"]
        except (json.JSONDecodeError, OSError):
            pass
    return ["⚠️ <i>Лист смены ещё не сверяли</i>"]


