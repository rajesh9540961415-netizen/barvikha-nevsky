def блок_направлений(день):
    from pl_menu import категория
    итог = defaultdict(float)
    месяц = день.strftime("%Y-%m")
    файлы = [f for f in glob.glob(str(ROOT / "data" / "ofd" / f"чеки*{месяц}.json"))]
    for ф in файлы:
        try:
            чеки = json.loads(Path(ф).read_text(encoding="utf-8"))
        except (json.JSONDecodeError, OSError):
            continue
        видели = set()
        for ч in чеки:
            фпд = ч.get("фпд")
            if фпд:
                if фпд in видели:
                    continue
                видели.add(фпд)
            if торговый_день(datetime.fromisoformat(ч["время"])) != день:
                continue
            for поз in ч.get("позиции", []):
                итог[категория(поз[0])] += float(поз[2] or 0)
    if not итог:
        return ["⚠️ <b>Из чего сложилась:</b> чеков ОФД за этот день ещё нет"]
    всего = sum(итог.values())
    подписи = {"кальяны": "Кальяны", "бар": "Бар", "кухня": "Кухня",
               "аренда": "Аренда VIP"}
    строки = ["Из чего сложилась:"]
    for к, v in sorted(итог.items(), key=lambda x: -x[1]):
        строки.append(f"• {подписи.get(к, к)} — {Д(v)} ₽ ({v / всего * 100:.0f} %)")
    return строки


