def продажи():
    """День → [наличные, безналичные, чеков] по обеим кассам."""
    дни = defaultdict(lambda: [0.0, 0.0, 0])
    for файл in ("qr_sales_mav.csv", "qr_sales_shalaeva.csv"):
        путь = DATA / файл
        if not путь.exists():
            continue
        for r in csv.DictReader(путь.open(encoding="utf-8")):
            д = дни[r["date"]]
            д[0] += float(r["cash"] or 0)
            д[1] += float(r["cashless"] or 0)
            д[2] += int(float(r["checks"] or 0))
    return дни


def блок_выручки(день, дни):
    к = день.isoformat()
    if к not in дни:
        return ["⚠️ <b>Выручки за этот день нет</b> — касса не выгрузилась"], 0.0, 0
    нал, безнал, чеков = дни[к]
    всего = нал + безнал
    хвост = "" if not всего else f" · наличными {нал / всего * 100:.0f} %"
    строки = [f"Выручка <b>{Д(всего)} ₽</b> · {чеков} {чеков_словом(чеков)}{хвост}"]

    сравнения = []
    неделю = (день - timedelta(days=7)).isoformat()
    если_было = sum(дни[неделю][:2]) if неделю in дни else 0
    if если_было and всего:
        сравнения.append(f"К тому же дню неделей раньше {П(всего / если_было - 1)} "
                         f"(было {Д(если_было)})")
    # Год назад берём тот же ДЕНЬ НЕДЕЛИ, а не ту же дату: пятница против
    # понедельника сравнивает не работу, а календарь.
    год = (день - timedelta(days=364)).isoformat()
    если_год = sum(дни[год][:2]) if год in дни else 0
    if если_год and всего:
        сравнения.append(f"к прошлому году {П(всего / если_год - 1)}")
    if сравнения:
        строки.append(", ".join(сравнения))
    return строки, всего, чеков


def блок_месяца(день, дни):
    месяц = день.strftime("%Y-%m")
    свои = [д for д in дни if д.startswith(месяц) and д <= день.isoformat()]
    if not свои:
        return []
    сумма = sum(sum(дни[д][:2]) for д in свои)
    средний = сумма / len(свои)
    всего_дней = calendar.monthrange(день.year, день.month)[1]
    прошлый = (день.replace(day=1) - timedelta(days=1)).strftime("%Y-%m")
    было = sum(sum(дни[д][:2]) for д in дни if д.startswith(прошлый))
    строки = [f"<b>Месяц:</b> {Д(сумма)} ₽ за {len(свои)} дн., в среднем {Д(средний)}/день",
              f"Таким темпом месяц закроется около {млн(средний * всего_дней)} ₽"]
    if было:
        строки[-1] += (f" ({ИМЕНИТЕЛЬНЫЙ[int(прошлый[5:]) - 1]} — {млн(было)} ₽)")
    return строки


