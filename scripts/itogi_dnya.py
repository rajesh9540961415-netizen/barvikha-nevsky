def собрать(день):
    """Возвращает (текст управляющему, текст владельцу)."""
    дни = продажи()
    выручка_строки, всего, чеков = блок_выручки(день, дни)
    шапка = [f"📊 <b>Барвиха Невский — {день.day} {МЕСЯЦЫ[день.month - 1]}</b>", ""]
    общее = (шапка + выручка_строки + [""]
             + блок_столов(день, всего, чеков) + [""]
             + блок_направлений(день) + [""]
             + блок_чаевых(день) + [""]
             + блок_месяца(день, дни) + [""]
             + блок_кассы(день) + блок_листа(день))
    полная = общее + [""] + блок_денег(день)
    return "\n".join(общее), "\n".join(полная)


