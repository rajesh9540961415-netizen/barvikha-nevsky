def перебивки_со_сменой_оплаты(день, окно=60):
    """Гашение и повторная пробивка той же суммы, у которых разошёлся тип оплаты.

    Считаем по чекам, а не по словам в комментарии: фильтр по слову «налич»
    ловит «нет в наличии» и завышает счёт втрое — проверено 17.09.2026.
    """
    import ofd_returns as о
    о.ТИХО = True
    месяц = день.strftime("%Y-%m")
    пар = 0
    for касса, опис in о.КАССЫ.items():
        чеки = (о.чеки_за([месяц], False) if опис["источник"] == "api"
                else о.чеки_бара())
        приходы = [ч for ч in чеки if ч["вид"] == о.ПРИХОД]
        возвраты = [ч for ч in чеки if ч["вид"] == о.ВОЗВРАТ_ПРИХОДА
                    and торговый_день(datetime.fromisoformat(ч["время"])) == день]
        занятые = set()
        for в in возвраты:
            t = datetime.fromisoformat(в["время"])
            налом_в = float(в.get("нал") or 0) > 0
            for п in приходы:
                if п["номер"] in занятые:
                    continue
                if abs(float(п["сумма"]) - float(в["сумма"])) > 0.01:
                    continue
                if abs((datetime.fromisoformat(п["время"]) - t).total_seconds()) > окно * 60:
                    continue
                if (float(п.get("нал") or 0) > 0) != налом_в:
                    пар += 1
                    занятые.add(п["номер"])
                break
    return пар


