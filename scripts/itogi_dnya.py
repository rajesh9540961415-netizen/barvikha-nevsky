def блок_столов(день, выручка_дня, чеков):
    файл = ROOT / "data" / "столы-рестоплейс.json"
    if not файл.exists():
        return ["⚠️ <b>Столы:</b> склад Рестоплейс не найден"]
    склад = json.loads(файл.read_text(encoding="utf-8"))
    брони = склад.get("брони") or {}
    записи = list(брони.values()) if isinstance(брони, dict) else брони
    столов = гостей = 0
    for б in записи:
        if isinstance(б, dict) and str(б.get("статус")) == ЗАКРЫТА \
                and б.get("день") == день.isoformat():
            столов += 1
            гостей += int(б.get("гостей") or 0)
    if not столов:
        по = (склад.get("покрытие") or {}).get("по", "")
        причина = "посадки не закрыты" if по >= день.isoformat() else \
                  f"склад заполнен по {по}"
        return [f"⚠️ <b>Столы:</b> данных за этот день нет — {причина}"]
    строки = [f"🪑 Столов <b>{столов}</b> · гостей {гостей}"]
    хвост = ""
    # Гостей меньше, чем чеков, почти не бывает: компания платит одним счётом.
    # Значит часть посадок не закрыли в Рестоплейс, и «на гостя» завышен.
    # Решение владельца 17.09.2026: цифру оставляем, но помечаем.
    if гостей and чеков and гостей < чеков:
        хвост = " ⚠️"
    строки.append(f"Средний чек по столу <b>{Д(выручка_дня / столов)} ₽</b>"
                  + (f" · на гостя <b>{Д(выручка_дня / гостей)} ₽</b>{хвост}"
                     if гостей else ""))
    if хвост:
        строки.append("<i>гостей меньше, чем чеков — возможно, не все посадки "
                      "закрыты в Рестоплейс</i>")
    return строки


