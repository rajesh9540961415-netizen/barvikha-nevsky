#!/usr/bin/env python3
"""
Приложение к отчёту: построчный разбор каждого звонка.

Собирает из двух файлов:
  - выгрузка Zoon (телефоны, время, расшифровки, ссылки на записи)
  - разбор по чек-листу (оценка каждого пункта)

Главное отличие от разбора коллеги: звонки идут не подряд, а
**по тяжести нарушений** — сначала критичные, потом существенные,
потом чистые. Открыл файл — сразу видно, что смотреть.

Запуск:
    python3 scripts/calls/make_appendix.py 2026-08-01_04
"""

import csv
import sys
from collections import Counter
from pathlib import Path

DATA = Path(__file__).resolve().parents[2] / "data" / "calls"

# Пункты чек-листа: код → как называется в отчёте
KRIT = {
    "K1_18плюс_и_документы": "18+ и документы",
    "K2_условия_депозита_аренды": "Условия депозита / аренды",
    "K3_бронь_заведена_в_системе": "Бронь заведена в системе",
    "K4_альтернатива_если_столов_нет": "Альтернатива, если столов нет",
}
SUSCH = {
    "S1_имя_гостя": "Имя гостя",
    "S2_время_визита": "Время визита",
    "S3_количество_гостей": "Количество гостей",
    "S4_размещение": "Размещение",
    "S5_продолжительность": "Продолжительность",
    "S6_резюме_брони": "Резюме брони",
    "S7_бронь_держится_15_минут": "Бронь держится 15 минут",
    "S8_вопрос_откуда_узнали": "Источник гостя",
    "S9_первый_визит": "Первый визит",
    "S10_контактный_номер": "Контактный номер",
    "S11_вопросы_по_другим_заведениям": "Вопросы по другим заведениям",
}
FORMA = {
    "F1_приветствие": "Приветствие",
    "F2_прощание": "Прощание",
    "F3_тон": "Тон",
}

ПРОПУСК = {"нет", "не", "-", "0"}
ЧАСТИЧНО = {"частично", "неполно"}
# то, что проверить нечем — это не оценка, а отсутствие данных
НЕТ_ДАННЫХ = {"нет данных", "не проверялось", "н/д", "неприменимо", "не применимо", "", "—"}


def norm(v):
    return (v or "").strip().lower()


def пропущен(v):
    return norm(v) in ПРОПУСК


def маска(phone):
    p = "".join(c for c in (phone or "") if c.isdigit())
    return f"+7 (9XX) XXX-{p[-4:-2]}-{p[-2:]}" if len(p) >= 4 else "—"


def тяжесть(row):
    """Чем больше, тем выше в файле."""
    k = sum(пропущен(row.get(c)) for c in KRIT)
    s = sum(пропущен(row.get(c)) for c in SUSCH)
    return k * 100 + s


def блок_оценок(row, поля):
    строки = []
    for код, имя in поля.items():
        v = (row.get(код) or "—").strip()
        if norm(v) in НЕТ_ДАННЫХ:
            значок = "—"
        elif пропущен(v):
            значок = "❌"
        elif norm(v) in ЧАСТИЧНО:
            значок = "◐"
        else:
            значок = "✅"
        строки.append(f"| {имя} | {значок} {v} |")
    return строки


def карточка(src, an, out):
    ts = f"{an.get('дата','')} {an.get('время','')}".strip()
    хостес = an.get("имя_хостес") or "имя не распознано"
    тип = an.get("тип_звонка") or "—"
    длит = an.get("длительность_сек") or "?"

    крит = [KRIT[c] for c in KRIT if пропущен(an.get(c))]
    сущ = [SUSCH[c] for c in SUSCH if пропущен(an.get(c))]

    out.append(f"### {ts} · {хостес} · {тип}")
    out.append("")
    out.append(
        f"Длительность {длит} с · гость {маска(src.get('phone_from'))} · "
        f"источник {an.get('источник_трафика') or 'не указан'}"
    )
    out.append("")
    if an.get("ссылка_на_запись"):
        out.append(f"[Прослушать запись]({an['ссылка_на_запись']})")
        out.append("")

    if крит:
        out.append(f"> 🔴 **Критично:** {', '.join(крит)}")
        out.append("")

    текст = (src.get("Транскрибация диалога") or "").strip()
    # первая строка — служебное объявление Zoon, в разбор не идёт
    строки = [l for l in текст.split("\n") if "Звонок от Зун точка ру" not in l]
    if строки:
        out.append("**Расшифровка:**")
        out.append("")
        for l in строки:
            l = l.strip()
            if l:
                # «Зун:» в выгрузке — это хостес заведения
                out.append("> " + l.replace("Зун:", "**Хостес:**").replace("Клиент:", "**Гость:**"))
        out.append("")

    out.append("**Разбор по чек-листу:**")
    out.append("")
    out.append("| Пункт | Вердикт |")
    out.append("|---|---|")
    out += блок_оценок(an, KRIT) + блок_оценок(an, SUSCH) + блок_оценок(an, FORMA)
    out.append("")

    if крит or сущ:
        out.append("**Расхождения:**")
        out.append("")
        for x in крит:
            out.append(f"- 🔴 {x}")
        for x in сущ:
            out.append(f"- {x}")
        out.append("")

    if an.get("комментарий"):
        out.append(f"**Комментарий:** {an['комментарий']}")
        out.append("")
    if an.get("ответ_гостя_про_источник"):
        out.append(f"**Откуда узнал гость:** {an['ответ_гостя_про_источник']}")
        out.append("")

    out.append("---")
    out.append("")


def main(период):
    исходник = DATA / f"zoon_{период}.csv"
    разбор = DATA / f"analysis-{период}.csv"
    for f in (исходник, разбор):
        if not f.exists():
            sys.exit(f"Не найден файл: {f}")

    src = list(csv.DictReader(open(исходник, encoding="utf-8")))
    an = list(csv.DictReader(open(разбор, encoding="utf-8-sig")))

    # сводим по дате+времени с точностью до минуты:
    # в выгрузке время с секундами, в разборе — без
    индекс = {}
    for r in src:
        индекс.setdefault(r["ts"][:16], r)
    пары = []
    без_пары = 0
    for a in an:
        ключ = f"{a.get('дата','')} {a.get('время','')}"[:16]
        исх = индекс.get(ключ)
        if исх is None:
            без_пары += 1
        пары.append((исх or {}, a))
    if без_пары:
        print(f"  ⚠️  без расшифровки не сопоставлено: {без_пары}")

    содержательные = [
        p for p in пары
        if (p[1].get("тип_звонка") or "").lower() not in ("служебный", "мусор", "без содержания", "")
    ]
    прочие = [p for p in пары if p not in содержательные]
    содержательные.sort(key=lambda p: тяжесть(p[1]), reverse=True)

    крит_шт = sum(1 for _, a in содержательные if any(пропущен(a.get(c)) for c in KRIT))

    out = [
        f"# Разбор звонков — Невский — {период.replace('_', ' – ')}",
        "",
        f"Приложение к отчёту. Разобрано **{len(содержательные)}** содержательных звонков "
        f"из {len(пары)}. Оценка — по чек-листу из `.business/quality/checklist.md`.",
        "",
        f"**Звонки отсортированы по тяжести нарушений**, а не по времени: сначала "
        f"{крит_шт} с критичными пропусками, дальше по убыванию.",
        "",
        "Обозначения: ✅ выполнено · ◐ частично · ❌ пропущено · — неприменимо",
        "",
        "Расшифровки автоматические и содержат ошибки распознавания. "
        "Перед разговором с сотрудницей слушайте запись, а не текст.",
        "",
        "---",
        "",
    ]

    for s, a in содержательные:
        карточка(s, a, out)

    if прочие:
        out.append(f"## Служебные и без содержания — {len(прочие)}")
        out.append("")
        out.append("| Время | Длительность | Тип |")
        out.append("|---|---|---|")
        for s, a in прочие:
            out.append(
                f"| {a.get('дата','')} {a.get('время','')} | "
                f"{a.get('длительность_сек','?')} с | {a.get('тип_звонка') or '—'} |"
            )
        out.append("")

    путь = DATA / f"приложение-{период}.md"
    путь.write_text("\n".join(out), encoding="utf-8")
    print(f"Готово: {путь}")
    print(f"  содержательных звонков: {len(содержательные)}")
    print(f"  из них с критичными пропусками: {крит_шт}")
    print(f"  служебных и пустых: {len(прочие)}")


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else "2026-08-01_04")
