#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Сверка звонков с реальными бронями Рестоплейс.

Закрывает пункт чек-листа K3 «бронь заведена в системе». До 28.08.2026 он стоял
в «нет данных» на всех строках: из разговора видно только, что хостес СКАЗАЛА
«забронировала». Теперь есть чем проверить.

Ключ сопоставления — телефон гостя плюс окно по времени: бронь должна быть
создана в пределах двух часов после звонка (и допускаем 10 минут до — часы
на разных системах расходятся).

⚠️ «Брони нет» — это подозрение, а не приговор. Гостя могли завести на другой
номер: хостес вписывает тот телефон, который гость назвал, а звонить он мог
с другого. Поэтому итог делится на три части, и разбирать нужно только третью.

Запуск:
    python3 scripts/calls/sverka.py 2026-08-01_04
"""

from __future__ import annotations

import collections
import csv
import json
import sys
from datetime import datetime, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent.parent
ПАПКА = ROOT / "data" / "calls"

ОКНО_ДО = timedelta(minutes=10)
ОКНО_ПОСЛЕ = timedelta(hours=2)

# Слова, по которым видно, что гость сам не стал бронировать. Тогда отсутствие
# брони — правильная работа, а не потеря.
УШЁЛ = ("ушёл", "ушла", "не забронировал", "перезвонить", "отказал",
        "не оформлена", "не закрыта", "думать", "без бронирования")


def время(s: str):
    try:
        return datetime.strptime(s, "%Y-%m-%d %H:%M:%S")
    except (ValueError, TypeError):
        return None


def свежие_брони() -> list[dict]:
    файлы = sorted(ПАПКА.glob("брони-рестоплейс-*.json"))
    if not файлы:
        sys.exit("✗ Нет выгрузки броней. Сначала: python3 scripts/rp_reserves.py")
    return json.loads(файлы[-1].read_text(encoding="utf-8"))


def сверить(период: str):
    файл = ПАПКА / f"analysis-{период}.csv"
    if not файл.exists():
        sys.exit(f"✗ Нет разбора звонков: {файл.name}")
    with файл.open(encoding="utf-8-sig") as f:
        читалка = csv.DictReader(f)
        звонки, колонки = list(читалка), читалка.fieldnames

    по_телефону = collections.defaultdict(list)
    for б in свежие_брони():
        тел = (б.get("phone") or "").strip()
        if тел:
            по_телефону[тел].append(б)

    итог = collections.Counter()
    подозрительные = []
    for з in звонки:
        if з.get("тип_звонка") != "бронирование":
            з["K3_бронь_заведена_в_системе"] = "неприменимо"
            continue
        тел = (з.get("телефон_гостя") or "").strip()
        момент = время(f"{з['дата']} {з['время']}:00")
        совпали = [
            б for б in по_телефону.get(тел, [])
            if (с := время(б.get("created") or ""))
            and момент - ОКНО_ДО <= с <= момент + ОКНО_ПОСЛЕ
        ] if (тел and момент) else []
        if совпали:
            б = совпали[0]
            з["K3_бронь_заведена_в_системе"] = "да"
            з["комментарий"] = (з.get("комментарий") or "") + (
                f" [бронь подтверждена: {б.get('time_from')}, гостей {б.get('count')}, "
                f"{б.get('floor_name')}]")
            итог["подтверждена"] += 1
        elif any(w in (з.get("комментарий") or "").lower() for w in УШЁЛ):
            з["K3_бронь_заведена_в_системе"] = "гость не бронировал"
            итог["гость ушёл"] += 1
        else:
            з["K3_бронь_заведена_в_системе"] = "НЕ НАЙДЕНА"
            итог["не найдена"] += 1
            подозрительные.append(з)

    выход = ПАПКА / f"analysis-{период}-со-сверкой.csv"
    with выход.open("w", newline="", encoding="utf-8-sig") as f:
        w = csv.DictWriter(f, fieldnames=колонки)
        w.writeheader()
        w.writerows(звонки)

    всего = sum(итог.values())
    print(f"Звонков-бронирований: {всего}\n")
    print(f"  ✓ бронь подтверждена в Рестоплейс      {итог['подтверждена']:>3}"
          f"   {итог['подтверждена']/всего*100:>5.0f} %")
    print(f"  · брони нет, гость сам не бронировал   {итог['гость ушёл']:>3}"
          f"   {итог['гость ушёл']/всего*100:>5.0f} %")
    print(f"  🔴 брони нет, а гость не уходил         {итог['не найдена']:>3}"
          f"   {итог['не найдена']/всего*100:>5.0f} %")
    if подозрительные:
        print("\n🔴 Разобрать вручную — гость не отказывался, а брони в системе нет:")
        for з in подозрительные:
            print(f"\n   {з['дата']} {з['время']}  хостес {з['имя_хостес'] or '—'}")
            print(f"      {(з.get('комментарий') or '')[:140]}")
    print(f"\nСохранено: {выход.relative_to(ROOT)}")


if __name__ == "__main__":
    сверить(sys.argv[1] if len(sys.argv) > 1 else "2026-08-01_04")
