#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Отработало ли утро: приехал лист, вписан ли он, ушёл ли вердикт.

Заведено 07.09.2026 разовой проверкой на одно утро. В тот же вечер решением
владельца стало ЕЖЕДНЕВНЫМ шагом задачи по чаевым: «надо, чтоб каждый день
проверяла». Разовая задача отработала и выключилась — сюда больше не ходят
по расписанию, зовёт утренняя задача четвёртой командой, до вердикта.

Проверяет она не данные, а работу самой задачи. Дописывание вчерашнего листа
в `data/листы-бумага.json` — единственное место, где утренняя задача пишет
в файл, и ровно оно может тихо не сработать: не дали разрешения, лист не
приехал, цифра прочитана не та. До 07.09.2026 никто ни разу не убедился,
что запись вообще случилась.

⚠️ Даты внутри команды быть не должно. Разрешение задачи по расписанию
хранится текстом команды целиком, поэтому `--день 2026-09-08` завтра станет
другой командой и повиснет. Вчерашний день скрипт считает сам.

Запуск:
    python3 scripts/proverka_utra.py
"""
from __future__ import annotations

import json
import sys
from datetime import datetime, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))

ЛИСТЫ_ФОТО = ROOT / "data" / "листы-смен"
ОТПРАВЛЕНО = ROOT / "data" / ".вердикт-отправлен"
ВЫГРУЗКИ = ROOT / "data" / "выгрузки-смен"


def главное() -> None:
    вчера = (datetime.now() - timedelta(days=1)).strftime("%Y-%m-%d")
    print(f"=== ПРОВЕРКА УТРА за {вчера} ===\n")

    фото = sorted(ЛИСТЫ_ФОТО.glob(f"лист-{вчера}*"))
    print(f"1. Фотография листа: {'ЕСТЬ — ' + ', '.join(p.name for p in фото) if фото else 'НЕТ'}")

    from tips_paper import D, сверка_с_приложением
    в_своде = вчера in D
    print(f"2. День в своде: {'ВПИСАН' if в_своде else 'НЕТ'}")
    if в_своде:
        нал, сбор, qr, безнал, всего = D[вчера]
        сумма = нал + сбор + qr + безнал
        print(f"     нал {нал}, сбор {сбор}, QR {qr}, безнал {безнал}, всего с листа {всего}")
        print(f"     контроль: столбцы дают {сумма} — "
              + ("сходится" if сумма == всего else f"РАСХОЖДЕНИЕ {сумма - всего:+}"))

    есть_выгрузка = (ВЫГРУЗКИ / f"смена-{вчера}.json").exists()
    print(f"3. Выгрузка смены: {'есть' if есть_выгрузка else 'НЕТ'}")

    if в_своде and есть_выгрузка:
        р = next((x for x in сверка_с_приложением() if x["день"] == вчера), None)
        print("4. Бумага и приложение: "
              + ("сошлись" if р is None
                 else f"РАЗОШЛИСЬ на {abs(р['разница']):,.2f} ₽".replace(",", " ")))
    else:
        print("4. Бумага и приложение: сверить не с чем")

    ушло = ОТПРАВЛЕНО.read_text(encoding="utf-8").strip() if ОТПРАВЛЕНО.exists() else ""
    print(f"5. Вердикт в группу: {'ушёл за ' + ушло if ушло == вчера else 'НЕ УШЁЛ (отметка: ' + (ушло or 'нет') + ')'}")

    print()
    if фото and not в_своде:
        print("ИТОГ: ✗ ЗАПИСЬ ЛИСТА НЕ СРАБОТАЛА — фотография приехала, а день не вписан.")
        print("      Это то самое, ради чего проверка и заводилась.")
    elif not фото:
        print("ИТОГ: лист за вчера в группу не приехал — проверять нечего, вина не наша.")
    elif в_своде and ушло == вчера:
        print("ИТОГ: ✓ всё сработало — лист вписан сам, вердикт ушёл.")
    else:
        print("ИТОГ: лист вписан, но вердикт не ушёл — смотреть отчёт задачи.")


if __name__ == "__main__":
    главное()
