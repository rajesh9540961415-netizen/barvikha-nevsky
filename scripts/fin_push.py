ВЫВОД = "Вывод собственнику"
ЗАИМСТВОВАНИЯ = "Заимствования между площадками"


def внутренние_столбцы() -> set:
    """Столбцы кассы, которые не расход, а движение денег.

    Список лежит рядом с самими данными, в `cash_categories.json` — там же,
    где карта статей, и правится тем же человеком в том же месте. Нет файла
    или ключа — считаем, что внутренних столбцов нет: пустой список делает
    поведение прежним, а не роняет заливку.
    """
    файл = DDS / "cash_categories.json"
    if not файл.exists():
        return set()
    return set(json.loads(файл.read_text(encoding="utf-8")).get("внутренние", {}))


ВНУТРЕННИЕ = внутренние_столбцы()


def из_env(имя: str, запасное: str = "") -> str:
    """Читает .env проекта. Кладём туда же, где остальные ключи."""
    if значение := os.environ.get(имя):
        return значение
    файл = ROOT / ".env"
    if файл.exists():
        for строка in файл.read_text(encoding="utf-8").splitlines():
            строка = строка.strip()
            if строка.startswith(f"{имя}="):
                return строка.split("=", 1)[1].strip().strip('"').strip("'")
    return запасное


def запрос(путь: str, тело: dict | None = None) -> dict:
    адрес = из_env("OFFICE_URL", АДРЕС_ПО_УМОЛЧАНИЮ).rstrip("/") + путь
    ключ = из_env("FINANCE_KEY")
    if not ключ:
        sys.exit(
            "✗ Не задан FINANCE_KEY.\n"
            "  Это ключ на ЗАПИСЬ в финансовый учёт, отдельный от EXPORT_KEY.\n"
            "  Одно и то же значение нужно в двух местах: в .env проекта\n"
            "  и в переменных приложения nevsky-office в панели Amvera."
        )

    данные = json.dumps(тело, ensure_ascii=False).encode("utf-8") if тело else None
    req = urllib.request.Request(
        адрес,
        data=данные,
        method="POST" if тело else "GET",
        headers={"X-Finance-Key": ключ, "Content-Type": "application/json"},
    )
    try:
        return json.loads(достучаться(req, таймаут=120))
    except urllib.error.HTTPError as e:
        подробности = e.read().decode("utf-8", errors="replace")
        try:
            причина = json.loads(подробности).get("причина", подробности)
        except json.JSONDecodeError:
            причина = подробности[:300]
        sys.exit(f"✗ Бэк-офис ответил {e.code}: {причина}")
    except urllib.error.URLError as e:
        sys.exit(f"✗ Не достучался до бэк-офиса: {e.reason}")


def банковские(месяц: str | None) -> list[dict]:
    """Платежи из bank_classified.csv, со статьёй расхода.

    ⚠️ **Статью считаем здесь, а не в бэк-офисе, и это принципиально.**
    В `bank_classified.csv` колонки со статьёй нет вовсе: статья выводится
    на лету функцией `article()` из `fin_articles.py` — по словарю ключевых
    слов, по назначению платежа и по решениям владельца в словаре `OWNER`.

    Написать эти правила заново на TypeScript означало бы завести им вторую
    копию, на другом языке. Проект уже держит две копии правил деления
    чаевых и платит за это проверкой `npm run copies`; третью такой проверкой
    не накрыть, и она разошлась бы молча — в деньгах.

    Поэтому статья едет готовым словом, а бэк-офис показывает присланное
    и ничего не вычисляет.
    """
    файл = DDS / "bank_classified.csv"
    if not файл.exists():
        sys.exit(f"✗ Нет {файл}. Сначала: python3 scripts/fin_classify.py")

    sys.path.insert(0, str(ROOT / "scripts"))
    from fin_articles import article, build_dictionary, transfer_detail  # noqa: E402

    словарь = build_dictionary()

    строки = []
    for r in csv.DictReader(файл.open(encoding="utf-8")):
        день = r.get("date", "")
        if месяц and not день.startswith(месяц):
            continue
        # Статья есть у внешних расходов и ещё у двух родов, которые расходами
        # не являются, но деньги со счёта уводят. У поступлений и внутренних
        # переводов статьи не бывает — подставлять туда «Прочее» нельзя:
        # в сводке по статьям они раздули бы расход на свою сумму.
        #
        # ⚠️ Вывод и заимствования получили СВОИ имена 16.08.2026. До этого
        # статьи у них не было вовсе, и экран показывал их в строке
        # «Не опознано» — то есть «мы не знаем, за что ушли деньги». Про эти
        # деньги известно ровно всё; неизвестно было только имя строки.
        # Владелец увидела 4 100 000 ₽ вывода под видом неопознанного
        # и справедливо спросила, что это.
        основа = {
            "day": день,
            "source": "bank",
            "entity": r.get("entity") or None,
            "account": r.get("account") or None,
            "direction": r.get("direction") or "out",
            "counterparty": r.get("counterparty") or None,
            "purpose": r.get("purpose") or None,
            "docNo": r.get("doc_no") or None,
        }
        сумма = float(r.get("amount") or 0)

        # Платёж, за которым стоит несколько наших счетов, раскрываем
        # на составляющие — так он разнесён в «Фин. своде», и свод здесь
        # главнее выписки.
        #
        # ⚠️ Выписка знает только «сколько ушло», а «за что» знает владелец.
        # 16.08.2026 я вывел 182 260 ₽ заново из выписки и назвал заёмом,
        # хотя разбор лежал готовым в двух местах сразу — в своде и в словаре
        # TRANSFER_DETAIL. Первичка отвечает на вопрос «что и когда»,
        # свод — на вопрос «куда отнести»; спорят они редко, и прав свод.
        части = transfer_detail(r) if r.get("direction") == "out" else None
        if части:
            # Самопроверка: части обязаны сойтись с платежом. Не сошлись —
            # останавливаемся. Разойдись они молча, месяц стал бы больше
            # или меньше на разницу, и увидеть это по суммам нельзя.
            собрано = sum(ч[2] for ч in части)
            if abs(собрано - сумма) > 0.01:
                sys.exit(
                    f"✗ Расшифровка платежа {день} №{r.get('doc_no')} "
                    f"не сходится: части дают {собрано:,.2f}, "
                    f"а платёж {сумма:,.2f}. Отправка отменена."
                    .replace(",", " ")
                )
            # Сам платёж всё равно отправляем — родом «split», чтобы экран
            # его пропустил. Если бы мы его просто не слали, прежняя строка
            # осталась бы в базе лежать как есть, и месяц посчитался бы
            # дважды: и платёж, и его части.
            строки.append({**основа, "amount": сумма, "article": None,
                           "opClass": "split",
                           "why": "раскрыт на составляющие, см. части ниже"})
            for кому, статья_части, сколько in части:
                строки.append({**основа, "amount": сколько,
                               "counterparty": кому, "article": статья_части,
                               "opClass": "external",
                               "why": f"часть платежа №{r.get('doc_no')} от {день}"})
            continue

        статья = None
        if r.get("direction") == "out":
            род = r.get("class")
            if род == "external":
                статья = article(r, словарь)[0]
            elif род == "withdrawal":
                статья = ВЫВОД
            elif род == "loan":
                статья = ЗАИМСТВОВАНИЯ
        строки.append({**основа, "amount": сумма, "article": статья,
                       "opClass": r.get("class") or None,
                       "why": r.get("why") or None})
    return строки


def остатки(месяц: str | None) -> list[dict]:
    """Остатки на счетах по дням — из выписки, как есть.

    ⚠️ Ничего не считаем и не сводим. Банк объявляет четыре числа: начало,
    списано, поступило, конец. Пересчитай мы конец из начала — потеряли бы
    единственную возможность заметить, что день не сходится: свой же расчёт
    всегда сойдётся сам с собой.

    Юрлицо подставляем из справочника, чтобы на экране счёт был подписан
    именем, а не двадцатью цифрами. Не нашли — оставляем пустым: незнакомый
    счёт лучше показать без имени, чем не показать вовсе.
    """
    файл = DDS / "bank_balances.csv"
    if not файл.exists():
        return []

    чей, тип, предел = {}, {}, {}
    справочник = json.loads((DDS / "registry.json").read_text(encoding="utf-8"))
    for e in справочник["entities"]:
        for a in e["accounts"]:
            if a.get("number"):
                чей[a["number"]] = e["id"]
                тип[a["number"]] = a.get("type")
                # Счёт, учёт по которому кончается датой. Решение владельца
                # про ИП Борзову: с 2026 года её нигде не должно быть —
                # значит и остатка на экране тоже.
                if a.get("в_учёте_до"):
                    предел[a["number"]] = a["в_учёте_до"]

    строки = []
    for r in csv.DictReader(файл.open(encoding="utf-8")):
        день = r.get("date", "")
        if месяц and not день.startswith(месяц):
            continue
        край = предел.get(r.get("account", ""))
        if край and день > край:
            continue
        число = lambda k: float(r[k]) if r.get(k) not in (None, "") else None  # noqa: E731
        строки.append({
            "day": день,
            "account": r.get("account") or "",
            "entity": чей.get(r.get("account", "")),
            "accountType": тип.get(r.get("account", "")),
            "opening": число("opening"),
            "debit": число("debit"),
            "credit": число("credit"),
            "closing": число("closing"),
        })
    return строки


def эквайринг(месяц: str | None) -> list[dict]:
    """Комиссия банка за приём карт — по дням.

    ⚠️ **Отдельным платежом она не приходит.** Банк удерживает её из зачисления:
    на счёт падает уже за вычетом, и в расходах её нет вовсе. Поэтому статью
    «Комиссия» приходится пополнять отдельно — так же делает `fin_articles.py`
    функцией `acquiring()`.

    Обнаружено 15.08.2026: расходы июля на экране разошлись с «Фин. сводом»
    ровно на 308 116,11 ₽ — это и оказалась она.

    Раскладываем по дням, а не одной строкой за месяц: ДДС ради дневного
    ритма и выбран, а месячный ком его бы сломал.
    """
    # ⚠️ Читаем размеченный файл, а не bank_transactions.csv, хотя `acquiring()`
    # в fin_articles читает именно его. Причина: в неразмеченном нет колонки
    # юрлица, и 15.08.2026 комиссия уехала на экране в отдельную группу
    # «юрлицо неизвестно». Строки в обоих файлах одни и те же — самопроверка
    # ниже это и подтверждает, сверяя итог с `acquiring()`.
    файл = DDS / "bank_classified.csv"
    if not файл.exists():
        return []

    строки = []
    for r in csv.DictReader(файл.open(encoding="utf-8")):
        день = r.get("date", "")
        if месяц and not день.startswith(месяц):
            continue
        if r.get("direction") != "in" or "эквайринг" not in (r.get("purpose") or "").lower():
            continue
        for m in re.finditer(r"Комиссия\s+([\d\s ]+[.,]\d+|[\d\s ]+)", r["purpose"]):
            сумма = float(m.group(1).replace(" ", "").replace(" ", "").replace(",", "."))
            строки.append({
                "day": день,
                "source": "bank",
                "entity": r.get("entity") or None,
                "account": r.get("account") or None,
                "direction": "out",
                "amount": сумма,
                "counterparty": "Сбербанк — эквайринг",
                "article": "Комиссия",
                "opClass": "external",
                "purpose": None,
                # Номер помечен, чтобы ключ повтора не столкнулся с самим
                # зачислением: у него тот же счёт, день и номер документа.
                "docNo": f"{r.get('doc_no') or ''}-эквайринг",
                "why": "удержана банком из зачисления, отдельным платежом не приходит",
            })
    return строки


def наличные(месяц: str | None) -> list[dict]:
    """Наличные расходы: кассовая книга, а где её нет — ручной ДДС владельца.

    ⚠️ Решение владельца 15.08.2026: таблицу ведём дальше, как есть. Значит
    у раздела два источника с разной свежестью — и это надо показывать честно,
    отметкой filledTo, а не смешивать молча.

    ⚠️ **Кассовая книга начинается только с января 2026.** За май 2024 –
    декабрь 2025 наличных расходов в учёте не было вовсе — около 53 млн ₽
    просто отсутствовали, и на экране это выглядело как «налом не тратили».
    Единственный источник за те месяцы — ручной ДДС владельца, разобранный
    `dds_import.py` в `transactions.csv`.

    Правило стыковки: **книга главнее.** ДДС берётся только за те месяцы,
    которых в книге нет вообще. Иначе два источника наложились бы и деньги
    задвоились: одни и те же расходы посчитаны в обоих.

    💡 Проверено на январе–марте 2026, где есть оба: ДДС даёт ровно на
    500 000 ₽ в месяц больше — это «Вознаграждение» наличными, которое
    в книгу не попадает. Расхождение известное и объяснённое; всё остальное
    сходится в пределах процента.
    """
    файл = DDS / "cash_expenses.csv"
    if not файл.exists():
        return []

    строки = []
    месяцы_книги = set()
    for r in csv.DictReader(файл.open(encoding="utf-8")):
        месяцы_книги.add(r.get("date", "")[:7])
    for r in csv.DictReader(файл.open(encoding="utf-8")):
        день = r.get("date", "")
        if месяц and not день.startswith(месяц):
            continue
        строки.append({
            "day": день,
            "source": "cash",
            "entity": None,
            "account": None,
            "direction": "out",
            "amount": float(r.get("amount") or 0),
            # «Столбец» таблицы — это и есть указание, кому и за что.
            # Своего поля контрагента там нет.
            "counterparty": r.get("column") or None,
            "article": r.get("category") or None,
            # 🔴 Не всякая строка кассы — расход. Прежде здесь стояло
            # «наличный расход всегда настоящий: перекладывать наличные между
            # своими счетами нечем». Владелец 07.09.2026 объяснила, что это
            # не так: инкассацией она забирает наличные из заведения, потом
            # управляющий оформляет приход, если деньги нужны, а остаток —
            # отдельной строкой как вывод босса. Посчитай инкассацию расходом,
            # и вывод ляжет ДВАЖДЫ: один раз ею, второй раз своей строкой.
            #
            # Список таких столбцов — в data/dds/cash_categories.json,
            # ключ «внутренние», с объяснением по каждому. Род `internal`
            # выбран не случайно: его уже пропускают все расчёты расходов,
            # и банковские переводы между своими счетами идут ровно так же.
            "opClass": "internal" if (r.get("column") or "") in ВНУТРЕННИЕ else "external",
            "purpose": None,
            "docNo": None,
            "why": None,
        })

    ддс = DDS / "transactions.csv"
    if not ддс.exists():
        return строки

    for r in csv.DictReader(ддс.open(encoding="utf-8")):
        if r.get("source") != "cash":
            continue
        день = r.get("date", "")
        if месяц and not день.startswith(месяц):
            continue
        if день[:7] in месяцы_книги:      # книга главнее, ДДС не наслаиваем
            continue
        строки.append({
            "day": день,
            "source": "cash",
            "entity": None,
            "account": None,
            "direction": "out",
            "amount": float(r.get("amount") or 0),
            # ⚠️ Подпись «из ДДС» обязательна. За 2024–2025 эти суммы стоят
            # ОДНОЙ строкой на последний день месяца: дневной разбивки налом
            # в старых листах нет. Без пометки владелец увидит горку платежей
            # 31-го числа и решит, что в этот день так и потратили.
            "counterparty": f"{r.get('counterparty') or 'наличные'} (из ДДС)",
            "article": r.get("category") or None,
            "opClass": "external",
            "purpose": None,
            "docNo": None,
            "why": "ручной ДДС владельца — кассовой книги за этот месяц нет",
        })
    return строки


def дни(месяц: str | None) -> list[dict]:
    """Выручка, чеки и остаток по дням — верхний блок формы ДДС.

    ⚠️ **Выручку берём из касс, а не из Google-таблицы.** Так же делают
    «Фин. свод» (`revenue_by_month` в fin_classify.py) и отчёт по чаевым.
    Взять её из таблицы значило бы завести третий ответ на вопрос «сколько
    заведение заработало», и однажды три ответа разошлись бы.

    ⚠️ **Касс две, и складывать надо обе.** С 07.07.2026 работают ООО «МАВ»
    и ИП Шалаева, у каждой своё облако Quick Resto. Взять одну — занизить
    выручку почти вдвое.

    Остаток на счетах — из наличной таблицы: в кассах его нет.
    """
    собрано: dict[str, dict] = {}

    for имя in ("qr_sales_mav.csv", "qr_sales_shalaeva.csv"):
        файл = DDS / имя
        if not файл.exists():
            continue
        for r in csv.DictReader(файл.open(encoding="utf-8")):
            день = r.get("date", "")
            if not день or (месяц and not день.startswith(месяц)):
                continue
            д = собрано.setdefault(день, {
                "day": день, "revenueCash": 0.0, "revenueCard": 0.0,
                "tablesCount": None, "checksCount": 0, "balanceTotal": None,
            })
            # ⚠️ Возвраты НЕ вычитаем: `qr_sales.py` уже вычел их, когда писал
            # эти колонки (`cash = totalCash − totalReturnCash`, так же
            # и `cashless`). То есть здесь уже «Выручка» Quick Resto,
            # а не «Сумма продаж».
            #
            # ⚠️ И колонка `returns` — это КОЛИЧЕСТВО возвратных заказов
            # (`returnOrdersCount`), а не сумма. 15.08.2026 я вычел её из
            # рублей: получилось вычитание штук из денег, и выручка августа
            # ушла на 214 ₽ вниз. Поймано сверкой с `report_revenue.py`,
            # который считает то же самое живым запросом к кассе.
            д["revenueCash"] += float(r.get("cash") or 0)
            д["revenueCard"] += float(r.get("cashless") or 0)
            д["checksCount"] += int(float(r.get("checks") or 0))

    файл = DDS / "cash_daily.csv"
    if файл.exists():
        for r in csv.DictReader(файл.open(encoding="utf-8")):
            день = r.get("date", "")
            if not день or (месяц and not день.startswith(месяц)):
                continue
            д = собрано.setdefault(день, {
                "day": день, "revenueCash": None, "revenueCard": None,
                "tablesCount": None, "checksCount": None, "balanceTotal": None,
            })
            д["balanceTotal"] = float(r["balance"]) if r.get("balance") else None

    return list(собрано.values())


# Какая касса какому юрлицу принадлежит.
#
# ⚠️ Ключи те же, что у банковских операций (`entity` в bank_classified.csv),
# иначе экран покажет одно и то же юрлицо дважды: расходы под «mav», выручку
# под каким-нибудь «ООО МАВ». Совпадение ключей здесь — не мелочь оформления,
# а условие, при котором две половины таблицы вообще сходятся.
# ⚠️ Имя должно совпасть со словарём ЮРЛИЦА в manager-app/src/lib/db/finance.ts,
# иначе экран покажет не название, а этот ключ.
МЯТА = "ooo_myata"

КАССЫ = {
    "qr_sales_mav.csv": "mav",
    "qr_sales_shalaeva.csv": "ip_shalaeva",
}


def выручка_по_юрлицам(месяц: str | None) -> list[dict]:
    """Та же выручка, что в `дни()`, но врозь по юрлицам.

    Нужна экрану месяца: владелец 16.08.2026 попросила видеть доходы и расходы
    в разбивке по юрлицам, накопительным итогом.

    ⚠️ Считается из тех же файлов и теми же правилами, что общий итог в `дни()`,
    нарочно. Завести здесь свой способ счёта значило бы получить второй ответ
    на вопрос «сколько заработали», и однажды два ответа разошлись бы. Экран
    их и не складывает: итог берёт из `days`, разбивку отсюда, и расхождение
    покажет, а не спрячет.
    """
    собрано: dict[tuple[str, str], dict] = {}

    for имя, юрлицо in КАССЫ.items():
        файл = DDS / имя
        if not файл.exists():
            continue
        for r in csv.DictReader(файл.open(encoding="utf-8")):
            день = r.get("date", "")
            if not день or (месяц and not день.startswith(месяц)):
                continue
            з = собрано.setdefault((день, юрлицо), {
                "day": день, "entity": юрлицо,
                "revenueCash": 0.0, "revenueCard": 0.0, "checksCount": 0,
            })
            # Возвраты уже вычтены в qr_sales.py, а `returns` — количество
            # заказов, а не рубли. Подробнее в `дни()`.
            з["revenueCash"] += float(r.get("cash") or 0)
            з["revenueCard"] += float(r.get("cashless") or 0)
            з["checksCount"] += int(float(r.get("checks") or 0))

    выделить_мяту(собрано, месяц)
    return [з for з in собрано.values()
            if з["revenueCash"] or з["revenueCard"] or з["checksCount"]]


def доли_мяты(месяц: str | None) -> dict:
    """{день: (доля наличных, доля безнала)} — сколько дня пришлось на «Мяту».

    Источник — ручной ДДС владельца, разобранный `dds_import.py`. В нём выручка
    каждого дня разложена по тому, КТО её принял: отдельно ИП, отдельно
    ООО «Мята». Касса такого не знает — она одна на всех и считает только
    «сколько».
    """
    файл = DDS / "daily_metrics.csv"
    if not файл.exists():
        return {}

    по_дням: dict[str, dict] = {}
    for r in csv.DictReader(файл.open(encoding="utf-8")):
        день = r.get("date", "")
        if not день or (месяц and not день.startswith(месяц)):
            continue
        try:
            по_дням.setdefault(день, {})[r["metric"]] = float(r["value"])
        except (TypeError, ValueError):
            continue

    доли = {}
    for день, x in по_дням.items():
        части = []
        for своё, мята in (("revenue_cash", "revenue_cash_myata"),
                           ("revenue_cashless", "revenue_cashless_myata")):
            если = x.get(своё, 0.0) + x.get(мята, 0.0)
            части.append(x.get(мята, 0.0) / если if если else 0.0)
        if any(части):
            доли[день] = tuple(части)
    return доли


def выделить_мяту(собрано: dict, месяц: str | None) -> None:
    """Отделяет долю ООО «Мята» от выручки, записанной на кассу МАВ.

    ⚠️ **Берём из ДДС ПРОПОРЦИЮ, а не суммы.** Суммы там расходятся с кассой
    на проценты — свести их к одному числу нельзя, да и не нужно: касса
    отвечает на вопрос «сколько», ДДС — на вопрос «чьё». Наложив долю
    на кассовое число, получаем разрез, который не спорит с итогом.

    ⚠️ И не спорит буквально: остаток после округления оставляем МАВ, поэтому
    сумма частей ВСЕГДА равна исходному дню до копейки. В `main` стоит
    самопроверка «разбивка по юрлицам обязана сойтись с общим итогом», и она
    откажется отправлять, если это перестанет быть правдой.

    ⚠️ Чеки делим той же долей и округляем вниз, остаток — МАВ. Чек нельзя
    разрезать пополам, а считать их точно по юрлицам нечем: в кассе они общие.

    💡 Почему это вообще понадобилось. До 17.08.2026 вся выручка с мая 2024
    приписывалась ООО «МАВ» — просто потому, что бралась из файла его кассы.
    А в 2024 – мае 2025 деньги принимали два юрлица сразу, и доля «Мяты»
    плавала от 10 до 28 %, чего по экрану видно не было вовсе.
    """
    доли = доли_мяты(месяц)
    if not доли:
        return

    for (день, юрлицо), з in list(собрано.items()):
        if юрлицо != "mav" or день not in доли:
            continue
        д_нал, д_безнал = доли[день]
        нал = round(з["revenueCash"] * д_нал, 2)
        безнал = round(з["revenueCard"] * д_безнал, 2)
        всего = з["revenueCash"] + з["revenueCard"]
        чеки = int(з["checksCount"] * ((нал + безнал) / всего)) if всего else 0
        if not (нал or безнал):
            continue

        з["revenueCash"] -= нал
        з["revenueCard"] -= безнал
        з["checksCount"] -= чеки
        собрано[(день, МЯТА)] = {
            "day": день, "entity": МЯТА,
            "revenueCash": нал, "revenueCard": безнал, "checksCount": чеки,
        }


def докуда(строки: list[dict], источник: str) -> str | None:
    """Последний день, за который у источника вообще есть данные."""
    дни_ = [с["day"] for с in строки if с["source"] == источник and с["day"]]
    return max(дни_) if дни_ else None


def отправить(месяц: str | None) -> None:
    """Отправляет один период: банк, эквайринг, наличные, дни, выручку, остатки."""
    экв = эквайринг(месяц)
    # Самопроверка, которая умеет не сойтись: раскладка по дням обязана дать
    # ровно тот же итог, что и `acquiring()` в fin_articles. Разошлось —
    # значит одна из двух читалок назначения платежа неверна, и молча
    # отправлять такое нельзя.
    if месяц and экв:
        sys.path.insert(0, str(ROOT / "scripts"))
        from fin_articles import acquiring
        должно = round(acquiring(месяц), 2)
        вышло = round(sum(с["amount"] for с in экв), 2)
        if должно != вышло:
            sys.exit(
                f"✗ Эквайринг по дням даёт {вышло:,.2f}, а по месяцу {должно:,.2f}.\n"
                "  Отправлять не буду: расхождение значит, что назначение платежа\n"
                "  читается двумя способами по-разному."
            )

    операции = банковские(месяц) + экв + наличные(месяц)
    список_дней = дни(месяц)
    по_юрлицам = выручка_по_юрлицам(месяц)

    # Самопроверка того же рода, что у эквайринга: разбивка по юрлицам обязана
    # дать ровно тот же итог, что общая выручка в `дни()`. Разошлось — значит
    # одна касса попала в один список и не попала в другой, и экран показал бы
    # разбивку, которая не складывается в собственный итог.
    итог_общий = round(sum((д.get("revenueCash") or 0) + (д.get("revenueCard") or 0)
                           for д in список_дней), 2)
    итог_врозь = round(sum(в["revenueCash"] + в["revenueCard"] for в in по_юрлицам), 2)
    if итог_общий != итог_врозь:
        sys.exit(
            f"✗ Выручка по юрлицам даёт {итог_врозь:,.2f}, а всего {итог_общий:,.2f}.\n"
            "  Отправлять не буду: разбивка не сходится с итогом, и экран\n"
            "  показал бы состав, который не складывается в целое."
        )

    что = месяц or "всю историю"
    print(f"Отправляю за {что}: платежей {len(операции)}, дней {len(список_дней)},"
          f" выручка врозь по {len({в['entity'] for в in по_юрлицам})} юрлицам")
    if not операции and not список_дней:
        sys.exit("✗ Отправлять нечего. Проверьте, что данные за этот период разобраны.")

    отметки = {}
    for источник in ("bank", "cash"):
        if д := докуда(операции, источник):
            отметки[источник] = д

    # ⚠️ Наличные просим ЗАМЕНИТЬ за период, а не дописать. Владелец
    # 15.08.2026: касса перепроверяется руками раз в 7–10 дней, и суммы
    # при перепроверке исправляются. Дописывание оставило бы старую неверную
    # строку рядом с новой, и расход дня вырос бы молча.
    #
    # Границы берём по календарю месяца, а не по присланным строкам: если
    # в таблице строку УДАЛИЛИ, её дня в пачке не будет вовсе — а стереть
    # её всё равно надо.
    остатки_счетов = остатки(месяц)
    тело = {"operations": операции, "days": список_дней,
            "revenue": по_юрлицам, "balances": остатки_счетов,
            "filledTo": отметки}
    if месяц:
        год, мес = (int(x) for x in месяц.split("-"))
        последний = calendar.monthrange(год, мес)[1]
        тело["replace"] = {
            "source": "cash",
            "from": f"{месяц}-01",
            "to": f"{месяц}-{последний:02d}",
        }
    else:
        # Отправляем всё — значит и наличные все, замена за весь срок.
        тело["replace"] = {"source": "cash", "from": "2000-01-01", "to": "2099-12-31"}

    # Счета, учёт по которым кончился датой. Присылаем ВСЕГДА, а не в тот раз,
    # когда решение принималось.
    #
    # ⚠️ Иначе так: отсечку завели, файлы у себя пересобрали, а строки, уехавшие
    # в учёт раньше, остались на экране навсегда — и решение выглядит
    # выполненным, потому что на компьютере их уже нет. Отправка добавляет
    # и обновляет, но сама по себе ничего не удаляет.
    #
    # 💡 Повторять безвредно: во второй раз удалять нечего, придёт ноль.
    справочник = json.loads((DDS / "registry.json").read_text(encoding="utf-8"))
    снять = [
        {"account": a["number"], "after": a["в_учёте_до"],
         "почему": a.get("_в_учёте_до", "решение владельца")[:300]}
        for e in справочник["entities"] for a in e["accounts"]
        if a.get("number") and a.get("в_учёте_до")
    ]
    if снять:
        тело["outOfScope"] = снять

    итог = запрос("/api/finance/import", тело)

    print(f"\n✓ Принято:  {итог['принято']}")
    print(f"  добавлено: {итог['добавлено']}")
    if итог.get("обновлено"):
        print(f"  разметка обновлена: {итог['обновлено']}"
              f"  ← у платежей поменялись статья, род или пояснение")
    print(f"  уже было:  {итог['ужеБыло']}")
    if итог.get("убрано"):
        # Одним числом идут две разные вещи: замена наличных и отсечка счетов.
        # Разделять их на стороне бэк-офиса значило бы менять ответ ручки ради
        # одной строчки на экране; здесь достаточно назвать обе причины.
        print(f"  убрано прежних строк: {итог['убрано']}"
              f"  ← замена наличных и/или счета вне учёта")
    print(f"  дней:      {итог['дней']}")
    if итог.get("выручки") is not None:
        print(f"  выручка по юрлицам: строк {итог['выручки']}")
    if итог.get("остатков"):
        print(f"  остатки по счетам: строк {итог['остатков']}")
    # ⚠️ Печатаем то, что ответила БАЗА, а не то, что отправили. Отметка
    # заполненности только растёт: пришлёшь август, когда сентябрь уже залит, —
    # база оставит сентябрь, и это правильно. Прежде здесь печаталось
    # отправленное, и отправка одного августа сообщала «заполнено по 31.08»
    # при шестом сентября в базе. 07.09.2026 я дважды пошёл чинить работающее.
    сохранено = итог.get("источники") or {}
    for источник, дата in отметки.items():
        вбазе = сохранено.get(источник)
        if вбазе and вбазе != дата:
            print(f"  {источник}: в базе «заполнено по {вбазе}» "
                  f"(отправляли {дата} — отметка назад не ходит)")
        else:
            print(f"  {источник}: в базе «заполнено по {вбазе or дата}»")

    if итог["добавлено"] == 0 and not итог.get("обновлено") and итог["принято"] > 0:
        print("\n💡 Ничего нового — всё это уже было загружено раньше. Так и должно быть.")


# Сколько первых дней нового месяца отправлять ещё и предыдущий месяц.
#
# ⚠️ Зачем это вообще есть. Выписку за последний день месяца банк отдаёт
# только на следующее утро — то есть уже в новом месяце. По умолчанию скрипт
# шлёт ТЕКУЩИЙ месяц, и получалось так: 31 августа его ещё нет в выписке,
# а 1 сентября отправляется уже сентябрь. Последний день месяца не уезжал
# в бэк-офис никогда.
#
# 💡 Нашла владелец 04.09.2026: на экране бэк-офиса 29, 30 и 31 августа
# пустые. 29 и 30 — суббота и воскресенье, банк не проводит; а 31-е — дыра
# в 11 платежей на 573 308 ₽. Повторная отправка безвредна: бэк-офис считает
# ключ повтора сам, дважды ничего не запишется.
ХВОСТ_ПРОШЛОГО_МЕСЯЦА_ДНЕЙ = 5


def main() -> None:
    if "--что-там" in sys.argv:
        с = запрос("/api/finance/import")
        print("Бэк-офис знает:")
        print(f"  платежей: {с['операций']}")
        print(f"  дней:     {с['дней']}")
        print(f"  период:   {с['первыйДень'] or '—'} — {с['последнийДень'] or '—'}")
        for и in с["источники"]:
            print(f"  {и['source']}: заполнено по {и['filledTo']}")
        return

    месяцы = [a for a in sys.argv[1:] if not a.startswith("--")]
    if "--всё" in sys.argv:
        цели: list[str | None] = [None]
    elif месяцы:
        цели = [месяцы[0]]
    else:
        сегодня = date.today()
        цели = [сегодня.strftime("%Y-%m")]
        if сегодня.day <= ХВОСТ_ПРОШЛОГО_МЕСЯЦА_ДНЕЙ:
            прошлый = (сегодня.replace(day=1) - timedelta(days=1)).strftime("%Y-%m")
            # Прошлый месяц первым: он закрыт, и если в нём чего-то не хватает,
            # это видно сразу, а не после отчёта за текущий.
            цели.insert(0, прошлый)

    for номер, м in enumerate(цели):
        if номер:
            print()
        отправить(м)


if __name__ == "__main__":
    main()
