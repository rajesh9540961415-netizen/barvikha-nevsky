#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Пачка правок чаевых через служебную дверь бэк-офиса.

Зачем. Сверка августа с листом управляющего (06.09.2026) дала 105 правок
получателя, отмену за 26.08 и 36 записей кальянного бара. Через экран это
500–600 действий мышью подряд по живой базе.

⚠️ Скрипт НЕ пишет в базу. Он отправляет список операций в `/api/tips-fix`,
а тот вызывает те же «поправить», «отменить» и «завести запись», что и экран,
со всеми проверками и следом. Правки подписаны служебной записью
«Сверка по ключу», войти под которой нельзя.

⚠️ Номера людей. В приложении один человек может быть заведён дважды: из кассы
и вписанным руками. Какой номер лежит в записях конкретного дня — заранее
не видно, поэтому замена отправляется на оба номера, а сверяется по числу
сделанных правок: оно должно совпасть с ожидаемым. Не совпало — разбираться,
а не гнать дальше.

Запуск:
    python3 scripts/tips_fix.py --что-будет      # только показать список
    python3 scripts/tips_fix.py --день 2026-08-08
    python3 scripts/tips_fix.py --всё
"""
from __future__ import annotations

import argparse
import json
import os
import sys
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
from seti import достучаться  # noqa: E402

АДРЕС = "https://office.barvikha-nevsky.ru/api/tips-fix"

ПОЧЕМУ = (
    "Сверка 06.09.2026 с листом управляющего. Решение владельца: эталон "
    "августа — отчёт управляющего."
)
ПОЧЕМУ_БАР = (
    "Внесено 06.09.2026 по листу управляющего: до 19 августа кальянного бара "
    "в приложении не было. Вид денег в листе не указан, записано наличными."
)

# Номера людей в приложении. Двойные — потому что человек может быть заведён
# и из кассы, и руками; какой номер в записях дня, покажет прогон.
ПАРХОМЕНКО = 916
ГОРБУНОВ = (919, -4)
САБЛИНА = (918, -5)
САМАРИНА = (-6,)
ГЕРАЩЕНКО = (900,)
СТАРОСТИНА = 873
ЩЕЛЯПА = 611
КОНОНОВСКАЯ = 822

# (день, кого меняем, на кого, сколько записей ждём)
ЗАМЕНЫ = [
    ("2026-08-08", ГОРБУНОВ, ПАРХОМЕНКО, 9),
    ("2026-08-07", ГОРБУНОВ, ПАРХОМЕНКО, 18),
    ("2026-08-07", ГЕРАЩЕНКО, СТАРОСТИНА, 17),
    ("2026-08-09", САБЛИНА, ПАРХОМЕНКО, 11),
    ("2026-08-13", САМАРИНА, ПАРХОМЕНКО, 14),
    ("2026-08-16", САМАРИНА, ПАРХОМЕНКО, 19),
    ("2026-08-27", САБЛИНА, ЩЕЛЯПА, 17),
]

ОТМЕНЫ = [("2026-08-26", КОНОНОВСКАЯ, 4)]

# День → (чаевые, сервисный сбор) по листу управляющего.
БАР = {
    "2026-08-01": (3200, 1290), "2026-08-02": (1100, 1600),
    "2026-08-03": (1005, 1200), "2026-08-05": (1500, 0),
    "2026-08-06": (500, 270),   "2026-08-07": (1250, 2100),
    "2026-08-08": (1800, 1390), "2026-08-09": (500, 650),
    "2026-08-10": (250, 1000),  "2026-08-11": (1300, 0),
    "2026-08-12": (1080, 0),    "2026-08-13": (300, 0),
    "2026-08-14": (750, 720),   "2026-08-15": (1950, 0),
    "2026-08-16": (500, 850),   "2026-08-17": (150, 4010),
    "2026-08-18": (1550, 1870), "2026-08-27": (1000, 3130),
}


def ключ() -> str:
    значение = os.environ.get("TIPS_FIX_KEY")
    if значение:
        return значение
    for строка in (ROOT / ".env").read_text(encoding="utf-8").splitlines():
        if строка.startswith("TIPS_FIX_KEY="):
            return строка.split("=", 1)[1].strip().strip('"').strip("'")
    sys.exit("✗ Нет TIPS_FIX_KEY ни в окружении, ни в .env")


def отправить(операции: list[dict]) -> dict:
    запрос = urllib.request.Request(
        АДРЕС,
        data=json.dumps({"операции": операции}, ensure_ascii=False).encode("utf-8"),
        method="POST",
        headers={"X-Tips-Fix-Key": ключ(), "Content-Type": "application/json"},
    )
    try:
        return json.loads(достучаться(запрос, таймаут=180))
    except urllib.error.HTTPError as e:
        sys.exit(f"✗ Бэк-офис ответил {e.code}: {e.read().decode('utf-8', 'replace')[:300]}")


def замены_дня(день: str) -> list[tuple[dict, int, str]]:
    """Замена официанта за день — три шага, и порядок между ними важен.

    ⚠️ Деньги нельзя записать на человека вне состава: приложение это
    запрещает, и правильно делает. А убрать прежнего сразу нельзя — за ним
    ещё висят записи, и его доля кассира разошлась бы по остальным.

    Поэтому: добавить нового в состав → перенести записи → убрать прежнего.
    """
    вышло = []
    for д, кого, на_кого, ждём in ЗАМЕНЫ:
        if д != день:
            continue
        вышло.append((
            {"вид": "состав", "день": д, "добавить": [на_кого], "почему": ПОЧЕМУ},
            1, f"{д} · в состав добавлен №{на_кого}",
        ))
        for номер in кого:
            вышло.append((
                {"вид": "замена", "день": д, "с": номер, "на": на_кого, "почему": ПОЧЕМУ},
                ждём, f"{д} · замена №{номер} → №{на_кого}",
            ))
        вышло.append((
            {"вид": "состав", "день": д, "убрать": list(кого), "почему": ПОЧЕМУ},
            1, f"{д} · из состава убран(ы) №{', №'.join(str(n) for n in кого)}",
        ))
    return вышло


def бар_дня(день: str) -> list[tuple[dict, int, str]]:
    чай, сбор = БАР.get(день, (0, 0))
    вышло = []
    if чай:
        вышло.append(({"вид": "бар", "день": день, "время": "23:00", "деньги": "cash",
                       "сумма": чай, "почему": ПОЧЕМУ_БАР}, 1,
                      f"{день} · бар, чаевые {чай:,} ₽"))
    if сбор:
        вышло.append(({"вид": "бар", "день": день, "время": "23:05", "деньги": "service",
                       "сумма": сбор, "почему": ПОЧЕМУ_БАР}, 1,
                      f"{день} · бар, сервисный сбор {сбор:,} ₽"))
    return вышло


def отмены_дня(день: str) -> list[tuple[dict, int, str]]:
    return [({"вид": "отмена", "день": д, "кто": кто, "почему": ПОЧЕМУ}, ждём,
             f"{д} · отмена записей №{кто}")
            for д, кто, ждём in ОТМЕНЫ if д == день]


def все_дни() -> list[str]:
    дни = {д for д, *_ in ЗАМЕНЫ} | {д for д, *_ in ОТМЕНЫ} | set(БАР)
    return sorted(дни)


def main() -> None:
    parser = argparse.ArgumentParser(description="Пачка правок чаевых.")
    parser.add_argument("--день", help="только этот день, вида 2026-08-08")
    parser.add_argument("--всё", action="store_true", help="все дни подряд")
    parser.add_argument("--что-будет", action="store_true", help="показать и не отправлять")
    parser.add_argument("--без-бара", action="store_true", help="пропустить записи бара")
    args = parser.parse_args()

    дни = [args.день] if args.день else (все_дни() if args.всё else [])
    if not дни:
        sys.exit("Укажите --день или --всё")

    задания: list[tuple[dict, int, str]] = []
    for день in дни:
        задания += замены_дня(день) + отмены_дня(день)
        if not args.без_бара:
            задания += бар_дня(день)

    if args.что_будет:
        for _, ждём, подпись in задания:
            print(f"  {подпись}   ждём записей: {ждём}")
        print(f"\nвсего операций: {len(задания)}")
        return

    сделано_всего = 0
    for операция, ждём, подпись in задания:
        ответ = отправить([операция])
        итог = ответ["итоги"][0]
        сделано = итог["сделано"]
        сделано_всего += сделано
        метка = "✓" if сделано else "·"
        print(f"{метка} {подпись}: правок {сделано}")
        for отказ in итог["отказы"]:
            print(f"    ⚠ {отказ}")
    print(f"\nвсего правок: {сделано_всего}")
    print(f"подписано: {ответ.get('подписано')}")


if __name__ == "__main__":
    main()
