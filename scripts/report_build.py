#!/usr/bin/env python3
"""Собирает отчёт по чаевым за месяц — блок на каждого сотрудника.

Заменяет пару report_new.py + report_fill.py для ежедневной сборки.
Те делали пустой шаблон и потом заполняли его; здесь так нельзя: состав
строк у человека зависит от того, чем он занимался. У официанта нет строк
администратора, у администратора нет строк чаевых. Значит лист надо
СОБИРАТЬ из данных, а не заполнять заранее нарисованный.

Устройство листа, решение владельца 11.08.2026:

    СВОДНАЯ ТАБЛИЦА            итоги дня по видам денег, выручка, процент
    ФАМИЛИЯ ИМЯ                строка-заголовок: на руки по дням и за месяц
      чаевые наличные          ↓ только те строки, где у человека есть деньги
      чаевые терминал
      чаевые QR
      сервисный сбор
      ЧАЕВЫЕ ВСЕГО             сумма четырёх строк выше
      начислено                что осталось после долей администратору и кассиру
      доля администратора      получено за работу администратором
      доля кассира             получено за работу кассиром

Блок сворачивается кнопкой слева. В свёрнутом виде лист — это список людей
с их заработком по дням, ровно то, чего не хватало в прежней раскладке:
там, чтобы собрать одного человека, приходилось читать пять блоков.

Данные берёт из выгрузок смен, которые кладёт report_pull.py.
Выручку — из обеих касс Quick Resto, как report_revenue.py.

Запуск:
    python3 scripts/report_build.py            # месяц вчерашнего дня
    python3 scripts/report_build.py 2026-08    # конкретный месяц
    python3 scripts/report_build.py 2026-08 --без-выручки   # не ходить в кассы
"""

from __future__ import annotations

import calendar
import json
import sys
from collections import defaultdict
from datetime import date, timedelta
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from openpyxl import Workbook  # noqa: E402
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side  # noqa: E402
from openpyxl.utils import get_column_letter  # noqa: E402

from report_path import describe, report_dir  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
ВЫГРУЗКИ = ROOT / "data" / "выгрузки-смен"

МЕСЯЦЫ = ("январь февраль март апрель май июнь июль "
          "август сентябрь октябрь ноябрь декабрь").split()

ШРИФТ = "Arial"
РАМКА = Border(*[Side("thin", color="D9D9D9")] * 4)
ЖЁЛТЫЙ = PatternFill("solid", fgColor="FFFFCC")
ЗАГОЛОВОК_ЧЕЛОВЕКА = PatternFill("solid", fgColor="DDEBF7")
ШАПКА = PatternFill("solid", fgColor="D9D9D9")

# Строки внутри блока человека: подпись → поле в выгрузке.
#
# Порядок неслучаен: сначала откуда деньги пришли, потом что человек получил.
# «ЧАЕВЫЕ ВСЕГО» стоит после четырёх видов, потому что подводит их итог,
# а не открывает список.
ВИДЫ = [
    ("чаевые наличные", "cash"),
    ("чаевые терминал", "terminal"),
    ("чаевые QR", "qr"),
    ("сервисный сбор", "service"),
]
ИТОГ_ЧАЕВЫХ = "ЧАЕВЫЕ ВСЕГО"
ВЫПЛАТЫ = [
    ("начислено", "accrued"),
    ("доля администратора", "admin"),
    ("доля кассира", "cashier"),
]


def читать_смены(месяц: str) -> dict[str, dict[str, dict[str, float]]]:
    """{имя: {день: {поле: сумма}}} из файлов выгрузок за месяц."""
    люди: dict[str, dict[str, dict[str, float]]] = defaultdict(
        lambda: defaultdict(lambda: defaultdict(float))
    )
    файлы = sorted(ВЫГРУЗКИ.glob(f"смена-{месяц}-*.json"))
    if not файлы:
        sys.exit(
            f"Нет выгрузок за {месяц} в {ВЫГРУЗКИ}.\n"
            f"  Сначала: python3 scripts/report_pull.py --month {месяц}"
        )

    for путь in файлы:
        d = json.loads(путь.read_text(encoding="utf-8"))
        день = d["businessDay"]
        for w in d.get("waiters", []):
            for _, поле in ВИДЫ:
                люди[w["name"]][день][поле] += w.get(поле, 0)
            # Выгрузки до 08.08.2026 звали начисленное полем `net`.
            люди[w["name"]][день]["accrued"] += w.get("accrued", w.get("net", 0))
        for роль in ("admin", "cashier"):
            кто = d.get(роль) or {}
            if кто.get("name") and кто.get("amount"):
                люди[кто["name"]][день][роль] += кто["amount"]
    return люди


def выручка(месяц: str) -> dict[str, float]:
    """Сумма по обеим кассам Quick Resto по дням. Пусто — если касса молчит."""
    from qr_sales import CLOUDS, business_day, fetch_shifts, read_env

    по_дням: dict[str, float] = defaultdict(float)
    for cloud, (_, название) in CLOUDS.items():
        всего = 0.0
        for s in fetch_shifts(read_env(cloud)):
            d = business_day(s)
            if not d or s.get("status") != "CLOSED" or d.strftime("%Y-%m") != месяц:
                continue
            сумма = ((s.get("totalCash") or 0) - (s.get("totalReturnCash") or 0)
                     + (s.get("totalCard") or 0) - (s.get("totalReturnCard") or 0))
            по_дням[d.isoformat()] += сумма
            всего += сумма
        print(f"  {название:<14} {всего:>14,.0f} ₽".replace(",", " "))
    return по_дням


def построить(месяц: str, брать_выручку: bool = True) -> Path:
    год, мес = (int(x) for x in месяц.split("-"))
    дней = calendar.monthrange(год, мес)[1]
    дни = [date(год, мес, d).isoformat() for d in range(1, дней + 1)]

    люди = читать_смены(месяц)
    деньги = {}
    if брать_выручку:
        print("Выручка:")
        деньги = выручка(месяц)

    wb = Workbook()
    ws = wb.active
    ws.title = f"{МЕСЯЦЫ[мес - 1].capitalize()} {год}"

    ПЕРВЫЙ, ПОСЛЕДНИЙ = 2, 1 + дней
    К_СМЕН = ПОСЛЕДНИЙ + 1
    К_ЧАЙ = К_СМЕН + 1
    К_ОКЛАД = К_ЧАЙ + 1
    К_ПРЕМИЯ = К_ОКЛАД + 1
    К_ДОХОД = К_ПРЕМИЯ + 1
    К_СРЕДНИЙ = К_ДОХОД + 1
    Б = lambda c: get_column_letter(c)  # noqa: E731

    # ── шапка ────────────────────────────────────────────────────────────
    ws.cell(1, 1, "Сотрудник").font = Font(name=ШРИФТ, bold=True, size=10)
    for i, д in enumerate(дни):
        c = ws.cell(1, ПЕРВЫЙ + i, f"{д[8:10]}.{д[5:7]}.{д[:4]}")
        c.font = Font(name=ШРИФТ, bold=True, size=9)
        c.alignment = Alignment(horizontal="center", wrap_text=True)
    for col, имя in (
        (К_СМЕН, "Кол-во смен"), (К_ЧАЙ, "Общий чай за месяц"),
        (К_ОКЛАД, "Оклад сотрудника (выходы в смену)"),
        (К_ПРЕМИЯ, "Сумма мотиваций, премий сотрудника"),
        (К_ДОХОД, "Итого доход сотрудника:"), (К_СРЕДНИЙ, "Средний чай за смену"),
    ):
        c = ws.cell(1, col, имя)
        c.font = Font(name=ШРИФТ, bold=True, size=9)
        c.alignment = Alignment(horizontal="center", wrap_text=True)
    for col in range(1, К_СРЕДНИЙ + 1):
        ws.cell(1, col).fill = ШАПКА
        ws.cell(1, col).border = РАМКА

    # ── сводная таблица ──────────────────────────────────────────────────
    #
    # Считается по подписям строк через SUMIF, а не по номерам блоков:
    # блоки теперь у каждого человека свои, и жёсткие номера строк
    # разъезжались бы при каждом новом сотруднике.
    СВОД = [
        "Общий чай всего", "Чаевые наличные", "Чаевые терминал", "Чаевые QR",
        "Сервисный сбор", "Итого распределено", "Начислено официантам",
        "На руки администраторам", "На руки кассирам", "Расхождение",
        "Выручка", "% чаевых от выручки",
    ]
    ЖИРНЫЕ = {"Общий чай всего", "Итого распределено", "Расхождение"}
    строки_свода = {}
    r = 3
    for имя in СВОД:
        строки_свода[имя] = r
        c = ws.cell(r, 1, имя)
        c.font = Font(name=ШРИФТ, bold=имя in ЖИРНЫЕ, size=10)
        c.border = РАМКА
        r += 1
    начало_людей = r + 1

    # ── блоки людей ──────────────────────────────────────────────────────
    #
    # Порядок — по убыванию заработка: наверху те, о ком чаще спрашивают.
    def получил(имя: str) -> float:
        return sum(д.get(п, 0) for д in люди[имя].values()
                   for п in ("accrued", "admin", "cashier"))

    r = начало_людей
    for имя in sorted(люди, key=lambda n: -получил(n)):
        по_дням = люди[имя]
        if not получил(имя) and not any(
            д.get(п, 0) for д in по_дням.values() for _, п in ВИДЫ
        ):
            continue  # человек в выгрузке есть, а денег нет — строку не заводим

        шапка_строка = r
        r += 1
        первая = r

        # Только те строки, где у человека вправду есть деньги. Пустые
        # строки у официанта («доля администратора» = 0 все тридцать дней)
        # ничего не сообщают, а лист удлиняют вдвое.
        подписи: list[str] = []
        for подпись, поле in ВИДЫ:
            if any(д.get(поле, 0) for д in по_дням.values()):
                for i, день in enumerate(дни):
                    ws.cell(r, ПЕРВЫЙ + i, round(по_дням.get(день, {}).get(поле, 0), 2) or None)
                ws.cell(r, 1, подпись).font = Font(name=ШРИФТ, size=10)
                подписи.append(подпись)
                r += 1

        # «ЧАЕВЫЕ ВСЕГО» — формулой, чтобы правка в строке вида денег
        # сразу отражалась в итоге, а не расходилась с ним молча.
        if подписи:
            ws.cell(r, 1, ИТОГ_ЧАЕВЫХ).font = Font(name=ШРИФТ, bold=True, size=10)
            for i in range(дней):
                L = Б(ПЕРВЫЙ + i)
                ws.cell(r, ПЕРВЫЙ + i,
                        f"=SUM({L}{первая}:{L}{r - 1})").font = Font(name=ШРИФТ, bold=True, size=10)
            r += 1

        for подпись, поле in ВЫПЛАТЫ:
            if any(д.get(поле, 0) for д in по_дням.values()):
                for i, день in enumerate(дни):
                    ws.cell(r, ПЕРВЫЙ + i, round(по_дням.get(день, {}).get(поле, 0), 2) or None)
                ws.cell(r, 1, подпись).font = Font(name=ШРИФТ, size=10)
                r += 1

        последняя = r - 1
        for x in range(первая, последняя + 1):
            ws.row_dimensions[x].outlineLevel = 1
            for col in range(1, К_СРЕДНИЙ + 1):
                ws.cell(x, col).border = РАМКА
                if col >= ПЕРВЫЙ:
                    ws.cell(x, col).number_format = "#,##0"

        # Строка-заголовок: «на руки» по дням. Это то, что человек реально
        # получил за вечер, — самое частое, о чём спрашивают. В свёрнутом
        # виде лист превращается ровно в такую таблицу.
        ws.cell(шапка_строка, 1, имя).font = Font(name=ШРИФТ, bold=True, size=10)
        выплатные = [x for x in range(первая, последняя + 1)
                     if ws.cell(x, 1).value in {п for п, _ in ВЫПЛАТЫ}]
        for i in range(дней):
            L = Б(ПЕРВЫЙ + i)
            формула = ("=" + "+".join(f"{L}{x}" for x in выплатные)) if выплатные else None
            c = ws.cell(шапка_строка, ПЕРВЫЙ + i, формула)
            c.font = Font(name=ШРИФТ, bold=True, size=10)
            c.number_format = "#,##0"

        # Правые колонки — на строке человека, а не на каждой строке вида
        # денег: оклад платят человеку, а не его наличным чаевым.
        Д = f"{Б(ПЕРВЫЙ)}{шапка_строка}:{Б(ПОСЛЕДНИЙ)}{шапка_строка}"
        ws.cell(шапка_строка, К_СМЕН, f'=COUNTIF({Д},">0")')
        чай_строка = next((x for x in range(первая, последняя + 1)
                           if ws.cell(x, 1).value == ИТОГ_ЧАЕВЫХ), None)
        if чай_строка:
            ws.cell(шапка_строка, К_ЧАЙ,
                    f"=SUM({Б(ПЕРВЫЙ)}{чай_строка}:{Б(ПОСЛЕДНИЙ)}{чай_строка})")
        ws.cell(шапка_строка, К_ОКЛАД).fill = ЖЁЛТЫЙ
        ws.cell(шапка_строка, К_ПРЕМИЯ).fill = ЖЁЛТЫЙ
        ws.cell(шапка_строка, К_ДОХОД,
                f"=SUM({Д})+{Б(К_ОКЛАД)}{шапка_строка}+{Б(К_ПРЕМИЯ)}{шапка_строка}")
        ws.cell(шапка_строка, К_СРЕДНИЙ,
                f"=IFERROR({Б(К_ЧАЙ)}{шапка_строка}/{Б(К_СМЕН)}{шапка_строка},0)")
        for col in range(1, К_СРЕДНИЙ + 1):
            ws.cell(шапка_строка, col).fill = ЗАГОЛОВОК_ЧЕЛОВЕКА
            ws.cell(шапка_строка, col).border = РАМКА
            if col >= К_СМЕН:
                ws.cell(шапка_строка, col).number_format = "#,##0"
                ws.cell(шапка_строка, col).font = Font(name=ШРИФТ, bold=True, size=10)
        r += 1

    конец = r
    # ── формулы сводной ──────────────────────────────────────────────────
    ПОД = {"Чаевые наличные": "чаевые наличные", "Чаевые терминал": "чаевые терминал",
           "Чаевые QR": "чаевые QR", "Сервисный сбор": "сервисный сбор",
           "Начислено официантам": "начислено",
           "На руки администраторам": "доля администратора",
           "На руки кассирам": "доля кассира"}
    for i in range(дней):
        L = Б(ПЕРВЫЙ + i)
        Я = f"$A${начало_людей}:$A${конец}"
        З = f"{L}${начало_людей}:{L}${конец}"
        для = lambda п: f'SUMIF({Я},"{п}",{З})'  # noqa: E731
        for имя, подпись in ПОД.items():
            ws.cell(строки_свода[имя], ПЕРВЫЙ + i, f"={для(подпись)}")
        ws.cell(строки_свода["Общий чай всего"], ПЕРВЫЙ + i,
                "=" + "+".join(для(п) for _, п in
                               [(0, "чаевые наличные"), (0, "чаевые терминал"),
                                (0, "чаевые QR"), (0, "сервисный сбор")]))
        ws.cell(строки_свода["Итого распределено"], ПЕРВЫЙ + i,
                "=" + "+".join(для(п) for п in
                               ("начислено", "доля администратора", "доля кассира")))
        # Округляем: таблица складывает десятки ячеек, и в последнем знаке
        # набегает пыль двоичной арифметики. Красное «−0» без причины учит
        # не смотреть на красное — и тогда настоящую пропажу пропустят.
        ws.cell(строки_свода["Расхождение"], ПЕРВЫЙ + i,
                f"=ROUND({L}{строки_свода['Общий чай всего']}"
                f"-{L}{строки_свода['Итого распределено']},2)")
        ws.cell(строки_свода["Выручка"], ПЕРВЫЙ + i,
                round(деньги.get(дни[i], 0), 2) or None)
        ws.cell(строки_свода["% чаевых от выручки"], ПЕРВЫЙ + i,
                f"=IFERROR({L}{строки_свода['Общий чай всего']}"
                f"/{L}{строки_свода['Выручка']},0)")

    for имя, стр in строки_свода.items():
        for col in range(ПЕРВЫЙ, К_СРЕДНИЙ + 1):
            c = ws.cell(стр, col)
            c.border = РАМКА
            c.font = Font(name=ШРИФТ, bold=имя in ЖИРНЫЕ, size=10)
            c.number_format = "0.0%" if имя == "% чаевых от выручки" else "#,##0"
        ws.cell(стр, К_ЧАЙ,
                f"=SUM({Б(ПЕРВЫЙ)}{стр}:{Б(ПОСЛЕДНИЙ)}{стр})")
        if имя == "Расхождение":
            ws.cell(стр, К_ЧАЙ).number_format = '#,##0.00;[Red]-#,##0.00;"—"'
        for col in range(ПЕРВЫЙ, ПОСЛЕДНИЙ + 1):
            if имя == "Расхождение":
                ws.cell(стр, col).number_format = '#,##0.00;[Red]-#,##0.00;"—"'

    # ── вид ──────────────────────────────────────────────────────────────
    ws.freeze_panes = "B3"
    ws.column_dimensions["A"].width = 32
    for col in range(ПЕРВЫЙ, ПОСЛЕДНИЙ + 1):
        ws.column_dimensions[Б(col)].width = 11
    for col in range(К_СМЕН, К_СРЕДНИЙ + 1):
        ws.column_dimensions[Б(col)].width = 14
    ws.sheet_properties.outlinePr.summaryBelow = False

    путь = report_dir() / f"Чаевые-дубль-{МЕСЯЦЫ[мес - 1]}-{год}.xlsx"
    wb.save(путь)
    return путь


def main() -> None:
    аргументы = [a for a in sys.argv[1:] if not a.startswith("--")]
    без_выручки = "--без-выручки" in sys.argv
    месяц = аргументы[0] if аргументы else (
        date.today() - timedelta(days=1)).strftime("%Y-%m")

    путь = построить(месяц, брать_выручку=not без_выручки)
    print(f"\nСобрано: {путь.name}")
    print(f"Папка: {describe(путь.parent)}")
    print("Блоки сворачиваются кнопками слева: свёрнутый лист — "
          "заработок каждого по дням.")


if __name__ == "__main__":
    main()
