def предупредить_о_ручных(данные) -> None:
    """Говорит, кого вписали руками, — там и живут двойники.

    Не гадаем похожестью имён: настоящий случай её обманывает — «Лиза Н.»
    и «Елизавета Недорезова» не совпадают ни одной буквой в имени. Поэтому
    просто показываем всех, кого нет в кассе, и владелец решает сама.
    """
    try:
        касса = {p["name"] for p in json.loads(
            СПИСОК_КАССЫ.read_text(encoding="utf-8"))}
    except OSError:
        return

    # Считаем ТОЛЬКО то, что человек получил на руки: «чистое» у официанта,
    # «отчисления» у администратора и кассира. Складывать подряд все поля
    # нельзя — виды чаевых и чистая сумма это одни и те же деньги на разных
    # стадиях, и сумма выходит вдвое больше правды. 11.08.2026 так и вышло:
    # у «Дарьи Б.» напечаталось 54 088 ₽ вместо настоящих 23 720 ₽.
    ручные = {}
    for роль, люди in данные.items():
        for имя, по_дням in люди.items():
            if имя in касса or имя in СКЛЕЙКА.values():
                continue
            получено = sum(с.get("чистое", 0) + с.get("отчисления", 0)
                           for с in по_дням.values())
            ручные[имя] = ручные.get(имя, 0) + получено

    if not ручные:
        return
    print("\n⚠ Вписаны руками, в Quick Resto их нет:")
    for имя, сумма in sorted(ручные.items(), key=lambda x: -x[1]):
        print(f"    {имя:<26} {сумма:>12,.0f} ₽".replace(",", " "))
    print("  Проверьте, не двойники ли это кого-то из кассы. Если да —")
    print("  впишите решение в словарь СКЛЕЙКА в scripts/report_build.py.")
    print("  И лучше завести человека в Quick Resto: тогда новые смены")
    print("  сразу пойдут под правильным именем.")


def предупредить_о_безымянных(потери) -> None:
    """Кричит о роли, чьё имя не нашлось НИГДЕ — ни в приложении, ни в словаре.

    ⚠️ Зачем отдельная проверка, а не «и так видно». Не видно ничем. Роль без
    имени просто не попадает в отчёт: у кассира она пропадала совершенно
    молча, у администратора — с предупреждением про split.ts, которое говорит
    о правилах деления и на пропавшее имя не показывает вовсе. Так за август
    2026 потерялись 44 998,72 ₽, и нашла их сверка, а не отчёт.

    💡 Молчание тут неотличимо от порядка: строка отчёта, где человека нет,
    выглядит нормальной пустотой. Поэтому говорим ДО того, как деньги
    выпадут, называем сумму и прямо пишем, что делать.
    """
    if not потери:
        return
    всего = sum(с for _, _, с in потери)
    print(f"\n🔴 ДЕНЬГИ БЕЗ ПОЛУЧАТЕЛЯ — {всего:,.2f} ₽. В отчёт они НЕ попали:"
          .replace(",", " "))
    for день, роль, сумма in потери:
        print(f"    {день}  {роль:<16} {сумма:>12,.2f} ₽".replace(",", " "))
    print("  Смена хранит номер человека, а имя ищется по кассе Quick Resto")
    print("  и по вписанным руками. Номер осиротел — имени нет.")
