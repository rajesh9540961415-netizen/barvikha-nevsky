def читать_смены(месяц: str):
    """Разбирает выгрузки: официанты, администраторы, кассиры.

    Возвращает {роль: {имя: {день: {поле: сумма}}}}.
    """
    данные = {роль: defaultdict(lambda: defaultdict(lambda: defaultdict(float)))
              for роль in РОЛИ}
    # Роли, чьё имя не нашлось ни в приложении, ни в словаре БЕЗ_ИМЕНИ.
    # Копим весь месяц и говорим разом: одна строка на день терялась бы
    # среди прочего вывода, а список в конце виден.
    потери: list[tuple[str, str, float]] = []

    файлы = sorted(ВЫГРУЗКИ.glob(f"смена-{месяц}-*.json"))
    if not файлы:
        sys.exit(
            f"Нет выгрузок за {месяц} в {ВЫГРУЗКИ}.\n"
            f"  Сначала: python3 scripts/report_pull.py --month {месяц}"
        )

    for путь in файлы:
        d = json.loads(путь.read_text(encoding="utf-8"))
        день = d["businessDay"]

        for w in d.get("waiters", []):
            куда = данные["ОФИЦИАНТЫ"][свести(w["name"])][день]
            for _, поле in ВИДЫ:
                куда[поле] += w.get(поле, 0)
            # Выгрузки до 08.08.2026 звали чистую сумму полем `net`.
            куда["чистое"] += w.get("accrued", w.get("net", 0))

        # Хостес и кальянный бар.
        #
        # Поле `total` — это и есть чистое: делить не с кем, ни порога,
        # ни отчислений здесь нет, поэтому «Начислено» и «Итого» у них
        # совпадают, и так и должно быть.
        #
        # ⚠️ Графы те же четыре, что у официантов, — включая терминал.
        # До 20.08.2026 терминала здесь не читали вовсе: своего терминала
        # у бара и хостес нет. Но гость платит на ЗАЛЬНОМ терминале и просит
        # поделить чаевые с кальянщиком — такая доля есть, и без этой графы
        # она не попала бы в отчёт ни одной цифрой. Заметить это можно было бы
        # только по «Расхождению»: сводка складывает графы по ВСЕМ блокам.
        #
        # ⚠️ Блоки появились в выгрузке 18.08.2026. У смен до этого дня их
        # нет — и пустой блок значит «приложение тогда их не вело», а не
        # «люди не работали». Разница важная: первое чинится временем,
        # второе искать не надо.
        for ключ, роль in БОКОВЫЕ.items():
            for строка in (d.get(ключ) or {}).get("rows", []):
                куда = данные[роль][свести(строка["name"])][день]
                for _, поле in ВИДЫ:
                    куда[поле] += строка.get(поле, 0)
                куда["чистое"] += строка.get("total", 0)

        # Кальянный бар до того, как приложение начало его вести.
        #
        # Приложение знает бар только с 19.08.2026 — раньше контура не было,
        # и внести те смены задним числом нечем: «завести запись» умеет
        # только зальный котёл. А деньги были: их вёл управляющий в таблице УК.
        # Задача владельца 21.08.2026 — поднять их с бумаги и внести.
        #
        # ⚠️ Берём ТОЛЬКО дни, которых у приложения нет. За 19 августа обе
        # стороны дают одно и то же (250 и 540) — сложи мы их, вышло бы вдвое.
        # Поэтому условие не «есть ли день в словаре», а «молчит ли приложение».
        if not (d.get("hookah") or {}).get("rows"):
            с_листа = БАР_С_ЛИСТА.get(день)
            if с_листа:
                нал, сбор, qr = с_листа
                куда = данные["КАЛЬЯННЫЙ БАР"][свести(ВЕСЬ_БАР)][день]
                # Где вид денег с листа непонятен — кладём наличными: решение
                # владельца 21.08.2026, «если нет понятия, каким способом
                # оставили, оставляешь в наличке». Где понятен — по нему.
                куда["cash"] += нал
                куда["service"] += сбор
                куда["qr"] += qr
                куда["чистое"] += нал + сбор + qr

        # Сколько из доли администратора пришло с сервисного сбора.
        #
        # Задача владельца 14.08.2026: «понимать, сколько администратор получает
        # именно со сбора». Отдельного правила для этого не нужно — оно следует
        # из действующего: доля считается от чаевых ВМЕСТЕ со сбором, значит
        # часть со сбора это те же 20 % от сбора у тех, кто перешагнул порог.
        #
        # ⚠️ У кассира такой строки не будет, и это не недоделка: его доля —
        # фиксированная сумма за официанта, процентом не считается и от сбора
        # не зависит. Сбор влияет на него лишь косвенно, через порог.
        со_сбора = проверка = 0.0
        for w in d.get("waiters", []):
            итого = sum(w.get(поле, 0) for _, поле in ВИДЫ)
            if итого >= ПОРОГ:
                со_сбора += w.get("service", 0) * ДОЛЯ_АДМИНА
                проверка += итого * ДОЛЯ_АДМИНА

        # Администраторов за смену может быть двое: с августа 2026 смену
        # делят надвое, и доля делится ПОПОЛАМ. Берём список `admins` —
        # он появился в выгрузке 18.08.2026 и содержит всех.
        #
        # ⚠️ Одиночное поле `admin` для этого больше не годится: в нём лежит
        # ПЕРВЫЙ администратор и ЕГО ПОЛОВИНА. Читать его как всю долю смены
        # значило бы потерять деньги второго — 5 августа так потерялись бы
        # 2 657,34 ₽, и ни одна строка отчёта об этом не сказала бы.
        # Запасной путь оставлен ради смен, выгруженных до 18.08.2026.
        админы = [
            a for a in (d.get("admins") or [d.get("admin") or {}])
            if a.get("amount")
        ]
        # Имени нет — берём решение владельца из БЕЗ_ИМЕНИ. Подставляем
        # только когда безымянный один: двоим одно имя не раздашь, а гадать,
        # кому из них оно принадлежит, в деньгах людей нельзя.
        безымянных = [a for a in админы if not a.get("name")]
        if len(безымянных) == 1:
            безымянных[0]["name"] = БЕЗ_ИМЕНИ.get((день, "admin"))
        # Имя не нашлось и в словаре — записываем в потери и кричим в конце.
        # Молча выбросить нельзя: это деньги, и выпадают они бесследно.
        потеряно_здесь = [a["amount"] for a in админы if not a.get("name")]
        for сумма in потеряно_здесь:
            потери.append((день, "администратор", сумма))
        админы = [a for a in админы if a.get("name")]
        всего_админам = sum(a["amount"] for a in админы)

        if админы:
            for кто in админы:
                данные["АДМИНИСТРАТОРЫ"][свести(кто["name"])][день]["отчисления"] += кто["amount"]

            # ⚠️ Сверяем СВОЙ расчёт с тем, что посчитало приложение.
            # Сойдётся — значит правило прочитано верно. Разойдётся —
            # молчать нельзя: доля со сбора тогда тоже посчитана не так.
            if abs(проверка - всего_админам) > 1:
                # ⚠️ Сперва называем настоящую причину, если она известна.
                # Прежде это сообщение выходило и тогда, когда правила
                # прочитаны верно, а не сошлось из-за выброшенного
                # безымянного, — и уводило разбор в сторону split.ts.
                причина = (
                    f" Скорее всего дело не в правилах: {len(потеряно_здесь)} "
                    f"безымянных в этот день выброшено, см. список ниже."
                    if потеряно_здесь else ""
                )
                print(f"⚠️  {день}: доля администраторов у приложения "
                      f"{всего_админам:,.2f} ₽, а по правилу из split.ts "
                      f"выходит {проверка:,.2f} ₽. Строку «{СО_СБОРА}» "
                      f"не заполняю — сначала разобраться.{причина}"
                      .replace(",", " "))
            else:
                # Часть со сбора делим между администраторами в той же
                # пропорции, что и всю долю, — то есть пополам, когда их
                # двое. Это пояснение к сумме, а не выплата, поэтому
                # копеечного дележа через shares() здесь не требуется.
                for кто in админы:
                    часть = кто["amount"] / всего_админам if всего_админам else 0
                    данные["АДМИНИСТРАТОРЫ"][свести(кто["name"])][день]["со_сбора"] += со_сбора * часть

        кассир = d.get("cashier") or {}
        имя_кассира = кассир.get("name") or БЕЗ_ИМЕНИ.get((день, "cashier"))
        if имя_кассира and кассир.get("amount"):
            данные["КАССИРЫ"][свести(имя_кассира)][день]["отчисления"] += кассир["amount"]
        elif кассир.get("amount"):
            потери.append((день, "кассир", кассир["amount"]))

    предупредить_о_безымянных(потери)
    предупредить_о_ручных(данные)
    return данные


def выручка(месяц: str) -> dict[str, float]:
    """Сумма по обеим кассам Quick Resto по дням.

    ⚠️ Отбор по залу — через `наша_смена` из `qr_sales`, а НЕ своими руками.
    До 22.08.2026 здесь его не было вовсе, и в отчёт по чаевым за 21.08
    попадало 366 750 ₽ чужой выручки: облако бара сетевое, в нём кроме
    Невского живут Митино, Красная площадь и Москва-Сити.
    """
    from qr_sales import CLOUDS, business_day, fetch_shifts, наша_смена, read_env

    по_дням: dict[str, float] = defaultdict(float)
    for cloud, (_, название) in CLOUDS.items():
        всего = 0.0
        чужих = 0.0
        for s in fetch_shifts(read_env(cloud)):
            d = business_day(s)
            if not d or s.get("status") != "CLOSED" or d.strftime("%Y-%m") != месяц:
                continue
            if not наша_смена(s):
                чужих += ((s.get("totalCash") or 0) - (s.get("totalReturnCash") or 0)
                          + (s.get("totalCard") or 0) - (s.get("totalReturnCard") or 0))
                continue
            сумма = ((s.get("totalCash") or 0) - (s.get("totalReturnCash") or 0)
                     + (s.get("totalCard") or 0) - (s.get("totalReturnCard") or 0))
            по_дням[d.isoformat()] += сумма
            всего += сумма
        print(f"  {название:<14} {всего:>14,.0f} ₽".replace(",", " "))
        if чужих:
            print(f"    ⚠ чужие залы облака: {чужих:,.0f} ₽ — "
                  f"в выручку не взяты".replace(",", " "))
    return по_дням


def показать_вчерашнюю_смену(данные: dict, деньги: dict, дни: list[str]) -> None:
    """Печатает итог вчерашней смены — то, о чём спрашивают каждое утро.

    Появилось 16.08.2026. Раньше этих чисел в выводе не было, а утренняя
    задача их требовала — и добывала сама: писала на ходу программу, чтобы
    открыть готовый .xlsx. Каждая такая программа просит разрешения, дать
    его в девять утра некому, и отчёт вставал на часы. Напечатать число
    здесь дешевле и надёжнее, чем разрешать задаче писать программы.

    ⚠️ Если вчерашнего дня в собираемом месяце нет — молчим: команда умеет
    собрать любой месяц, и «вчера» в июльском отчёте было бы бессмыслицей.
    """
    вчера = (date.today() - timedelta(days=1)).isoformat()
    if вчера not in дни:
        return

    def сложить(роль: str, поле: str) -> float:
        return sum(по_дням.get(вчера, {}).get(поле, 0)
                   for по_дням in данные[роль].values())

    def кто(роль: str, поле: str) -> str:
        return ", ".join(имя for имя, по_дням in данные[роль].items()
                         if по_дням.get(вчера, {}).get(поле))

    def строка(текст: str, сумма: float | None, хвост: str = "") -> None:
        число = (f"{сумма:>12,.0f} ₽".replace(",", " ")
                 if сумма is not None else f"{'—':>14}")
        print(f"  {текст:<22}{число}{хвост}")

    чай = sum(сложить(роль, поле)
              for роль in ("ОФИЦИАНТЫ", "ХОСТЕС", "КАЛЬЯННЫЙ БАР") for _, поле in ВИДЫ)
    на_руки = sum(сложить(роль, "чистое")
                  for роль in ("ОФИЦИАНТЫ", "ХОСТЕС", "КАЛЬЯННЫЙ БАР"))
    админ = сложить("АДМИНИСТРАТОРЫ", "отчисления")
    кассир = сложить("КАССИРЫ", "отчисления")

    print(f"\nВчерашняя смена, {вчера[8:10]}.{вчера[5:7]}:")

    if not (чай or админ or кассир):
        # Молчать нельзя: несостоявшаяся смена и недоехавшая выгрузка
        # выглядят одинаково — пусто. А разница между «заведение не работало»
        # и «данные не пришли» решает, надо ли что-то делать.
        print("  чаевых нет — либо смены не было, либо она не выгрузилась")
        return

    строка("Общий чай", чай)
    строка("Официантам на руки", на_руки)
    if админ:
        строка("Администратору", админ, f"  — {кто('АДМИНИСТРАТОРЫ', 'отчисления')}")
    if кассир:
        строка("Кассиру", кассир, f"  — {кто('КАССИРЫ', 'отчисления')}")

    выручка_дня = деньги.get(вчера)
    if выручка_дня:
        доля = f"{чай / выручка_дня * 100:.1f}".replace(".", ",")
        строка("Выручка", выручка_дня, f"  — чаевые {доля} % от неё")
    else:
        # Ноль здесь означал бы «продаж не было». Касса могла просто
        # не ответить, и путать эти два случая нельзя.
        строка("Выручка", None, "  касса не ответила, процент не считаю")

    смена = {имя: по_дням.get(вчера, {}).get("чистое", 0)
             for имя, по_дням in данные["ОФИЦИАНТЫ"].items()}
    смена = {имя: сумма for имя, сумма in смена.items() if сумма}
    if смена:
        лучший = max(смена, key=смена.get)
        сколько = f"{смена[лучший]:,.0f}".replace(",", " ")
        print(f"  Официантов в смене: {len(смена)},"
              f" больше всех — {лучший}, {сколько} ₽")


def построить(месяц: str, брать_выручку: bool = True) -> Path:
    год, мес = (int(x) for x in месяц.split("-"))
    дней = calendar.monthrange(год, мес)[1]
    дни = [date(год, мес, d).isoformat() for d in range(1, дней + 1)]

    данные = читать_смены(месяц)
    деньги = {}
    if брать_выручку:
        print("Выручка:")
        деньги = выручка(месяц)

    # ⚠️ Отчёт без выручки выглядит готовым, но врёт: строка «% чаевых
    # от выручки» показывает 0,0 % по всем дням, и это читается как факт,
    # а не как «данных нет». 11.08.2026 владелец увидела именно такой файл —
    # его положил мой же прогон с ключом «--без-выручки».
    #
    # Поэтому: день, в котором есть чаевые, обязан иметь выручку. Нет —
    # говорим громко и называем дни. Молчание нельзя считать нулём.
    дни_с_чаевыми = {
        день
        for люди in данные.values()
        for по_дням in люди.values()
        for день, суммы in по_дням.items()
        if any(суммы.values())
    }
    без_выручки = sorted(д for д in дни_с_чаевыми if not деньги.get(д))
    if без_выручки:
        print(
            "\n⚠ ВЫРУЧКИ НЕТ за дни, где чаевые есть: "
            + ", ".join(d[8:10] + "." + d[5:7] for d in без_выручки),
            file=sys.stderr,
        )
        print(
            "  В этих днях отчёт напишет «нет выручки» вместо процента —\n"
            "  сравнивать не с чем. Причина обычно одна из двух: касса\n"
            "  не ответила либо сборку запустили ключом «--без-выручки».\n"
            "  Пересоберите без него: python3 scripts/report_build.py " + месяц,
            file=sys.stderr,
        )

    показать_вчерашнюю_смену(данные, деньги, дни)

    wb = Workbook()
    ws = wb.active
    ws.title = f"{МЕСЯЦЫ[мес - 1].capitalize()} {год}"

    ПЕРВЫЙ, ПОСЛЕДНИЙ = 2, 1 + дней
    К_СМЕН, К_ЧАЙ = ПОСЛЕДНИЙ + 1, ПОСЛЕДНИЙ + 2
    К_ОКЛАД, К_ПРЕМИЯ = ПОСЛЕДНИЙ + 3, ПОСЛЕДНИЙ + 4
    К_ДОХОД, К_СРЕДНИЙ = ПОСЛЕДНИЙ + 5, ПОСЛЕДНИЙ + 6
    Б = get_column_letter

    # ── шапка ────────────────────────────────────────────────────────────
    ws.cell(1, 1, "Сотрудник").font = Font(name=ШРИФТ, bold=True, size=10)
    for i, д in enumerate(дни):
        c = ws.cell(1, ПЕРВЫЙ + i, f"{д[8:10]}.{д[5:7]}.{д[:4]}")
        c.font = Font(name=ШРИФТ, bold=True, size=9)
        c.alignment = Alignment(horizontal="center", wrap_text=True)
    for col, имя in (
        (К_СМЕН, "Кол-во смен"), (К_ЧАЙ, "Общий чай за месяц"),
        (К_ОКЛАД, "Оклад сотрудника"), (К_ПРЕМИЯ, "Премии, мотивации"),
        (К_ДОХОД, "Итого доход сотрудника"), (К_СРЕДНИЙ, "Средний чай за смену"),
    ):
        c = ws.cell(1, col, имя)
        c.font = Font(name=ШРИФТ, bold=True, size=9)
        c.alignment = Alignment(horizontal="center", wrap_text=True)
    for col in range(1, К_СРЕДНИЙ + 1):
        ws.cell(1, col).fill = ШАПКА
        ws.cell(1, col).border = РАМКА

    # ── сводная таблица ──────────────────────────────────────────────────
    #
    # Считается по подписям строк через SUMIF, а не по номерам блоков:
    # блоки у каждого человека свои, жёсткие номера разъезжались бы
    # при каждом новом сотруднике.
    СВОД = ["Общий чай всего", "Чаевые наличные", "Чаевые терминал", "Чаевые QR",
            ЖДУТ, "Сервисный сбор", "Итого распределено", "Официантам на руки",
            "Отчисления администраторам", "Отчисления кассирам", "Расхождение",
            "Выручка", "% чаевых от выручки"]
    ЖИРНЫЕ = {"Общий чай всего", "Итого распределено", "Расхождение"}
    свод, r = {}, 3
    for имя in СВОД:
        свод[имя] = r
        c = ws.cell(r, 1, имя)
        c.font = Font(name=ШРИФТ, bold=имя in ЖИРНЫЕ, size=10)
        c.border = РАМКА
        r += 1
    начало = r + 1
    r = начало

    # ── роли, люди, строки ───────────────────────────────────────────────
    def заполнить(строка: int, подпись: str, по_дням: dict, поле: str, уровень: int):
        ws.cell(строка, 1, подпись).font = Font(name=ШРИФТ, size=10)
        for i, день in enumerate(дни):
            ws.cell(строка, ПЕРВЫЙ + i,
                    round(по_дням.get(день, {}).get(поле, 0), 2) or None)
        ws.row_dimensions[строка].outlineLevel = уровень

    for роль in РОЛИ:
        люди = данные[роль]
        # Порядок — по убыванию заработка: наверху те, о ком чаще спрашивают.
        def всего(имя):
            д = люди[имя]
            return sum(v for сут in д.values() for v in сут.values())

        строка_роли = r
        ws.cell(r, 1, роль).font = Font(name=ШРИФТ, bold=True, size=11)
        for col in range(1, К_СРЕДНИЙ + 1):
            ws.cell(r, col).fill = ФОН_РОЛИ
            ws.cell(r, col).border = РАМКА
        r += 1
        строки_людей = []

        for имя in sorted(люди, key=lambda n: -всего(n)):
            по_дням = люди[имя]
            if not всего(имя):
                continue

            строка_человека = r
            r += 1
            первая = r

            if роль in ("ОФИЦИАНТЫ", "ХОСТЕС", "КАЛЬЯННЫЙ БАР"):
                виды_строки = []
                for подпись, поле in ВИДЫ:
                    # ⚠️ Строки заводим ВСЕ ЧЕТЫРЕ, всегда — даже если денег
                    # этого вида у человека не было.
                    #
                    # Прежде строка появлялась только под непустой вид, «чтобы
                    # не удлинять лист». Из-за этого блоки людей выходили разной
                    # высоты: у Тарасова четыре строки, у Селютиной шесть,
                    # у Исмаилова нет QR, у Пархоменко нет сбора. Владелец
                    # 21.08.2026: «какая-то петрушка с наполнением строк».
                    #
                    # Цена экономии оказалась выше выгоды: у одинаковых людей
                    # одинаковые строки стоят на разных высотах, и сравнить их
                    # глазом нельзя — а отчёт для того и читают. Пустая строка
                    # сообщает ровно то, что нужно: этого вида денег не было.
                    заполнить(r, подпись, по_дням, поле, 2)
                    виды_строки.append(r)
                    r += 1
                # «Начислено» — формулой поверх видов: правка в виде денег
                # сразу видна в итоге, а не расходится с ним молча.
                ws.cell(r, 1, НАЧИСЛЕНО).font = Font(name=ШРИФТ, bold=True, size=10)
                for i in range(дней):
                    L = Б(ПЕРВЫЙ + i)
                    ws.cell(r, ПЕРВЫЙ + i,
                            "=" + "+".join(f"{L}{x}" for x in виды_строки)
                            if виды_строки else None)
                ws.row_dimensions[r].outlineLevel = 2
                r += 1
                заполнить(r, ИТОГО, по_дням, "чистое", 2)
                ws.cell(r, 1).font = Font(name=ШРИФТ, bold=True, size=10)
                итоговая = r
                r += 1
            else:
                подпись = ОТЧ_АДМИН if роль == "АДМИНИСТРАТОРЫ" else ОТЧ_КАССИР
                заполнить(r, подпись, по_дням, "отчисления", 2)
                итоговая = r
                r += 1
                # У администратора — вторая строка: сколько из этой доли
                # пришло с сервисного сбора. Она ПОЯСНЯЕТ строку выше,
                # а не добавляется к ней, поэтому в сводную таблицу
                # не собирается и в «Итого распределено» не входит.
                if роль == "АДМИНИСТРАТОРЫ" and any(
                    с.get("со_сбора") for с in по_дням.values()
                ):
                    заполнить(r, СО_СБОРА, по_дням, "со_сбора", 3)
                    ws.cell(r, 1).font = Font(name=ШРИФТ, size=9, italic=True,
                                              color="808080")
                    r += 1

            последняя = r - 1
            for x in range(первая, последняя + 1):
                for col in range(1, К_СРЕДНИЙ + 1):
                    ws.cell(x, col).border = РАМКА
                    if col >= ПЕРВЫЙ:
                        ws.cell(x, col).number_format = "#,##0"

            # Строка человека: то, что он реально получил, по дням.
            # В свёрнутом виде лист превращается ровно в такую таблицу.
            ws.cell(строка_человека, 1, имя).font = Font(name=ШРИФТ, bold=True, size=10)
            for i in range(дней):
                L = Б(ПЕРВЫЙ + i)
                c = ws.cell(строка_человека, ПЕРВЫЙ + i, f"={L}{итоговая}")
                c.font = Font(name=ШРИФТ, bold=True, size=10)
                c.number_format = "#,##0"
            Д = f"{Б(ПЕРВЫЙ)}{строка_человека}:{Б(ПОСЛЕДНИЙ)}{строка_человека}"
            ws.cell(строка_человека, К_СМЕН, f'=COUNTIF({Д},">0")')
            ws.cell(строка_человека, К_ЧАЙ, f"=SUM({Д})")
            ws.cell(строка_человека, К_ОКЛАД).fill = ЖЁЛТЫЙ
            ws.cell(строка_человека, К_ПРЕМИЯ).fill = ЖЁЛТЫЙ
            ws.cell(строка_человека, К_ДОХОД,
                    f"={Б(К_ЧАЙ)}{строка_человека}+{Б(К_ОКЛАД)}{строка_человека}"
                    f"+{Б(К_ПРЕМИЯ)}{строка_человека}")
            ws.cell(строка_человека, К_СРЕДНИЙ,
                    f"=IFERROR({Б(К_ЧАЙ)}{строка_человека}"
                    f"/{Б(К_СМЕН)}{строка_человека},0)")
            for col in range(1, К_СРЕДНИЙ + 1):
                ws.cell(строка_человека, col).fill = ФОН_ЧЕЛОВЕКА
                ws.cell(строка_человека, col).border = РАМКА
                if col >= К_СМЕН:
                    ws.cell(строка_человека, col).number_format = "#,##0"
                    ws.cell(строка_человека, col).font = Font(name=ШРИФТ, bold=True, size=10)
            ws.row_dimensions[строка_человека].outlineLevel = 1
            строки_людей.append(строка_человека)

        # Итог роли — в её же строку заголовка, по каждому дню.
        # Складываем ТОЛЬКО строки с именами людей: внутри блока человека
        # есть ещё «Начислено» и виды денег — если сложить по всем
        # подписанным строкам подряд, заработок посчитается по два-три раза.
        for i in range(дней):
            L = Б(ПЕРВЫЙ + i)
            c = ws.cell(строка_роли, ПЕРВЫЙ + i,
                        "=" + "+".join(f"{L}{x}" for x in строки_людей)
                        if строки_людей else None)
            c.font = Font(name=ШРИФТ, bold=True, size=11)
        r += 1

    конец = r

    # ── формулы сводной ──────────────────────────────────────────────────
    ПОД = {"Чаевые наличные": "чаевые наличные", "Чаевые терминал": "чаевые терминал",
           "Чаевые QR": "QR код", "Сервисный сбор": "сервисный сбор",
           "Официантам на руки": ИТОГО,
           "Отчисления администраторам": ОТЧ_АДМИН,
           "Отчисления кассирам": ОТЧ_КАССИР}
    for i in range(дней):
        L = Б(ПЕРВЫЙ + i)
        Я, З = f"$A${начало}:$A${конец}", f"{L}${начало}:{L}${конец}"
        для = lambda п: f'SUMIF({Я},"{п}",{З})'  # noqa: E731
        for имя, подпись in ПОД.items():
            ws.cell(свод[имя], ПЕРВЫЙ + i, f"={для(подпись)}")
        ws.cell(свод["Общий чай всего"], ПЕРВЫЙ + i,
                "=" + "+".join(для(п) for п, _ in ВИДЫ))
        ws.cell(свод["Итого распределено"], ПЕРВЫЙ + i,
                "=" + "+".join(для(п) for п in (ИТОГО, ОТЧ_АДМИН, ОТЧ_КАССИР)))
        # Округляем: таблица складывает десятки ячеек, и в последнем знаке
        # набегает пыль двоичной арифметики. Красное «−0» без причины учит
        # не смотреть на красное — и тогда настоящую пропажу пропустят.
        ws.cell(свод["Расхождение"], ПЕРВЫЙ + i,
                f"=ROUND({L}{свод['Общий чай всего']}-{L}{свод['Итого распределено']},2)")

    # ── по QR пришло, но не разнесено ────────────────────────────────────
    #
    # Числа, а не формула: они приходят не из блоков людей, а из очереди
    # приложения — там этих денег ещё ни у кого нет.
    ожидают = неразнесённые()
    if ожидают is None:
        # Спросить не вышло. Пишем об этом в НАЗВАНИИ строки, а не в клетке
        # первого числа: там надпись читалась бы как значение за 1 августа.
        # Пустую строку молча оставлять нельзя — пустота читается как
        # «всё разнесено», а это была бы уверенная ложь.
        c = ws.cell(свод[ЖДУТ], 1, f"{ЖДУТ} — не удалось спросить приложение")
        c.font = Font(name=ШРИФТ, size=10, italic=True, color="C00000")
    else:
        по_дням = ожидают.get("поДням") or {}
        for i, д in enumerate(дни):
            сумма = по_дням.get(д)
            if сумма:
                c = ws.cell(свод[ЖДУТ], ПЕРВЫЙ + i, round(float(сумма), 2))
                c.number_format = "#,##0"
                # Красным: это не заработок, а деньги, которые ждут кассира.
                c.font = Font(name=ШРИФТ, size=10, color="C00000")

    # ── выручка и процент ────────────────────────────────────────────────
    #
    # ⚠️ Своим циклом, а не хвостом предыдущего блока. 14.08.2026 эти две
    # строки уехали внутрь `иначе` про неразнесённые деньги и остались
    # за циклом по дням: заполнялся ровно один день — последний, да и то
    # лишь когда приложение ответило про очередь. С 1-го по 30-е выручка
    # стояла пустой, а «% чаевых от выручки» честно писал «нет выручки» —
    # поломка выглядела как молчание кассы, хотя касса отвечала и суммы
    # печатались в вывод команды. Выручка к очереди по QR отношения
    # не имеет, поэтому и стоит отдельно.
    for i, д in enumerate(дни):
        L = Б(ПЕРВЫЙ + i)
        ws.cell(свод["Выручка"], ПЕРВЫЙ + i, round(деньги.get(д, 0), 2) or None)
        # Пустая выручка — это «данных нет», а не ноль. Прежняя формула
        # с IFERROR(...,0) рисовала в такой день ровные 0,0 %, и цифра
        # читалась как факт: чаевых от выручки — ноль процентов. Теперь
        # ячейка честно говорит, что сравнивать не с чем.
        ws.cell(свод["% чаевых от выручки"], ПЕРВЫЙ + i,
                f'=IF(N({L}{свод["Выручка"]})=0,"нет выручки",'
                f'{L}{свод["Общий чай всего"]}/{L}{свод["Выручка"]})')

    for имя, стр in свод.items():
        for col in range(ПЕРВЫЙ, К_СРЕДНИЙ + 1):
            c = ws.cell(стр, col)
            c.border = РАМКА
            c.font = Font(name=ШРИФТ, bold=имя in ЖИРНЫЕ, size=10)
            c.number_format = "0.0%" if имя == "% чаевых от выручки" else "#,##0"
        ws.cell(стр, К_ЧАЙ, f"=SUM({Б(ПЕРВЫЙ)}{стр}:{Б(ПОСЛЕДНИЙ)}{стр})")
        if имя == "Расхождение":
            for col in list(range(ПЕРВЫЙ, ПОСЛЕДНИЙ + 1)) + [К_ЧАЙ]:
                ws.cell(стр, col).number_format = '#,##0.00;[Red]-#,##0.00;"—"'

    # ── вид ──────────────────────────────────────────────────────────────
    ws.freeze_panes = "B3"
    ws.column_dimensions["A"].width = 34
    for col in range(ПЕРВЫЙ, ПОСЛЕДНИЙ + 1):
        ws.column_dimensions[Б(col)].width = 11
    for col in range(К_СМЕН, К_СРЕДНИЙ + 1):
        ws.column_dimensions[Б(col)].width = 14
    ws.sheet_properties.outlinePr.summaryBelow = False

    путь = report_dir() / f"Чаевые-дубль-{МЕСЯЦЫ[мес - 1]}-{год}.xlsx"
    wb.save(путь)
    return путь


def main() -> None:
    аргументы = [a for a in sys.argv[1:] if not a.startswith("--")]
    месяц = аргументы[0] if аргументы else (
        date.today() - timedelta(days=1)).strftime("%Y-%m")
    путь = построить(месяц, брать_выручку="--без-выручки" not in sys.argv)
    print(f"\nСобрано: {путь.name}")
    print(f"Папка: {describe(путь.parent)}")
    print("Три уровня группировки: роль → человек → виды денег.")


if __name__ == "__main__":
    main()
