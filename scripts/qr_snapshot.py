#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Снимок облака Quick Resto — «до» и «после» перенастройки.

Зачем. 22.08.2026 управляющая компания взяла в работу разделение облака
`gt464`: сейчас в нём четыре заведения, останется одно. Перенастройку нельзя
проверить, не имея снимка ДО неё — «стало правильно» и «стало иначе»
различаются только сравнением.

⚠️ Что именно может сломаться при переезде, и почему смотреть надо шире,
чем на выручку:

  * зал ПЕРЕИМЕНУЮТ — отбор в qr_sales.py держится на точной строке
    «Барвиха Lounge Невский», и наша выручка молча станет нулём;
  * наш зал вынесут в ДРУГОЕ облако — тогда неверен сам адрес gt464 в .env;
  * история НЕ ПЕРЕЕДЕТ — смены за июль-август останутся в старом облаке,
    и месяц опустеет задним числом;
  * смены ПЕРЕНУМЕРУЮТСЯ — у чужих залов уже была своя нумерация с №1;
  * у сотрудников появятся ВТОРЫЕ НОМЕРА — это уже случалось с Асей
    Самариной (№825 → №941) и стоило дня разбора.

💡 Фискальные данные (ОФД) от всего этого не зависят: чек привязан к КАССЕ,
а не к облаку. Поэтому сверять «после» надо не только со снимком, но и с ОФД —
он единственный источник, который перенастройка не может сдвинуть.

Запуск:
    python3 scripts/qr_snapshot.py                 снять оба облака сейчас
    python3 scripts/qr_snapshot.py --сравнить A B  сравнить два снимка
    python3 scripts/qr_snapshot.py --сравнить A    сравнить A с самым свежим

Файлы: data/снимки-облака/снимок-ГГГГ-ММ-ДД-ЧЧММ.json
"""

import json
import sys
from collections import defaultdict
from datetime import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

import qr_employees as E  # noqa: E402
import qr_sales as S  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
ПАПКА = ROOT / "data" / "снимки-облака"


def снять_облако(облако: str) -> dict:
    cfg = S.read_env(облако)
    смены = S.fetch_shifts(cfg)

    залы, строки = {}, []
    for s in смены:
        сх = s.get("tableScheme") or {}
        if сх.get("name") and сх.get("id") not in залы:
            времена = [t.get("serverRegisterTime") for t in (сх.get("tables") or [])
                       if t.get("serverRegisterTime")]
            залы[сх["id"]] = {
                "имя": сх["name"], "столов": len(сх.get("tables") or []),
                "заведён": min(времена) if времена else None,
            }
        д = S.business_day(s)
        строки.append({
            "id": s.get("id"), "номер": s.get("shiftNumber"),
            "зал": S.зал_смены(s), "день": д.isoformat() if д else None,
            "статус": s.get("status"),
            "нал": round((s.get("totalCash") or 0) - (s.get("totalReturnCash") or 0), 2),
            "безнал": round((s.get("totalCard") or 0) - (s.get("totalReturnCard") or 0), 2),
            "чеков": s.get("ordersCount") or 0,
            "возвратов": s.get("returnOrdersCount") or 0,
        })
    строки.sort(key=lambda r: (r["день"] or "", r["номер"] or 0))
    return {"смены": строки, "залы": залы}


def снять_людей() -> dict:
    cfg = E.read_env()
    люди = {}
    for облако, префикс in (("mav", "QR_MAV"), ("shalaeva", "QR_SHALAEVA")):
        карточки = []
        for e in E.fetch(cfg, префикс):
            карточки.append({
                "код": e.get("code"),
                "имя": " ".join(x for x in [e.get("lastName"), e.get("firstName")] if x)
                       or e.get("name") or "?",
                "залы": sorted({s.get("name") for s in (e.get("allowedTablesSchemes") or [])
                                if s.get("name")}),
                "убран": bool(e.get("deleted")),
            })
        карточки.sort(key=lambda k: (k["имя"], str(k["код"])))
        люди[облако] = карточки
    return люди


def снять() -> Path:
    снимок = {"снят": datetime.now().isoformat(timespec="seconds"), "облака": {}}
    for облако in ("mav", "shalaeva"):
        print(f"снимаю {облако}…")
        снимок["облака"][облако] = снять_облако(облако)
    print("снимаю справочник людей…")
    снимок["люди"] = снять_людей()

    ПАПКА.mkdir(parents=True, exist_ok=True)
    путь = ПАПКА / f"снимок-{datetime.now():%Y-%m-%d-%H%M}.json"
    путь.write_text(json.dumps(снимок, ensure_ascii=False, indent=1), encoding="utf-8")
    return путь


def деньги(v) -> str:
    return f"{v:,.0f}".replace(",", " ")


def отчёт(снимок: dict) -> None:
    for облако, д in снимок["облака"].items():
        по_залам = defaultdict(lambda: [0, 0.0])
        for r in д["смены"]:
            а = по_залам[r["зал"] or "(зал не указан)"]
            а[0] += 1
            а[1] += r["нал"] + r["безнал"]
        print(f"\n  облако {облако}: смен {len(д['смены'])}, залов {len(д['залы'])}")
        for зал, (n, деньгами) in sorted(по_залам.items(), key=lambda x: -x[1][1]):
            print(f"      {зал:36} смен {n:>3}  {деньги(деньгами):>12} ₽")
    for облако, карточки in снимок["люди"].items():
        живых = sum(1 for k in карточки if not k["убран"])
        print(f"  люди {облако}: карточек {len(карточки)}, живых {живых}")


def сравнить(а: dict, б: dict) -> int:
    """Печатает всё, что изменилось. Возвращает число тревожных отличий."""
    тревог = 0
    print(f"\nСНИМОК «ДО»    {а['снят']}")
    print(f"СНИМОК «ПОСЛЕ» {б['снят']}\n" + "─" * 66)

    for облако in sorted(set(а["облака"]) | set(б["облака"])):
        да = а["облака"].get(облако, {"смены": [], "залы": {}})
        дб = б["облака"].get(облако, {"смены": [], "залы": {}})
        print(f"\n▌ облако {облако}")

        имена_а = {з["имя"] for з in да["залы"].values()}
        имена_б = {з["имя"] for з in дб["залы"].values()}
        for имя in sorted(имена_а - имена_б):
            знак = "🔴" if имя == S.НАШ_ЗАЛ else "  ✔"
            print(f"  {знак} зал ИСЧЕЗ: «{имя}»"
                  + ("  — ЭТО НАШ ЗАЛ, отбор в qr_sales.py сломан" if имя == S.НАШ_ЗАЛ else ""))
            тревог += имя == S.НАШ_ЗАЛ
        for имя in sorted(имена_б - имена_а):
            print(f"  🟡 зал ПОЯВИЛСЯ: «{имя}»")
            тревог += 1

        # ⚠️ Смену опознаём по ДНЮ и НОМЕРУ, но НЕ по названию зала.
        #
        # На учениях 22.08 ключ включал зал — и одно переименование зала
        # выдало 92 строки «смена пропала / смена новая», внутри которых
        # утонули две настоящие беды: не переехавший день и уехавшие деньги
        # закрытой смены. Одна причина не должна печататься девяносто раз.
        ключ = lambda r: (r["день"], r["номер"])  # noqa: E731
        ка = {ключ(r): r for r in да["смены"]}
        кб = {ключ(r): r for r in дб["смены"]}
        пропали = [k for k in ка if k not in кб]
        новые = [k for k in кб if k not in ка]
        for k in sorted(пропали):
            r = ка[k]
            наш = r["зал"] == S.НАШ_ЗАЛ
            print(f"  {'🔴' if наш else '  '} смена ПРОПАЛА: {r['день']} №{r['номер']} "
                  f"«{r['зал']}» {деньги(r['нал'] + r['безнал'])} ₽")
            тревог += наш
        for k in sorted(новые):
            r = кб[k]
            print(f"  🟡 смена НОВАЯ:  {r['день']} №{r['номер']} «{r['зал']}» "
                  f"{деньги(r['нал'] + r['безнал'])} ₽")

        # Переименование зала трогает все смены разом — печатаем ОДНОЙ строкой
        # с числом и краями периода, иначе одна причина заливает экран.
        переезды = defaultdict(list)

        # ⚠️ Главное: деньги закрытой смены меняться НЕ ДОЛЖНЫ. Если сдвинулись —
        # переехали не данные, а их пересчёт, и верить облаку нельзя.
        for k in sorted(set(ка) & set(кб)):
            ра, рб = ка[k], кб[k]
            if ра["зал"] != рб["зал"]:
                переезды[(ра["зал"], рб["зал"])].append(ра["день"])
            if ра["статус"] != "CLOSED" or рб["статус"] != "CLOSED":
                continue
            for поле in ("нал", "безнал", "чеков", "возвратов"):
                if ра[поле] != рб[поле]:
                    print(f"  🔴 ЗАКРЫТАЯ смена ИЗМЕНИЛАСЬ: {ра['день']} №{ра['номер']} "
                          f"«{ра['зал']}» — {поле}: {ра[поле]} → {рб[поле]}")
                    тревог += 1

        for (было, стало), дни in sorted(переезды.items()):
            print(f"  🟡 смен переехало из «{было}» в «{стало}»: {len(дни)} "
                  f"({min(дни)} … {max(дни)})")
            тревог += 1

    for облако in sorted(set(а["люди"]) | set(б["люди"])):
        ка = {(k["код"], k["имя"]): k for k in а["люди"].get(облако, [])}
        кб = {(k["код"], k["имя"]): k for k in б["люди"].get(облако, [])}
        for k in sorted(set(кб) - set(ка), key=str):
            print(f"  🟡 человек ПОЯВИЛСЯ ({облако}): №{k[0]} {k[1]}")
            тревог += 1
        for k in sorted(set(ка) - set(кб), key=str):
            print(f"  🔴 человек ПРОПАЛ ({облако}): №{k[0]} {k[1]}")
            тревог += 1
        # Второй номер у знакомого имени — та самая беда, что была с Асей.
        имена_б = defaultdict(list)
        for (код, имя) in кб:
            имена_б[имя].append(код)
        for имя, коды in sorted(имена_б.items()):
            if len(коды) > 1 and len([c for c in ка if c[1] == имя]) < len(коды):
                print(f"  🔴 У «{имя}» теперь НЕСКОЛЬКО номеров ({облако}): "
                      + ", ".join(f"№{c}" for c in sorted(коды, key=str)))
                тревог += 1

    print("\n" + "─" * 66)
    print("✅ Отличий, требующих внимания, нет." if not тревог
          else f"⚠️  Тревожных отличий: {тревог}. Разбирать по одному.")
    return тревог


def свежие(n: int) -> list[Path]:
    return sorted(ПАПКА.glob("снимок-*.json"))[-n:]


def главное() -> None:
    if "--сравнить" in sys.argv:
        имена = sys.argv[sys.argv.index("--сравнить") + 1:]
        пути = [Path(x) if Path(x).exists() else ПАПКА / x for x in имена]
        if len(пути) == 1:
            пути.append(свежие(1)[0])
        if len(пути) != 2:
            sys.exit("Нужно два снимка: --сравнить ДО ПОСЛЕ")
        а, б = (json.loads(p.read_text(encoding="utf-8")) for p in пути)
        sys.exit(1 if сравнить(а, б) else 0)

    путь = снять()
    снимок = json.loads(путь.read_text(encoding="utf-8"))
    print(f"\nСнимок сохранён: {путь.name}")
    отчёт(снимок)


if __name__ == "__main__":
    главное()
