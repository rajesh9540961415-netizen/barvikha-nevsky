def business_day(shift):
    """Дата открытия смены по местному времени."""
    s = shift.get("localOpenedTime") or shift.get("opened")
    if not s:
        return None
    return datetime.strptime(s[:10], "%Y-%m-%d").date()


def main():
    # ⚠️ Раньше кассой считался ЛЮБОЙ ключ с двумя чёрточками: `--заново`
    # молча превращался в «неизвестную кассу». Теперь ключи разобраны по имени.
    ключи = [a for a in sys.argv[1:] if a.startswith("--")]
    args = [a for a in sys.argv[1:] if not a.startswith("--")]
    заново = "--заново" in ключи
    срок = 45
    for k in ключи:
        if k.startswith("--срок="):
            срок = int(k.split("=", 1)[1])
    чужие = [k for k in ключи
             if k[2:] not in CLOUDS and k != "--заново" and not k.startswith("--срок=")]
    if чужие:
        raise SystemExit(f"Непонятный ключ: {' '.join(чужие)}. "
                         f"Кассы: {', '.join('--' + c for c in CLOUDS)}; "
                         "ещё есть --заново и --срок=<минут>.")
    cloud = next((k[2:] for k in ключи if k[2:] in CLOUDS), "mav")
    cfg = read_env(cloud)
    print(f"касса: {cfg['_title']} ({cfg['QR_URL']})")
    shifts = смены(cfg, cloud, заново=заново, срок_минут=срок)
    rows = []
    чужие = {}
    for s in shifts:
        d = business_day(s)
        if not d or s.get("status") != "CLOSED":
            continue
        зал = зал_смены(s)
        if not наша_смена(s):
            зал = зал or "«зал не указан»"
            деньги = ((s.get("totalCash") or 0) - (s.get("totalReturnCash") or 0)
                      + (s.get("totalCard") or 0) - (s.get("totalReturnCard") or 0))
            з = чужие.setdefault(зал, [0, 0.0])
            з[0] += 1
            з[1] += деньги
            continue
        cash = (s.get("totalCash") or 0) - (s.get("totalReturnCash") or 0)
        card = (s.get("totalCard") or 0) - (s.get("totalReturnCard") or 0)
        rows.append({"date": d, "shift": s.get("shiftNumber"),
                     "cash": round(cash, 2), "cashless": round(card, 2),
                     "bonuses": round(s.get("totalBonuses") or 0, 2),
                     "checks": s.get("ordersCount") or 0,
                     "returns": s.get("returnOrdersCount") or 0})
    rows.sort(key=lambda r: (r["date"], r["shift"] or 0))

    # Кричим вслух: молчаливый отбор однажды выбросит наш же зал,
    # если его переименуют в кассе, и выручка просядет без объяснений.
    for зал, (смен, деньги) in sorted(чужие.items(), key=lambda x: -x[1][1]):
        print(f"  ⚠ не наш зал «{зал}»: смен {смен}, "
              f"{деньги:,.0f} ₽ — в выручку не берём".replace(",", " "))
    if not rows:
        raise SystemExit(
            f"Ни одной смены зала «{НАШ_ЗАЛ}». Если зал переименовали в кассе — "
            "поправьте НАШ_ЗАЛ в этом скрипте.")

    # 🔴 Неполной историей файл переписывать НЕЛЬЗЯ.
    #
    # Первая закачка длинная и может оборваться на середине: в хранилище тогда
    # лежат свежие месяцы и нет старых. Пересобранный из него CSV выглядел бы
    # здоровым — те же колонки, те же свежие дни, — но молча потерял бы
    # 2025 год, а следом за ним P&L и все годовые сверки.
    #
    # 💡 Поэтому правило простое: пока история не докачана, прежний файл
    # остаётся как есть. Он старый, но целый, и это видно по последней дате;
    # потеря середины не видна никак.
    путь_csv = OUT / f"qr_sales_{cloud}.csv"
    if ПОЛНАЯ_ИСТОРИЯ is False and путь_csv.exists():
        with путь_csv.open(encoding="utf-8") as f:
            прежние = [r["date"] for r in csv.DictReader(f)]
        print(f"  ⚠ история докачана не до конца — {путь_csv.name} НЕ переписан.")
        print(f"     в файле как было: {len(прежние)} строк, "
              f"{прежние[0] if прежние else '—'} … {прежние[-1] if прежние else '—'}")
        print(f"     в хранилище сейчас: {len(rows)} смен нашего зала, "
              f"{rows[0]['date']} … {rows[-1]['date']}")
        print("     запустите ещё раз — докачка продолжится с того же места.")
        return

    OUT.mkdir(parents=True, exist_ok=True)
    with путь_csv.open("w", newline="", encoding="utf-8") as f:
        w = csv.DictWriter(f, ["date", "shift", "cash", "cashless", "bonuses", "checks", "returns"])
        w.writeheader(); w.writerows(rows)

    M = lambda v: f"{v:,.0f}".replace(",", " ")
    if args:
        lo, hi = args[0], args[-1]
        sel = [r for r in rows if lo <= r["date"].strftime("%Y-%m") <= hi]
        print(f"{'дата':<12}{'безнал':>13}{'наличные':>12}{'итого':>13}{'чеков':>8}")
        print("─" * 58)
        day = defaultdict(lambda: [0.0, 0.0, 0])
        for r in sel:
            a = day[r["date"]]
            a[0] += r["cashless"]; a[1] += r["cash"]; a[2] += r["checks"]
        for d in sorted(day):
            c, n, k = day[d]
            print(f"{d.strftime('%d.%m.%Y'):<12}{M(c):>13}{M(n):>12}{M(c+n):>13}{k:>8}")
        print("─" * 58)
        tc = sum(v[0] for v in day.values()); tn = sum(v[1] for v in day.values())
        print(f"{'ИТОГО':<12}{M(tc):>13}{M(tn):>12}{M(tc+tn):>13}"
              f"{sum(v[2] for v in day.values()):>8}")
        return

    mon = defaultdict(lambda: [0.0, 0.0, 0, 0])
    for r in rows:
        a = mon[(r["date"].year, r["date"].month)]
        a[0] += r["cashless"]; a[1] += r["cash"]; a[2] += r["checks"]; a[3] += 1
    print(f"смен получено: {len(rows)}   период: {rows[0]['date']} … {rows[-1]['date']}\n")
    print(f"{'месяц':<10}{'безнал':>14}{'наличные':>13}{'итого':>14}{'нал %':>7}{'чеков':>8}{'смен':>6}")
    print("─" * 72)
    for k in sorted(mon):
        c, n, ch, sh = mon[k]
        share = f"{n/(c+n)*100:.0f}%" if (c + n) else "—"
        print(f"{k[1]:02d}.{k[0]:<7}{M(c):>14}{M(n):>13}{M(c+n):>14}{share:>7}{ch:>8}{sh:>6}")


