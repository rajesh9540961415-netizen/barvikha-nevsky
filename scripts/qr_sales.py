# поэтому его помнит модуль, а не отдельный вызов.
ПОРЦИЯ = 150
МИНИМУМ = 25


def страница(cfg, offset, осталось_секунд):
    """Одна страница смен, с повторами при обрыве.

    Одним запросом вся история весит десятки мегабайт, и соединение рвётся
    на середине — приходит обрезанный ответ. Раньше это молча оставляло
    старые данные в CSV. Теперь: маленькие страницы, повтор при обрыве и
    громкая ошибка, если страницу так и не удалось получить.

    🔴 20.09.2026: облако МАВ (fk381) не выгружалось с 18.09 — в выжимке
    два дня подряд стояло «⚠️ выручки за этот день нет», хотя касса работала
    и вторая, шалаевская, выгрузка приходила исправно.

    Замеры того дня:

        5 смен  →  19 c        300 смен →  обрыв на 351-й секунде
        50 смен →   4 c        100 смен → 370 c (дошло!)
        150 смен →  10 c

    Время гуляет: 150 смен пришли за 10 секунд, а 100 — за шесть минут.
    Облако отвечает рывками и зависает посреди передачи; облако Шалаевой
    на тот же запрос отвечает за 3 секунды стабильно.

    🔴 Сначала по этим числам решили, что размер порции ни при чём, и
    починили одну выдержку. Прогон показал обратное: страница в 300 смен
    прошла со второй попытки на offset=0 и не прошла ВООБЩЕ на offset=300 —
    три обрыва подряд. А мелкие порции, 50 и 150, доходили за секунды
    каждый раз. Вывод был снят с одной страницы, а страниц пять.

    💡 Поэтому лечим двумя руками сразу:
      • выдержка — ждём ответа 600 секунд вместо 120 (запрос, который
        убивали на второй минуте, дошёл бы за шесть), и между попытками
        30–90 секунд вместо 2–8: облако отходит не мгновенно;
      • порция — просим по 150 смен, а на каждом обрыве делим надвое
        до `минимум`. Обратно не растим: 150 смен идут 10 секунд, вся
        история — это десяток страниц, экономить тут не на чем, а рост
        порции просто вернул бы нас к обрывам.

    ⚠️ Раз попытки стали долгими, у всей выгрузки есть общий срок
    (`срок_минут`). Без него утренняя задача, которую никто не сторожит,
    висела бы часами на кассе, которая уже не ответит.

    ⚠️ И громко пишем о каждой неудачной попытке. Три дня выгрузка падала
    молча: скрипт ничего не печатал, пока ждал, и обрыв было видно только
    по тому, что назавтра в отчёте не было выручки.

    📌 Касса отдаёт смены ОТ НОВЫХ К СТАРЫМ: на offset=0 лежит сегодняшняя.
    Проверено 20.09.2026 — №157 (20.09), №156 (19.09), №155 (18.09).
    Отсюда напрашивается ранний выход: за новым днём незачем перекачивать
    полторы тысячи смен с 2025 года, а весит история десятки мегабайт
    и рвётся именно из-за объёма. НО это значит дописывать в готовый CSV
    вместо пересборки с нуля, а такой размен решает владелец, не скрипт.
    Пока качаем всё: медленно, зато файл всегда равен источнику.
    """
    global ПОРЦИЯ
    token = base64.b64encode(f"{cfg['QR_LOGIN']}:{cfg['QR_PASSWORD']}".encode()).decode()
    q = urllib.parse.urlencode({"moduleName": MODULE, "className": CLASS})
    url = cfg["QR_URL"].rstrip("/") + "/platform/online/api/list?" + q
    head = {"Authorization": "Basic " + token,
            "Content-Type": "application/json", "Connection": "close"}
    for attempt in range(4):
        try:
            req = urllib.request.Request(
                url, data=json.dumps({"limit": ПОРЦИЯ, "offset": offset}).encode(),
                headers=head, method="POST")
            with urllib.request.urlopen(req, timeout=min(600, max(30, осталось_секунд))) as r:
                return json.loads(r.read().decode())
        except Exception as e:
            if attempt == 3:
                raise SystemExit(
                    f"Касса не отдала страницу offset={offset} после 4 попыток: "
                    f"{type(e).__name__}. Хранилище смен оставлено как есть.")
            пауза = 30 * (attempt + 1)
            было, ПОРЦИЯ = ПОРЦИЯ, max(МИНИМУМ, ПОРЦИЯ // 2)
            print(f"  ⚠ offset={offset}: {type(e).__name__} — "
                  f"порция {было} → {ПОРЦИЯ}, жду {пауза} c, "
                  f"попытка {attempt + 2} из 4", flush=True)
            time.sleep(пауза)


