# это секунды вместо часа.
#
# ⚠️ CSV при этом по-прежнему СОБИРАЕТСЯ ЗАНОВО ЦЕЛИКОМ из хранилища на
# каждом запуске — накопления в файле-результате нет, он равен источнику.
# Накапливается только сырьё, как у чеков ОФД.
#
# ⚠️ Раз записи обрезаны, нового поля из хранилища не достать: понадобится —
# качаем историю заново ключом `--заново`.
КЭШ_ВЕРСИЯ = 1

# Сколько подряд известных смен считаем доказательством, что новое кончилось.
# Одной мало: касса отдаёт смены от новых к старым, но у разных залов одного
# облака смены перемешаны, и свежая чужая может стоять выше нашей.
ДОСТАТОЧНО_ИЗВЕСТНЫХ = 20

# Докачана ли история целиком у последней прочитанной кассы. Нужна не счёту,
# а решению «можно ли переписывать CSV» — см. main().
ПОЛНАЯ_ИСТОРИЯ = None


def путь_кэша(cloud):
    return OUT / f"смены-{cloud}.json"


def пустой_кэш():
    return {"версия": КЭШ_ВЕРСИЯ, "полная_история": False, "докачано_до": 0, "смены": {}}


def читать_кэш(cloud):
    p = путь_кэша(cloud)
    if not p.exists():
        return пустой_кэш()
    try:
        d = json.loads(p.read_text(encoding="utf-8"))
    except Exception as e:
        print(f"  ⚠ хранилище смен не читается ({type(e).__name__}) — качаю заново")
        return пустой_кэш()
    if d.get("версия") != КЭШ_ВЕРСИЯ:
        print("  ⚠ хранилище смен старой версии — качаю заново")
        return пустой_кэш()
    return d


def писать_кэш(cloud, кэш):
    """Пишем через временный файл: обрыв на полуслове не должен оставить
    битое хранилище — иначе одна неудача стоила бы часа перекачки."""
    p = путь_кэша(cloud)
    OUT.mkdir(parents=True, exist_ok=True)
    врем = p.with_name(p.name + ".tmp")
    врем.write_text(json.dumps(кэш, ensure_ascii=False), encoding="utf-8")
    врем.replace(p)


def обрезать(s):
    """Оставляем от смены только то, из чего считается CSV.

    Зал вычисляем здесь же — одним и тем же `зал_смены`, чтобы в хранилище
    не попало сырое поле, которое потом читалось бы вторым способом.
    Время закрытия храним не для счёта, а чтобы знать, когда касса реально
    закрывается: от этого зависит, в какой час имеет смысл запускать отчёты.
    """
    return {
        "id": s.get("id"),
        "version": s.get("version"),
        "shiftNumber": s.get("shiftNumber"),
        "localOpenedTime": s.get("localOpenedTime") or s.get("opened"),
        "localClosedTime": s.get("localClosedTime") or s.get("closed"),
        "status": s.get("status"),
        "salePlace": {"name": зал_смены(s)},
        "totalCash": s.get("totalCash") or 0,
        "totalReturnCash": s.get("totalReturnCash") or 0,
        "totalCard": s.get("totalCard") or 0,
        "totalReturnCard": s.get("totalReturnCard") or 0,
        "totalBonuses": s.get("totalBonuses") or 0,
        "ordersCount": s.get("ordersCount") or 0,
        "returnOrdersCount": s.get("returnOrdersCount") or 0,
    }


def смены(cfg, cloud, заново=False, срок_минут=45):
    """Смены кассы: сперва догружаем новое в хранилище, потом отдаём всё.

    Две руки:
      • голова — идём от offset=0 вниз, пока не встретим
        ДОСТАТОЧНО_ИЗВЕСТНЫХ смен подряд, уже лежащих в хранилище той же
        версии. Это и есть ежедневный случай: одна-две страницы;
      • хвост — если история докачана не до конца (первый запуск оборвался),
        продолжаем с того места, где встали, и идём до конца.

    ⚠️ Хранилище пишем после КАЖДОЙ страницы. Первый проход длинный, и
    обрыв на середине не должен обнулять сделанное: следующий запуск
    продолжит с той же глубины, а не начнёт сначала.
    """
    кэш = пустой_кэш() if заново else читать_кэш(cloud)
    было = len(кэш["смены"])
    крайний_срок = time.time() + срок_минут * 60

    def сложить(chunk):
        новых = изменённых = знакомых_подряд = 0
        for s in chunk:
            t = обрезать(s)
            ключ = str(t["id"])
            старая = кэш["смены"].get(ключ)
            if старая is None:
                новых += 1
                знакомых_подряд = 0
            elif старая.get("version") != t["version"]:
                изменённых += 1
                знакомых_подряд = 0
            else:
                знакомых_подряд += 1
            кэш["смены"][ключ] = t
        return новых, изменённых, знакомых_подряд

    def обойти(начало, останавливаться_на_знакомых, метка):
        offset, подряд = начало, 0
        while True:
            осталось = крайний_срок - time.time()
            if осталось <= 0:
                print(f"  ⚠ срок {срок_минут} мин вышел на offset={offset} — "
                      "что успели, то в хранилище; остальное догрузит следующий запуск")
                return False
            chunk = страница(cfg, offset, осталось)
            if not chunk:
                return True
            новых, изменённых, подряд_в_странице = сложить(chunk)
            подряд = подряд + подряд_в_странице if новых == 0 and изменённых == 0 else подряд_в_странице
            offset += len(chunk)
            if not останавливаться_на_знакомых:
                кэш["докачано_до"] = max(кэш["докачано_до"], offset)
            писать_кэш(cloud, кэш)
            print(f"  {метка}: смен в хранилище {len(кэш['смены'])}"
                  f"  (новых +{новых}, обновлено {изменённых})", flush=True)
            if останавливаться_на_знакомых and подряд >= ДОСТАТОЧНО_ИЗВЕСТНЫХ:
                return True
            if len(chunk) < ПОРЦИЯ:
                return True

    # Голова: свежие смены. Нужна всегда — и когда история ещё не докачана.
    догнали = обойти(0, останавливаться_на_знакомых=кэш["полная_история"], метка="свежие")

    # Хвост: остаток истории. Отступаем на пять смен назад — пока мы качали,
    # касса могла открыть новую смену, и тогда всё сдвинулось бы на единицу.
    if догнали and not кэш["полная_история"]:
        начало = max(0, кэш["докачано_до"] - 5)
        if обойти(начало, останавливаться_на_знакомых=False, метка="история"):
            кэш["полная_история"] = True
            писать_кэш(cloud, кэш)
            print("  история докачана целиком", flush=True)

    global ПОЛНАЯ_ИСТОРИЯ
    ПОЛНАЯ_ИСТОРИЯ = кэш["полная_история"]
    стало = len(кэш["смены"])
    if not стало:
        raise SystemExit("Касса не отдала ни одной смены — хранилище пустое, "
                         "CSV не трогаем.")
    if not кэш["полная_история"]:
        print("  ⚠ история докачана НЕ до конца — в CSV пока не все старые дни")
    print(f"  смен в хранилище: {стало} (за этот раз +{стало - было})")
    return list(кэш["смены"].values())


