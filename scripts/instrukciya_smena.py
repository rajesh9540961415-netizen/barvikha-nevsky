#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Инструкция администраторам и кассирам по приложению смены.

Отличается от «Инструкция смене — пять ошибок» (19.08.2026) тем, что та
разбирала ошибки, а эта описывает работу целиком: от открытия смены
до выгрузки. Просьба владельца 06.09.2026.

Всё, что здесь написано про экраны и правила, взято из самого приложения:
mini-app/src/components/*.tsx и mini-app/src/lib/split.ts. Придуманных
кнопок здесь нет — если приложение изменится, инструкцию надо править
вместе с ним.

Запуск:  python3 scripts/instrukciya_smena.py
"""
from __future__ import annotations

from pathlib import Path

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Cm, Pt, RGBColor

ФАЙЛ = Path(__file__).resolve().parent.parent / "Инструкция по приложению — администраторам и кассирам.docx"


def собрать() -> Path:
    d = Document()
    ст = d.styles["Normal"]
    ст.font.name = "Times New Roman"
    ст.font.size = Pt(12)
    for s in d.sections:
        s.left_margin, s.right_margin = Cm(2.5), Cm(1.5)
        s.top_margin, s.bottom_margin = Cm(2), Cm(2)

    def п(текст="", ж=False, размер=12, отступ=6, выравн=None, курсив=False, отст_слева=0):
        par = d.add_paragraph()
        par.paragraph_format.space_after = Pt(отступ)
        if отст_слева:
            par.paragraph_format.left_indent = Cm(отст_слева)
        if выравн is not None:
            par.alignment = выравн
        if текст:
            r = par.add_run(текст)
            r.bold, r.italic = ж, курсив
            r.font.size = Pt(размер)
        return par

    def заголовок(текст, размер=14):
        par = d.add_paragraph()
        par.paragraph_format.space_before = Pt(16)
        par.paragraph_format.space_after = Pt(6)
        r = par.add_run(текст)
        r.bold = True
        r.font.size = Pt(размер)
        return par

    def пункт(текст, отступ=4):
        par = d.add_paragraph(style="List Bullet")
        par.paragraph_format.space_after = Pt(отступ)
        par.paragraph_format.left_indent = Cm(0.8)
        r = par.add_run(текст)
        r.font.size = Pt(12)
        return par

    def таблица(шапка, строки, ширины):
        t = d.add_table(rows=1, cols=len(шапка))
        t.style = "Table Grid"
        for i, з in enumerate(шапка):
            кл = t.rows[0].cells[i]
            кл.text = ""
            r = кл.paragraphs[0].add_run(з)
            r.bold = True
            r.font.size = Pt(11)
        for стр in строки:
            ячейки = t.add_row().cells
            for i, з in enumerate(стр):
                ячейки[i].text = ""
                r = ячейки[i].paragraphs[0].add_run(str(з))
                r.font.size = Pt(11)
        for строка in t.rows:
            for i, ш in enumerate(ширины):
                строка.cells[i].width = Cm(ш)
        d.add_paragraph().paragraph_format.space_after = Pt(6)
        return t

    # ── шапка
    п("Как работать в приложении смены", ж=True, размер=17, отступ=2,
      выравн=WD_ALIGN_PARAGRAPH.CENTER)
    п("Инструкция администраторам и кассирам", размер=12, отступ=2,
      выравн=WD_ALIGN_PARAGRAPH.CENTER)
    п("«Барвиха Лаунж Невский» · 6 сентября 2026 года", размер=11, отступ=14,
      выравн=WD_ALIGN_PARAGRAPH.CENTER, курсив=True)

    п("Эта инструкция описывает всю работу со сменой по порядку: от того, "
      "что сделать в начале вечера, до того, чем вечер закончить. Она "
      "дополняет памятку «Пять ошибок, из-за которых деньги не доходят "
      "до людей» от 19 августа — та про ошибки, эта про порядок работы.", отступ=10)

    заголовок("Главное, что нужно понять про приложение", 14)
    п("Приложение не знает ничего, кроме того, что вы в него внесли. Оно не "
      "видит зал, не видит кассу и не видит, кто сегодня вышел. Всё, что "
      "не внесено, для него не существует — и значит, не существует для "
      "расчёта денег.", отступ=6)
    п("Отсюда простое правило: сначала состав смены, потом записи. Человека "
      "нет в составе — записать на него деньги нельзя, приложение просто "
      "не покажет его в списке.", отступ=10)

    # ── 1. состав
    заголовок("1. Начало смены: состав", 14)
    п("Открывая смену, заполните состав. Это семь строк, и пропускать нельзя "
      "ни одну из тех, что относятся к вашему вечеру.", отступ=8)
    таблица(
        ["Строка", "Что в неё ставить"],
        [
            ["Кто вносит записи",
             "Вы сами. Без этого приложение не даст работать: оно должно знать, "
             "чьей рукой сделана каждая запись."],
            ["Официанты",
             "Все, кто сегодня в зале. Отмечайте глазами по залу, а не по памяти "
             "вчерашнего дня. Кто-то вышел позже — вернитесь и добавьте."],
            ["Администратор смены",
             "Вы, если администратор один. Ему уходят 20 % с заработка официантов."],
            ["Второй администратор",
             "Только если смену делили надвое. Тогда доля администратора делится "
             "пополам между двумя. В обычный вечер строка остаётся пустой."],
            ["Кассир смены",
             "Кассир вечера. Его доля считается от чаевых официантов."],
            ["Хостес",
             "Если хостес работала и ей оставляли деньги. Её чаевые не делятся "
             "ни с кем."],
            ["Кальянный бар",
             "Если кальянщики сегодня работали. Поимённо бар не заводится: "
             "у него общий котёл, и это правильно, а не пробел."],
        ],
        [4.5, 11.5],
    )
    п("Заполнили — нажмите «Сохранить состав».", отступ=6)
    п("⚠ Второго администратора не отмечайте в первой строке. Там администратор "
      "один, и галочка просто переедет с первого на второго: первый останется "
      "без доли, и никто этого не заметит.", отступ=10)

    # ── 2. запись
    заголовок("2. Как внести чаевые", 14)
    п("Каждая запись собирается в одном и том же порядке. Порядок важен: "
      "вид денег выбирается до суммы, иначе легко нажать «как обычно».", отступ=8)
    for i, (шаг, текст) in enumerate([
        ("Стол", "Выберите стол, за которым гость оставил деньги. Стол нужен "
                 "не для красоты: по нему потом находят вечер, если что-то "
                 "не сошлось."),
        ("Вид денег", "Наличные, терминал или сервисный сбор. Спросите себя не "
                      "«как обычно», а «как гость заплатил именно сейчас»."),
        ("Сумма", "Ровно та, что была. Про терминал — отдельно ниже."),
        ("Кому", "Официант, которому эти деньги. Если гость оставил на "
                 "нескольких — нажмите «＋ разделить» и отметьте всех: "
                 "приложение разложит поровну, а двоим — пополам."),
    ], start=1):
        p = d.add_paragraph()
        p.paragraph_format.space_after = Pt(4)
        p.paragraph_format.left_indent = Cm(0.8)
        r = p.add_run(f"{i}. {шаг}. ")
        r.bold = True
        r.font.size = Pt(12)
        r2 = p.add_run(текст)
        r2.font.size = Pt(12)
    п(отступ=6)
    п("Про сумму с терминала — самое частое место ошибки. Чаевые на терминале "
      "почти всегда некруглые: гость нажимает 10, 15 или 20 % от чека. "
      "Вводите ровно то, что показал терминал, вместе с копейками: "
      "1 247,50 — значит 1247,50, не 1247 и не 1250.", отступ=6)
    п("Комиссию считать самим не нужно. Сбер удерживает с чаевых на терминале "
      "8 %, и приложение вычитает их само. Ваше дело — ввести полную сумму, "
      "которую видел гость.", отступ=10)

    # ── 3. QR
    заголовок("3. Чаевые по QR", 14)
    п("По QR деньги приходят в приложение сами: Сбер сообщает о поступлении, "
      "и сумма встаёт отдельной строкой. Но приложение не знает, кому она.", отступ=6)
    п("Пока вы не разнесли поступление, деньги ничьи. На экране такая строка "
      "подписана прямо: «нажмите, чтобы разнести по официантам», а если день "
      "уже прошёл — «не разнесли в ту смену, деньги до сих пор ничьи».", отступ=6)
    п("Нажмите на строку и укажите, кому. Можно одному, можно всем на смене. "
      "Сумма по QR приходит уже чистой — комиссию Сбер удержал до нас, "
      "вычитать ничего не надо.", отступ=10)

    # ── 4. бар и хостес
    заголовок("4. Кальянный бар и хостес", 14)
    п("У бара и хостес свои котлы, и деньги из них не делятся ни с "
      "администратором, ни с кассиром. Вносятся они на отдельном экране — "
      "там те же наличные, терминал, сервисный сбор и QR.", отступ=6)
    п("Если экран говорит «Кальянщиков нет в составе смены» или «Хостес нет "
      "в составе смены» — сначала отметьте их в составе, прямо оттуда. "
      "Без этого записи не будет.", отступ=6)
    п("У бара имён нет и быть не должно: система чаевых кальянного бара "
      "не предполагает личных сумм. Одна строка на весь бар — это устройство, "
      "а не недоделка.", отступ=10)

    # ── 5. питание
    заголовок("5. Питание", 14)
    п("Питание — это не доход, а вычет: сумма, которую у человека удерживают "
      "из выплаты. Вносится на своём экране, через «кто ел».", отступ=6)
    п("Важно: на порог 1 300 ₽ питание не влияет. Человек делится с "
      "администратором и кассиром от того, что заработал, а не от того, "
      "что получил на руки.", отступ=10)

    # ── 6. как считаются деньги
    заголовок("6. Как приложение делит деньги", 14)
    п("Это стоит знать наизусть: половина споров в конце смены — от незнания "
      "этих четырёх правил.", отступ=8)
    таблица(
        ["Правило", "Как работает"],
        [
            ["Порог 1 300 ₽",
             "Заработал за смену меньше 1 300 ₽ — не отдаёт никому ничего. "
             "Порог защищает тех, кто вышел в слабую смену."],
            ["Администратору 20 %",
             "От ВСЕГО заработка официанта, а не от превышения над порогом. "
             "Считается и с чаевых, и с сервисного сбора."],
            ["Кассиру — доля",
             "Общая сумма делится на число официантов смены. Обычный день — "
             "750 ₽, пятница и суббота — 1 000 ₽. Порог при этом не меняется."],
            ["Кассиру — только с чаевых",
             "Сервисный сбор кассира не касается. У кого чаевых не было вовсе, "
             "тот кассиру не платит."],
        ],
        [4.5, 11.5],
    )
    п("Тонкость про кассира: сумма делится на всех, кто работал, но платят "
      "только те, кто перешагнул порог. Поэтому кассир обычно получает меньше "
      "полной суммы — это потолок, а не обещание.", отступ=10)

    # ── 7. ошибки и правки
    заголовок("7. Если ошиблись", 14)
    п("Пока смена идёт — правьте прямо в приложении. Правка не стирает запись: "
      "старая остаётся в истории, и видно, что и когда поменяли. "
      "Это не слежка, а защита: через месяц никто не вспомнит, почему цифра "
      "изменилась, а запись об этом помнит.", отступ=6)
    п("Если ошибку заметили после смены — ничего не переписывайте задним "
      "числом на бумаге и не «досыпайте» в следующий вечер. Скажите владельцу: "
      "в бэк-офисе есть отдельные действия ровно на такие случаи, и они тоже "
      "оставляют след.", отступ=10)

    # ── 8. связь
    заголовок("8. Если пропала связь", 14)
    п("Работайте дальше — записи сохраняются на телефоне и уйдут сами, когда "
      "связь вернётся. Вверху появится полоса «Нет сети» или «Не всё "
      "отправлено».", отступ=6)
    п("⚠ Пока полоса горит, приложение закрывать нельзя. Телефон не хранит "
      "очередь после закрытия — несохранённые записи пропадут. Дождитесь, "
      "пока полоса исчезнет, или нажмите на неё, чтобы отправить сразу.", отступ=10)

    # ── 9. конец смены
    заголовок("9. Конец смены", 14)
    п("Три действия, всегда в этом порядке:", отступ=6)
    пункт("Разнесите все поступления по QR. Строка, оставшаяся неразнесённой, "
          "означает деньги, которые не достанутся никому.")
    пункт("Сложите итог в приложении и итог на бумажном листе. Разошлись — "
          "ищите сразу, пока помните вечер. Утром это уже раскопки.")
    пункт("Нажмите «Выгрузить смену для отчёта». Пока смена не выгружена, "
          "утренний отчёт её не увидит.")
    п(отступ=8)
    п("На экране итогов видно, как разошлись деньги: заработано за смену, "
      "официантам на руки, администратору, кассиру, удержано за питание, "
      "отдельно кальянный бар и хостес. Посмотрите на эти строки перед "
      "выгрузкой — они и есть проверка.", отступ=10)

    # ── 10. что показала сверка
    заголовок("10. Что показала сверка августа", 14)
    п("6 сентября лист управляющей компании сверили с приложением день за днём. "
      "Вот что нашлось — не для разбора виноватых, а чтобы стало понятно, "
      "какие ошибки бывают на самом деле.", отступ=8)
    таблица(
        ["Что случилось", "Сколько раз", "Цена"],
        [
            ["Деньги записаны на другого человека: сумма верная, "
             "фамилия чужая", "8 дней", "44 000 ₽ числятся не за теми"],
            ["Администратор за вечер не отмечен вовсе", "3 августа", "6 292 ₽"],
            ["Кассир отмечен не тот", "13 и 28 августа", "1 750 ₽"],
            ["Кальянный бар не вносили, пока не было кнопки", "1–18 августа",
             "41 867 ₽ есть только на бумаге"],
        ],
        [8.5, 3.5, 4.0],
    )
    п("Пять из восьми случаев с чужим именем — на одном и том же человеке: "
      "его ставили в лист, когда не помнили, кто именно работал. "
      "Не помните — посмотрите состав смены в приложении, он сохраняется.", отступ=10)

    # ── памятка
    заголовок("Памятка на конец смены", 14)
    п("Шесть вопросов, минута времени.", отступ=6)
    for в in [
        "Все, кто работал, есть в составе смены?",
        "Если администраторов было двое — второй вписан во вторую строку?",
        "Все поступления по QR разнесены по людям?",
        "Суммы с терминала внесены так, как показал терминал, — с копейками?",
        "Итог в приложении сходится с итогом на бумажном листе?",
        "Смена выгружена для отчёта?",
    ]:
        пункт(в)
    п(отступ=10)
    п("Если хоть на один ответ «нет» — деньги кого-то из смены до него "
      "не дойдут, и узнается это через две недели.", курсив=True, отступ=6)

    d.save(ФАЙЛ)
    return ФАЙЛ


if __name__ == "__main__":
    путь = собрать()
    print(f"✓ готово: {путь}")
