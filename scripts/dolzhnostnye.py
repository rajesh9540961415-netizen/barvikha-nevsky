def собрать(фамилия, имя, отчество, роль, куда: Path) -> Path:
    d = Document()
    ст = d.styles["Normal"]
    ст.font.name = "Times New Roman"
    ст.font.size = Pt(12)
    for s in d.sections:
        s.left_margin, s.right_margin = Cm(2.5), Cm(1.5)

    def п(текст="", ж=False, размер=12, отступ=6, выравн=None):
        par = d.add_paragraph()
        par.paragraph_format.space_after = Pt(отступ)
        if выравн:
            par.alignment = выравн
        if текст:
            r = par.add_run(текст)
            r.bold = ж
            r.font.size = Pt(размер)
        return par

    шапка = d.add_table(rows=1, cols=2)
    л, пр = шапка.rows[0].cells
    л.text = ""
    л.paragraphs[0].add_run("Приложение №1\nк Трудовому договору № ____ от «___» ______ 20___ г.").font.size = Pt(10)
    пр.text = ""
    r = пр.paragraphs[0].add_run(
        "Утверждаю\nИП Шалаева В. Е.\n_____________ В. Е. Шалаева\n«____» ____________ 20____ г.\nМ.П.")
    r.font.size = Pt(10)
    пр.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.RIGHT

    п()
    п("ДОЛЖНОСТНАЯ ИНСТРУКЦИЯ", ж=True, размер=14, выравн=WD_ALIGN_PARAGRAPH.CENTER, отступ=2)
    п("КАЛЬЯННОГО МАСТЕРА / ПОМОЩНИКА КАЛЬЯННОГО МАСТЕРА", ж=True, размер=14,
      выравн=WD_ALIGN_PARAGRAPH.CENTER, отступ=10)
    п(f"Работник: {фамилия} {имя} {отчество}", ж=True, отступ=2)
    п(f"Должность: {ДОЛЖНОСТИ[роль]}", ж=True, отступ=12)

    for номер, (заголовок, пункты) in enumerate((
        ("Общие положения", ОБЩИЕ),
        ("Должностные обязанности", ОБЯЗАННОСТИ),
        ("Права", ПРАВА),
        ("Ответственность", ОТВЕТСТВЕННОСТЬ),
    ), start=1):
        п(f"{номер}. {заголовок}", ж=True, размер=13, отступ=6)
        for i, текст in enumerate(пункты, start=1):
            par = d.add_paragraph()
            par.paragraph_format.space_after = Pt(4)
            par.paragraph_format.left_indent = Cm(0.5)
            par.add_run(f"{номер}.{i}. {текст}").font.size = Pt(12)
        п(отступ=6)

    п("Руководство организации/управляющий заведения, в связи с производственной "
      "необходимостью, вправе поручать работнику иные задания, вытекающие из его "
      "функциональных обязанностей.", отступ=16)

    п(f"С должностной инструкцией ознакомлен, экземпляр получил:", отступ=14)
    п(f"{фамилия} {имя[0]}. {отчество[0]}.   ______________________   "
      f"«____» ____________ 20____ г.", отступ=4)
    п("        (подпись)", размер=9)

    файл = куда / f"Должностная инструкция — {фамилия} {имя[0]}.{отчество[0]}. ({роль}).docx"
    d.save(файл)
    return файл


def главное() -> None:
    куда = ПАПКА
    куда.mkdir(parents=True, exist_ok=True)
    print(f"Складываю в: {куда}\n")
    for фамилия, имя, отчество, роль in ЛЮДИ:
        файл = собрать(фамилия, имя, отчество, роль, куда)
        print(f"  ✓ {файл.name}")
    print(f"\nГотово: {len(ЛЮДИ)} документа.")


if __name__ == "__main__":
    главное()
