#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Очередь утренних задач: две сразу не считают.

🔴 22.09.2026. Компьютер проспал одиннадцать утра, а когда проснулся,
система запустила ВСЕ четыре ежедневные задачи разом — в 17:16, одна минута
на всех. Финансовая сводка, отчёт по чаевым, итоги дня и проверка зависших
полезли в одни и те же файлы выгрузок одновременно.

Расписание разводило их по часам именно для того, чтобы такого не было:
они делят кассу, выгрузки и `data/dds/*.csv`, и порядок между ними
обязателен — выжимка читает то, что положили сводка и чаевые. Но
расписание разводит ЗАПУСКИ, а догоняющий залп идёт мимо расписания.

💡 Поэтому очередь живёт не в расписании, а в самих скриптах: кто пришёл
вторым, тот ждёт первого. Работает независимо от того, кто запустил —
задача, сторож или человек руками из окна сессии.

⚠️ Замок не «пропускает вперёд»: ждущий стоит ровно столько, сколько идёт
предыдущий, и заходит следом. Порядок при заторе получается не по
расписанию, а по приходу, — и это честнее, чем считать по файлам, которые
прямо сейчас переписывает сосед.

Как пользоваться — в конце скрипта, одной строкой:

    from ochered import очередь
    if __name__ == "__main__":
        with очередь("финансовая сводка"):
            main()
"""
import fcntl
import os
import sys
import time
from contextlib import contextmanager
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ЗАМОК = ROOT / "data" / ".очередь"

# Вложенный запуск не должен ждать сам себя: если скрипт когда-нибудь позовёт
# соседний как отдельную программу, тот увидит эту переменную и пройдёт мимо.
ПЕРЕМЕННАЯ = "NEVSKY_QUEUE_HELD"

# Сколько ждать соседа. Самая долгая задача — финансовая сводка, около 50
# минут; два часа это она же с запасом. Дольше ждать незачем: если сосед
# стоит третий час, он не работает, а висит на запросе разрешения, и тогда
# правильный ответ — громко сказать об этом, а не молча ждать до вечера.
ЖДАТЬ_МИНУТ = 120


@contextmanager
def очередь(имя, ждать_минут=ЖДАТЬ_МИНУТ):
    if os.environ.get(ПЕРЕМЕННАЯ):
        yield
        return

    ЗАМОК.parent.mkdir(parents=True, exist_ok=True)
    f = ЗАМОК.open("a+", encoding="utf-8")
    начало_ожидания = time.time()
    сказали = False
    while True:
        try:
            fcntl.flock(f.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
            break
        except OSError:
            if not сказали:
                f.seek(0)
                кто = f.read().strip() or "неизвестно кто"
                print(f"⏳ Сейчас считает: {кто}", flush=True)
                print(f"   «{имя}» встала в очередь — начну, как освободится "
                      f"(жду не дольше {ждать_минут} мин).", flush=True)
                сказали = True
            if time.time() - начало_ожидания > ждать_минут * 60:
                f.seek(0)
                кто = f.read().strip() or "неизвестно кто"
                raise SystemExit(
                    f"⚠️ «{имя}» прождала {ждать_минут} мин и не дождалась: "
                    f"всё это время считает {кто}.\n"
                    "   Ничего не посчитано и ничего не испорчено. Скорее всего "
                    "сосед висит на запросе разрешения — посмотрите его окно.")
            time.sleep(10)

    ждали = int(time.time() - начало_ожидания)
    if ждали > 5:
        print(f"✓ Дождалась своей очереди ({ждали // 60} мин {ждали % 60} с), начинаю.",
              flush=True)
    f.seek(0)
    f.truncate()
    f.write(f"{имя}, запущена {datetime.now():%H:%M:%S}, номер процесса {os.getpid()}")
    f.flush()

    os.environ[ПЕРЕМЕННАЯ] = имя
    try:
        yield
    finally:
        os.environ.pop(ПЕРЕМЕННАЯ, None)
        f.seek(0)
        f.truncate()
        f.write(f"никто (последней была «{имя}», кончила {datetime.now():%H:%M:%S})")
        f.flush()
        fcntl.flock(f.fileno(), fcntl.LOCK_UN)
        f.close()


if __name__ == "__main__":
    # Запуск руками показывает, занята ли очередь прямо сейчас.
    if not ЗАМОК.exists():
        print("Очередь пуста: никто ещё не запускался.")
        sys.exit()
    with ЗАМОК.open("a+", encoding="utf-8") as f:
        f.seek(0)
        кто = f.read().strip()
        try:
            fcntl.flock(f.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
            print(f"Очередь свободна. В записи: {кто}")
        except OSError:
            print(f"Очередь ЗАНЯТА: {кто}")
