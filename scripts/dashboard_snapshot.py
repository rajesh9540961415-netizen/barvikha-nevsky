#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Слепок для первого экрана бэк-офиса: день за днём, из фискальных чеков.

Заведено 07.09.2026 по задаче владельца «сделать первую страничку с основными
показателями работы заведения».

🔴 **Зачем слепок, а не запрос на лету.** Amvera собирает `manager-app`
отдельным корнем: всё, что лежит за его пределами, до сервера не доезжает —
ни `data/ofd`, ни `data/выгрузки-смен`. Значит бэк-офис не может посчитать
выручку сам. Поэтому здесь, на Маке, считается день за днём и кладётся
в `manager-app/src/data/dashboard.json`, откуда страница берёт готовое.

⚠️ **Сутки — с 11:00 до 10:59**, как во всём проекте (`СДВИГ_СУТОК` в
`qr_cancellations.py`). Иначе субботняя ночь после полуночи ушла бы
в воскресенье, а суббота — главный день недели, и терять её половину нельзя.
Час в гистограмме при этом настоящий, часовой: ради него всё и затевалось —
пик приходится на полночь.

⚠️ **Две кассы, но НЕ три файла.** С июля 2026 бар пробивается через вторую
кассу (`чеки-бар-*`). Складываем зал и бар. А `чеки-шалаева-*` брать НЕЛЬЗЯ:
проверено 07.09.2026 — все 1931 его чеков за август уже лежат внутри
`чеки-бар-2026-08` (совпадение по ФПД полное). Сложи их — и август вырастет
на 7,1 млн из ниоткуда.

⚠️ **`цена` в позиции чека — это сумма СТРОКИ, а не цена за штуку.** Проверено
07.09.2026: сумма всех `цена` по августу совпала с суммой чеков до рубля,
а `количество × цена` завысило её в полтора раза. Умножать нельзя.

Запуск:
    python3 scripts/dashboard_snapshot.py
"""
from __future__ import annotations

import collections
import glob
import json
import re
import sys
from datetime import datetime, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))

from pl_menu import категория  # noqa: E402  разнесение позиций по направлениям

СДВИГ_СУТОК = 11
КУДА = ROOT / "manager-app" / "src" / "data" / "dashboard.json"
ВЫГРУЗКИ = ROOT / "data" / "выгрузки-смен"
НАПРАВЛЕНИЯ = ("бар", "кухня", "кальяны", "аренда")


def торговый_день(iso: str) -> str:
    т = datetime.fromisoformat(iso.replace("Z", ""))
    return (т - timedelta(hours=СДВИГ_СУТОК)).date().isoformat()


def файлы_чеков() -> list[str]:
    """Зал и бар. Всё остальное — либо повтор, либо не наш контур."""
    зал = sorted(glob.glob(str(ROOT / "data" / "ofd" / "чеки-20*.json")))
    зал = [f for f in зал if re.search(r"чеки-\d{4}-\d{2}\.json$", f)]
    бар = sorted(glob.glob(str(ROOT / "data" / "ofd" / "чеки-бар-*.json")))
    return зал + бар


def пустой_день() -> dict:
    return {
        "выручка": 0.0, "чеков": 0, "нал": 0.0, "безнал": 0.0,
        "возвраты": 0.0, "возвратов": 0,
        "направления": {н: 0.0 for н in НАПРАВЛЕНИЯ},
        "часы": [0.0] * 24,
    }


def собрать_чеки() -> dict:
    дни: dict[str, dict] = collections.defaultdict(пустой_день)
    прочитано = 0
    for путь in файлы_чеков():
        сырое = json.load(open(путь, encoding="utf-8"))
        чеки = сырое if isinstance(сырое, list) else list(сырое.values())[0]
        прочитано += len(чеки)
        for ч in чеки:
            время = ч.get("время")
            if not время:
                continue
            д = дни[торговый_день(время)]
            сумма = float(ч.get("сумма") or 0)
            if ч.get("вид") == 2:
                д["возвраты"] += сумма
                д["возвратов"] += 1
                continue
            д["выручка"] += сумма
            д["чеков"] += 1
            д["нал"] += float(ч.get("нал") or 0)
            д["безнал"] += float(ч.get("безнал") or 0)
            д["часы"][datetime.fromisoformat(время.replace("Z", "")).hour] += сумма
            for имя, _кол, строка in (ч.get("позиции") or []):
                к = категория(имя)
                if к in д["направления"]:
                    д["направления"][к] += float(строка or 0)
    print(f"  чеков прочитано: {прочитано}, дней получилось: {len(дни)}")
    return дни


def добавить_чаевые(дни: dict) -> int:
    """Чаевые из выгрузок смен — те же файлы, что кормят утренний отчёт.

    Берём отсюда, а не из базы, нарочно: с Мака боевая база недоступна
    (VPN incy), а слепок должен собираться в любой момент, не только там,
    где есть доступ к базе.
    """
    сколько = 0
    for файл in sorted(ВЫГРУЗКИ.glob("смена-*.json")):
        try:
            смена = json.loads(файл.read_text(encoding="utf-8"))
        except Exception:
            continue
        день = смена.get("businessDay")
        итоги = смена.get("totals") or {}
        if not день or not итоги:
            continue
        if день not in дни:
            дни[день] = пустой_день()
        дни[день]["чаевые"] = round(float(итоги.get("earned") or 0), 2)
        сколько += 1
    return сколько


def главное() -> None:
    print("Слепок для дашборда")
    дни = собрать_чеки()
    с_чаевыми = добавить_чаевые(дни)
    print(f"  смен с чаевыми: {с_чаевыми}")

    готово = {}
    for день in sorted(дни):
        д = дни[день]
        готово[день] = {
            "выручка": round(д["выручка"], 2),
            "чеков": д["чеков"],
            "нал": round(д["нал"], 2),
            "безнал": round(д["безнал"], 2),
            "возвраты": round(д["возвраты"], 2),
            "возвратов": д["возвратов"],
            "направления": {н: round(д["направления"][н], 2) for н in НАПРАВЛЕНИЯ},
            "часы": [round(ч, 2) for ч in д["часы"]],
            **({"чаевые": д["чаевые"]} if "чаевые" in д else {}),
        }

    КУДА.parent.mkdir(parents=True, exist_ok=True)
    КУДА.write_text(
        json.dumps({"собрано": datetime.now().isoformat(timespec="minutes"),
                    "дни": готово}, ensure_ascii=False, separators=(",", ":")),
        encoding="utf-8")

    выручка = sum(д["выручка"] for д in готово.values())
    print(f"  записано в: {КУДА.relative_to(ROOT)} "
          f"({КУДА.stat().st_size / 1024:.0f} КБ)")
    print(f"  период: {min(готово)} — {max(готово)}")
    print(f"  выручка за весь период: {выручка:,.0f} ₽".replace(",", " "))


if __name__ == "__main__":
    главное()
