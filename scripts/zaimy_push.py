#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Заимствования между площадками → экран «Москва» в бэк-офисе.

Задача владельца 11.09.2026: отдельная страница, где видно, какая сумма
уходила с питерской площадки на московскую и что приходило обратно, с итоговой
цифрой фактического долга и комментарием напротив каждой строки — за что
именно ушли деньги.

🔴 **Это заём, а не расход и не вывод** — решение владельца 15.08.2026.
У ИП Шалаевой два расчётных счёта, и второй принадлежит московскому
заведению. Обычная разметка считает перевод между ними внутренним, и он
исчезает из отчёта совсем.

⚠️ **Видно только невскую сторону.** Выписку по московскому счёту владелец
сознательно не берёт (то же решение). Возврат, сделанный внутри Москвы, сюда
не попадёт: отсутствие возврата долга не доказывает. Страница пишет об этом
сама, но знать надо и тому, кто читает вывод скрипта.

⚠️ **Направление проверять обязательно.** 14.08.2026 возврат на 24 000 ₽
лежит в выписке среди тех же «заимствований» и отличается только полем
`direction`. Отбор по одному счёту даёт его как расход — на этом уже
ошиблись 17.08.2026 и завысили отток.

Комментарии живут в `data/dds/заимствования.json` — их пишет владелец через
переписку, а страница только показывает. Ключ строки тот же, что у правил
в registry.json: «дата + номер документа + сумма».

Запуск:
    python3 scripts/zaimy_push.py             посчитать и показать
    python3 scripts/zaimy_push.py --залить    отправить в бэк-офис
"""
from __future__ import annotations

import argparse
import csv
import json
import sys
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "dds"
КОММЕНТАРИИ = DATA / "заимствования.json"
АДРЕС_ПО_УМОЛЧАНИЮ = "https://nevsky-office-borzovavv.msk1.amvera.tech"


def из_env(имя: str, запасное: str = "") -> str:
    путь = ROOT / ".env"
    if путь.exists():
        for строка in путь.read_text(encoding="utf-8").splitlines():
            if строка.startswith(f"{имя}="):
                return строка.split("=", 1)[1].strip().strip('"').strip("'")
    return запасное


def деньги(v: float) -> str:
    return f"{v:,.0f}".replace(",", " ")


def ключ(дата: str, документ, сумма) -> str:
    """Тройка «дата + документ + сумма» — тот же ключ, что у правил разбора.

    Один ключ на оба места нарочно: разойдись они, разобранное перестало бы
    находиться, и долг вырос бы на ровном месте.
    """
    return f"{дата}|{документ}|{round(float(сумма), 2)}"


def собрать() -> list[dict]:
    реестр = json.loads((DATA / "registry.json").read_text(encoding="utf-8"))
    счёт = реестр["rules"].get("moscow_account")
    if not счёт:
        sys.exit("✗ В registry.json нет rules.moscow_account — не с чем сверять.")

    # Разобранное — не заём. Правила лежат в registry.json, там же записано,
    # ЗА ЧТО. Отличать по колонке `why` нельзя: она заполнена у всех, но
    # у неразобранных там общая причина разметки, а не объяснение.
    разобрано = {
        ключ(п["date"], п.get("doc_no", ""), п["amount"]): п.get("why", "")
        for п in реестр["rules"].get("reclassify", [])
    }

    свои = {}
    if КОММЕНТАРИИ.exists():
        свои = json.loads(КОММЕНТАРИИ.read_text(encoding="utf-8")).get("комментарии", {})

    движения = []
    файл = DATA / "bank_classified.csv"
    for r in csv.DictReader(файл.open(encoding="utf-8")):
        if r.get("counter_account") != счёт and r.get("account") != счёт:
            continue
        к = ключ(r["date"], r.get("doc_no", ""), r["amount"])
        движения.append({
            "день": r["date"],
            "документ": str(r.get("doc_no", "")),
            "сумма": round(abs(float(r["amount"])), 2),
            "направление": "out" if r["direction"] == "out" else "in",
            "комментарий": свои.get(к) or None,
            "не_заём": к in разобрано,
            "почему": разобрано.get(к) or None,
        })
    движения.sort(key=lambda д: (д["день"], д["документ"]))
    return движения


def показать(движения: list[dict]) -> None:
    живые = [д for д in движения if not д["не_заём"]]
    выдано = sum(д["сумма"] for д in живые if д["направление"] == "out")
    вернулось = sum(д["сумма"] for д in живые if д["направление"] == "in")
    объяснено = sum(д["сумма"] for д in живые
                    if д["направление"] == "out" and д["комментарий"])

    print("ЗАИМСТВОВАНИЯ МЕЖДУ ПЛОЩАДКАМИ")
    print("=" * 72)
    for д in движения:
        куда = "Питер → Москва" if д["направление"] == "out" else "Москва → Питер"
        текст = д["почему"] or д["комментарий"] or "— ещё не разбирали"
        метка = "✅ не заём" if д["не_заём"] else "         "
        print(f"{д['день']}  {куда:<16}{деньги(д['сумма']):>12} ₽  {метка}  {текст[:44]}")
    print("-" * 72)
    print(f"{'выдано займов':<28}{деньги(выдано):>14} ₽")
    print(f"{'вернулось из Москвы':<28}{деньги(вернулось):>14} ₽")
    print(f"{'ОСТАЁТСЯ ЗА МОСКВОЙ':<28}{деньги(выдано - вернулось):>14} ₽")
    print(f"{'  из них объяснено':<28}{деньги(объяснено):>14} ₽")
    print(f"{'  не разобрано':<28}{деньги(выдано - объяснено):>14} ₽")
    print()
    print("⚠️  Считаем по невским счетам: выписку по московскому счёту не берём.")
    print("    Возврат, сделанный внутри Москвы, сюда не попадёт — цифра может")
    print("    быть завышена, и отсутствие возврата долга не доказывает.")


def залить(движения: list[dict]) -> None:
    адрес = из_env("OFFICE_URL", АДРЕС_ПО_УМОЛЧАНИЮ).rstrip("/") + "/api/zaimy"
    ключ_доступа = из_env("FINANCE_KEY")
    if not ключ_доступа:
        sys.exit(
            "✗ Не задан FINANCE_KEY.\n"
            "  Тот же ключ, которым заливаются финансы: заимствования — те же\n"
            "  движения из той же выписки. Значение нужно в двух местах: в .env\n"
            "  проекта и в переменных приложения nevsky-office в панели Amvera."
        )

    тело = json.dumps({"движения": движения}, ensure_ascii=False).encode("utf-8")
    req = urllib.request.Request(
        адрес, data=тело, method="POST",
        headers={"X-Finance-Key": ключ_доступа, "Content-Type": "application/json"},
    )
    try:
        with urllib.request.urlopen(req, timeout=120) as ответ:
            итог = json.loads(ответ.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        подробности = e.read().decode("utf-8", errors="replace")
        try:
            разобрано = json.loads(подробности)
            причина = разобрано.get("причина", подробности)
            if разобрано.get("ошибки"):
                причина += "\n    " + "\n    ".join(разобрано["ошибки"])
        except json.JSONDecodeError:
            причина = подробности[:400]
        sys.exit(f"✗ Бэк-офис ответил {e.code}: {причина}")
    except urllib.error.URLError as e:
        sys.exit(f"✗ Не достучался до бэк-офиса: {e.reason}")
    print(f"\n✓ Залито движений: {итог.get('записано', 0)}")


def главное() -> None:
    разбор = argparse.ArgumentParser(description="Заимствования между площадками.")
    разбор.add_argument("--залить", action="store_true",
                        help="отправить в бэк-офис (без ключа — только показать)")
    аргументы = разбор.parse_args()

    движения = собрать()
    if not движения:
        sys.exit("✗ Движений с московским счётом не нашлось — проверьте выписку.")
    показать(движения)
    if аргументы.залить:
        залить(движения)
    else:
        print("\nЭто был показ. Чтобы отправить — добавьте --залить")


if __name__ == "__main__":
    главное()
