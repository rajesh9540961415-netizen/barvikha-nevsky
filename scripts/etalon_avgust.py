#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Август по эталону управляющего: его цифры + наш сервисный сбор и хостес.

Решение владельца 06.09.2026: «за эталон августа мы берём отчёт управляющего,
за исключением сервисного сбора». Причина — сверка 06.09 показала, что ошибки
есть с обеих сторон, и разбирать их по одной дороже, чем принять один источник.

Что откуда:
  — чаевые официантов, администраторы, кассиры, чаевые кальянного бара —
    ЛИСТ УК;
  — сервисный сбор и хостес — НАШИ: у управляющего блок сбора официантов
    и блок хостес пустые весь месяц, а пустая клетка значит «не заполнял»,
    а не «ноль».

⚠️ Сервисный сбор получают И официанты, И кальянщики — поправка владельца
06.09.2026. Поэтому исключение относится к сервисному сбору как таковому,
а не к блоку официантов. Но бар появился в приложении только 19 августа,
и за 1–18.08 у нас нет вообще ничего. Поэтому по бару сбор берётся так:
1–18.08 — лист УК (единственный источник), с 19.08 — наш. Отдельно 27.08:
бар в приложении не заведён вовсе, поэтому за этот день сбор тоже берётся
с листа УК — решение владельца 06.09.2026. Правило общее: если за день
приложение бар не вело, берём лист УК.

⚠️ Данные приложения этот скрипт НЕ меняет. В приложении остаётся то, что
внесла смена, — иначе история правок стала бы неправдой. Здесь собирается
отдельный файл-итог, и в нём же лежит список всех отличий.

Запуск:  python3 scripts/etalon_avgust.py
"""
from __future__ import annotations

import glob
import json
import re
import sys
import warnings
from collections import defaultdict
from pathlib import Path

warnings.filterwarnings("ignore")
ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))

from google.oauth2 import service_account            # noqa: E402
from googleapiclient.discovery import build          # noqa: E402
from openpyxl import Workbook                        # noqa: E402
from openpyxl.styles import Alignment, Font, PatternFill  # noqa: E402
from report_path import report_dir                   # noqa: E402

ТАБЛИЦА = "1DF6E-0R2yCSGsbszqScQJ4IBDjIhDXtcJb-lAtVNnn0"
ЛИСТ_УК = "Август 2026 "
МЕСЯЦ = "2026-08"

# Строки блоков в листе УК. Разметка их, менять нельзя.
БЛОКИ_УК = {
    "Чаевые официантов": (4, 24),
    "Администраторы": (52, 61),
    "Кассиры": (78, 87),
}
КАЛЬЯН_ЧАЙ, КАЛЬЯН_СБОР = 132, 133

# Как зовут одного человека лист УК, приложение и касса.
СЛОВАРЬ = {"лев и": "леонов лев", "лева и": "леонов лев",
           "щеляпа анаставсия": "щеляпа анастасия"}
ФАМИЛИИ = {"тарасов", "щеляпа", "леонов", "беков", "селютина", "миллес",
           "саблина", "горбунов", "пархоменко", "старостина", "геращенко",
           "самарина", "бактияр", "недорезова", "смирнова", "кононовская",
           "исмаилов", "гурылев", "ходжаева", "бобылева", "васильева",
           "воронков", "хостес"}


def ключ(имя: str) -> str:
    """Одно имя человека для всех трёх источников: по фамилии."""
    s = (имя or "").strip().lower().replace("ё", "е")
    s = re.sub(r"[^а-я ]", " ", s)
    s = re.sub(r"\s+", " ", s).strip()
    s = СЛОВАРЬ.get(s, s)
    фамилии = [t for t in s.split() if t in ФАМИЛИИ]
    return фамилии[0] if фамилии else " ".join(sorted(s.split()))


def число(x) -> float:
    if isinstance(x, (int, float)):
        return round(float(x), 2)
    if not x:
        return 0.0
    s = re.sub(r"[^0-9.\-]", "", str(x).replace(",", "."))
    return round(float(s), 2) if s else 0.0


def лист_ук():
    ключ_файл = ROOT / "data" / "certs" / "google-robot.json"
    creds = service_account.Credentials.from_service_account_file(
        str(ключ_файл), scopes=["https://www.googleapis.com/auth/spreadsheets"])
    api = build("sheets", "v4", credentials=creds, cache_discovery=False)
    значения = api.spreadsheets().values().get(
        spreadsheetId=ТАБЛИЦА, range=f"'{ЛИСТ_УК}'!A1:AF140",
        valueRenderOption="UNFORMATTED_VALUE").execute().get("values", [])
    return {i: r for i, r in enumerate(значения, start=1)}


def блок(сетка, r1, r2):
    данные, подписи = defaultdict(dict), {}
    for i in range(r1, r2 + 1):
        строка = сетка.get(i, [])
        имя = str(строка[0]).strip() if строка else ""
        if not имя:
            continue
        k = ключ(имя)
        подписи.setdefault(k, имя)
        for д in range(1, 32):
            v = число(строка[д]) if len(строка) > д else 0
            if v:
                данные[k][д] = round(данные[k].get(д, 0) + v, 2)
    return данные, подписи


def наши():
    """Сервисный сбор, хостес и то, что посчитало приложение, — для сверки."""
    сбор, хостес, чай, админ, кассир = (defaultdict(dict) for _ in range(5))
    бар: dict[int, float] = {}
    подписи = {}
    for путь in sorted(glob.glob(str(ROOT / "data" / "выгрузки-смен" / f"смена-{МЕСЯЦ}-*.json"))):
        смена = json.loads(Path(путь).read_text(encoding="utf-8"))
        день = int(смена["businessDay"].split("-")[2])

        def положить(куда, имя, сумма):
            k = ключ(имя)
            подписи.setdefault(k, имя)
            куда[k][день] = round(куда[k].get(день, 0) + сумма, 2)

        for о in смена["waiters"]:
            if о["accrued"]:
                положить(чай, о["name"], о["accrued"])
            if о["service"]:
                положить(сбор, о["name"], о["service"])
        for а in (смена.get("admins") or []):
            if а and а.get("amount") and а.get("name"):
                положить(админ, а["name"], а["amount"])
        к = смена.get("cashier")
        if к and к.get("amount") and к.get("name"):
            положить(кассир, к["name"], к["amount"])
        for х in смена["hostess"]["rows"]:
            положить(хостес, х["name"], х.get("total", 0))
        итоги_бара = смена["hookah"]["totals"] or {}
        # Различаем «сбора не было» и «бар в этот вечер не вели вовсе»:
        # во втором случае нулём подменять лист УК нельзя.
        if (итоги_бара.get("total") or 0) or (итоги_бара.get("service") or 0):
            бар[день] = round(итоги_бара.get("service") or 0, 2)
    return сбор, хостес, чай, админ, кассир, подписи, бар


def собрать():
    сетка = лист_ук()
    ук = {}
    подписи_ук = {}
    for название, (r1, r2) in БЛОКИ_УК.items():
        данные, подписи = блок(сетка, r1, r2)
        ук[название] = данные
        подписи_ук.update(подписи)
    сбор, хостес, чай_наш, админ_наш, кассир_наш, подписи_наши, бар_наш = наши()

    кальян = {}
    стр = сетка.get(КАЛЬЯН_ЧАЙ, [])
    кальян["Кальянный бар — чаевые"] = {д: число(стр[д]) for д in range(1, 32)
                                        if len(стр) > д and число(стр[д])}
    # Сбор бара: до 19.08 брать неоткуда, кроме листа УК; дальше — наш.
    стр = сетка.get(КАЛЬЯН_СБОР, [])
    сбор_бара = {д: число(стр[д]) for д in range(1, 32)
                 if (д <= 18 or д not in бар_наш)
                 and len(стр) > д and число(стр[д])}
    сбор_бара.update({д: v for д, v in бар_наш.items() if д >= 19 and v})
    кальян["Кальянный бар — сервисный сбор"] = сбор_бара
    подписи = {**подписи_наши, **подписи_ук}

    wb = Workbook()

    # ── лист 1: итог по людям
    ws = wb.active
    ws.title = "Август — итог"
    ws.append(["Сотрудник", "Блок", "Чаевые (эталон УК)",
               "Сервисный сбор (наш)", "Итого"])
    строки = []
    for название in ("Чаевые официантов", "Администраторы", "Кассиры"):
        for k, дни in ук[название].items():
            чай = round(sum(дни.values()), 2)
            сб = round(sum(сбор.get(k, {}).values()), 2) if название == "Чаевые официантов" else 0.0
            строки.append([подписи.get(k, k), название, чай, сб, round(чай + сб, 2)])
    for k, дни in хостес.items():
        s = round(sum(дни.values()), 2)
        строки.append([подписи.get(k, k), "Хостес (наш)", s, 0.0, s])
    for название, дни in кальян.items():
        s = round(sum(дни.values()), 2)
        строки.append(["весь бар", название + " (эталон УК)", s, 0.0, s])
    порядок = {"Чаевые официантов": 1, "Администраторы": 2, "Кассиры": 3,
               "Хостес (наш)": 4}
    for с in sorted(строки, key=lambda x: (порядок.get(x[1], 5), -x[4])):
        ws.append(с)
    ws.append([])
    ws.append(["ВСЕГО", "", round(sum(с[2] for с in строки), 2),
               round(sum(с[3] for с in строки), 2),
               round(sum(с[4] for с in строки), 2)])

    # ── лист 2: по дням, чаевые официантов
    ws2 = wb.create_sheet("Официанты по дням")
    ws2.append(["Сотрудник"] + [f"{д:02d}.08" for д in range(1, 32)] + ["Итого"])
    for k, дни in sorted(ук["Чаевые официантов"].items(),
                         key=lambda x: -sum(x[1].values())):
        ws2.append([подписи.get(k, k)] + [дни.get(д, "") for д in range(1, 32)]
                   + [round(sum(дни.values()), 2)])

    # ── лист 3: чем это отличается от того, что посчитало приложение
    ws3 = wb.create_sheet("Отличия от приложения")
    ws3.append(["Блок", "Дата", "Сотрудник", "Лист УК (принято)",
                "Приложение (было)", "Разница"])
    пары = (("Чаевые официантов", ук["Чаевые официантов"], чай_наш),
            ("Администраторы", ук["Администраторы"], админ_наш),
            ("Кассиры", ук["Кассиры"], кассир_наш))
    всего_отличий = 0
    for название, эталон, наше in пары:
        for k in sorted(set(эталон) | set(наше)):
            дЭ, дН = эталон.get(k, {}), наше.get(k, {})
            for д in sorted(set(дЭ) | set(дН)):
                a, b = дЭ.get(д, 0.0), дН.get(д, 0.0)
                if abs(a - b) >= 0.01:
                    ws3.append([название, f"{д:02d}.08.2026", подписи.get(k, k),
                                a, b, round(a - b, 2)])
                    всего_отличий += 1
    for название, дни in кальян.items():
        ws3.append([название, "весь месяц", "весь бар",
                    round(sum(дни.values()), 2), "", ""])

    for w, лист in ((ws, [26, 22, 20, 20, 14]), (ws2, [24] + [9] * 31 + [12]),
                    (ws3, [22, 14, 26, 18, 18, 12])):
        for i, ширина in enumerate(лист, start=1):
            буква = w.cell(row=1, column=i).column_letter
            w.column_dimensions[буква].width = ширина
        for клетка in w[1]:
            клетка.font = Font(bold=True)
            клетка.fill = PatternFill("solid", start_color="DDDDDD")
            клетка.alignment = Alignment(horizontal="center", wrap_text=True)
        w.freeze_panes = "B2"

    путь = report_dir() / "Чаевые — август 2026 (эталон отчёт управляющего).xlsx"
    wb.save(путь)
    return путь, всего_отличий, строки


if __name__ == "__main__":
    путь, отличий, строки = собрать()
    итого = sum(с[4] for с in строки)
    print(f"✓ собрано: {путь}")
    print(f"  людям за август: {итого:,.2f} ₽")
    print(f"  клеток, где эталон разошёлся с приложением: {отличий}")
