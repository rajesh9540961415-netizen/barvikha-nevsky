#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Столы из Рестоплейс: копим историю посадок и считаем их по дням.

🔴 **Зачем накопитель.** Рестоплейс отдаёт скользящее окно примерно в 33 дня.
Снимок от 28.08.2026 накрывал 27.07 — 28.08; снимок от 07.09 накрывает уже
06.08 — 07.09, и июля в нём нет вовсе. История существует ровно до тех пор,
пока мы не сложим её сами: не спросишь потом ни у кого, сколько было столов
в июле. Поэтому здесь — постоянный склад, который только растёт.

**Стол — это ЗАКРЫТАЯ бронь (статус 5), то есть одна посадка.** Не физический
столик: компания, севшая на два сдвинутых стола, — одна посадка и один счёт.
Проверено 07.09.2026 на августе: закрытых броней 2462, чеков зала 2485 —
почти один к одному, значит счёт и посадка совпадают.

⚠️ **Зачем это на «Сводке».** Средний чек по чекам врёт про температуру зала:
стол платит двумя чеками — кухня и бар на одной кассе, кальян на второй.
За 1–26 августа на чек выходило 4 578 ₽, а на стол — 8 242 ₽.

⚠️ **Глубже 27 июля 2026 столов не будет никогда.** Раньше этой даты
Рестоплейс уже ничего не отдаёт, а копить мы начали 07.09.2026 с двух
имеющихся снимков. На периодах «90 дней» и «год» плитка честно смолчит.

⚠️ **Последний день склада всегда неполный:** брони закрываются по ходу
вечера, и снимок, снятый днём, вечерних посадок ещё не видит.

Запуск:
    python3 scripts/rp_stoly.py              # забрать свежее и слить в склад
    python3 scripts/rp_stoly.py --без-сети   # слить только уже скачанное
    python3 scripts/rp_stoly.py --дни        # показать посадки по дням
"""
from __future__ import annotations

import json
import sys
from datetime import datetime, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))

ПАПКА = ROOT / "data" / "calls"
# 🔴 Склад лежит НЕ в data/calls, хотя снимки — там. Причина: data/calls
# исключена из гита, в ней голоса гостей и их телефоны. А склад — ровно то,
# что восстановить неоткуда: выпавшее из окна Рестоплейс не вернуть ничем,
# и держать его в единственном экземпляре на одном Маке нельзя. Имён и
# телефонов в нём нет вовсе — только статус, день, число гостей и зал.
СКЛАД = ROOT / "data" / "столы-рестоплейс.json"
ЗАКРЫТ = 5
# Те же торговые сутки, что во всём проекте: субботняя ночь после полуночи
# принадлежит субботе, а суббота — главный день недели.
СДВИГ_СУТОК = 11


def торговый_день(когда: object) -> str | None:
    """Торговый день брони или None, если время нечитаемое.

    ⚠️ Пустое время Рестоплейс отдаёт не пустым, а нулевым:
    «0000-00-00 00:00:00». На незакрытых бронях так приходит `time_open`,
    и разбор такой строки падает с «year 0 is out of range».
    """
    try:
        т = datetime.fromisoformat(str(когда).replace("T", " ").replace("Z", ""))
    except ValueError:
        return None
    return (т - timedelta(hours=СДВИГ_СУТОК)).date().isoformat()


def худая(б: dict) -> dict | None:
    """Только то, что нужно для счёта посадок. Целая бронь весит впятеро
    больше, а имена и телефоны гостей на «Сводке» не нужны вовсе.

    День считаем один раз, здесь: складу потом достаточно сложить готовое.
    """
    день = торговый_день(б.get("time_open")) or торговый_день(б.get("time_from"))
    if not день:
        return None
    столы = б.get("item_ids") or ([б["item_id"]] if б.get("item_id") else [])
    return {
        "статус": б.get("status"),
        "день": день,
        "гостей": int(б.get("count") or 0),
        "зал": б.get("floor_name"),
        "банкет": int(б.get("is_banquet") or 0),
        "столиков": len(столы),
        "изменена": б.get("last_updated"),
    }


def прочитать_склад() -> dict:
    if not СКЛАД.exists():
        return {}
    хранимое = json.loads(СКЛАД.read_text(encoding="utf-8"))
    return хранимое.get("брони") or {}


def снимки() -> list[Path]:
    """Разовые выгрузки `rp_reserves.py`, по возрастанию даты в имени.

    Порядок важен: сливаем от старых к свежим, и более поздний снимок
    перекрывает более ранний. Бронь могли закрыть, отменить или передвинуть
    уже после того, как её впервые увидели.
    """
    return sorted(ПАПКА.glob("брони-рестоплейс-*.json"))


def слить(свежие: list[dict], склад: dict) -> tuple[int, int]:
    новых = обновлённых = 0
    for б in свежие:
        ид = str(б.get("id") or "")
        запись = худая(б) if ид else None
        if not запись:
            continue
        if ид not in склад:
            склад[ид] = запись
            новых += 1
            continue
        # ⚠️ Старое поверх нового не кладём. Снимки сливаются после сетевого
        # запроса, и вчерашний файл иначе затирал бы сегодняшнее состояние
        # брони: открытый вечером стол снова становился бы «ожидаем».
        было = склад[ид].get("изменена") or ""
        стало = запись.get("изменена") or ""
        if стало < было:
            continue
        if склад[ид] != запись:
            склад[ид] = запись
            обновлённых += 1
    return новых, обновлённых


def записать_склад(склад: dict) -> None:
    # Покрытие считаем по ЗАКРЫТЫМ броням, а не по всем. В складе лежат
    # и будущие брони — Рестоплейс отдаёт их на месяц вперёд, — и если
    # взять по ним, «Сводка» решит, что про 20 сентября уже всё известно
    # и посадок там ноль.
    дни = sorted(з["день"] for з in склад.values() if з.get("статус") == ЗАКРЫТ)
    ПАПКА.mkdir(parents=True, exist_ok=True)
    СКЛАД.write_text(json.dumps({
        "обновлено": datetime.now().isoformat(timespec="seconds"),
        # Покрытие — не украшение: по нему «Сводка» отличает день без посадок
        # от дня, про который мы просто ничего не знаем. Ноль и прочерк —
        # разные вещи, и путать их нельзя.
        "покрытие": {"с": дни[0], "по": дни[-1]} if дни else None,
        "брони": склад,
    }, ensure_ascii=False, indent=1), encoding="utf-8")


def по_дням() -> tuple[dict[str, dict], tuple[str, str] | None]:
    """Посадки и гости по торговым дням плюс границы того, что мы знаем.

    Читает только склад, в сеть не ходит: этим пользуется `dashboard_push.py`,
    и заливка чисел не должна зависеть от того, дошёл ли запрос до Рестоплейс.
    """
    if not СКЛАД.exists():
        return {}, None
    хранимое = json.loads(СКЛАД.read_text(encoding="utf-8"))
    итог: dict[str, dict] = {}
    for з in (хранимое.get("брони") or {}).values():
        if з.get("статус") != ЗАКРЫТ:
            continue
        д = итог.setdefault(з["день"], {"столов": 0, "гостей": 0})
        д["столов"] += 1
        д["гостей"] += int(з.get("гостей") or 0)
    п = хранимое.get("покрытие")
    return итог, ((п["с"], п["по"]) if п else None)


def главное() -> None:
    аргументы = sys.argv[1:]
    склад = прочитать_склад()
    было = len(склад)

    if "--дни" not in аргументы and "--без-сети" not in аргументы:
        from rp_reserves import все_брони, ключ  # noqa: E402  тянет по сети
        print("Рестоплейс: беру свежие брони")
        новых, обновлённых = слить(все_брони(ключ()), склад)
        print(f"  из сети: новых {новых}, обновлённых {обновлённых}")

    for файл in снимки():
        брони = json.loads(файл.read_text(encoding="utf-8"))
        новых, обновлённых = слить(брони, склад)
        if новых or обновлённых:
            print(f"  {файл.name}: новых {новых}, обновлённых {обновлённых}")

    записать_склад(склад)
    дни, покрытие = по_дням()
    столов = sum(д["столов"] for д in дни.values())
    гостей = sum(д["гостей"] for д in дни.values())
    print(f"\nСклад: броней {len(склад)} (было {было}), из них закрытых {столов}")
    if покрытие:
        print(f"  дни: {покрытие[0]} — {покрытие[1]}, с посадками {len(дни)}")
    print(f"  гостей {гостей}, в среднем {гостей / столов:.2f} на стол"
          if столов else "  посадок нет")
    print(f"  файл: {СКЛАД.relative_to(ROOT)}")

    if "--дни" in аргументы:
        print(f"\n{'день':12} {'столов':>7} {'гостей':>7} {'на стол':>8}")
        for д in sorted(дни):
            з = дни[д]
            print(f"{д:12} {з['столов']:7d} {з['гостей']:7d} "
                  f"{з['гостей'] / з['столов']:8.2f}")


if __name__ == "__main__":
    главное()
