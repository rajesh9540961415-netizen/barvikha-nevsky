#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Разнести выводы собственнику по месяцам, ЗА которые платили.

Источник месяцев — таблица владельца от 12.09.2026: по каждому месяцу она
назвала сумму и источник (Хисамов, Борзова, Шалаева, а также Мята, МАВ
и наличка — последние три через наши счета не проходят и здесь не живут).

🔴 **Правило разнесения — не догадка, а слова владельца.** 12.09.2026:
«по Хисамову 4 100 000 июля — это часть, которая пошла в выплату за июнь,
но там в совокупности за июнь 5,5 миллионов по моей таблице». То есть
за месяц платят В ЭТОТ месяц и ПОСЛЕ него, частями, и один платёж может
закрыть хвост одного месяца и начало другого.

Отсюда две стороны разнесения, и обе важны:

  — **Хисамов: идём ОТ КОНЦА.** Свежий платёж закрывает свежий месяц,
    дальше вглубь. Проверка на словах владельца сходится: за июнь 2026
    получается 1 400 000 июньских платежей плюс 4 100 000 июльских —
    ровно 5 500 000, как у неё в таблице.
  — **Борзова: идём ОТ НАЧАЛА.** Её первый месяц (июль 2024) — начало
    работы ИП, раньше него платить было не за что, поэтому излишек обязан
    лечь в конец, а не в начало.

⚠️ **Излишек не размазываем.** У обоих ИП платежей больше, чем месяцев
в таблице, и лишнее остаётся БЕЗ месяца — видной строкой на экране.
Оба излишка ложатся в один и тот же стык: декабрь 2024 — март 2025,
когда деятельность переходила с ИП Борзовой на ИП Хисамова и платили
оба счёта разом. Что там чьё — знает владелец, догадываться нельзя.

⚠️ **Возврат 24 000 ₽ (14.08.2026, документ 997) выводом не стал.**
Поэтому платёж 1 524 000 того же дня участвует в разнесении суммой
1 500 000: остаток, не разнесённый по месяцам, в месяцы не идёт.

Запуск:
    python3 scripts/boss_raskidat.py            показать, что получится
    python3 scripts/boss_raskidat.py --записать  переписать вознаграждение.json
"""
from __future__ import annotations

import argparse
import csv
import json
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "dds"
ФАЙЛ = DATA / "вознаграждение.json"

# ── Таблица владельца от 12.09.2026, только строки через наши счета ──────
#
# «ИП» января и февраля 2025 отнесены к Хисамову: 4 400 000 января совпали
# с его январскими платежами до рубля. «ИП» ноября и декабря 2024 — к Борзовой:
# счёт Хисамова тогда ещё не работал (первые операции — 12.12.2024).
ХИСАМОВ = {
    "2025-01": 4_400_000, "2025-02": 200_000, "2025-03": 4_000_000,
    "2025-04": 4_800_000, "2025-05": 4_000_000, "2025-06": 1_322_000,
    "2025-07": 2_909_250, "2025-08": 4_256_000, "2025-09": 2_900_000,
    "2025-10": 3_500_000, "2025-11": 5_160_000, "2025-12": 3_160_000,
    "2026-01": 2_000_000, "2026-02": 2_000_000, "2026-03": 2_500_000,
    "2026-04": 4_500_000, "2026-05": 6_920_000, "2026-06": 5_500_000,
}
БОРЗОВА = {
    "2024-07": 7_500_000, "2024-08": 2_000_000, "2024-09": 2_700_000,
    "2024-10": 3_300_000, "2024-11": 3_000_000, "2024-12": 3_700_000,
}
# Июль 2026: 2 000 000 «Питер» + 4 500 000 «Москва» = 6 500 000 через банк.
# Остальные 2 500 000 того месяца — наличные, через счета они не проходили.
ШАЛАЕВА = {"2026-07": 6_500_000}

# Платежи, участвующие в разнесении не полной суммой.
УРЕЗАНЫ = {("2026-08-14", "995"): 1_500_000}  # 24 000 вернулись в тот же день


def платежи(лицо: str) -> list[list]:
    свои = []
    for r in csv.DictReader((DATA / "bank_classified.csv").open(encoding="utf-8")):
        if r["entity"] != лицо or r["direction"] != "out" or r.get("class") != "withdrawal":
            continue
        полная = round(float(r["amount"]), 2)
        доступно = УРЕЗАНЫ.get((r["date"], r.get("doc_no", "")), abs(полная))
        свои.append([r["date"], r.get("doc_no", ""), полная, abs(доступно)])
    свои.sort(key=lambda x: (x[0], x[1]))
    return свои


def разнести(лицо: str, месяцы: dict, от_конца: bool) -> tuple[dict, list]:
    очередь = платежи(лицо)
    порядок = sorted(месяцы, reverse=от_конца)
    ряд = list(reversed(очередь)) if от_конца else list(очередь)
    разметка: dict[str, dict] = defaultdict(dict)
    полные: dict[str, float] = {}
    доступно: dict[str, float] = {}
    _доступно_было = [п[3] for п in ряд]
    i = 0
    for м in порядок:
        надо = месяцы[м]
        while надо > 0.004 and i < len(ряд):
            берём = min(ряд[i][3], надо)
            if берём > 0.004:
                ключ = f"{ряд[i][0]}|{ряд[i][1]}|{ряд[i][2]}"
                разметка[ключ][м] = round(разметка[ключ].get(м, 0) + берём, 2)
                полные[ключ] = abs(ряд[i][2])
                доступно[ключ] = доступно.get(ключ, 0) or _доступно_было[i]
            ряд[i][3] -= берём
            надо -= берём
            if ряд[i][3] <= 0.004:
                i += 1
    # ⚠️ Платёж, поделённый между названным месяцем и безымянным хвостом,
    # обязан показать и хвост. Разметка словарём говорит «в месяцы идёт
    # только перечисленное», и остальное с экрана исчезает совсем — так
    # задумано для возврата 24 000 ₽, но не для этих денег. Пустой ключ
    # означает «месяц не назван» и возвращает хвост на экран.
    #
    # 🔴 Без этой строки на первом прогоне 12.09.2026 пропали 3 071 591 ₽:
    # итог сошёлся сам с собой и был меньше выписки. Поймано сравнением
    # итога с суммой выводов в банке — своей же проверкой изнутри не ловится.
    for ключ, доли in разметка.items():
        хвост = round(доступно.get(ключ, 0) - sum(доли.values()), 2)
        if хвост > 0.004:
            доли[""] = хвост

    остаток = [п for п in ряд[i:] if п[3] > 0.004]
    return разметка, остаток, полные


def деньги(v) -> str:
    return f"{v:,.0f}".replace(",", " ")


def main() -> None:
    разбор = argparse.ArgumentParser()
    разбор.add_argument("--записать", action="store_true")
    args = разбор.parse_args()

    всё: dict[str, dict] = {}
    суммы: dict[str, float] = {}
    итоги = []
    for имя, лицо, месяцы, от_конца in [
        ("ИП Хисамов", "ip_khisamov", ХИСАМОВ, True),
        ("ИП Борзова", "ip_borzova", БОРЗОВА, False),
        ("ИП Шалаева", "ip_shalaeva", ШАЛАЕВА, False),
    ]:
        разметка, остаток, полные = разнести(лицо, месяцы, от_конца)
        всё.update(разметка)
        суммы.update(полные)
        разнесено = sum(sum(v.values()) for v in разметка.values())
        итоги.append((имя, разнесено, sum(п[3] for п in остаток), остаток))

    print("РАЗНЕСЕНИЕ ВЫВОДОВ ПО МЕСЯЦАМ")
    print("-" * 62)
    for имя, разнесено, без, остаток in итоги:
        print(f"{имя:<13} разнесено {деньги(разнесено):>13} ₽    без месяца {деньги(без):>11} ₽")
    print("-" * 62)
    print(f"{'ВСЕГО':<13} разнесено {деньги(sum(и[1] for и in итоги)):>13} ₽"
          f"    без месяца {деньги(sum(и[2] for и in итоги)):>11} ₽")

    for имя, _, без, остаток in итоги:
        if остаток:
            print(f"\nБЕЗ МЕСЯЦА — {имя}:")
            for д, н, _, с in sorted(остаток):
                print(f"   {д}  док {н or '—':>7}  {деньги(с):>12} ₽")

    if not args.записать:
        print("\nЭто был показ. Чтобы записать — добавьте --записать")
        return

    прежнее = json.loads(ФАЙЛ.read_text(encoding="utf-8")) if ФАЙЛ.exists() else {}
    # Месяцы переписываем целиком, комментарии владельца сохраняем: это разные
    # вещи, и её пояснения к платежам не должны гибнуть при пересборке.
    новое = {
        "_описание": прежнее.get("_описание",
            "Месяцы, ЗА которые платили вознаграждение. Ключ: «дата|документ|сумма»."),
        "_как_получено": "scripts/boss_raskidat.py по таблице владельца от 12.09.2026",
        # 🔴 Строкой месяц пишем ТОЛЬКО когда платёж ушёл в один месяц
        # ЦЕЛИКОМ. Строка в файле разметки значит «весь платёж за этот месяц»,
        # и написав её у платежа, из которого в месяц ушла лишь часть, мы
        # молча добавили бы в месяц чужие деньги. На первом прогоне 12.09.2026
        # это дало июль 2026 = 7 374 000 вместо 6 500 000 и лишние три
        # миллиона в разнесённом: словарь с одной парой — не то же самое,
        # что строка.
        "месяцы": {
            к: (next(iter(v)) if len(v) == 1
                and abs(sum(v.values()) - суммы.get(к, 0)) < 0.01 else v)
            for к, v in всё.items()
        },
        "комментарии": прежнее.get("комментарии", {}),
    }
    ФАЙЛ.write_text(json.dumps(новое, ensure_ascii=False, indent=2), encoding="utf-8")
    print(f"\n✓ Записано в {ФАЙЛ.name}: строк {len(новое['месяцы'])}")


if __name__ == "__main__":
    main()
