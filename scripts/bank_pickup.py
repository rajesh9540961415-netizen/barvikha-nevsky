#!/usr/bin/env python3
"""Забирает выписки, скачанные руками, из «Загрузок» в папку проекта.

⚠️ **Зачем отдельный скрипт вместо одной строчки `cp`.** В инструкции
ежедневной задачи стояло:

    cp /Users/user/Downloads/kl_to_1c*.txt /Users/user/Downloads/sber_*.zip \\
       "data/dds/выписки/" 2>/dev/null

Под zsh — а это оболочка на этом Маке — такая команда не копирует **ничего**,
если хотя бы один из двух образцов ни с чем не совпал. zsh в этом случае
не подставляет образец и не запускает `cp` вовсе, а печатает «no matches
found» и останавливается. В bash поведение обратное, поэтому строчка выглядела
рабочей. `2>/dev/null` делало только хуже: гасило единственный признак беды.

Обнаружено 15.08.2026. Цена ошибки: выписка ИП Хисамова за 09.2024–07.2026
и выписка ИП Борзовой за 05.2024–04.2025 пролежали в «Загрузках» с 13 августа
и в учёт не попали — а вместе с ними 2 508 операций первого ИП.

Питон разбирает образцы сам и на пустой отвечает пустым списком, а не отказом
работать. Правило шире случая: **если тишина при неудаче неотличима от тишины
при успехе, беда живёт ровно столько, сколько её никто не ищет.**

Запуск:
    python3 scripts/bank_pickup.py           # забрать и показать, что забрал
    python3 scripts/bank_pickup.py --import  # и сразу пересобрать таблицы
"""

from __future__ import annotations

import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ЗАГРУЗКИ = Path.home() / "Downloads"
ВЫПИСКИ = ROOT / "data" / "dds" / "выписки"

# Как Сбер называет то, что скачивают руками: выгрузка «1С» и архив рассылки.
ОБРАЗЦЫ = ("kl_to_1c*.txt", "sber_*.zip", "СберБизнес*.zip", "Выписка*.txt")


def main() -> None:
    ВЫПИСКИ.mkdir(parents=True, exist_ok=True)

    найдено = sorted({p for о in ОБРАЗЦЫ for p in ЗАГРУЗКИ.glob(о) if p.is_file()})
    if not найдено:
        print("В «Загрузках» новых выписок нет.")
        новых = 0
    else:
        новых = 0
        for источник in найдено:
            цель = ВЫПИСКИ / источник.name
            # Тот же файл уже лежит — не трогаем: даты не сбиваем, шум не плодим.
            if цель.exists() and цель.read_bytes() == источник.read_bytes():
                print(f"· уже есть, пропускаю: {источник.name}")
                continue
            цель.write_bytes(источник.read_bytes())
            print(f"✓ забрал: {источник.name} ({источник.stat().st_size:,} байт)"
                  .replace(",", " "))
            новых += 1
        print(f"\nВсего в «Загрузках» подходящих файлов: {len(найдено)}, "
              f"новых или изменившихся: {новых}")

    if "--import" in sys.argv and новых:
        print()
        subprocess.run([sys.executable, str(ROOT / "scripts" / "bank_import.py")],
                       check=True)
    elif "--import" in sys.argv:
        print("Пересобирать таблицы не из чего — ничего нового не появилось.")


if __name__ == "__main__":
    main()
