ГРУППА = -1002111693197  # «НЕВСКИЙ | АДМИН»
СЕССИЯ = ROOT / "scripts" / ".tg-mac-session"
НАЧАЛО = "мотивация кальянного бара"

# Разбор отчёта живёт в tg-reader/bar_parse.py: с 20.10.2026 тот же отчёт
# читает робот в Варшаве и кладёт в базу. Две копии разбора разошлись бы,
# и сверка показывала бы расхождение там, где его нет.
from db import use_reader_code  # noqa: E402

use_reader_code()
