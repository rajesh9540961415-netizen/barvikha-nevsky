#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Сверка нашей мотивации кальянного бара с отчётом администратора.

🔴 **Зачем.** Владелец 08.09.2026: «отчёт администратора надо читать в любом
случае для проверки». В этот день её сверка с этим отчётом поймала ЧЕТЫРЕ
ошибки нашего счёта подряд — электронную чашу, начисленную дважды; нулёвки,
получавшие доплату; недосбор кэша чеков; и задвоение чеков на границе
месяцев. Ни одну из них не увидела бы проверка внутри программы: она считала
уверенно и складно, а сторож «сходится ли сумма сама с собой» молчал.

💡 Отсюда правило: **ошибку такого рода находит только сверка с чем-то
СНАРУЖИ.** Внутренняя проверка подтверждает согласованность, а не правду.

⚠️ Сверять НАДО ПО ТИПАМ, а не по итогу. Итог сходится и при двух ошибках,
гасящих друг друга: 08.09 недосбор кэша и задвоение файлов гасили друг друга
ровно наполовину, и общая сумма выглядела почти верной.

⚠️ **Чат «НЕВСКИЙ | АДМИН» служебному аккаунту недоступен** — его туда
не добавляли (проверено 08.09.2026: аккаунт состоит в пяти группах, этой
среди них нет). Пока так, текст отчёта скармливается файлом.

Запуск:
    python3 scripts/motivaciya_sverka.py --файл отчёт.txt
    pbpaste | python3 scripts/motivaciya_sverka.py
"""
from __future__ import annotations

import argparse
import re
import sys
from datetime import datetime
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))

# Как администратор называет типы и как называем их мы.
ИМЕНА = {
    "perfume чаша": "Perfume чаша",
    "perfume фрукт": "Perfume фрукт",
    "кальян на фрукте": "Кальян на фрукте",
    "авторское предложение": "Авторское предложение",
    "арт-кальян": "Арт-кальян",
    "фирменный кальян барвиха": "Фирменный Барвиха",
    "чемпионат мира": "Чемпионат мира",
}


def разобрать(текст: str) -> tuple[str | None, dict, float | None]:
    """Из сообщения администратора — день, штуки по типам и его итог.

    Формат из группы «НЕВСКИЙ | АДМИН», снимок владельца 08.09.2026:

        Мотивация кальянного бара:
        31.08.26

        1. Perfume чаша
        18*200=3600₽
        ...
        Итого: 8600₽
    """
    день = None
    м = re.search(r"(\d{2})\.(\d{2})\.(\d{2,4})", текст)
    if м:
        д, мес, г = м.groups()
        г = г if len(г) == 4 else f"20{г}"
        день = f"{г}-{мес}-{д}"

    штук: dict[str, float] = {}
    строки = [с.strip() for с in текст.splitlines()]
    последний = None
    for с in строки:
        подпись = re.sub(r"^\d+\.\s*", "", с).strip().lower().rstrip(":")
        if подпись in ИМЕНА:
            последний = ИМЕНА[подпись]
            continue
        # «18*200=3600₽» — количество, ставка, сумма
        ч = re.match(r"^(\d+)\s*[*х×]\s*(\d+)\s*₽?\s*=", с.replace(" ", ""))
        if ч and последний:
            штук[последний] = штук.get(последний, 0) + int(ч.group(1))
            последний = None

    итог = None
    м = re.search(r"Итого:\s*([\d\s]+)", текст)
    if м:
        итог = float(м.group(1).replace(" ", ""))
    return день, штук, итог


def наши(день: str) -> tuple[dict, float]:
    from hookah_push import правила, категории, начисления, чеки_месяца, торговый_день, ВОЗВРАТ
    ставки, комплект, вне = правила()
    карта = категории()
    штук: dict[str, float] = {}
    всего = 0.0
    for ч in чеки_месяца(день[:7]):
        if not ч.get("время") or торговый_день(ч["время"]) != день:
            continue
        знак = -1 if ч.get("вид") == ВОЗВРАТ else 1
        позиции = [(str(и), float(к or 0), float(с or 0))
                   for и, к, с in (ч.get("позиции") or [])]
        начислено, _ = начисления(позиции, ставки, комплект, карта, вне)
        for _и, тип, кол, ставка in начислено:
            штук[тип] = штук.get(тип, 0) + знак * кол
            всего += знак * кол * ставка
    return штук, всего


def главное() -> None:
    разбор = argparse.ArgumentParser(description="Сверка мотивации с отчётом администратора.")
    разбор.add_argument("--файл", help="файл с текстом отчёта; без него читаю из ввода")
    аргументы = разбор.parse_args()

    текст = (Path(аргументы.файл).read_text(encoding="utf-8")
             if аргументы.файл else sys.stdin.read())
    день, его, его_итог = разобрать(текст)
    if not день:
        sys.exit("✗ В тексте не нашлось даты вида 31.08.26 — сверять нечего")
    if not его:
        sys.exit("✗ Ни одного типа кальяна не разобралось. Формат отчёта изменился?")

    наши_штук, наш_итог = наши(день)
    print(f"СВЕРКА МОТИВАЦИИ за {день}\n")
    print(f"{'тип':<26} {'у него':>7} {'у нас':>7} {'разница':>9}")
    print("─" * 53)
    расхождений = 0
    for тип in sorted(set(его) | set(наши_штук)):
        а, б = его.get(тип, 0), наши_штук.get(тип, 0)
        знак = "" if а == б else f"{б - а:+.0f}"
        if а != б:
            расхождений += 1
        print(f"{тип:<26} {а:>7.0f} {б:>7.0f} {знак:>9}")
    print("─" * 53)
    if его_итог is not None:
        print(f"{'ИТОГО, ₽':<26} {его_итог:>7.0f} {наш_итог:>7.0f} "
              f"{'' if его_итог == наш_итог else f'{наш_итог - его_итог:+.0f}':>9}")

    if расхождений:
        print(f"\n🔴 Расходится типов: {расхождений}. Разбираться ОБЯЗАТЕЛЬНО: "
              f"08.09.2026 такое расхождение в одну штуку вскрыло четыре ошибки счёта.")
    else:
        print("\n✅ Сошлось по всем типам.")


if __name__ == "__main__":
    главное()
