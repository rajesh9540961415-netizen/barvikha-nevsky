def разобрать(текст: str) -> tuple[str | None, dict, float | None]:
    """Из сообщения администратора — день, штуки по типам и его итог.

    ⚠️ Тип, которого нет в списке, теперь не пропускается, а приходит под
    именем администратора — и в сверке встаёт строкой «у нас 0».
    """
    м = разобрать_мотивацию(текст)
    if м is None:
        # Старое поведение: текст без заголовка (вставлен руками) тоже разбирать.
        м = разобрать_мотивацию(f"Мотивация кальянного бара\n{текст}")
    штук: dict[str, float] = {}
    for п in м.позиции:
        штук[п.тип] = штук.get(п.тип, 0) + п.штук
    for замечание in м.замечания:
        print(f"⚠️ В самом отчёте: {замечание}", file=sys.stderr)
    return м.день, штук, None if м.итог is None else float(м.итог)


# ⚠️ Здесь жило правило «он считает ЧМ арт-кальяном, а мы порознь». 08.09.2026
