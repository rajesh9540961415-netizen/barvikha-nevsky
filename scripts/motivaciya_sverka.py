def наши(день: str) -> tuple[dict, float]:
    from hookah_push import правила, категории, начисления, чеки_месяца, торговый_день, ВОЗВРАТ
    ставки, комплект, вне = правила()
    карта = категории()
    штук: dict[str, float] = {}
    всего = 0.0
    for ч in чеки_месяца(день[:7]):
        if not ч.get("время") or торговый_день(ч["время"]) != день:
            continue
        знак = -1 if ч.get("вид") == ВОЗВРАТ else 1
        позиции = [(str(и), float(к or 0), float(с or 0))
                   for и, к, с in (ч.get("позиции") or [])]
        начислено, _ = начисления(позиции, ставки, комплект, карта, вне)
        for _и, тип, кол, ставка in начислено:
            штук[тип] = штук.get(тип, 0) + знак * кол
            всего += знак * кол * ставка
    return штук, всего


def из_env(имя: str) -> str:
    for строка in (ROOT / ".env").read_text(encoding="utf-8").splitlines():
        строка = строка.strip()
        if строка.startswith(f"{имя}="):
            return строка.split("=", 1)[1].strip().strip('"').strip("'")
    sys.exit(f"✗ В .env нет {имя}")


async def из_чата(день: str) -> str | None:
    """Отчёт администратора за нужный день из группы «НЕВСКИЙ | АДМИН».

    ⚠️ Ищем по ТЕКСТУ сообщения, а не по времени его отправки: отчёт за смену
    пишут ночью или под утро, и календарная дата сообщения не совпадает
    с днём смены. Дата стоит внутри самого отчёта — на неё и смотрим.
    """
    try:
        from telethon import TelegramClient
    except ImportError:
        sys.exit("✗ Нет telethon: pip3 install telethon")
    if not Path(f"{СЕССИЯ}.session").exists():
        sys.exit(f"✗ Нет файла сессии {СЕССИЯ.name}.session — заведите её: "
                 "python3 scripts/tg_login.py --мак")
    клиент = TelegramClient(str(СЕССИЯ), int(из_env("TG_API_ID")), из_env("TG_API_HASH"))
    await клиент.start()
    найдено = None
    async for сообщение in клиент.iter_messages(ГРУППА, limit=300):
        текст = сообщение.message or ""
        if НАЧАЛО not in текст.lower():
            continue
        его_день, _штук, _итог = разобрать(текст)
        if его_день == день:
            найдено = текст
            break
    await клиент.disconnect()
    return найдено


def главное() -> None:
    разбор = argparse.ArgumentParser(description="Сверка мотивации с отчётом администратора.")
    разбор.add_argument("день", nargs="?", help="день смены; по умолчанию вчерашний")
    разбор.add_argument("--файл", help="файл с текстом отчёта вместо чата")
    аргументы = разбор.parse_args()

    # ⚠️ Проверяем не «терминал ли ввод», а есть ли в нём что-то. Запуск
    # из задачи по расписанию или в фоне терминалом не считается, и проверка
    # `isatty()` уводила скрипт читать пустоту вместо чата — молча, с жалобой
    # «в тексте не нашлось даты».
    из_ввода = "" if sys.stdin.isatty() else sys.stdin.read()
    if аргументы.файл:
        текст = Path(аргументы.файл).read_text(encoding="utf-8")
    elif из_ввода.strip():
        текст = из_ввода
    else:
        import asyncio
        from datetime import timedelta
        нужен = аргументы.день or (datetime.now() - timedelta(days=1)).strftime("%Y-%m-%d")
        текст = asyncio.run(из_чата(нужен))
        if not текст:
            sys.exit(f"✗ В группе «НЕВСКИЙ | АДМИН» нет отчёта за {нужен} "
                     f"среди трёхсот последних сообщений")
    день, его, его_итог = разобрать(текст)
    if not день:
        sys.exit("✗ В тексте не нашлось даты вида 31.08.26 — сверять нечего")
    if not его:
        sys.exit("✗ Ни одного типа кальяна не разобралось. Формат отчёта изменился?")

    наши_штук, наш_итог = наши(день)
    print(f"СВЕРКА МОТИВАЦИИ за {день}\n")
    print(f"{'тип':<26} {'у него':>7} {'у нас':>7} {'разница':>9}")
    print("─" * 53)
    расхождений = 0
    for тип in sorted(set(его) | set(наши_штук)):
        а, б = его.get(тип, 0), наши_штук.get(тип, 0)
        знак = "" if а == б else f"{б - а:+.0f}"
        if а != б:
            расхождений += 1
        print(f"{тип:<26} {а:>7.0f} {б:>7.0f} {знак:>9}")
    print("─" * 53)
    if его_итог is not None:
        print(f"{'ИТОГО, ₽':<26} {его_итог:>7.0f} {наш_итог:>7.0f} "
              f"{'' if его_итог == наш_итог else f'{наш_итог - его_итог:+.0f}':>9}")

    if расхождений:
        print(f"\n🔴 Расходится типов: {расхождений}. Разбираться ОБЯЗАТЕЛЬНО: "
              f"08.09.2026 такое расхождение в одну штуку вскрыло четыре ошибки счёта.")
    else:
        print("\n✅ Сошлось по всем типам.")


if __name__ == "__main__":
    главное()
