def учебное_зависание():
    """Подсовывает сторожу заведомо повисший запуск и смотрит, узнал ли он его.

    ⚠️ Настоящих зависших запусков в журналах нет и быть не должно — их
    снимают в тот же день. Поэтому единственный способ проверить главную
    проверку сторожа — собрать такой журнал самому: имя задачи в начале,
    вызов инструмента без ответа в конце, время — вчерашнее.

    Если однажды приложение начнёт писать журналы иначе, эта строчка скажет
    «не узнал» — и это будет единственное предупреждение, которое мы получим.
    Молча ослепший сторож хуже, чем никакого.
    """
    import tempfile

    вчера = (datetime.now() - timedelta(days=1)).astimezone()
    записи = [
        {"type": "user", "timestamp": вчера.isoformat(),
         "message": {"content": '<scheduled-task name="учебная-тревога"> задание </scheduled-task>'}},
        {"type": "assistant", "timestamp": вчера.isoformat(),
         "message": {"content": [{"type": "tool_use", "name": "Bash",
                                  "input": {"command": "сочинённая команда"}}]}},
    ]
    with tempfile.TemporaryDirectory() as д:
        файл = Path(д) / "uchebnyj.jsonl"
        файл.write_text("\n".join(json.dumps(z, ensure_ascii=False) for z in записи),
                        encoding="utf-8")
        разбор = разобрать_журнал(файл)

    if разбор and разбор[0] == "учебная-тревога" and разбор[3] and not разбор[4]:
        строки.append("   учения: подсунутый зависший запуск узнан — читать журналы сторож умеет")
    else:
        тревоги.append("СТОРОЖ ОСЛЕП: учебный зависший запуск не узнан — "
                       "журналы сессий выглядят не так, как он ждёт")


def учебное_снятие():
    """Проверяет саму руку: заводит безобидный процесс и снимает его.

    ⚠️ Без этой проверки сторож обещает то, чего никто не видел. Настоящее
    снятие случается раз в несколько недель и всегда среди ночи — если рука
    отсохла, узнать об этом можно будет только по пропавшей сводке, то есть
    ровно тогда, когда проверять поздно.

    Берём `sleep`, потому что он ничей: снять его безопасно в любую секунду.
    Заодно смотрим, попадает ли собственный номер процесса в список
    неприкосновенных — это то, что удерживает сторожа от самоубийства.
    """
    вспомогательный = subprocess.Popen(["sleep", "120"])
    вышло, как = снять_запуск(вспомогательный.pid)
    if вышло:
        строки.append(f"   учения: учебный процесс {как} — рука сторожа работает")
    else:
        тревоги.append(f"СТОРОЖ БЕЗ РУК: учебный процесс снять не удалось ({как}) — "
                       f"значит и зависший запуск он не снимет, только напишет о нём")
        вспомогательный.kill()

    свои = предки()
    if os.getpid() in свои and len(свои) > 1:
        строки.append(f"   учения: свой номер и {len(свои) - 1} над ним в неприкосновенных — "
                      f"сам себя не сниму")
    else:
        тревоги.append("СТОРОЖ ОПАСЕН: список своих процессов не собрался — "
                       "он способен снять задачу, внутри которой работает")

    видно = живые_запуски()
    if видно:
        строки.append(f"   учения: идущих запусков вижу {len(видно)}, номера процессов читаются")
    else:
        строки.append("   учения: идущих запусков не вижу ни одного — либо их правда нет, "
                      "либо разбор `ps` ослеп; проверить, когда задача точно идёт")


