# -*- coding: utf-8 -*-
"""Сторож утренних задач: почему финансовой сводки нет, если её нет.

Зачем. 13–17 августа 2026 финансовая сводка не выходила четыре дня подряд,
и об этом никто не узнал. Не потому, что сообщение потерялось, — сообщения
не было вовсе: задача не запускалась, а молчание никем не читается. Владелец
заметила на четвёртый день и спросила сама.

Отсюда правило, на котором стоит весь этот файл:

    задача не может рассказать о себе — она не запустилась.
    Значит, спрашивать должен кто-то снаружи.

Снаружи — это утренний отчёт по чаевым: он ходит каждый день исправно, в том
числе все четыре дня тишины. Сторож запускается последним шагом той задачи
и печатает одну строку в её отчёт.

⚠️ **Сторож спрашивает про учёт, а не про задачу.** «Задача запустилась» —
не ответ: 17.08.2026 она запустилась, скачала выписку, упёрлась в сломанный
скрипт и повисла. По журналу запусков утро выглядело удачным, а сводки не было.
Поэтому главный вопрос здесь — легла ли вчерашняя выписка в учёт; журнал
запусков нужен потом, чтобы назвать причину.

⚠️ **Молчит, когда всё свежо** — почти. Печатает одну строку с датами,
но не «✅»: галочка приучает не читать, а дата, отставшая на день, видна
даже боковым зрением. Кричит блоком, только когда есть чему.

Что знает и чего не знает:

- видит, скачана ли вчерашняя выписка и разобраны ли операции за вчера;
- видит по журналу планировщика, когда каждая ежедневная задача запускалась;
- видит запуск, который висит прямо сейчас, — это он съест завтрашнее утро,
  и **снимает его сам**, если тот стоит дольше двух часов. 21.08.2026 стало
  ясно, что кричать мало: сторож назвал висяк и лечение в 9:05, всё было
  верно до слова, а прочитали это в 10:50 — и только потому, что владелец
  спросила про другое. Крик, который некому услышать, стоит столько же,
  сколько молчание;
- видит запуск, который отработал, но НЕ КОНЧИЛСЯ ОТЧЁТОМ: свежий учёт
  не значит, что владелец что-то получила;
- **не видит сам себя.** Если утренний отчёт по чаевым не выйдет, сторож
  не выйдет вместе с ним. Это цена того, что он живёт на чужих ногах,
  и другого сторожа над ним нет.

Запуск:
    python3 scripts/storozh.py            # проверить и напечатать
    python3 scripts/storozh.py --учения   # соврать про даты и проверить, что кричит

Код возврата: 0 — всё свежо, 1 — есть тревога, 2 — проверить не смог.
"""
from __future__ import annotations

import csv
import json
import os
import re
import signal
import subprocess
import sys
import time
from datetime import datetime, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ВЫПИСКИ = ROOT / "data" / "dds" / "выписки"
ОПЕРАЦИИ = ROOT / "data" / "dds" / "bank_classified.csv"

СОСТОЯНИЕ = Path.home() / "Library" / "Application Support" / "Claude" / "claude-code-sessions"
ЖУРНАЛЫ = Path.home() / ".claude" / "projects"

# Запуск, стоящий дольше этого, считается зависшим, а не медленным. Самый
# долгий честный шаг — fin_daily.py, она ходит в обе кассы по сети и идёт
# до пяти минут. Полчаса — с шестикратным запасом.
ПОРОГ_ЗАВИСАНИЯ = timedelta(minutes=30)

# Через сколько сторож не только кричит, но и снимает запуск сам. Порог нарочно
# сильно больше того, при котором он кричит: полчаса — это «пора сказать», два
# часа — это «честной работы столько не бывает». Разводить их обязательно.
# Один порог на оба дела означал бы, что однажды сторож убьёт не зависшего,
# а медленного, и мы узнаем об этом по пропавшей сводке.
ПОРОГ_СНЯТИЯ = timedelta(hours=2)

тревоги: list[str] = []
строки: list[str] = []


def мск(s):
    """ISO-время из журналов планировщика → местное время."""
    if not s:
        return None
    return datetime.fromisoformat(s.replace("Z", "+00:00")).astimezone().replace(tzinfo=None)


def дата_ру(d):
    return d.strftime("%d.%m") if d else "—"


# ─────────────────────────────────────────────────────────── состояние задач

def найти_состояние():
    """Файл, в котором планировщик держит расписание и время последних запусков.

    ⚠️ Это внутренний файл приложения, и лежит он под двумя случайными
    номерами в пути. Поэтому ищем перебором, а не по жёсткому адресу:
    номера меняются при переустановке, и жёсткий адрес однажды молча
    перестанет находиться — то есть сторож ослепнет и не скажет об этом.
    """
    найденные = sorted(СОСТОЯНИЕ.glob("*/*/scheduled-tasks.json"),
                       key=lambda p: p.stat().st_mtime, reverse=True)
    return найденные[0] if найденные else None


def ежедневная(cron):
    """«0 9 * * *» — каждый день. Месячные и недельные сторожу не по адресу."""
    части = (cron or "").split()
    return len(части) == 5 and части[2] == "*" and части[3] == "*" and части[4] == "*"


def проверить_запуски(сегодня):
    """Когда каждая ежедневная задача запускалась в последний раз.

    Попутно собирает папки с журналами сессий — по полю `cwd` самих задач.
    ⚠️ Выводить эту папку из адреса проекта нельзя: задачи живут не в папке
    ресторана, а в «Обучение ИИ», и первая же попытка угадать дала несуществующий
    адрес. Спрашиваем у того, кто знает точно.
    """
    файл = найти_состояние()
    if not файл:
        строки.append("   журнал запусков не найден — сказать, запускались ли задачи, не могу")
        return {}, []

    данные = json.loads(файл.read_text(encoding="utf-8"))
    когда, папки = {}, []
    for з in данные.get("scheduledTasks", []):
        cwd = з.get("cwd")
        if cwd:
            п = ЖУРНАЛЫ / re.sub(r"[^A-Za-z0-9]", "-", cwd)
            if п not in папки:
                папки.append(п)
        if not з.get("enabled") or not ежедневная(з.get("cronExpression")):
            continue
        t = мск(з.get("lastRunAt"))
        когда[з["id"]] = t
        if t is None:
            тревоги.append(f"задача «{з['id']}» не запускалась ни разу")
        elif t.date() < сегодня - timedelta(days=1):
            дней = (сегодня - t.date()).days
            тревоги.append(f"задача «{з['id']}» не запускалась {дней} дн. — "
                           f"последний раз {t.strftime('%d.%m в %H:%M')}")
        elif t.date() < сегодня:
            строки.append(f"   «{з['id']}»: сегодня ещё не запускалась "
                          f"(последний раз вчера в {t.strftime('%H:%M')})")
        else:
            строки.append(f"   «{з['id']}»: отработала сегодня в {t.strftime('%H:%M')}")
    return когда, папки


# ───────────────────────────────────────────────────────────── свежесть учёта

def последняя_выписка():
    """Дата самой свежей выписки, скачанной задачей самостоятельно.

    ⚠️ Смотрим только на имена вида «выписка-<счёт>-<дата>.txt» — так называет
    файлы bank_fetch.py. Всё, что владелец скачала руками, лежит здесь же,
    но под именами банка («kl_to_1c (12).txt») и без даты в названии: по ним
    нельзя понять, за какое число выписка, и считать их свежестью нельзя.
    """
    даты = []
    for p in ВЫПИСКИ.glob("выписка-*-*.txt"):
        m = re.search(r"(\d{4}-\d{2}-\d{2})\.txt$", p.name)
        if m:
            даты.append(datetime.strptime(m.group(1), "%Y-%m-%d").date())
    return max(даты) if даты else None


def последняя_операция():
    """Дата последней разобранной операции — доехал ли конвейер до конца."""
    if not ОПЕРАЦИИ.exists():
        return None
    даты = []
    with open(ОПЕРАЦИИ, encoding="utf-8") as f:
        for r in csv.DictReader(f):
            d = (r.get("date") or "")[:10]
            if len(d) == 10:
                даты.append(d)
    return datetime.strptime(max(даты), "%Y-%m-%d").date() if даты else None


def проверить_свежесть(вчера, идёт_прямо_сейчас):
    выписка, операция = последняя_выписка(), последняя_операция()

    строки.append(f"   выписка: последняя за {дата_ру(выписка)}, "
                  f"операции разобраны по {дата_ру(операция)}")

    for что, когда in (("выписка за вчера не скачана", выписка),
                       ("операции за вчера не разобраны", операция)):
        if когда and когда >= вчера:
            continue
        if идёт_прямо_сейчас:
            строки.append("   финансовая задача идёт прямо сейчас — подожду до завтра")
            return
        отстало = (вчера - когда).days if когда else None
        хвост = f" (последняя за {дата_ру(когда)}, отстаём на {отстало} дн.)" if когда else " (нет вообще)"
        тревоги.append(что + хвост)


# ────────────────────────────────────────────────────────── зависшие запуски

def предки():
    """Номера всех процессов над нами — от оболочки до самого приложения.

    ⚠️ Без этого списка сторож способен убить сам себя. Он живёт не отдельно,
    а внутри утренней задачи по чаевым, а она — такой же запуск
    `claude --output-format`, как и те, за которыми он смотрит. Совпадения
    по времени старта хватило бы, чтобы он снял задачу, в которой работает,
    и отчёт по чаевым оборвался бы на полуслове.
    """
    цепочка, pid = set(), os.getpid()
    for _ in range(12):
        цепочка.add(pid)
        try:
            вывод = subprocess.run(["ps", "-o", "ppid=", "-p", str(pid)],
                                   capture_output=True, text=True, timeout=10).stdout.strip()
            pid = int(вывод)
        except Exception:
            break
        if pid <= 1:
            break
    return цепочка


def живые_запуски():
    """Время старта и номер процесса всех идущих сейчас запусков.

    Отличить зависший запуск от закончившегося по журналу нельзя: обрыв
    на последнем вызове выглядит одинаково и у повисшего, и у снятого.
    Поэтому спрашиваем систему, жив ли процесс.

    Номер процесса нужен, чтобы зависший запуск можно было не только назвать,
    но и снять. Раньше здесь брались только даты — по ним видно, что беда есть,
    и непонятно, кого именно останавливать.
    """
    try:
        вывод = subprocess.run(["ps", "-eo", "pid,lstart,command"],
                               capture_output=True, text=True, timeout=20).stdout
    except Exception:
        return []
    # ⚠️ Разбирать по номерам столбцов нельзя: число месяца выравнивается
    # пробелом («Aug  7»), а ширина колонки с номером процесса плавает.
    образец = re.compile(r"^\s*(\d+)\s+(\w{3}\s+\w{3}\s+\d+\s+\d{2}:\d{2}:\d{2}\s+\d{4})\s")
    живые = []
    for строка in вывод.splitlines():
        if "MacOS/claude" not in строка or "--output-format" not in строка:
            continue
        m = образец.match(строка)
        if not m:
            continue
        try:
            когда = datetime.strptime(re.sub(r"\s+", " ", m.group(2)), "%a %b %d %H:%M:%S %Y")
        except ValueError:
            continue
        живые.append((когда, int(m.group(1))))
    return живые


def снять_запуск(pid):
    """Останавливает зависший запуск и проверяет, что он действительно умер.

    Сначала вежливо, через три секунды — насильно.

    ⚠️ Возвращает правду о том, что вышло, и это здесь главное. Молчаливая
    неудача опаснее самого зависания: если сторож напишет «снял», а место
    останется занятым, следующее утро пропадёт молча — и проверять уже никто
    не станет, потому что в отчёте написано, что всё улажено.
    """
    if not жив(pid):
        return True, "сам закончился"
    for сигнал in (signal.SIGTERM, signal.SIGKILL):
        try:
            os.kill(pid, сигнал)
        except ProcessLookupError:
            return True, "сам закончился"
        except PermissionError:
            return False, "система не дала его остановить"
        for _ in range(6):
            time.sleep(0.5)
            if not жив(pid):
                return True, "снят"
    return False, "не остановился даже насильно"


def жив(pid):
    """Работает ли процесс — или уже мёртв, просто ещё не убран.

    ⚠️ Зомби считаем мёртвым. Это процесс, который кончился, но родитель ещё
    не забрал его расписку: работы за ним нет, места он не занимает. Проверка
    `os.kill(pid, 0)` отвечает про такого «жив», и учения 21.08.2026 из-за
    этого написали «сторож без рук» — снятие сработало, а проверка снятия
    соврала. Сама проверка тоже должна быть проверена.
    """
    try:
        os.kill(pid, 0)
    except ProcessLookupError:
        return False
    except PermissionError:
        return True
    try:
        состояние = subprocess.run(["ps", "-o", "state=", "-p", str(pid)],
                                   capture_output=True, text=True, timeout=10).stdout.strip()
    except Exception:
        return True
    return not состояние.startswith("Z")


def разобрать_журнал(файл):
    """Читает журнал одной сессии: чья это задача, когда шла и ждёт ли ответа.

    Возвращает None, если это не запуск задачи по расписанию, — обычных
    разговоров с владельцем в той же папке лежат десятки, и они тут ни при чём.

    ⚠️ Признак запуска ищем в первых записях: имя задачи приходит вместе
    с заданием, самой первой репликой. Читать ради этого весь файл нельзя —
    среди журналов есть шестимегабайтные, а сторож бежит внутри утреннего
    отчёта и задерживать его не должен.
    """
    try:
        имя = None
        with open(файл, encoding="utf-8") as f:
            for i, строка in enumerate(f):
                if i >= 6:
                    break
                # ⚠️ Кавычки внутри журнала записаны с косой чертой: name=\"…\".
                # Ищем оба вида — иначе не находится ничего и сторож молчит
                # ровно так же, как если бы всё было хорошо.
                m = re.search(r'<scheduled-task name=\\?"([^"\\]+)', строка)
                if m:
                    имя = m.group(1)
                    break
        if not имя:
            return None
        записи = [json.loads(s) for s in open(файл, encoding="utf-8") if s.strip()]
    except Exception:
        return None

    со_временем = [z for z in записи if z.get("timestamp")]
    if not со_временем:
        return None

    # ⚠️ Смотрим только записи разговора. В журнале попадаются служебные
    # («queue-operation» от отложенной побудки), и они ложатся ПОСЛЕ
    # неотвеченного вызова. 18.08.2026 из-за одной такой записи сторож
    # не увидел зависший запуск: проверка «последняя запись — вызов»
    # не сработала, хотя вызов так и остался без ответа.
    разговор = [z for z in со_временем if z.get("message")]
    if not разговор:
        return None

    # Ждёт ответа, если последний ход разговора — вызов инструмента: значит,
    # вопрос «разрешить?» задан и ответа на него не пришло. У снятого запуска
    # в конце появляется обычная запись-текст, поэтому мёртвые сюда не попадают.
    содержимое = (разговор[-1].get("message") or {}).get("content")
    ждёт = isinstance(содержимое, list) and any(
        isinstance(x, dict) and x.get("type") == "tool_use" for x in содержимое)

    # Дошёл ли запуск до отчёта. Отработавшая задача заканчивает СЛОВАМИ —
    # сводкой для владельца. Если слов в конце нет, работа могла быть сделана
    # целиком, а владелец всё равно ничего не получил: 18.08.2026 задача
    # скачала выписки, разнесла их, посчитала сводку — и не сказала ни слова,
    # потому что повисла на чтении фонового вывода.
    отчёт = False
    for z in reversed(разговор):
        c = (z.get("message") or {}).get("content")
        if isinstance(c, list) and any(
                isinstance(x, dict) and x.get("type") == "tool_use" for x in c):
            break
        if isinstance(c, list) and any(
                isinstance(x, dict) and x.get("type") == "text"
                and str(x.get("text", "")).strip() for x in c):
            отчёт = True
            break

    return (имя, мск(разговор[0]["timestamp"]), мск(разговор[-1]["timestamp"]),
            ждёт, отчёт)


def проверить_зависшие(живые, папки, учения=False, снимать=True):
    """Ищет запуск задачи, который стоит и ждёт разрешения.

    Признак — последняя запись в журнале сессии это вызов инструмента,
    на который так и не пришёл ответ. Пока такой запуск жив, следующий
    той же задачи не начнётся: у планировщика правило «один за раз».
    Именно так были съедены четыре утра подряд.

    ⚠️ **И отдельно — дошёл ли сегодняшний запуск до отчёта.** 18.08.2026
    задача отработала всё: скачала обе выписки, разнесла операции, посчитала
    сводку — и повисла на последнем шаге, читая вывод фоновой команды. Данные
    в учёт легли, поэтому проверка свежести молчала, а владелец не получила
    ни строчки и написала сама. Свежий учёт не значит, что отчёт вышел.

    На учениях проверка «жив ли процесс» снимается. Иначе учения были бы
    возможны только в тот редкий час, когда что-то действительно висит, —
    то есть ровно тогда, когда проверять уже поздно. Без неё сторож находит
    те же обрывы в старых журналах и показывает, что читать их умеет.
    """
    сейчас = datetime.now()
    порог_файла = сейчас - timedelta(days=7)
    найдено = 0
    неприкосновенные = предки()

    for папка in папки:
        if not папка.exists():
            continue
        for файл in папка.glob("*.jsonl"):
            if datetime.fromtimestamp(файл.stat().st_mtime) < порог_файла:
                continue
            запуск = разобрать_журнал(файл)
            if not запуск:
                continue
            найдено += 1
            имя, старт, конец, ждёт, отчёт = запуск

            # Запуск сегодняшний, давно не шевелится и слов в конце нет —
            # значит владелец ничего не получила, чем бы дело ни кончилось.
            if (старт.date() == сейчас.date() and not отчёт
                    and сейчас - конец >= ПОРОГ_ЗАВИСАНИЯ):
                тревоги.append(
                    f"задача «{имя}» запускалась сегодня в {старт.strftime('%H:%M')}, "
                    f"но отчётом не кончилась — работа могла быть сделана, "
                    f"а сводки владелец не увидела")

            if not ждёт or сейчас - конец < ПОРОГ_ЗАВИСАНИЯ:
                continue

            # Жив ли он на самом деле: процесс, стартовавший в ту же секунду.
            свой = next((p for ж, p in живые if abs((ж - старт).total_seconds()) < 5), None)
            if not учения and свой is None:
                continue

            часов = int((сейчас - конец).total_seconds() // 3600)
            беда = (f"запуск задачи «{имя}» от {старт.strftime('%d.%m %H:%M')} висит без движения "
                    f"{часов} ч. — он ждёт разрешения, и пока он жив, следующий не начнётся")

            # ⚠️ На учениях не снимаем НИКОГДА: там проверка «жив ли процесс»
            # выключена нарочно, и под руку попадут старые оборванные журналы,
            # за которыми стоят живые чужие процессы.
            пора = (снимать and not учения and свой is not None
                    and сейчас - конец >= ПОРОГ_СНЯТИЯ)
            if not пора:
                тревоги.append(беда)
            elif свой in неприкосновенные:
                тревоги.append(беда + ". ⚠️ Снять не могу: это тот самый запуск, "
                                      "внутри которого я работаю")
            else:
                вышло, как = снять_запуск(свой)
                тревоги.append(беда + (f". Сторож его {как} — место освободилось, "
                                       f"следующее утро пойдёт само"
                                       if вышло else f". Снять не удалось: {как}"))

    if учения:
        места = ", ".join(str(п) for п in папки) or "— ни одной"
        строки.append(f"   учения: смотрю журналы в {места}; запусков за неделю — {найдено}")
        часы = int(ПОРОГ_СНЯТИЯ.total_seconds() // 3600)
        строки.append(f"   учения: снятие на учениях выключено нарочно; в бою снимаю то, "
                      f"что стоит дольше {часы} ч., своих {len(неприкосновенные)} процессов "
                      f"не трогаю")


