def main():
    учения = "--учения" in sys.argv
    снимать = "--не-снимать" not in sys.argv
    сегодня = datetime.now().date()
    вчера = сегодня - timedelta(days=1)
    if учения:
        # Сдвигаем ожидание на неделю вперёд: свежий учёт обязан стать
        # «отставшим». Проверка, которая никогда не кричала, ничего не сторожит.
        вчера = сегодня + timedelta(days=7)

    когда, папки = проверить_запуски(сегодня)
    финансы = когда.get("finansy-nevskiy-9utra")
    идёт = bool(финансы and datetime.now() - финансы < ПОРОГ_ЗАВИСАНИЯ) and not учения

    проверить_свежесть(вчера, идёт)
    проверить_зависшие(живые_запуски(), папки, учения, снимать)
    if учения:
        учебное_зависание()
        учебное_снятие()

    if not тревоги:
        print("Сторож: " + "; ".join(s.strip() for s in строки))
        return 0

    print("\n⚠️  СТОРОЖ: С УТРЕННИМИ ЗАДАЧАМИ ЧТО-ТО НЕ ТАК")
    for т in тревоги:
        print(f"   • {т}")
    print()
    for s in строки:
        print(s)
    print("\n   Зависший запуск сторож снимает сам, но только когда тот стоит дольше "
          "двух часов.\n   Если выше написано, что снять не удалось или что запуск пока "
          "не тронут, —\n   открыть в приложении сессию с названием задачи и остановить "
          "её руками.\n\n   Если сводки нет второй день подряд, дело не в разрешениях, "
          "а в скрипте:\n   запустить шаги руками и увидеть ошибку.")
    return 1


if __name__ == "__main__":
    sys.exit(main())
