            ч["смена"], ч["кассир"] or "—",
            "наличные" if ч["нал"] else "безнал",
            ч["сумма"], ч["за_30"], ч["не_вернулось"], доля,
            "; ".join(f"{и} ×{к:g}" for и, к in ч["чего_не_нашли"]),
