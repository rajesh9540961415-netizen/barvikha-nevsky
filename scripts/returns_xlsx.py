def человек_писал(текст) -> bool:
    """Комментарий написан человеком, а не подставлен нами?"""
    if not текст:
        return False
    т = str(текст).lstrip()
    return not т.startswith(МЕТКА) and not т.startswith(СТАРЫЕ_МЕТКИ)


def из_чата() -> dict:
    """Сообщения «ЧАТ КАССЫ!» по торговым дням — из data/чат-кассы.json.

    Файл кладёт scripts/tg_kassa.py. Нет файла — молчим и не подставляем:
    пустая колонка честнее выдуманной.

    ⚠️ Связать сообщение с КОНКРЕТНЫМ чеком фискальные данные не позволяют:
    в чате пишут словами, а не номерами документов. Поэтому подставляем
    сообщения ТОГО ЖЕ ТОРГОВОГО ДНЯ и помечаем это словом «день:». Если
    в тексте нашлась сумма чека — такое сообщение ставим первым и метим
    «сумма:»: это уже не просто «в тот день», а прямое попадание.

    💡 Ничего не затирает: подставленное идёт только туда, где человек
    ещё ничего не написал сам.
    """
    if not ЧАТ.exists():
        return {}
    import json
    по_дням = defaultdict(list)
    for з in json.loads(ЧАТ.read_text(encoding="utf-8")):
        по_дням[з["день"]].append(з)
    return по_дням


def подсказка_из_чата(ч: dict, по_дням: dict) -> str | None:
    """Что писали в чате ПОСЛЕ этого счёта, в тот же торговый день.

    ⚠️ Только ПОСЛЕ. 22.08.2026 первая редакция брала все сообщения дня —
    и к чеку в 00:13 подставила сообщения от 14:27 и 20:19, написанные
    на десять часов РАНЬШЕ. Объяснением такое быть не может ни при каком
    чтении; выглядело же оно совершенно правдоподобно.

    ⚠️ Ветку «совпала сумма» первая редакция тоже завела — и она не сработала
    НИ РАЗУ на 153 строках: администраторы пишут причину словами, сумм
    не указывают. Убрана, чтобы не создавать вида проверки, которой нет.

    💡 Печатаем разрыв во времени: «+7 мин» и «+6 ч 40 мин» — это подсказки
    очень разного веса, и решает человек, а не скрипт.
    """
    момент = datetime.fromisoformat(ч["время"])
    сообщения = по_дням.get(R.торговый_день(момент).isoformat())
    if not сообщения:
        return None
    после = []
    for з in сообщения:
        когда = datetime.fromisoformat(з["время"])
        if когда < момент:
            continue
        минут = int((когда - момент).total_seconds() // 60)
        разрыв = f"+{минут} мин" if минут < 90 else f"+{minutes_h(минут)}"
        после.append((минут, f"{разрыв} {з['автор'] or '—'}: "
                             + з["текст"].replace("\n", " ")))
    if not после:
        return None
    после.sort()
    хвост = f"  (всего в тот день сообщений: {len(сообщения)})"
    return (МЕТКА + " | ".join(с for _, с in после[:3]) + хвост)[:900]


def minutes_h(минут: int) -> str:
    """«6 ч 40 мин» — читаемее, чем «400 мин»."""
    return f"{минут // 60} ч {минут % 60} мин"


def прежние_комментарии() -> dict:
    """Комментарии и пометки из старого файла, по ФПД."""
    если_нет = {}
    if not ФАЙЛ.exists():
        return если_нет
    книга = load_workbook(ФАЙЛ, data_only=True)
    if "Счета без перебивки" not in книга.sheetnames:
        return если_нет
    лист = книга["Счета без перебивки"]
    шапка = [c.value for c in лист[1]]
    try:
        i_фпд = шапка.index("ФПД")
    except ValueError:
        return если_нет
    i_ком = next((i for i, h in enumerate(шапка) if h and "омментарий" in str(h)), None)
    i_раз = next((i for i, h in enumerate(шапка) if h and "азобрано" in str(h)), None)
    for r in лист.iter_rows(min_row=2, values_only=True):
        if i_фпд < len(r) and r[i_фпд]:
            ком = r[i_ком] if i_ком is not None and i_ком < len(r) else None
            если_нет[str(r[i_фпд])] = (
                ком if человек_писал(ком) else None,
                r[i_раз] if i_раз is not None and i_раз < len(r) else None,
            )
    return если_нет


