    # посадила бы январский чек за апрельский стол. См. scripts/qr_orders.py.
    # ⚠️ Через кэш: столы нужны и сборщику (разбор_оплаты ищет пару в пределах
    # одного стола), и этой записи. Две выгрузки за запуск — лишний поход
