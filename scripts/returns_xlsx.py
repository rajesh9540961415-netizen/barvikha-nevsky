# Снимок сумм из ручной выгрузки — единственное, чего нет по ключу.
СУММЫ_ОТМЕН = ROOT / "data" / "отмены-суммы.json"


def отмены_лист(книга) -> None:
    """Лист «Отмены Quick Resto» — собирается ЗАНОВО из кассы, каждый раз.

    🔴 Раньше лист достраивал сам себя: читал собственный вчерашний вид
    и подмешивал в него свежее. За один вечер 22.08.2026 это дало сначала
    89 задвоенных строк бара, потом 169 строк, переехавших из бара в зал.
    Каждый раз ошибка выглядела правдоподобно и оставалась в файле навсегда:
    **накопительный лист лечится только полной пересборкой.**

    Теперь источник один — касса. Из файла не читается ничего.

    ⚠️ Единственное, чего в кассе по ключу НЕТ, — «Сумма» и «Себестоимость».
    Они были в ручной выгрузке из Генератора отчётов и заморожены один раз
    в `data/отмены-суммы.json` (1873 строки, по 18.08.2026). Файл не растёт
    и не пересобирается: это снимок того, что иначе потерялось бы.
    """
    import json as _json
    суммы = {}
    if СУММЫ_ОТМЕН.exists():
        суммы = _json.loads(СУММЫ_ОТМЕН.read_text(encoding="utf-8"))

    try:
        строки = C.отмены(date(2026, 1, 1))
    except SystemExit as e:
        print(f"  ⚠️  отмены ключом не пришли ({e}) — лист не собран")
        return
    if not строки:
        return

    лист = книга.create_sheet("Отмены Quick Resto")
    лист.append(ОТМЕНЫ_ЗАГОЛОВКИ)
    for c in лист[1]:
        c.font = Font(bold=True)
        c.fill = ЗАГОЛОВОК

    # Свежее сверху — решение владельца 22.08.2026.
    строки.sort(key=lambda р: (р["дата"], р["время"]), reverse=True)
    чужих = 0
    for р in строки:
        д = суммы.get(str(р["номер"]), {})
        в = C.вердикт(р["касса"], р["дата"], р["время"], р["учётка"])
        лист.append([
            р["номер"], р["дата"], р["время"], р.get("стол", ""), р["касса"],
            ЮРЛИЦО.get(р["касса"], р["касса"]), р["учётка"], р["причина"],
            р["комментарий"], "Да" if р["со_списанием"] else "Нет",
            д.get("сумма"), д.get("себестоимость"), в,
        ])
        if в.startswith("🔴"):
            чужих += 1
            for c in лист[лист.max_row]:
                c.fill = РОЗОВЫЙ

    лист.freeze_panes = "A2"
    лист.auto_filter.ref = f"A1:M{лист.max_row}"
    for стлб, шир in zip("ABCDEFGHIJKLM",
                         (11, 11, 7, 8, 7, 14, 22, 22, 44, 12, 11, 15, 30)):
        лист.column_dimensions[стлб].width = шир
    for стлб in ("K", "L"):
        for c in лист[стлб][1:]:
            c.number_format = "#,##0.00"
    с_суммой = sum(1 for р in строки if str(р["номер"]) in суммы)
    по_кассам = defaultdict(int)
    for р in строки:
        по_кассам[р["касса"]] += 1
    print(f"  отмен в листе: {len(строки)} "
          f"({', '.join(f'{k} {v}' for k, v in sorted(по_кассам.items()))}), "
          f"с суммой из выгрузки: {с_суммой}, под чужой учёткой: {чужих}")


