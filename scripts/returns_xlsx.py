def способ_оплаты(чек: dict) -> str:
    """Чем платили: «наличными», «картой» или «смешанно»."""
    if чек["нал"] > 0 and чек["безнал"] > 0:
        return "смешанно"
    if чек["нал"] > 0:
        return "наличными"
    return "картой" if чек["безнал"] > 0 else "—"


def разбор_оплаты(чеки: list, столы: dict) -> tuple[dict, dict]:
    """Возврат → его перебивка ЦЕЛЫМ СЧЁТОМ. Отдаёт (смена оплаты по дням, подсказки).

    Зачем. Владелец 10.09.2026: показать в отчёте, сколько возвратов за день —
    это смена способа оплаты. Закрыли стол по карте, гость рассчитался
    наличными: возврат есть, нарушения нет. За сентябрь таких 26 из 33 —
    основная причина возвратов в заведении.

    🔴 Пару ищем ЦЕЛЫМ СЧЁТОМ, а не по блюдам, и это не придирка.
    Рабочий разбор (`R.разобрать`) закрывает позиции возврата жадно, из любых
    ближайших приходов, — ему важно только, нашлись ли блюда. 08.09.2026
    салат из возврата за столом Н5 он закрыл салатом ЧУЖОГО стола Н1, а чай —
    правильным чеком. Со стороны это выглядело как «полсчёта картой,
    полсчёта наличными», хотя весь счёт целиком перебили наличными.
    Сравнивать способ оплаты на такой раскладке нельзя: она про блюда,
    а не про то, кто с кем расплатился.

    ⚠️ Сперва списываем ИСХОДНЫЙ чек — тот же набор, ближайший раньше
    ПО НОМЕРУ, — как это делает рабочий разбор. Без этого возврат находит
    парой сам свой исходник: он рядом по времени и совпадает набором,
    а способ оплаты у них один и тот же. Смена оплаты тогда не находится
    вовсе, и колонка молча показывает нули.

    Пара — тот же набор блюд, та же сумма, тот же стол, ближайшая по времени
    в пределах часа. Нет такой — возврат остаётся без пары: либо это дыра,
    либо счёт перебили частями.
    """
    приходы = sorted([ч for ч in чеки if ч["вид"] == R.ПРИХОД],
                     key=lambda ч: int(ч["номер"]))
    возвраты = sorted([ч for ч in чеки if ч["вид"] == R.ВОЗВРАТ_ПРИХОДА],
                      key=lambda ч: int(ч["номер"]))
    занят: set = set()
    смена: dict = defaultdict(int)
    подсказки: dict = {}

    for в in возвраты:
        т, н, мой = datetime.fromisoformat(в["время"]), int(в["номер"]), R.набор(в)

        for п in reversed(приходы):
            if п["номер"] in занят or int(п["номер"]) > н:
                continue
            if R.набор(п) == мой:
                занят.add(п["номер"])
                break

        стол_в = qr_orders.стол_чека(в, столы) if столы else ""
        пары = []
        for п in приходы:
            if п["номер"] in занят:
                continue
            тп = datetime.fromisoformat(п["время"])
            if abs(тп - т) > ОКНО_ПЕРЕБИВКИ:
                continue
            if R.набор(п) != мой or abs(п["сумма"] - в["сумма"]) > 0.01:
                continue
            if стол_в and столы and qr_orders.стол_чека(п, столы) != стол_в:
                continue
            пары.append((abs((тп - т).total_seconds()), п))

        if пары:
            пары.sort(key=lambda пара: пара[0])
            п = пары[0][1]
            занят.add(п["номер"])
            if способ_оплаты(п) != способ_оплаты(в):
                смена[R.торговый_день(т)] += 1
            continue

        # Пары нет. Может, счёт перебили ДРУГИМ товаром на ту же сумму?
        #
        # 01.09.2026 в баре так и было: вернули «Кальян на чаше PERFUME МИКС»
        # за 4 000 ₽, а минутой позже пробили «PERFUME СОЛО» — те же 4 000 ₽,
        # но другой товар, и разбор честно записал дыру. Похоже на исправление
        # позиции; утверждать это может только человек, который там был.
        #
        # ⚠️ Это ПОДСКАЗКА, а не зачёт перебивки. Считать «та же сумма, другой
        # товар» перебивкой нельзя: дробление счёта — идеальное прикрытие,
        # ради этого сверка и ведётся по блюдам. Здесь мы только показываем
        # человеку, куда смотреть.
        for п in приходы:
            if п["номер"] in занят:
                continue
            тп = datetime.fromisoformat(п["время"])
            if abs(тп - т) > ОКНО_ПЕРЕБИВКИ or abs(п["сумма"] - в["сумма"]) > 0.01:
                continue
            if R.набор(п) == мой:
                continue
            # ⚠️ Сумма названа прямо. «Та же сумма» — это сумма ВСЕГО возврата,
            # а не дыры: у возврата на 7 230 ₽ дырой может быть одно пиво
            # за 600 ₽, и без числа подсказка читалась бы как «нашлись
            # те самые 600 ₽».
            подсказки[str(в["фпд"])] = (
                f"рядом приход на {R.деньги(п['сумма'])} ₽ — во столько же встал "
                f"весь возврат — в {тп:%H:%M}, другим товаром: "
                f"{', '.join(R.набор(п))}; оплачен {способ_оплаты(п)}"
            )
            break

    return смена, подсказки


def собрать(по_день: date) -> tuple:
    """Неперебитые счета обеих касс — и СПИСОК ПРОВЕРЕННЫХ ДНЕЙ.

    ⚠️ Дни возвращаются отдельно нарочно. 22.08.2026 владелец спросила, почему
    в отчёте нет 19–21 августа. Данные были, проверка прошла, нарушений в те
    дни не нашлось — и строк, естественно, не появилось. Но пустота читается
    как «данные не дошли», а не как «проверено, чисто».

    💡 Чистый день обязан быть ВИДЕН строкой с нулём. Отсутствие строки
    и отсутствие нарушений — разные новости, и различать их должен отчёт,
    а не человек по памяти.
    """
    итог = []
    дни_проверки = []
    месяцы = [f"2026-{m:02d}" for m in range(1, по_день.month + 1)]
    for касса, о in R.КАССЫ.items():
        чеки = (R.чеки_за(месяцы, False) if о["источник"] == "api" else R.чеки_бара())
        чеки = [ч for ч in чеки
                if R.торговый_день(datetime.fromisoformat(ч["время"])) <= по_день]
        if not чеки:
            print(f"  ⚠️  {о['титул']}: чеков нет вовсе — данные не загружены")
            continue
        _, час = R.разобрать(чеки, 60)
        _, полчаса = R.разобрать(чеки, 30)
        за_полчаса = {ч["фпд"]: ч["не_вернулось"] for ч in полчаса}
        # Смена способа оплаты и подсказки про «двойника» — см. разбор_оплаты.
        чеки_кассы = [dict(ч, касса=касса) for ч in чеки]
        смена_оплаты, подсказки = разбор_оплаты(чеки_кассы, столы_кэш())
        дни = sorted(R.торговый_день(datetime.fromisoformat(ч["время"])) for ч in чеки)
        print(f"  {о['титул']}: чеков {len(чеки)} ({дни[0]} … {дни[-1]}), "
              f"не пробито заново {len(час)} на {R.деньги(sum(ч['не_вернулось'] for ч in час))} ₽")
        for ч in час:
            ч = dict(ч)
            ч["касса"] = касса
            ч["за_30"] = за_полчаса.get(ч["фпд"], 0.0)
            ч["двойник"] = подсказки.get(str(ч["фпд"]), "")
            итог.append(ч)

        # 🔴 Ключи заводим по ВСЕМ дням, где есть чеки, а не только по тем,
        # где были возвраты. Иначе день без единого возврата не попадает
        # в лист вовсе — а это ровно та дыра, ради которой лист и заведён
        # 22.08.2026 («где 19–21 августа?»). Тогда починили наполовину:
        # день стал виден, если возврат был хотя бы один. День, где их ноль,
        # по-прежнему исчезал.
        #
        # Владелец 08.09.2026: «почему файл не показывает, что 7 число
        # проверено?». 7 сентября возвратов не было ни в зале, ни в баре —
        # день был проверен и чист, а лист об этом молчал. Так же молчал
        # он и про зал 03.09.
        по_дням = defaultdict(lambda: [0, 0.0, 0, 0, 0.0])
        for ч in чеки:
            по_дням[R.торговый_день(datetime.fromisoformat(ч["время"]))]
        for ч in чеки:
            if ч["вид"] != R.ВОЗВРАТ_ПРИХОДА:
                continue
            д = по_дням[R.торговый_день(datetime.fromisoformat(ч["время"]))]
            д[0] += 1
            д[1] += ч["сумма"]
        for ч in час:
            д = по_дням[R.торговый_день(datetime.fromisoformat(ч["время"]))]
            д[3] += 1
            д[4] += ч["не_вернулось"]
        for день, сколько in смена_оплаты.items():
            по_дням[день][2] += сколько
        for день, (n, s, со, пн, пс) in по_дням.items():
            дни_проверки.append([день, касса, n, s, со, пн, пс])

    # 🔴 Порядок ОБРАТНЫЙ — свежее сверху. Решение владельца 22.08.2026.
    # В листе за две тысячи строк, и вчерашний день, лежащий в самом низу,
    # человек не видит вовсе: чтобы дойти до него, надо промотать весь год.
    итог.sort(key=lambda ч: ч["время"], reverse=True)
    дни_проверки.sort(key=lambda с: (с[0], с[1]), reverse=True)
    return итог, дни_проверки


