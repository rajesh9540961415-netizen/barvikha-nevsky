#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Заказы Quick Resto: номер документа → СТОЛ.

Зачем. В фискальном чеке стола нет — оператор данных его не хранит. А в листе
«Счета без перебивки» стол нужен: без него вопрос смене звучит как «что было
в 22:38», и его никто не помнит. Со столом — «что было за столом Н13 в 22:38».

🔴 СКЛЕИВАТЬ ПО НОМЕРУ НЕЛЬЗЯ, хотя нумерация у чека и у заказа общая.
У чека ВОЗВРАТА свой номер, на 1–3 больше номера исходного заказа: возврат
№16690 в 21:31 на 8 560 ₽ — это заказ 16687 в 21:29, стол Н10. Проверено
на августе: по номеру совпало 0 из 18, по сумме и времени — 16 из 18.

Склейка идёт по трём условиям сразу: та же календарная дата, ТА ЖЕ СУММА
до копейки и признак `returned` у заказа, время в пределах 20 минут.
Приблизительно не ищем: счёт без уверенного совпадения останется без стола,
и это честнее, чем посадить его за соседний.

⚠️ И ЕЩЁ: номер не уникален за год. В апреле 2026 нумерация дошла до 25603
и сбросилась на 3 — 2026-03: 21227…23880, 2026-04: 3…25603, 2026-05:
1754…5457. Поэтому кэш и разбор всегда идут парой «дата + номер».

⚠️ Дата берётся календарная, а не торговая: у обоих источников это одна
и та же стенная дата, и приводить её к торговым суткам нужно ОДИНАКОВО
либо не приводить вовсе. Не приводим.

Запуск:
    python3 scripts/qr_orders.py                 добрать новое поверх кэша
    python3 scripts/qr_orders.py --с 2026-01-01  добрать до этой даты
    python3 scripts/qr_orders.py --заново        забыть кэш и выгрузить всё

Кэш — data/qr/заказы-<касса>-<год>.json. Ключ «ГГГГ-ММ-ДД|номер».
"""

from __future__ import annotations

import json
import sys
from datetime import date, datetime, timedelta
from pathlib import Path

ПАПКА = Path(__file__).resolve().parent
sys.path.insert(0, str(ПАПКА))

from qr_cancellations import (  # noqa: E402
    API, КАССЫ, доступ, страницами, читать_env,
)

КЭШ = ПАПКА.parent / "data" / "qr"
МОДУЛЬ = "front.orders"
КЛАСС = "ru.edgex.quickresto.modules.front.orders.OrderInfo"
НАЧАЛО = date(2026, 1, 1)


def ключ(дата: str, номер) -> str:
    return f"{дата[:10]}|{номер}"


def файл_кэша(касса: str, год: int) -> Path:
    return КЭШ / f"заказы-{касса}-{год}.json"


def прочитать(касса: str, год: int) -> dict:
    ф = файл_кэша(касса, год)
    return json.loads(ф.read_text(encoding="utf-8")) if ф.exists() else {}


def выгрузить(касса: dict, с: date, заново: bool, тихо: bool = False) -> dict:
    """Заказы кассы с указанной даты. Дополняет кэш, а не собирает заново."""
    cfg = читать_env()
    url, head = доступ(cfg, касса["prefix"])
    было = {} if заново else прочитать(касса["title"], с.year)

    # Список идёт от свежих к старым: останавливаемся, когда страница целиком
    # старше нужной даты. Тот же приём, что в отменах.
    def стоп(кусок):
        return all((x.get("localCreateDate") or "")[:10] < с.isoformat()
                   for x in кусок)

    сырые = страницами(url, head, МОДУЛЬ, КЛАСС, стоп=стоп,
                       размер=200, максимум=400)
    добавлено = 0
    for z in сырые:
        д = (z.get("localCreateDate") or "")[:10]
        н = z.get("documentNumber")
        if not д or н is None or д < с.isoformat():
            continue
        стол = (z.get("table") or {}).get("title") or ""
        к = ключ(д, н)
        if к not in было:
            добавлено += 1
        было[к] = {
            "стол": стол,
            "время": (z.get("localCreateDate") or "")[11:16],
            "сумма": z.get("frontSum"),
            "официант": (z.get("waiter") or {}).get("id"),
            "возврат": bool(z.get("returned")),
        }
    КЭШ.mkdir(parents=True, exist_ok=True)
    файл_кэша(касса["title"], с.year).write_text(
        json.dumps(было, ensure_ascii=False), encoding="utf-8")
    if not тихо:
        со_столом = sum(1 for v in было.values() if v["стол"])
        print(f"  {касса['title']}: заказов в кэше {len(было)} "
              f"(+{добавлено} новых), со столом {со_столом}")
    return было


ОКНО_МИНУТ = 20
БЛИЗКО_МИНУТ = 5


def по_дням(данные: dict) -> dict:
    """Заказы, разложенные по календарной дате — для поиска по сумме и времени."""
    итог = {}
    for к, v in данные.items():
        д, н = к.split("|")
        итог.setdefault(д, []).append((int(н), v))
    return итог


def докуда_в_кэше(касса: str, год: int) -> date | None:
    было = прочитать(касса, год)
    дни = sorted({к.split("|")[0] for к in было})
    return date.fromisoformat(дни[-1]) if дни else None


def столы_заказов(с: date = НАЧАЛО, обновить: bool = True,
                  тихо: bool = False) -> dict:
    """{касса: {дата: [(номер, заказ)]}} — заказы, готовые к поиску.

    ⚠️ Добираем ТОЛЬКО ХВОСТ, а не весь год. Первая выгрузка января–августа
    заняла восемь минут и 125 страниц на кассу; если бы утренний отчёт делал
    это каждый день, он бы вставал на восемь минут ни за чем. Берём с даты
    «последний день в кэше минус два дня» — запас на поздние правки заказов.
    """
    итог = {}
    for касса in КАССЫ:
        если_надо = с
        if обновить:
            край = докуда_в_кэше(касса["title"], с.year)
            if край:
                если_надо = max(с, край - timedelta(days=2))
            данные = выгрузить(касса, если_надо, False, тихо)
        else:
            данные = прочитать(касса["title"], с.year)
        итог[касса["title"]] = по_дням(данные)
    return итог


def стол_чека(чек: dict, индекс: dict) -> str:
    """Стол по чеку ВОЗВРАТА. Пусто — если уверенного совпадения нет.

    🔴 По номеру склеить НЕЛЬЗЯ, хотя нумерация общая. У чека возврата свой
    номер, на 1–3 больше номера исходного заказа: возврат №16690 в 21:31
    на 8 560 ₽ — это заказ 16687 в 21:29, стол Н10. Проверено на августе:
    по номеру совпало 0 из 18, по сумме и времени — 16 из 18.

    Ищем заказ с признаком возврата, той же суммой и близким временем.
    ⚠️ Приблизительно НЕ ищем: два оставшихся счёта останутся без стола,
    и это честнее, чем посадить их за соседний.
    """
    т = datetime.fromisoformat(чек["время"])
    по_кассе = индекс.get(чек["касса"], {})
    рядом = []
    # Соседние сутки нужны из-за полуночи: чек в 00:26 ищет заказ вчерашним днём.
    for сдвиг in (-1, 0, 1):
        дата = (т.date() + timedelta(days=сдвиг)).isoformat()
        for _, з in по_кассе.get(дата, []):
            if abs((з.get("сумма") or 0) - чек["сумма"]) > 0.5:
                continue
            try:
                вт = datetime.fromisoformat(f'{дата}T{з["время"]}:00')
            except ValueError:
                continue
            рядом.append((abs((вт - т).total_seconds()) / 60, з))
    рядом.sort(key=lambda пара: пара[0])
    # Сначала заказ с признаком возврата в пределах окна — это надёжное совпадение.
    for разница, з in рядом:
        if з.get("возврат") and разница <= ОКНО_МИНУТ:
            return з.get("стол") or ""
    # Признак возврата иногда не проставлен. Тогда годится только попадание
    # почти в ту же минуту: проверено на 157 счетах — добавляет ровно один
    # (07.06, 5 100 ₽, стол Б13, разница 3 минуты) и НЕ меняет ни одного
    # уже определённого стола.
    for разница, з in рядом:
        if разница <= БЛИЗКО_МИНУТ:
            return з.get("стол") or ""
    return ""


def главное() -> None:
    args = sys.argv[1:]
    заново = "--заново" in args
    с = НАЧАЛО
    if "--с" in args:
        с = date.fromisoformat(args[args.index("--с") + 1])
    print(f"Заказы Quick Resto с {с:%d.%m.%Y} — за столами")
    for касса in КАССЫ:
        выгрузить(касса, с, заново)


if __name__ == "__main__":
    главное()
