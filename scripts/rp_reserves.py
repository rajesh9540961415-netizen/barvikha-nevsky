#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Брони из Рестоплейс: выгрузка и проверка на красные флаги.

Зачем. Два самых денежных пункта чек-листа по звонкам непроверяемы без этих
данных: мы знаем только, что хостес СКАЗАЛА «забронировала». Здесь берём то,
что на самом деле стоит в системе.

🚩 И отдельно — то, чего из звонков не видно вовсе. На Невском депозитов нет
(решение собственника 07.08.2026). Значит броней, слетевших из-за неоплаченного
депозита, существовать не должно. Появились — это не работа хостес и не гость,
а сбой в настройках: гостю выставили требование оплатить то, чего заведение
не берёт, он не оплатил, бронь тихо слетела, и заведение об этом не узнало.

Запуск:
    python3 scripts/rp_reserves.py                 # всё, что отдаёт API
    python3 scripts/rp_reserves.py --с 2026-08-01  # изменённые после даты
    python3 scripts/rp_reserves.py --флаги         # только красные флаги

⚠️ История ограничена самим Рестоплейс: отдают текущий месяц, и то если
тариф ПРО+ действовал весь месяц. У нас он два года — значит месяц придёт
целиком (владелец, 28.08.2026).
"""

from __future__ import annotations

import json
import sys
import time
import urllib.error
import urllib.parse
import urllib.request
from collections import Counter
from datetime import datetime
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from seti import достучаться  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
ENV = ROOT / ".env"
ВЫХОД = ROOT / "data" / "calls"
АДРЕС = "https://api.restoplace.cc"

# Ограничение Рестоплейс — 7 запросов в секунду (поддержка, 28.08.2026).
# Держимся вдвое ниже: нам нужны десятки запросов в день, а не в секунду,
# и упереться в лимит ради нескольких секунд экономии незачем.
ПАУЗА_МЕЖДУ_СТРАНИЦАМИ = 0.3

СТАТУСЫ = {
    1: "новая заявка", 2: "просмотренная заявка", 3: "ожидаем",
    4: "открыт стол", 5: "закрыт", 6: "отменён",
    8: "🚩 отменён из-за неоплаченного депозита",
}
ДЕПОЗИТ = {0: "не внесён", 1: "внесён", 2: "оплата не прошла"}


def ключ() -> str:
    if not ENV.exists():
        sys.exit("Нет файла .env рядом с проектом.")
    for строка in ENV.read_text(encoding="utf-8").splitlines():
        строка = строка.strip()
        if строка.startswith("RP_API_KEY=") and строка.split("=", 1)[1].strip():
            return строка.split("=", 1)[1].strip()
    sys.exit(
        "✗ В .env нет ключа RP_API_KEY.\n"
        "  Взять его: app.restoplace.cc → адрес «Невский» → настройки (шестерёнка\n"
        "  справа вверху) → «Интеграции» → «API / Webhook» → «Включить API».\n"
        "  Дописать в .env строкой:  RP_API_KEY=<ключ>\n"
        "  ⚠️ У каждого адреса свой ключ — нужен именно невский."
    )


def страница(путь: str, номер: int, ключ_api: str, **параметры) -> dict:
    """Одна страница ответа. Ключ идёт заголовком, а не в адресе.

    Параметром `?api_key=` тоже можно, но тогда ключ осядет в журналах
    сервера и в истории команд вместе с адресом.
    """
    параметры = {k: v for k, v in параметры.items() if v is not None}
    параметры["page"] = номер
    адрес = f"{АДРЕС}{путь}?{urllib.parse.urlencode(параметры)}"
    запрос = urllib.request.Request(адрес, headers={"X-API-Key": ключ_api})
    try:
        return json.loads(достучаться(запрос, таймаут=60).decode("utf-8"))
    except urllib.error.HTTPError as e:
        тело = e.read().decode("utf-8", "replace")[:200]
        if e.code == 401:
            sys.exit(
                f"✗ Рестоплейс не принял ключ: {тело}\n"
                "  Ключ свой у каждого адреса — проверьте, что это ключ Невского,\n"
                "  и что в кабинете включён тумблер «Включить API»."
            )
        sys.exit(f"✗ Рестоплейс ответил {e.code}: {тело}")


def все_брони(ключ_api: str, изменённые_после: int | None = None) -> list[dict]:
    """Все страницы подряд. Ответ говорит, сколько их всего."""
    первая = страница("/reserves", 1, ключ_api, updatedAfterTime=изменённые_после)
    всего_страниц = int(первая.get("totalPages") or 1)
    брони = list(первая.get("responseData") or [])
    print(f"  страница 1 из {всего_страниц}: {len(брони)} броней")
    for номер in range(2, всего_страниц + 1):
        time.sleep(ПАУЗА_МЕЖДУ_СТРАНИЦАМИ)
        ещё = страница("/reserves", номер, ключ_api, updatedAfterTime=изменённые_после)
        порция = ещё.get("responseData") or []
        брони += порция
        print(f"  страница {номер} из {всего_страниц}: {len(порция)} броней")
    return брони


def разобрать(брони: list[dict]) -> None:
    """Печатает сводку и красные флаги."""
    if not брони:
        print("\nБроней не пришло ни одной.")
        return
    по_статусам = Counter(б.get("status") for б in брони)
    print(f"\nВсего броней: {len(брони)}")
    print("\nПо статусам:")
    for код, сколько in sorted(по_статусам.items(), key=lambda x: -x[1]):
        print(f"   {сколько:>5}  {код} — {СТАТУСЫ.get(код, 'неизвестный статус')}")

    восьмёрки = [б for б in брони if б.get("status") == 8]
    с_депозитом = [б for б in брони if б.get("depositPaid") not in (0, None)]

    print()
    if восьмёрки:
        print(f"🚩 БРОНЕЙ, СЛЕТЕВШИХ ИЗ-ЗА ДЕПОЗИТА: {len(восьмёрки)}")
        print("   На Невском депозитов нет — таких броней быть не должно вовсе.")
        print("   Это сбой в настройках Рестоплейс, а не работа хостес.")
        for б in восьмёрки[:15]:
            print(f"     {б.get('date','?')} {б.get('time_from','')}  "
                  f"{(б.get('name') or '—')[:24]:<24} {б.get('phone') or '—'}  "
                  f"гостей {б.get('count') or '?'}")
        if len(восьмёрки) > 15:
            print(f"     …и ещё {len(восьмёрки) - 15}")
    else:
        print("✓ Броней, слетевших из-за неоплаченного депозита, нет.")

    if с_депозитом:
        print(f"\n🚩 БРОНЕЙ С ОТМЕТКОЙ О ДЕПОЗИТЕ: {len(с_депозитом)}")
        print("   Поле depositPaid должно быть пустым на всех бронях Невского.")
        for б in с_депозитом[:15]:
            код = б.get("depositPaid")
            print(f"     {б.get('date','?')} {б.get('time_from','')}  "
                  f"{(б.get('name') or '—')[:24]:<24} "
                  f"depositPaid={код} ({ДЕПОЗИТ.get(код, 'неизвестно')})")
    else:
        print("✓ Отметок о депозите нет ни на одной броне.")


def главное() -> None:
    аргументы = sys.argv[1:]
    после = None
    if "--с" in аргументы:
        дата = аргументы[аргументы.index("--с") + 1]
        после = int(datetime.strptime(дата, "%Y-%m-%d").timestamp())
        print(f"Беру брони, изменённые после {дата}")
    к = ключ()
    print(f"Рестоплейс: {АДРЕС}")
    брони = все_брони(к, после)
    разобрать(брони)
    if "--флаги" not in аргументы:
        ВЫХОД.mkdir(parents=True, exist_ok=True)
        файл = ВЫХОД / f"брони-рестоплейс-{datetime.now():%Y-%m-%d}.json"
        файл.write_text(json.dumps(брони, ensure_ascii=False, indent=1), encoding="utf-8")
        print(f"\nСохранено: {файл.relative_to(ROOT)}")


if __name__ == "__main__":
    главное()
