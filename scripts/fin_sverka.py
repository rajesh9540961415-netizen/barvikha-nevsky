#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Сверка ДДС с «Фин. сводом» по статьям расходов.

Зачем. У каждой суммы должен быть эталон, посчитанный другим путём. Для наших
расходов такой эталон существует и ведётся руками владельца — «Фин. свод».
До 16.08.2026 им не пользовался никто: ДДС собирался из первички заново,
а свод лежал рядом и молчал. В тот день выяснилось, что 182 260 ₽ за июль
разнесены в своде по четырём счетам, а в ДДС стояли одной безымянной суммой —
и заметить это можно было только глазами.

Правило, из которого всё следует:

    выписка отвечает на вопрос «что и когда ушло»,
    «Фин. свод» — на вопрос «куда это отнести».

Спорят они редко. Когда спорят — прав свод, а код должен выучить его ответ.

⚠️ **Считает статьи не сам, а вызывает `articles_for_month`** — ту же функцию,
которой пользуется отправка в бэк-офис. Посчитай сверка по-своему, она сверяла
бы свод не с тем, что реально уходит в учёт, а со своим представлением о нём:
ошибка в общем месте прошла бы мимо, то есть сверка молчала бы ровно в самом
опасном случае.

Запуск:
    python3 scripts/fin_sverka.py                # последний закрытый месяц
    python3 scripts/fin_sverka.py 2026-07
    python3 scripts/fin_sverka.py 2026-05 2026-06 2026-07

Код возврата: 0 — сошлось, 1 — есть расхождения, 2 — сверять не с чем.
"""
from __future__ import annotations

import sys
from collections import defaultdict
from datetime import date
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from fin_articles import ARTICLES, articles_for_month  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent

МЕСЯЦЫ = ("Январь Февраль Март Апрель Май Июнь "
          "Июль Август Сентябрь Октябрь Ноябрь Декабрь").split()

# Расхождение мельче рубля — это округление, а не ошибка. Свод ведётся руками
# и местами округлён; ловить копейки значило бы приучить не смотреть на вывод.
ПОРОГ = 1.0


def файл_свода() -> Path | None:
    """Самый свежий «Фин-свод-*.xlsx» в папке проекта.

    ⚠️ Берём по времени правки, а не по имени: имя содержит диапазон месяцев
    («май-июль»), и сортировка по нему поставила бы «май-июнь» после
    «май-июль» — то есть выбрала бы файл постарее.
    """
    файлы = [p for p in ROOT.glob("Фин-свод-*.xlsx") if not p.name.startswith("~$")]
    return max(файлы, key=lambda p: p.stat().st_mtime) if файлы else None


def свод_по_статьям(путь: Path, месяц: str) -> dict[str, float] | None:
    """Расходы месяца из свода: {статья: сумма}. None — листа за месяц нет."""
    import openpyxl

    год, м = (int(x) for x in месяц.split("-"))
    имя = f"{МЕСЯЦЫ[м - 1]} {год}"
    # ⚠️ Файл только читаем. Открывать его командой `open` нельзя — Excel
    # возьмёт его в работу и запишет поверх свою копию.
    wb = openpyxl.load_workbook(путь, data_only=True, read_only=True)
    if имя not in wb.sheetnames:
        return None

    ws = wb[имя]
    по_статьям: dict[str, float] = defaultdict(float)
    в_расходе = False
    for строка in ws.iter_rows(values_only=True):
        подпись = str(строка[0]).strip() if строка and строка[0] else ""
        if подпись.upper().startswith("РАСХОД"):
            в_расходе = True
            continue
        if not в_расходе:
            continue
        # Слева статья, справа сумма. Всё остальное — заголовки разделов
        # («Безнал ООО»), итоги и пояснения: у них слева не статья.
        сумма = строка[2] if len(строка) > 2 else None
        if подпись in ARTICLES and isinstance(сумма, (int, float)):
            по_статьям[подпись] += float(сумма)
    return dict(по_статьям)


def последний_закрытый() -> str:
    """Месяц, который уже закончился. Текущий сверять бессмысленно: свод
    за него ещё не написан, и расхождением окажется весь месяц целиком."""
    сегодня = date.today()
    год, м = сегодня.year, сегодня.month - 1
    if м == 0:
        год, м = год - 1, 12
    return f"{год}-{м:02d}"


def сверить(месяц: str, путь: Path) -> bool:
    """True — сошлось. Печатает разбор в любом случае."""
    эталон = свод_по_статьям(путь, месяц)
    if эталон is None:
        print(f"\n{месяц}: в своде нет листа за этот месяц — сверять не с чем.")
        return True

    наши, _, _ = articles_for_month(месяц)
    M = lambda v: f"{v:,.0f}".replace(",", " ")  # noqa: E731

    итог_свода = sum(эталон.values())
    итог_наш = sum(наши.values())
    расхождения = []
    for статья in sorted(set(эталон) | set(наши)):
        разница = наши.get(статья, 0) - эталон.get(статья, 0)
        if abs(разница) > ПОРОГ:
            расхождения.append((статья, эталон.get(статья, 0), наши.get(статья, 0), разница))

    print(f"\n{'═' * 72}")
    print(f"  СВЕРКА СО СВОДОМ — {месяц}")
    print(f"{'═' * 72}")
    print(f"   свод {M(итог_свода):>16}      ДДС {M(итог_наш):>16}"
          f"      разница {M(итог_наш - итог_свода):>12}")

    if not расхождения:
        print("\n   ✅ по статьям всё сходится")
        return True

    print(f"\n   ⚠️  расхождений по статьям: {len(расхождения)}")
    print(f"   {'статья':<28}{'свод':>14}{'ДДС':>14}{'разница':>14}")
    for статья, было, стало, разница in sorted(расхождения, key=lambda x: -abs(x[3])):
        print(f"   {статья:<28}{M(было):>14}{M(стало):>14}{M(разница):>14}")
    print("\n   💡 Прав свод: он отвечает на вопрос «куда отнести».")
    print("      Правило статьи живёт в scripts/fin_articles.py — поправить надо там,")
    print("      а не в своде и не руками в базе.")
    return False


def main() -> None:
    путь = файл_свода()
    if not путь:
        print("✗ Не нашёл «Фин-свод-*.xlsx» в папке проекта — сверять не с чем.")
        sys.exit(2)

    месяцы = [a for a in sys.argv[1:] if not a.startswith("-")] or [последний_закрытый()]
    print(f"Эталон: {путь.name}")

    всё_сошлось = True
    for месяц in месяцы:
        if not сверить(месяц, путь):
            всё_сошлось = False

    sys.exit(0 if всё_сошлось else 1)


if __name__ == "__main__":
    main()
