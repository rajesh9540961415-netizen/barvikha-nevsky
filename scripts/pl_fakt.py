def месяцы_с_выручкой():
    """Все месяцы, по которым есть чеки, начиная с января 2025."""
    м = set()
    for файл in ("qr_sales_mav.csv", "qr_sales_shalaeva.csv"):
        путь = DATA / файл
        if not путь.exists():
            continue
        for r in csv.DictReader(путь.open(encoding="utf-8")):
            if r["date"][:7] >= ПЕРВЫЙ_МЕСЯЦ:
                м.add(r["date"][:7])
    return sorted(м)


def выручка():
    """Месяц → (наличные, безналичные, последний день с чеками)."""
    нал, безнал, последний = defaultdict(float), defaultdict(float), {}
    for файл in ("qr_sales_mav.csv", "qr_sales_shalaeva.csv"):
        путь = DATA / файл
        if not путь.exists():
            continue
        for r in csv.DictReader(путь.open(encoding="utf-8")):
            м = r["date"][:7]
            if м < ПЕРВЫЙ_МЕСЯЦ:
                continue
            нал[м] += float(r["cash"] or 0)
            безнал[м] += float(r["cashless"] or 0)
            последний[м] = max(последний.get(м, ""), r["date"])
    return нал, безнал, последний


# Один и тот же получатель под двумя именами: в ручном ДДС владелец пишет
# «МИ ФНС РОССИИ +Казначейство+ ФСС», банк — «Казначейство России (ФНС России)»
# и «УФК по г. Москве». По первому слову это три разные строки, и выходит, что
# до мая 2026 в казначейство будто бы ничего не платили, а потом вдруг начали.
# Владелец на это и споткнулась 17.09.2026. Деньги были на месте, подпись врала.
# Четвёртый элемент — статьи, в которых правило работает; None значит «везде».
СЛИЯНИЕ = [
    (re.compile(r"фнс|казначейств|уфк|фсс|сфр|пенсионн", re.I),
     "фнс", "ФНС, казначейство, фонды", None),
    # То же самое с зарплатой по банковским реестрам: в ручном ДДС это
    # «Зарплата Сбер МАВ» и «Зарплата Сбер ИП», в выписке — «ПАО Сбербанк».
    # Владелец спросила 17.09.2026, почему строка «ПАО Сбербанк» в зарплате
    # начинается только с мая 2026. Деньги шли всегда, разошлись подписи.
    (re.compile(r"сбербанк|сбер", re.I),
     "зп-банк", "Зарплата по реестрам банка", ("Зарплата/аванс/мотивация",)),
]


def имя_ключ(имя, статья=None):
    """Ключ контрагента: первое значимое слово названия.

    Одного поставщика пишут по-разному — «ИП ФОМОЧКИН И. Ю. (кухня)» в ручном
    ДДС и «Фомочкин Илья Юрьевич» в банке. По первому слову они сходятся,
    по полному имени — нет, и один поставщик встал бы в отчёт двумя строками.

    ⚠️ У наличных «контрагент» — это колонка тетради: «Аванс/зп», «Уборщицы»,
    «КЭЛ». Общее первое слово у них одно на всех — «Наличные», и по общему
    правилу все они склеились бы в одну строку с чужой подписью. Поймано
    16.09.2026 на первой же сборке: зарплата, сервисный сбор, реклама и
    командировочные вышли под подписью «Наличные: Ремонт/содержание».
    Поэтому у наличных ключ — вся колонка целиком.
    """
    if имя.startswith("Наличные: "):
        return "нал:" + имя[len("Наличные: "):].strip().lower()
    for признак, ключ, _, статьи in СЛИЯНИЕ:
        if (статьи is None or статья in статьи) and признак.search(имя):
            return ключ
    т = fa.tokens(имя)
    return т[0] if т else имя.strip().lower()


