def ручной_месяц(месяц, детали, вывод, служебное):
    """Статьи месяца из ручного ДДС. Возвращает число разобранных строк."""
    строк = 0
    for r in csv.DictReader((DATA / "transactions.csv").open(encoding="utf-8")):
        if r["date"][:7] != месяц:
            continue
        строк += 1
        сумма = float(r["amount"])
        статья = r["category"] or НЕТ_СТАТЬИ
        контрагент = r["counterparty"] or "без названия"
        if r["source"] == "cash":
            контрагент = f"Наличные: {контрагент}"
        if статья == "Вознаграждение":
            # Вывод берём ТОЛЬКО из бэк-офиса — решение владельца 16.09.2026.
            # Из ручного ДДС он не берётся вовсе, даже там, где бэк-офис его
            # не видит: наличные до 2026 года (3,5 млн ₽), счёт ООО «Мята»
            # (6,0 млн ₽ в марте и апреле 2025) и покрытия по аккредитиву
            # (6,0 млн ₽ в июне и сентябре 2025). Цифра в файле должна
            # совпадать с экраном бэк-офиса — это важнее полноты.
            continue
        if статья == "Комиссия":            # комиссии считаем по банку, не отсюда
            служебное.append((месяц, "комиссия из ручного ДДС пропущена", сумма))
            continue
        if статья == "Прочие расходы" and КЭЛ_ПРИЗНАК.search(r["counterparty"]):
            служебное.append((месяц, f"в КЭЛ из «прочих»: {контрагент}", сумма))
            статья = "Прочие расходы на КЭЛ"
        детали[(месяц, статья, контрагент)] += сумма
    return строк


# Возврат гостю по карте банк забирает отдельной строкой «Завершение расчетов
# с ТСТ». Это НЕ наш расход: выручка из кассы приходит уже за вычетом возвратов.
# Признак тот же, что в `fin_articles`, и другим он быть не может — иначе один
# и тот же платёж в двух местах считался бы по-разному.
НЕ_РАСХОД = "с ТСТ"


def разметка_месяц(месяц, банк, ключи, детали, вывод, не_опознано, не_расход):
    """Статьи месяца по банку и наличным — тем же кодом, что «Фин. свод»."""
    строк = 0
    for r in банк:
        if r["date"][:7] != месяц:
            continue
        if r["class"] == "withdrawal":
            continue                 # вывод считается отдельно, по всем месяцам
        if r["direction"] != "out" or r["class"] != "external":
            continue
        строк += 1
        сумма = float(r["amount"])
        части = fa.transfer_detail(r)
        if части:
            for получатель, статья, часть in части:
                детали[(месяц, статья, получатель)] += часть
            continue
        статья, почему = fa.article(r, ключи)
        if статья is None:
            # Статьи нет по двум разным причинам, и путать их нельзя. Если
            # причина названа — платёж опознан и расходом не является (возврат
            # гостю). Если причина пустая — мы просто не поняли платёж, и он
            # должен быть виден отдельной строкой, а не спрятан.
            if почему:
                не_расход.append((месяц, сумма, r["counterparty"], почему))
                continue
            не_опознано.append((месяц, сумма, r["counterparty"], r["purpose"][:60]))
            статья = НЕТ_СТАТЬИ
        детали[(месяц, статья, r["counterparty"])] += сумма

    # Возврат нашей покупки по карте уменьшает ту же статью — иначе расход завышен.
    for r in банк:
        if (r["date"][:7] != месяц or r["direction"] != "in"
                or not fa.CARD.search(r["purpose"])):
            continue
        статья, _ = fa.article(r, ключи)
        if статья:
            детали[(месяц, статья, r["counterparty"])] -= float(r["amount"])

    for r in csv.DictReader((DATA / "cash_expenses.csv").open(encoding="utf-8")):
        if r["date"][:7] != месяц:
            continue
        строк += 1
        сумма = float(r["amount"])
        расшифровка = fa.CASH_DETAIL.get((r["date"], r["column"]))
        if расшифровка:
            if abs(sum(v for _, v in расшифровка) - сумма) > 0.01:
                не_опознано.append((месяц, сумма, f"наличные: {r['column']}",
                                    "расшифровка не сходится"))
                continue
            for статья, часть in расшифровка:
                детали[(месяц, статья, f"Наличные: {r['column']}")] += часть
            continue
        статья = fa.CASH_MAP.get(r["column"])
        if статья == ВЫВОД:
            вывод[месяц] += сумма
            continue
        if статья is None:
            не_опознано.append((месяц, сумма, f"наличные: {r['column']}", ""))
            статья = НЕТ_СТАТЬИ
        детали[(месяц, статья, f"Наличные: {r['column']}")] += сумма
    return строк


# Настоящая комиссия банка называет себя сама: «Комиссия за перевод…»,
# «Плата за опцию…», «Плата за обслуживание…». Всё остальное, что правило
# «Фин. свода» относит к комиссии до мая 2026, комиссией не является —
# см. комментарий в `комиссии()`.
КОМИССИЯ_ПО_НАЗВАНИЮ = re.compile(r"комисси|плата за", re.I)


def комиссии(месяц, банк, ключи, детали):
    """Эквайринг и комиссии банка — на весь период по банку, а не по ДДС.

    Эквайринг банк удерживает прямо из зачисления, отдельным платежом он не
    приходит, поэтому в ручном ДДС его нет ни одного месяца. Без этой строки
    расходы занижены примерно на 2 млн ₽ в год.

    ⚠️ Комиссии банка до мая 2026 берём НЕ по общему правилу «Фин. свода»,
    а только те платежи, которые называют себя комиссией. Причина проверена
    16.09.2026: общее правило опирается на колонку «почему», а до 2026 года она
    пустая, и в комиссию попадает чужое — 6,0 млн ₽ «списание покрытия по
    аккредитиву» (16.06.2025 это 4,5 млн, и ровно та же сумма тем же днём стоит
    в ручном ДДС как вознаграждение) и 285 тыс. ₽ зарплатных авансов по реестру.
    Оставить общее правило значило бы посчитать вывод собственнику дважды и
    назвать его комиссией. По названию за 16 месяцев набирается 209,6 тыс. ₽ —
    4–38 тыс. в месяц, и это похоже на правду.

    С мая 2026 фильтр не нужен и не применяется: там колонка «почему» заполнена,
    комиссии разбираются общим кодом вместе со всеми расходами, и сверка сверяет
    файл ровно с тем числом, которое видит бэк-офис.
    """
    экв = fa.acquiring(месяц)
    if экв:
        детали[(месяц, "Комиссия", "Эквайринг — удержан банком из зачисления")] += экв
    if месяц > РУЧНОЙ_ПО:
        return
    банковские = 0.0
    for r in банк:
        if (r["date"][:7] != месяц or r["direction"] != "out"
                or r["class"] != "external"):
            continue
        if not КОМИССИЯ_ПО_НАЗВАНИЮ.search(r["purpose"]):
            continue
        статья, _ = fa.article(r, ключи)
        if статья == "Комиссия":
            банковские += float(r["amount"])
    if банковские:
        детали[(месяц, "Комиссия", "Комиссии банка")] += банковские


def вывод_по_банку(месяцы_, банк, вывод):
    """Вывод собственнику — ровно тем же признаком, что в бэк-офисе.

    Бэк-офис считает выводом род операции `withdrawal` (`fin_push.py`), и здесь
    берётся только он, плюс наличная колонка «Вознаграждение Боссам» — она тоже
    едет в бэк-офис выводом (`cash_categories.json`). Больше ничего: решение
    владельца 16.09.2026 — цифра должна сходиться с её экраном.
    """
    for r in банк:
        м = r["date"][:7]
        if м in месяцы_ and r["class"] == "withdrawal":
            # Возврат с вывода бывает — тогда он уменьшает вывод месяца.
            вывод[м] += float(r["amount"]) * (1 if r["direction"] == "out" else -1)


def собрать_расходы(месяцы_):
    банк = list(csv.DictReader((DATA / "bank_classified.csv").open(encoding="utf-8")))
    ключи = fa.build_dictionary()
    детали, вывод = defaultdict(float), defaultdict(float)
    служебное, не_опознано, не_расход, строки = [], [], [], {}

    for м in месяцы_:
        if м <= РУЧНОЙ_ПО:
            строки[м] = ручной_месяц(м, детали, вывод, служебное)
        else:
            строки[м] = разметка_месяц(м, банк, ключи, детали, вывод,
                                       не_опознано, не_расход)
        комиссии(м, банк, ключи, детали)

    вывод_по_банку(set(месяцы_), банк, вывод)
    return (детали, вывод, служебное, не_опознано, не_расход, строки, банк, ключи)


