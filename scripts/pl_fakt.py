def сверка(месяцы_, детали, вывод, банк, ключи):
    """Наш расход против того же расхода, посчитанного независимо.

    Для месяцев разметки независимый счёт — `fin_articles.articles_for_month`,
    то есть ровно то число, которое видит бэк-офис. Для ручных месяцев — сумма
    ручного ДДС за вычетом вознаграждения. Разойдутся — значит я потерял или
    задвоил платёж, и файл собирать нельзя.
    """
    итог = []
    for м in месяцы_:
        наш = sum(с for (мм, _, _), с in детали.items() if мм == м)
        if м <= РУЧНОЙ_ПО:
            ручной = 0.0
            for r in csv.DictReader((DATA / "transactions.csv").open(encoding="utf-8")):
                if r["date"][:7] == м and r["category"] != "Вознаграждение":
                    ручной += float(r["amount"])
            комиссия = sum(с for (мм, ст, _), с in детали.items()
                           if мм == м and ст == "Комиссия")
            эталон = ручной + комиссия
        else:
            agg, неизвестные, _ = fa.articles_for_month(м, банк, ключи)
            # У «Фин. свода» неопознанное лежит отдельным списком и в статьи не
            # входит. У нас оно стоит в файле строкой «Статья не проставлена» —
            # прятать деньги нельзя. Поэтому к эталону его прибавляем.
            # Возвраты гостям «Фин. свод» держит в том же списке неизвестного,
            # что и непонятые платежи. Здесь они в расход не идут, поэтому и из
            # эталона их вычитаем — иначе сверка сверяла бы себя с собой и
            # молчала бы ровно про ту ошибку, которую я только что исправил.
            эталон = (sum(v for k, v in agg.items() if k != ВЫВОД)
                      + sum(a for a, _, p in неизвестные if НЕ_РАСХОД not in p))
        итог.append((м, наш, эталон, наш - эталон))
    return итог


