FONT = '<w:rFonts w:ascii="Calibri" w:cs="Calibri" w:eastAsia="Calibri" w:hAnsi="Calibri"/>'


def run(text, *, bold=False, size=21, color='1F1F1F'):
    b = '<w:b/><w:bCs/>' if bold else '<w:b w:val="false"/><w:bCs w:val="false"/>'
    return (f'<w:r><w:rPr>{FONT}{b}<w:color w:val="{color}"/>'
            f'<w:sz w:val="{size}"/><w:szCs w:val="{size}"/></w:rPr>'
            f'<w:t xml:space="preserve">{escape(text)}</w:t></w:r>')


def para(text, *, bold=False, size=21, color='1F1F1F', after=200, before=0, style=None):
    st = f'<w:pStyle w:val="{style}"/>' if style else ''
    return (f'<w:p><w:pPr>{st}<w:spacing w:after="{after}" w:before="{before}" w:line="276"/>'
            f'<w:jc w:val="left"/></w:pPr>{run(text, bold=bold, size=size, color=color)}</w:p>')


def heading(text):
    return para(text, bold=True, size=23, color='1B6B4A', after=140)


def sub(text):
    """Мелкая серая подпись под таблицей."""
    return para(text, size=17, color='595959', after=260, before=140)


def divider():
    return ('<w:p><w:pPr><w:pBdr><w:bottom w:val="single" w:color="D9D9D9" w:sz="6" w:space="1"/></w:pBdr>'
            '<w:spacing w:after="200" w:before="120"/></w:pPr>'
            '<w:r><w:rPr><w:sz w:val="2"/><w:szCs w:val="2"/></w:rPr><w:t xml:space="preserve"> </w:t></w:r></w:p>')


def cell(text, width, *, bold=False, align='right', shade=None, size=20):
    shd = f'<w:shd w:fill="{shade}" w:color="auto" w:val="clear"/>' if shade else ''
    return (f'<w:tc><w:tcPr><w:tcW w:type="dxa" w:w="{width}"/>{shd}'
            f'<w:tcMar><w:top w:type="dxa" w:w="80"/><w:left w:type="dxa" w:w="120"/>'
            f'<w:bottom w:type="dxa" w:w="80"/><w:right w:type="dxa" w:w="120"/></w:tcMar></w:tcPr>'
            f'<w:p><w:pPr><w:spacing w:after="0" w:before="0"/><w:jc w:val="{align}"/></w:pPr>'
            f'{run(text, bold=bold, size=size)}</w:p></w:tc>')


def table(widths, rows):
    """rows: список (cells, kind); kind = 'head' | 'body' | 'key'."""
    total = sum(widths)
    grid = ''.join(f'<w:gridCol w:w="{w}"/>' for w in widths)
    out = [f'<w:tbl><w:tblPr><w:tblW w:type="dxa" w:w="{total}"/><w:tblBorders>'
           '<w:top w:val="single" w:color="auto" w:sz="4"/><w:left w:val="single" w:color="auto" w:sz="4"/>'
           '<w:bottom w:val="single" w:color="auto" w:sz="4"/><w:right w:val="single" w:color="auto" w:sz="4"/>'
           '<w:insideH w:val="single" w:color="auto" w:sz="4"/><w:insideV w:val="single" w:color="auto" w:sz="4"/>'
           f'</w:tblBorders></w:tblPr><w:tblGrid>{grid}</w:tblGrid>']
    for cells, kind in rows:
        shade = {'head': 'F2F2F2', 'key': 'F7F7F7'}.get(kind)
        bold = kind in ('head', 'key')
        size = 19 if kind == 'head' else 20
        tr = ['<w:tr>']
        for i, (w, txt) in enumerate(zip(widths, cells)):
            tr.append(cell(txt, w, bold=bold, align='left' if i == 0 else 'right',
                           shade=shade, size=size))
        tr.append('</w:tr>')
        out.append(''.join(tr))
    out.append('</w:tbl>')
    return ''.join(out)


