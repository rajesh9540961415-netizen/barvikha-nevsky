#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Дневные итоги для экрана «Обзор»: посчитать из чеков и залить в базу.

Заведено 07.09.2026 по задаче владельца «первая страничка с основными
показателями». В первой версии того же дня числа лежали файлом внутри
сборки бэк-офиса и обновлялись только вместе с выкладкой; владелец:
«делай живое обновление через базу». Файл убран, числа живут в таблице
`dashboard_days`.

🔴 **Почему считаем здесь, а заливаем по HTTPS.** Amvera собирает бэк-офис
отдельным корнем: папка `data/ofd` с фискальными чеками до сервера не
доезжает, посчитать выручку на месте он не может. Напрямую в базу с этого
компьютера тоже не достучаться — порт 5432 перехватывает VPN incy, а
выключать его нельзя (решение владельца 28.08.2026). Остаётся служебная
дверь `/api/dashboard`.

⚠️ **Сутки — торговые, с 11:00 до 10:59**, как во всём проекте
(`СДВИГ_СУТОК` в `qr_cancellations.py`). Иначе субботняя ночь после полуночи
уехала бы в воскресенье, а суббота — главный день недели, и терять её
половину нельзя. Час в почасовой раскладке при этом настоящий, часовой:
ради него всё и затевалось — пик приходится на полночь.

⚠️ **Две кассы, но НЕ три файла.** С июля 2026 бар пробивается через вторую
кассу (`чеки-бар-*`). Складываем зал и бар. А `чеки-шалаева-*` брать НЕЛЬЗЯ:
проверено 07.09.2026 — все 1931 его чеков за август уже лежат внутри
`чеки-бар-2026-08`, совпадение по ФПД полное. Сложи их — и август вырастет
на 7,1 млн из ниоткуда.

⚠️ **`цена` в позиции чека — это сумма СТРОКИ, а не цена за штуку.** Проверено
07.09.2026: сумма всех `цена` по августу совпала с суммой чеков до рубля,
а «количество × цена» завысило её в полтора раза. Умножать нельзя.

⚠️ **Заливаем всё целиком, а не «что появилось».** Слепок пересобирается
из чеков заново, и поздно доехавший чек должен переписать свой день.
Накопление вместо пересборки — как раз тот способ тихо разойтись с кассой,
от которого проект уходил везде.

Адрес и ключ — в `.env`: OFFICE_URL и DASHBOARD_KEY.

Запуск:
    python3 scripts/dashboard_push.py            # посчитать и залить
    python3 scripts/dashboard_push.py --показать # только посчитать, не заливать
"""
from __future__ import annotations

import argparse
import collections
import glob
import json
import os
import re
import sys
import urllib.error
import urllib.request
from datetime import datetime, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))

from pl_menu import категория  # noqa: E402  разнесение позиций по направлениям

СДВИГ_СУТОК = 11
ВЫГРУЗКИ = ROOT / "data" / "выгрузки-смен"
НАПРАВЛЕНИЯ = ("бар", "кухня", "кальяны", "аренда")
АДРЕС_ПО_УМОЛЧАНИЮ = "https://nevsky-office-borzovavv.amvera.io"
# Пачками, а не одним куском: год чеков — это четверть мегабайта JSON,
# и отправлять её одним запросом значит один раз не дождаться ответа
# и не знать, записалось ли хоть что-то.
ПАЧКА = 90


# ── считаем ──────────────────────────────────────────────────────────────

def торговый_день(iso: str) -> str:
    т = datetime.fromisoformat(iso.replace("Z", ""))
    return (т - timedelta(hours=СДВИГ_СУТОК)).date().isoformat()


def файлы_чеков() -> list[str]:
    """Зал и бар. Всё остальное — либо повтор, либо не наш контур."""
    зал = sorted(glob.glob(str(ROOT / "data" / "ofd" / "чеки-20*.json")))
    зал = [f for f in зал if re.search(r"чеки-\d{4}-\d{2}\.json$", f)]
    бар = sorted(glob.glob(str(ROOT / "data" / "ofd" / "чеки-бар-*.json")))
    return зал + бар


def пустой_день() -> dict:
    return {
        "выручка": 0.0, "чеков": 0, "нал": 0.0, "безнал": 0.0,
        "возвраты": 0.0, "возвратов": 0,
        "направления": {н: 0.0 for н in НАПРАВЛЕНИЯ},
        "часы": [0.0] * 24,
    }


def собрать() -> list[dict]:
    дни: dict[str, dict] = collections.defaultdict(пустой_день)
    прочитано = 0
    for путь in файлы_чеков():
        сырое = json.load(open(путь, encoding="utf-8"))
        чеки = сырое if isinstance(сырое, list) else list(сырое.values())[0]
        прочитано += len(чеки)
        for ч in чеки:
            время = ч.get("время")
            if not время:
                continue
            д = дни[торговый_день(время)]
            сумма = float(ч.get("сумма") or 0)
            if ч.get("вид") == 2:
                д["возвраты"] += сумма
                д["возвратов"] += 1
                continue
            д["выручка"] += сумма
            д["чеков"] += 1
            д["нал"] += float(ч.get("нал") or 0)
            д["безнал"] += float(ч.get("безнал") or 0)
            д["часы"][datetime.fromisoformat(время.replace("Z", "")).hour] += сумма
            for имя, _кол, строка in (ч.get("позиции") or []):
                к = категория(имя)
                if к in д["направления"]:
                    д["направления"][к] += float(строка or 0)
    print(f"  чеков прочитано: {прочитано}, дней получилось: {len(дни)}")

    # Чаевые — из выгрузок смен, тех же файлов, что кормят утренний отчёт.
    # Не из базы: с этого компьютера база недоступна, а слепок должен
    # собираться в любой момент, не только там, где есть доступ к базе.
    с_чаевыми = 0
    for файл in sorted(ВЫГРУЗКИ.glob("смена-*.json")):
        try:
            смена = json.loads(файл.read_text(encoding="utf-8"))
        except Exception:
            continue
        день = смена.get("businessDay")
        итоги = смена.get("totals") or {}
        if not день or not итоги:
            continue
        if день not in дни:
            дни[день] = пустой_день()
        дни[день]["чаевые"] = round(float(итоги.get("earned") or 0), 2)
        с_чаевыми += 1
    print(f"  смен с чаевыми: {с_чаевыми}")

    готово = []
    for день in sorted(дни):
        д = дни[день]
        готово.append({
            "день": день,
            "выручка": round(д["выручка"], 2),
            "чеков": д["чеков"],
            "нал": round(д["нал"], 2),
            "безнал": round(д["безнал"], 2),
            "возвраты": round(д["возвраты"], 2),
            "возвратов": д["возвратов"],
            "направления": {н: round(д["направления"][н], 2) for н in НАПРАВЛЕНИЯ},
            "часы": [round(ч, 2) for ч in д["часы"]],
            "чаевые": д.get("чаевые"),
        })
    return готово


# ── заливаем ─────────────────────────────────────────────────────────────

def из_env(имя: str, запасное: str = "") -> str:
    if значение := os.environ.get(имя):
        return значение
    файл = ROOT / ".env"
    if файл.exists():
        for строка in файл.read_text(encoding="utf-8").splitlines():
            строка = строка.strip()
            if строка.startswith(f"{имя}="):
                return строка.split("=", 1)[1].strip().strip('"').strip("'")
    return запасное


def залить(дни: list[dict]) -> None:
    адрес = из_env("OFFICE_URL", АДРЕС_ПО_УМОЛЧАНИЮ).rstrip("/") + "/api/dashboard"
    ключ = из_env("DASHBOARD_KEY")
    if not ключ:
        sys.exit(
            "✗ Не задан DASHBOARD_KEY.\n"
            "  Это отдельный ключ на заливку «Обзора», не EXPORT_KEY и не FINANCE_KEY.\n"
            "  Одно и то же значение нужно в двух местах: в .env проекта\n"
            "  и в переменных приложения nevsky-office в панели Amvera."
        )

    записано = 0
    for н in range(0, len(дни), ПАЧКА):
        кусок = дни[н:н + ПАЧКА]
        тело = json.dumps({"дни": кусок}, ensure_ascii=False).encode("utf-8")
        req = urllib.request.Request(
            адрес, data=тело, method="POST",
            headers={"X-Dashboard-Key": ключ, "Content-Type": "application/json"},
        )
        try:
            with urllib.request.urlopen(req, timeout=120) as ответ:
                итог = json.loads(ответ.read().decode("utf-8"))
        except urllib.error.HTTPError as e:
            подробности = e.read().decode("utf-8", errors="replace")
            try:
                разобрано = json.loads(подробности)
                причина = разобрано.get("причина", подробности)
                if разобрано.get("ошибки"):
                    причина += "\n    " + "\n    ".join(разобрано["ошибки"])
            except json.JSONDecodeError:
                причина = подробности[:400]
            sys.exit(f"✗ Бэк-офис ответил {e.code}: {причина}")
        except urllib.error.URLError as e:
            sys.exit(f"✗ Не достучался до бэк-офиса: {e.reason}")
        записано += итог.get("записано", 0)
        print(f"  залито {записано} из {len(дни)}  ({кусок[0]['день']} — {кусок[-1]['день']})")
    print(f"✓ Готово: {записано} дней в базе бэк-офиса")


def главное() -> None:
    разбор = argparse.ArgumentParser(description="Дневные итоги для «Обзора».")
    разбор.add_argument("--показать", action="store_true",
                        help="только посчитать и показать итог, не заливать")
    аргументы = разбор.parse_args()

    print("Дневные итоги для «Обзора»")
    дни = собрать()
    if not дни:
        sys.exit("✗ Ни одного дня не собралось — проверьте data/ofd")

    выручка = sum(д["выручка"] for д in дни)
    print(f"  период: {дни[0]['день']} — {дни[-1]['день']}")
    print(f"  выручка за весь период: {выручка:,.0f} ₽".replace(",", " "))

    # Проверка, которая ловит самую дорогую ошибку: направления и часы
    # обязаны в сумме давать выручку. Разошлись — значит позиции чеков
    # прочитаны неверно, и заливать такое нельзя.
    напр = sum(sum(д["направления"].values()) for д in дни)
    часы = sum(sum(д["часы"]) for д in дни)
    for имя, значение in (("направления", напр), ("часы", часы)):
        if abs(значение - выручка) > 1:
            sys.exit(f"✗ {имя.capitalize()} не сходятся с выручкой: "
                     f"{значение:,.0f} против {выручка:,.0f}. Не заливаю."
                     .replace(",", " "))
    print("  проверка: направления и часы сходятся с выручкой ✓")

    if аргументы.показать:
        print("\nЭто был показ. Чтобы залить — запустите без --показать")
        return
    залить(дни)


if __name__ == "__main__":
    главное()
