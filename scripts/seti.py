# -*- coding: utf-8 -*-
"""Один запрос в сеть — с повторами. Общий для всех скриптов проекта.

⚠️ Зачем это понадобилось. 28.08.2026 утренний отчёт по чаевым не собрался:
запросы к приложению обрывались, не дойдя до него. Разбор показал, что дело
не в приложении и не в хостинге — **теряет VPN incy на компьютере владельца**.
Проверка: до домашнего роутера 20 пакетов из 20 без потерь, а наружу не
доходит примерно каждый третий запрос, причём одинаково к ya.ru, к Google
и к нашему приложению. Выключить VPN нельзя — решение владельца 28.08.2026.

Значит, сеть для нас ненадёжна по определению, и каждый скрипт обязан
переживать потерянный пакет сам. Раньше повторы были у половины скриптов,
и у каждого свои; здесь они одни на всех.

Повторяем ТОЛЬКО обрывы связи и пятисотые ошибки шлюза. Ответы вроде 401
(не тот ключ) и 404 (нет такого) повторять незачем: они не изменятся,
а ждать пришлось бы впустую и молча.
"""

from __future__ import annotations

import http.client
import json
import socket
import ssl
import sys
import time
import urllib.error
import urllib.request

ПОПЫТОК = 5
ПАУЗА = 4                       # секунд перед вторым заходом, дальше вдвое
ПОВТОРЯТЬ_КОДЫ = (500, 502, 503, 504)

# Обрыв связи приходит в очень разном виде: таймаут TLS-рукопожатия — это
# ssl.SSLError, оборванный ответ — http.client.IncompleteRead, а несостоявшееся
# соединение — urllib.error.URLError. Ловим все, иначе повторы не сработают
# ровно в том случае, ради которого написаны.
ОБРЫВЫ = (urllib.error.URLError, ssl.SSLError, socket.timeout, TimeoutError,
          ConnectionError, http.client.IncompleteRead, http.client.RemoteDisconnected,
          OSError)


def достучаться(запрос, таймаут: int = 90, попыток: int = ПОПЫТОК,
                тихо: bool = False, **kwargs) -> bytes:
    """Открывает запрос и возвращает тело ответа, повторяя при обрывах.

    `запрос` — то же, что принимает urlopen: строка-адрес или Request.
    Последняя неудача поднимается наружу как есть, чтобы вызвавший
    скрипт напечатал свою привычную ошибку.
    """
    пауза = ПАУЗА
    for попытка in range(1, попыток + 1):
        try:
            with urllib.request.urlopen(запрос, timeout=таймаут, **kwargs) as ответ:
                if попытка > 1 and not тихо:
                    print(f"   связь восстановилась с {попытка}-й попытки")
                return ответ.read()
        except urllib.error.HTTPError as e:
            # HTTPError — наследник URLError, поэтому проверяем его первым,
            # иначе 401 попал бы в повторы вместе с обрывами.
            if e.code not in ПОВТОРЯТЬ_КОДЫ or попытка == попыток:
                raise
            if not тихо:
                print(f"   сервер ответил {e.code}, попытка {попытка} из {попыток}")
        except ОБРЫВЫ as e:
            if попытка == попыток:
                raise
            if not тихо:
                причина = getattr(e, "reason", e)
                print(f"   нет связи ({причина}), попытка {попытка} из {попыток}")
        time.sleep(пауза)
        пауза *= 2
    raise RuntimeError("недостижимо: цикл повторов всегда выходит через return или raise")


def достучаться_json(запрос, **kwargs):
    """То же, но сразу разбирает JSON."""
    return json.loads(достучаться(запрос, **kwargs).decode("utf-8"))


if __name__ == "__main__":
    # Проверка связи: сколько запросов доходит. Полезно, когда что-то отвалилось.
    адрес = sys.argv[1] if len(sys.argv) > 1 else "https://chaevye-borzovavv.msk1.amvera.tech/api/health"
    сколько = int(sys.argv[2]) if len(sys.argv) > 2 else 10
    дошло = 0
    коды = {}
    for i in range(сколько):
        try:
            ответ = urllib.request.urlopen(адрес, timeout=10)
            ответ.read()
            дошло += 1
            коды[ответ.status] = коды.get(ответ.status, 0) + 1
        except urllib.error.HTTPError as e:
            # ⚠️ 401 и 404 — это ОТВЕТ сервера, значит связь есть. Раньше они
            # считались потерей, и пробник врал: 28.08.2026 он показал «дошло
            # 0 из 6» на живом API, который исправно отвечал «неверный ключ».
            дошло += 1
            коды[e.code] = коды.get(e.code, 0) + 1
        except ОБРЫВЫ:
            pass
    расшифровка = ", ".join(f"{к}: {n}" for к, n in sorted(коды.items()))
    print(f"{адрес}: дошло {дошло} из {сколько}, потеряно {сколько - дошло}"
          + (f"  (ответы — {расшифровка})" if коды else ""))
