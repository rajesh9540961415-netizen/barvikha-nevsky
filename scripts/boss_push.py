#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Вознаграждение собственнику → экран «Вознаграждение босса» в бэк-офисе.

Задача владельца 11.09.2026: «отдельная страничка, где нужно описать вывод
в порядке: месяц, за который мы заплатили, общая сумма, с каких юридических
лиц какие суммы были выведены».

🔴 **Две даты, и путать их дороже всего остального.**
  — дата платежа берётся из выписки, это факт;
  — месяц, ЗА который вознаграждение, знает только владелец: в банковских
    данных его нет вовсе.
За июль 2026 платили пятью платежами с 22 июля по 8 сентября, и часть одного
сентябрьского платежа тоже относится к июлю. По дате платежа такую картину
не собрать никаким способом.

⚠️ Месяц не назван — это «ещё не разбирали», а не «ни за какой». На 11.09.2026
месяц известен у восьми выплат из ста десяти. Догадываться нельзя: страница
показывает такие выплаты отдельной строкой.

Месяцы живут в `data/dds/вознаграждение.json` — их называет владелец через
переписку. Ключ строки тот же, что у заимствований: «дата|документ|сумма».

Запуск:
    python3 scripts/boss_push.py             посчитать и показать
    python3 scripts/boss_push.py --залить    отправить в бэк-офис
"""
from __future__ import annotations

import argparse
import calendar
import csv
import json
import sys
import urllib.error
import urllib.request
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / "data" / "dds"
МЕСЯЦЫ_ФАЙЛ = DATA / "вознаграждение.json"
ВНЕ_БАНКА_ФАЙЛ = DATA / "вознаграждение-вне-банка.json"
АДРЕС_ПО_УМОЛЧАНИЮ = "https://nevsky-office-borzovavv.msk1.amvera.tech"

ПОДПИСЬ = {
    "ip_shalaeva": "ИП Шалаева",
    "ip_khisamov": "ИП Хисамов",
    "ip_borzova": "ИП Борзова",
    # 🔴 Три источника, которых в выписках нет вовсе. Стоят в одном ряду
    # с юрлицами намеренно: владелец получает эти деньги так же, как
    # переводит себе со счёта, и месяц без них показывает неправду —
    # за июль 2026 по счетам 6 500 000, а на самом деле 9 000 000.
    # Просьба владельца 12.09.2026, сперва наличные, следом остальные два.
    "mav": "ООО МАВ",
    "myata": "ООО Мята",
    "nal": "Наличные",
}
НАЗВАНИЕ = ["", "январь", "февраль", "март", "апрель", "май", "июнь",
            "июль", "август", "сентябрь", "октябрь", "ноябрь", "декабрь"]


def из_env(имя: str, запасное: str = "") -> str:
    путь = ROOT / ".env"
    if путь.exists():
        for строка in путь.read_text(encoding="utf-8").splitlines():
            if строка.startswith(f"{имя}="):
                return строка.split("=", 1)[1].strip().strip('"').strip("'")
    return запасное


def деньги(v: float) -> str:
    return f"{v:,.0f}".replace(",", " ")


def ключ(дата: str, документ, сумма) -> str:
    return f"{дата}|{документ}|{round(float(сумма), 2)}"


def собрать() -> list[dict]:
    свои = {"месяцы": {}, "комментарии": {}}
    if МЕСЯЦЫ_ФАЙЛ.exists():
        свои = json.loads(МЕСЯЦЫ_ФАЙЛ.read_text(encoding="utf-8"))

    выплаты = []
    for r in csv.DictReader((DATA / "bank_classified.csv").open(encoding="utf-8")):
        # Только расход: у класса withdrawal приход означал бы возврат,
        # а возврат вознаграждения — не вознаграждение.
        if r["direction"] != "out" or r.get("class") != "withdrawal":
            continue
        к = ключ(r["date"], r.get("doc_no", ""), r["amount"])
        весь = round(abs(float(r["amount"])), 2)
        разметка = свои.get("месяцы", {}).get(к)
        комментарий = свои.get("комментарии", {}).get(к) or None

        # 🔴 Разметка бывает двух видов, и это не прихоть формата.
        # Строка «2026-07» — весь платёж за один месяц.
        # Словарь {"2026-07": 150000, "2026-08": 1500000} — платёж делится:
        # 08.09.2026 из 1 650 000 ₽ к июлю относятся 150 000 (владелец
        # 11.09.2026). Одной строкой такую выплату не показать: либо июль
        # занижен, либо август завышен.
        #
        # ⚠️ Остаток, не разнесённый по месяцам, в месяцы НЕ идёт: 14.08 из
        # 1 524 000 ₽ вознаграждением стали 1 500 000, а 24 000 вернулись
        # в тот же день. Приписать их к июлю значило бы завысить месяц.
        if isinstance(разметка, dict):
            доли = [(м, round(float(с), 2)) for м, с in разметка.items()]
            сумма_долей = round(sum(с for _, с in доли), 2)
            if сумма_долей > весь + 0.01:
                sys.exit(f"✗ {к}: доли дают {сумма_долей}, а платёж {весь}")
        else:
            доли = [(разметка or None, весь)]

        for месяц, доля in доли:
            выплаты.append({
                "день": r["date"],
                "документ": str(r.get("doc_no", "")),
                "весь_платёж": весь,
                "доля": доля,
                "юрлицо": r.get("entity", ""),
                "за_месяц": месяц,
                "комментарий": комментарий,
            })
    выплаты.extend(вне_банка())
    выплаты.sort(key=lambda в: (в["день"], в["документ"]))
    return выплаты


def вне_банка() -> list[dict]:
    """Вознаграждение, которого в выписках нет: наличные, «Мята», «МАВ».

    🔴 Источник — только слово владельца, и это главное отличие этих строк
    от всех остальных на экране. Наличная выручка смешана между ООО «МАВ»
    и ИП Хисамовым и через расчётные счета не проходит; по ООО «Мята»
    выписок у нас не было никогда; выплаты Ереминой не встречаются в наших
    данных ни разу. Перепроверить эти числа нечем, поэтому у каждой такой
    строки стоит комментарий, говорящий это прямо.

    ⚠️ Дата условная — последний день месяца. Ни даты платежа, ни номера
    документа у этих денег нет, а место в таблице им нужно.

    ⚠️ Аккредитивы ООО «МАВ» в выписке есть (6 033 500 ₽ против 6 000 000
    в таблице), но взяты числа таблицы: месяц, собранный наполовину
    из банка и наполовину из таблицы, не сходится ни с тем, ни с другим.
    Разница 33 500 ₽ ждёт владельца — записана в самом файле.
    """
    if not ВНЕ_БАНКА_ФАЙЛ.exists():
        return []
    файл = json.loads(ВНЕ_БАНКА_ФАЙЛ.read_text(encoding="utf-8"))
    пояснения = файл.get("пояснения", {})
    откуда = {
        "nal": "наличными",
        "myata": "через ООО «Мята»",
        "mav": "через ООО «МАВ»",
    }
    строки = []
    for источник, месяцы in файл.get("источники", {}).items():
        for месяц, сумма in sorted(месяцы.items()):
            if not сумма:
                continue
            год, номер = int(месяц[:4]), int(месяц[5:7])
            последний = calendar.monthrange(год, номер)[1]
            подпись = (f"{откуда.get(источник, источник)}, по таблице владельца "
                       f"— в выписках этих денег нет")
            своё = пояснения.get(источник, {}).get(месяц)
            строки.append({
                "день": f"{месяц}-{последний:02d}",
                "документ": "",
                "весь_платёж": round(float(сумма), 2),
                "доля": round(float(сумма), 2),
                "юрлицо": источник,
                "за_месяц": месяц,
                "комментарий": f"{подпись}. {своё}" if своё else подпись,
            })
    return строки


def показать(выплаты: list[dict]) -> None:
    по_месяцам = defaultdict(lambda: defaultdict(float))
    по_юрлицам = defaultdict(float)
    for в in выплаты:
        по_месяцам[в["за_месяц"] or "—"][в["юрлицо"]] += в["доля"]
        по_юрлицам[в["юрлицо"]] += в["доля"]

    юрлица = [ю for ю in ПОДПИСЬ if по_юрлицам.get(ю)]
    print("ВОЗНАГРАЖДЕНИЕ СОБСТВЕННИКА")
    print("=" * 74)
    шапка = f"{'за месяц':<18}{'всего':>14}" + "".join(
        f"{ПОДПИСЬ[ю]:>14}" for ю in юрлица)
    print(шапка)
    print("-" * 74)

    def имя(м: str) -> str:
        if м == "—":
            return "месяц не назван"
        год, номер = м.split("-")
        return f"{НАЗВАНИЕ[int(номер)]} {год}"

    # Названные месяцы сверху по убыванию, неназванное — в самый низ.
    порядок = sorted((м for м in по_месяцам if м != "—"), reverse=True)
    if "—" in по_месяцам:
        порядок.append("—")
    for м in порядок:
        всего = sum(по_месяцам[м].values())
        части = "".join(
            f"{деньги(по_месяцам[м][ю]) if по_месяцам[м].get(ю) else '—':>14}"
            for ю in юрлица)
        print(f"{имя(м):<18}{деньги(всего):>14}{части}")
    print("-" * 74)
    итог = "".join(f"{деньги(по_юрлицам[ю]):>14}" for ю in юрлица)
    print(f"{'ИТОГО':<18}{деньги(sum(по_юрлицам.values())):>14}{итог}")
    без = sum(в["доля"] for в in выплаты if not в["за_месяц"])
    платежей = len({(в["день"], в["документ"], в["весь_платёж"]) for в in выплаты})
    print(f"\nплатежей {платежей}, строк {len(выплаты)} (делёные дают две), "
          f"без названного месяца — {деньги(без)} ₽")


def залить(выплаты: list[dict]) -> None:
    адрес = из_env("OFFICE_URL", АДРЕС_ПО_УМОЛЧАНИЮ).rstrip("/") + "/api/boss"
    ключ_доступа = из_env("FINANCE_KEY")
    if not ключ_доступа:
        sys.exit("✗ Не задан FINANCE_KEY — тот же ключ, что у финансов.")

    тело = json.dumps({"выплаты": выплаты}, ensure_ascii=False).encode("utf-8")
    req = urllib.request.Request(
        адрес, data=тело, method="POST",
        headers={"X-Finance-Key": ключ_доступа, "Content-Type": "application/json"},
    )
    try:
        with urllib.request.urlopen(req, timeout=180) as ответ:
            итог = json.loads(ответ.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        подробности = e.read().decode("utf-8", errors="replace")
        try:
            разобрано = json.loads(подробности)
            причина = разобрано.get("причина", подробности)
            if разобрано.get("ошибки"):
                причина += "\n    " + "\n    ".join(разобрано["ошибки"][:10])
        except json.JSONDecodeError:
            причина = подробности[:400]
        sys.exit(f"✗ Бэк-офис ответил {e.code}: {причина}")
    except urllib.error.URLError as e:
        sys.exit(f"✗ Не достучался до бэк-офиса: {e.reason}")
    print(f"\n✓ Залито выплат: {итог.get('записано', 0)}")


def главное() -> None:
    разбор = argparse.ArgumentParser(description="Вознаграждение собственнику.")
    разбор.add_argument("--залить", action="store_true",
                        help="отправить в бэк-офис (без ключа — только показать)")
    аргументы = разбор.parse_args()

    выплаты = собрать()
    if not выплаты:
        sys.exit("✗ Выплат класса «вывод собственнику» не нашлось.")
    показать(выплаты)
    if аргументы.залить:
        залить(выплаты)
    else:
        print("\nЭто был показ. Чтобы отправить — добавьте --залить")


if __name__ == "__main__":
    главное()
