#!/usr/bin/env python3
"""Забирает смену из приложения и вписывает её в отчёт.

Раньше это делалось руками в четыре шага: администратор жал «Выгрузить смену
для отчёта», файл падал в загрузки его телефона, оттуда его надо было принести
на компьютер владельца и там запустить report_fill.py. Не сделал ни разу
никто — в отчёте за август на 11.08.2026 была заполнена одна ячейка.

Теперь смена берётся прямо у приложения по адресу /api/export/<день>.
Он отдаёт ровно тот же JSON, что и кнопка: и адрес, и кнопка зовут один
и тот же код, поэтому разойтись цифрам негде.

Запуск:
    python3 scripts/report_pull.py                 # вчерашняя смена
    python3 scripts/report_pull.py 2026-08-10      # конкретный день
    python3 scripts/report_pull.py --month 2026-08 # весь месяц по вчера

Ключ берётся из переменной CHAEVYE_EXPORT_KEY — её же кладут в `.env`
строкой  CHAEVYE_EXPORT_KEY=<то же значение, что EXPORT_KEY в панели Amvera>.

⚠️ Заполнение столбца перезаписывает то, что там было. Это нарочно: смену
можно перезабрать, если данные поправили задним числом.
"""

from __future__ import annotations

import argparse
import calendar
import json
import os
import subprocess
import sys
import urllib.error
import urllib.request
from datetime import date, timedelta
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from db import load_env  # noqa: E402

ROOT = Path(__file__).resolve().parent.parent
СКАЧАННЫЕ = ROOT / "data" / "выгрузки-смен"

БОЕВОЙ_АДРЕС = "https://chaevye-borzovavv.amvera.io"


def адрес() -> str:
    """Куда ходить за сменой. Можно подменить на время проверки."""
    return os.environ.get("CHAEVYE_APP_URL", БОЕВОЙ_АДРЕС).rstrip("/")


def забрать_неразнесённые(ключ: str) -> dict | None:
    """Сколько по QR пришло, но ещё не разнесено кассиром по официантам.

    ⚠️ Зачем отдельно. Пока поступление не разнесено, деньги не лежат ни у кого
    в записях смены — и в отчёт они не попадают ВОВСЕ. Ноль по QR выглядит
    одинаково в двух случаях: «сегодня по QR не платили» и «рассылка молчит
    десять суток». Второй случай в августе 2026 стоил 32 тыс. ₽, и заметили
    его глазами, а не отчётом.

    Не достучались — возвращаем None, а не ноль. Ноль означал бы «всё разнесено»
    и был бы прямой ложью: различать «не вышло» и «нечего» здесь обязательно.
    """
    запрос = urllib.request.Request(
        f"{адрес()}/api/qr-tips", headers={"X-Export-Key": ключ}
    )
    try:
        with urllib.request.urlopen(запрос, timeout=60) as ответ:
            данные = json.loads(ответ.read().decode("utf-8"))
    except Exception as e:  # noqa: BLE001 — причина печатается, работа продолжается
        print(f"⚠️  Не удалось спросить про неразнесённые чаевые: {e}")
        return None
    ожидают = данные.get("неразнесённые")
    if not isinstance(ожидают, dict):
        # Старое приложение, ещё без этого поля. Молча подставить ноль нельзя.
        print("⚠️  Приложение не отдаёт неразнесённые чаевые — версия старее правки.")
        return None
    return ожидают


def забрать(день: str, ключ: str) -> dict:
    """Скачивает выгрузку одной смены.

    Ключ идёт заголовком, а не в адресе: адреса оседают в журналах сервера
    и в истории команд, и ключ утёк бы туда вместе с ними.
    """
    запрос = urllib.request.Request(
        f"{адрес()}/api/export/{день}",
        headers={"X-Export-Key": ключ},
    )
    try:
        with urllib.request.urlopen(запрос, timeout=60) as ответ:
            return json.loads(ответ.read().decode("utf-8"))
    except urllib.error.HTTPError as e:
        тело = e.read().decode("utf-8", "replace")
        try:
            причина = json.loads(тело).get("причина", тело)
        except json.JSONDecodeError:
            причина = тело[:200]
        if e.code == 401:
            sys.exit(
                "✗ Приложение не приняло ключ.\n"
                "  Значение CHAEVYE_EXPORT_KEY в `.env` должно совпадать\n"
                "  с EXPORT_KEY в панели Amvera, у приложения chaevye."
            )
        if e.code == 503:
            sys.exit(
                "✗ Выдача выключена на стороне приложения.\n"
                f"  Ответ: {причина}\n"
                "  Задайте EXPORT_KEY в панели Amvera и перезапустите приложение."
            )
        sys.exit(f"✗ Приложение ответило {e.code}: {причина}")
    except urllib.error.URLError as e:
        sys.exit(f"✗ Не достучаться до приложения: {e.reason}")


def собрать_отчёт(месяц: str) -> bool:
    """Пересобирает отчёт за месяц из скачанных выгрузок.

    Отдельным запуском, а не импортом: сборщик ходит в кассы Quick Resto
    за выручкой, и держать это внутри забиральщика значило бы, что молчащая
    касса роняет и скачивание смен.

    Собираем ЦЕЛИКОМ, а не дописываем день: с 11.08.2026 блок в отчёте —
    это человек, и состав его строк зависит от того, чем он занимался.
    Дописать такое в готовый лист нельзя, у нового сотрудника блока
    ещё нет вовсе.
    """
    готово = subprocess.run(
        [sys.executable, str(Path(__file__).parent / "report_build.py"), месяц],
        cwd=ROOT,
    )
    return готово.returncode == 0


def дни_месяца(месяц: str, по: date) -> list[str]:
    год, мес = (int(x) for x in месяц.split("-"))
    последний = calendar.monthrange(год, мес)[1]
    все = [date(год, мес, д) for д in range(1, последний + 1)]
    return [d.isoformat() for d in все if d <= по]



def обновить_ук(месяц: str) -> None:
    """Кладёт месяц в таблицу управляющей компании.

    ⚠️ ЧУЖОЙ ДОКУМЕНТ. Пишем только в свой лист «— из приложения», их
    заполненный руками не трогаем — правила целиком в scripts/uk_push.py.

    Сбой здесь НЕ роняет пересборку отчёта: наш отчёт уже собран, и валить
    его из-за чужой таблицы нельзя. Говорим вслух и идём дальше — молчащая
    ошибка в чужом документе обнаружится через месяц на сверке.
    """
    команда = [
        sys.executable,
        str(Path(__file__).resolve().parent / "uk_push.py"),
        месяц,
        "--записать",
        # Лист уже есть — пишем поверх. Без этого ключа скрипт откажется,
        # и ежедневное обновление вставало бы на второй же день.
        "--поверх",
        # Месяц мог только начаться, а лист у УК ещё не заведён.
        "--новый-месяц",
    ]
    print("\n── Таблица управляющей компании ──")
    итог = subprocess.run(команда, capture_output=True, text=True)
    # Из вывода берём итоги и тревоги: полный список людей уже напечатан
    # выше, в отчёте, и повторять его здесь незачем.
    #
    # ⚠️ Отступ в шесть пробелов — это подробности блока «деньги без имени»:
    # день, роль и сумма. Без них остаётся голое «деньги без имени», по
    # которому нельзя ни понять размер беды, ни начать разбираться. Первый
    # прогон 20.08.2026 их и потерял.
    хвост = [
        с
        for с in итог.stdout.splitlines()
        if с.startswith(("✓", "⚠", "Всего людям", "      "))
    ]
    for строка in хвост:
        print(f"  {строка}")
    if итог.returncode != 0:
        print("  ✗ Лист УК обновить не удалось:")
        for строка in (итог.stderr or итог.stdout).strip().splitlines()[-3:]:
            print(f"    {строка}")


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("день", nargs="?", help="день смены, например 2026-08-10")
    ap.add_argument(
        "--month",
        nargs="?",
        const="",
        help="весь месяц: --month 2026-08. Без значения — месяц вчерашнего дня",
    )
    ap.add_argument(
        "--без-ук",
        action="store_true",
        help="не трогать таблицу управляющей компании (по умолчанию обновляем)",
    )
    args = ap.parse_args()

    load_env()
    ключ = os.environ.get("CHAEVYE_EXPORT_KEY")
    if not ключ:
        sys.exit(
            "✗ Не задан CHAEVYE_EXPORT_KEY.\n"
            "  Добавьте в файл `.env` строку:\n"
            "     CHAEVYE_EXPORT_KEY=<то же значение, что EXPORT_KEY в Amvera>"
        )

    вчера = date.today() - timedelta(days=1)
    # Отдельным признаком, а не проверкой самой строки: у «--month» без
    # значения строка пустая, и обычное «если задан» на ней не срабатывает.
    месяцем = args.month is not None
    if месяцем:
        # Месяц берём по ВЧЕРАШНЕМУ дню, а не по сегодняшнему: первого числа
        # забирать надо ещё прошлый месяц, там лежит последняя смена.
        дни = дни_месяца(args.month or вчера.strftime("%Y-%m"), вчера)
    elif args.день:
        дни = [args.день]
    else:
        дни = [вчера.isoformat()]

    СКАЧАННЫЕ.mkdir(parents=True, exist_ok=True)

    записано = 0
    пустых = 0
    for день in дни:
        данные = забрать(день, ключ)

        # Смены без единого официанта пропускаем молча только в режиме месяца:
        # заведение работает не каждый день, и десяток «пусто» подряд в выводе
        # мешал бы увидеть настоящую беду.
        if not данные.get("waiters"):
            пустых += 1
            if not месяцем:
                print(f"· {день}: смена пустая, в отчёт вписывать нечего")
            continue

        путь = СКАЧАННЫЕ / f"смена-{день}.json"
        путь.write_text(
            json.dumps(данные, ensure_ascii=False, indent=2), encoding="utf-8"
        )
        записано += 1
        if not месяцем:
            print(f"· {день}: смена скачана")

    # Неразнесённое спрашиваем один раз, отдельно от смен: оно живёт не в смене,
    # а в общей очереди, и к конкретному дню скачивания отношения не имеет.
    ожидают = забрать_неразнесённые(ключ)
    путь = СКАЧАННЫЕ / "qr-неразнесённые.json"
    if ожидают is None:
        # Прежний файл убираем: устаревшее число хуже отсутствующего — оно
        # выглядит свежим и ему верят.
        путь.unlink(missing_ok=True)
    else:
        путь.write_text(
            json.dumps(ожидают, ensure_ascii=False, indent=2), encoding="utf-8"
        )
        if ожидают.get("всего"):
            print(
                f"⚠️  По QR не разнесено: {ожидают['всего']:,.2f} ₽"
                f" ({ожидают.get('сколько', 0)} поступлений)".replace(",", " ")
            )

    # Отчёт собираем ОДИН раз в конце, а не после каждой смены: сборка
    # перестраивает лист целиком и ходит в кассы за выручкой. Делать это
    # тридцать раз подряд значило бы тридцать раз опросить обе кассы.
    месяц = (дни[0][:7] if дни else вчера.strftime("%Y-%m"))
    if записано and not собрать_отчёт(месяц):
        print("✗ Смены скачаны, но собрать отчёт не удалось", file=sys.stderr)
        sys.exit(1)

    # Третий шаг: сверка с бумажными листами смен.
    #
    # Заведена 19.08.2026 по решению владельца. Причина: за 5, 13 и 16 августа
    # приложение недосчитало 13 116 ₽, и увидеть это по экрану было нельзя
    # в принципе. Не внесённая запись — не «пустая строка», а отсутствие
    # строки: выглядит как тихий вечер. Второй источник тут единственный
    # способ, и он у нас есть — бумажные листы, которые владелец фотографирует.
    #
    # ⚠️ Печатаем ПОСЛЕ сборки отчёта и отдельным блоком: строки обращены
    # к владельцу, а не к утренней задаче. Задача их пересказывает, и всё.
    from tips_paper import печать_сверки
    print()
    печать_сверки()

    # Четвёртый шаг: тот же месяц — в таблицу управляющей компании.
    #
    # Решение владельца 20.08.2026: «обновляем наш файл — автоматом должен
    # обновляться и лист УК». До этого лист заливали руками, и он отстал
    # на сутки, чего никто не заметил: он выглядит заполненным всегда,
    # а на сколько дней он отстал — по нему не видно.
    #
    # ⚠️ Здесь, а не в утренней задаче, намеренно. Отчёт пересобирают
    # и днём — после каждой правки в бэк-офисе, — и правило «наш файл
    # обновился, значит и лист УК» должно держаться само, а не памятью
    # человека о второй команде.
    if записано and not args.без_ук:
        обновить_ук(месяц)

    if месяцем:
        print(f"\nГотово. Смен записано: {записано}, пустых дней: {пустых}")


if __name__ == "__main__":
    main()
