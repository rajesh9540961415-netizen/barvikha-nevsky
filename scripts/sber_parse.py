"""Разбор уведомлений «СберЧаевые PRO» из Telegram.

Уведомления приходят в группу «СберЧаевые Невский». По словам владельца
(03.08.2026) туда попадают **только** поступления по персональному QR —
чаевые с терминала в этот чат не пишутся. Значит отбирать по типу не нужно:
каждое сообщение «Получены чаевые» — это QR.

Формат сообщения:

    Получены чаевые
    Чаевые: 460.00 р.
    Команда: Официант 1

Между суммой и командой могут стоять необязательные строки — оценка,
отметки и текстовый отзыв:

    Получены чаевые
    Чаевые: 200.00 р.
    Оценка: ⭐⭐⭐⭐⭐
    Отметили: Сервис; Скорость; Вежливость; Рекомендую
    Отзыв: Секси
    Команда: Официант 5

Из сообщения берём только сумму и команду. Отзыв гостя и оценку не
сохраняем: это чужие слова о конкретном человеке, а для учёта денег
они не нужны.
"""

from __future__ import annotations

import re
from dataclasses import dataclass

# «Чаевые: 1 460.00 р.» — пробелы внутри числа бывают разделителем тысяч,
# запятая и точка равноправны как десятичный знак.
AMOUNT = re.compile(r"Чаевые:\s*([\d\s ]+(?:[.,]\d{1,2})?)\s*р", re.IGNORECASE)
TEAM = re.compile(r"Команда:\s*(.+)", re.IGNORECASE)
HEADER = "получены чаевые"


@dataclass(frozen=True)
class TipNotice:
    """Поступление по QR: сколько и в какой котёл."""

    amount: float
    team: str


def parse(text: str) -> TipNotice | None:
    """Разбирает одно сообщение. Возвращает None, если это не про чаевые.

    Молчаливый отказ намеренный: в группе 12 участников, там пишут и люди,
    и любое чужое сообщение не должно ронять чтение.
    """
    if not text or HEADER not in text.lower():
        return None

    amount_match = AMOUNT.search(text)
    team_match = TEAM.search(text)
    if not amount_match or not team_match:
        return None

    raw = amount_match.group(1)
    raw = raw.replace(" ", "").replace(" ", "").replace(",", ".")
    try:
        amount = float(raw)
    except ValueError:
        return None
    if amount <= 0:
        return None

    return TipNotice(amount=amount, team=team_match.group(1).strip())


if __name__ == "__main__":
    # Проверка на настоящих сообщениях со скриншота от 03.08.2026.
    samples: list[tuple[str, TipNotice | None]] = [
        (
            "Получены чаевые\nЧаевые: 460.00 р.\nКоманда: Официант 1",
            TipNotice(460.0, "Официант 1"),
        ),
        (
            "Получены чаевые\nЧаевые: 300.00 р.\nКоманда: Официант 5",
            TipNotice(300.0, "Официант 5"),
        ),
        (
            "Получены чаевые\nЧаевые: 200.00 р.\nОценка: ⭐⭐⭐⭐⭐\n"
            "Отметили: Сервис; Скорость; Вежливость; Рекомендую\n"
            "Отзыв: Секси\nКоманда: Официант 5",
            TipNotice(200.0, "Официант 5"),
        ),
        (
            "Получены чаевые\nЧаевые: 400.00 р.\nКоманда: Официант 5",
            TipNotice(400.0, "Официант 5"),
        ),
        # Тысячи с разделителем и запятой вместо точки.
        (
            "Получены чаевые\nЧаевые: 1 250,50 р.\nКоманда: Хостес",
            TipNotice(1250.5, "Хостес"),
        ),
        # Чужие сообщения в группе игнорируются.
        ("Привет, кто сегодня на смене?", None),
        ("Получены чаевые\nбез суммы\nКоманда: Официант 1", None),
    ]

    ok = 0
    for text, expected in samples:
        got = parse(text)
        mark = "✓" if got == expected else "✗"
        if got == expected:
            ok += 1
        first = text.splitlines()[0][:40]
        print(f"  {mark} «{first}…» → {got}")

    print(f"\n{ok} из {len(samples)} разобрано верно")
