import json
from pathlib import Path

# -*- coding: utf-8 -*-
"""Свод бумажных «Таблиц чаевых» за июнь–сентябрь 2026.

По каждому дню: наличные, сервисный сбор, QR, безнал, «ВСЕГО» с листа.
Контроль — нал + сбор + qr + безнал должно равняться ВСЕГО. Расхождения печатаем.
Кальянный бар не берём: отдельный контур.
"""
# ─────────────────────────────────────────────────────────────────────────
# Числа листов лежат в data/листы-бумага.json, а НЕ здесь.
#
# Вынесены туда 07.09.2026. Пока они жили внутри программы, дописать новый
# день значило «править код», а утренней задаче правка кода запрещена —
# и запрещена не зря: 14.08.2026 она полезла чинить код и встала на шесть
# часов. Из-за этого сверка за вчера молчала каждое утро: лист приезжал,
# прочитать его было некому, и «сравнивать не с чем» повторялось изо дня
# в день.
#
# Теперь задача дописывает ОДИН файл с числами, к коду доступа у неё нет.
# Формат записи:
#     "2026-09-06": {"нал": 6600, "сбор": 6741, "qr": 1050,
#                    "безнал": 18436, "всего": 32828,
#                    "примечание": "1 ₽ у Насти С"}
# «всего» — то, что написано на листе, а не пересчитанное. Расходится
# с суммой столбцов — так и оставляем: это ошибка сложения на бумаге,
# и контроль ниже её показывает. Примечание необязательно.
# ─────────────────────────────────────────────────────────────────────────

ЛИСТЫ = Path(__file__).resolve().parent.parent / "data" / "листы-бумага.json"
ПОЛЯ = ("нал", "сбор", "qr", "безнал", "всего")


def читать_листы(путь: Path = ЛИСТЫ) -> dict[str, tuple[int, int, int, int, int]]:
    """День → (нал, сбор, qr, безнал, всего_с_листа).

    Файла нет — свод пуст, и это не поломка: значит листы ещё не вносили.
    А вот запись без нужного поля — поломка, и молчать о ней нельзя:
    день молча выпал бы из сверки, а пустая сверка выглядит как «сошлось».
    """
    if not путь.exists():
        return {}
    сырое = json.loads(путь.read_text(encoding="utf-8"))
    свод: dict[str, tuple[int, int, int, int, int]] = {}
    for день, з in сырое.items():
        нет = [к for к in ПОЛЯ if к not in з]
        if нет:
            raise ValueError(
                f"{путь.name}, день {день}: не хватает полей {', '.join(нет)}")
        свод[день] = tuple(з[к] for к in ПОЛЯ)  # type: ignore[assignment]
    return dict(sorted(свод.items()))


def примечания(путь: Path = ЛИСТЫ) -> dict[str, str]:
    """День → пометка с листа, если она есть."""
    if not путь.exists():
        return {}
    сырое = json.loads(путь.read_text(encoding="utf-8"))
    return {д: з["примечание"] for д, з in сырое.items() if з.get("примечание")}


D = читать_листы()


def f(x):
    return f"{x:,.0f}".replace(",", " ")


# ─────────────────────────────────────────────────────────────────────────
# Сверка бумаги с приложением — второй источник для каждой суммы
#
# Заведена 19.08.2026, когда выяснилось, чего эта сверка стоит: за 5, 13
# и 16 августа приложение недосчитало 13 116 ₽, и ни один экран об этом
# не сказал. Причина всегда одна — человека не внесли в смену.
#
# ⚠️ Почему в отчёте этого не видно и не будет видно без бумаги. Строка
# «По QR не разнесено» ловит только QR: про него приложению сообщает Сбер
# через варшавского робота, то есть со стороны. У наличных и терминала
# такого канала нет — деньги попадают в приложение только когда их вбил
# кассир. Не вбил — записи НЕТ ВОВСЕ, и пустая клетка выглядит ровно так
# же, как тихий вечер. Пустота с законной причиной перестаёт быть сигналом.
# ─────────────────────────────────────────────────────────────────────────

ВЫГРУЗКИ = Path(__file__).resolve().parent.parent / "data" / "выгрузки-смен"

# Порог молчания. Копейки округления и мелкая руква кассира — не повод
# кричать; всё, что крупнее, стоит посмотреть глазами.
ПОРОГ_РУБЛЕЙ = 100


def сверка_с_приложением(выгрузки: Path = ВЫГРУЗКИ) -> list[dict]:
    """Дни, где бумага и приложение разошлись. Пусто — значит сошлось."""
    расхождения = []
    for день, (нал, сбор, qr, безнал, всего) in sorted(D.items()):
        файл = выгрузки / f"смена-{день}.json"
        if not файл.exists():
            continue
        итоги = json.loads(файл.read_text(encoding="utf-8")).get("totals") or {}
        разница = round(итоги.get("earned", 0) - всего, 2)
        if abs(разница) < ПОРОГ_РУБЛЕЙ:
            continue
        расхождения.append({
            "день": день,
            "бумага": всего,
            "приложение": итоги.get("earned", 0),
            "разница": разница,
            "нал": round(итоги.get("cash", 0) - нал, 2),
            "безнал": round(итоги.get("terminal", 0) - безнал, 2),
            "qr": round(итоги.get("qr", 0) - qr, 2),
            "сбор": round(итоги.get("service", 0) - сбор, 2),
        })
    return расхождения


def печать_сверки(выгрузки: Path = ВЫГРУЗКИ) -> None:
    """Печатает блок для утреннего отчёта. Читает его человек, не задача."""
    дни = сверка_с_приложением(выгрузки)
    if not дни:
        print("Бумага и приложение: сходятся по всем дням, где есть лист.")
        return
    недостаёт = sum(-d["разница"] for d in дни if d["разница"] < 0)
    print(f"⚠️  БУМАГА И ПРИЛОЖЕНИЕ РАЗОШЛИСЬ — дней {len(дни)}:")
    for d in дни:
        знак = "приложение меньше" if d["разница"] < 0 else "приложение больше"
        print(f"    {d['день']}  лист {d['бумага']:>9,.0f}   приложение "
              f"{d['приложение']:>10,.2f}   {знак} на {abs(d['разница']):>9,.2f} ₽"
              .replace(",", " "))
    if недостаёт > 0:
        print(f"    Всего приложение недосчитывает {недостаёт:,.2f} ₽."
              .replace(",", " "))
    print("    Чаще всего причина одна: человека не внесли в состав смены.")


if __name__ == "__main__":
    # Сверку печатаем ПЕРВОЙ и всегда: ради неё эту программу и зовут утром.
    # Контроль и разрезы по периодам — справка, их читают редко.
    print("=== БУМАГА И ПРИЛОЖЕНИЕ ===")
    печать_сверки()
    print()

    print("=== КОНТРОЛЬ ===")
    bad = 0
    for d, (c, s, q, b, t) in sorted(D.items()):
        if c + s + q + b != t:
            bad += 1
            print(f"  ⚠ {d}: посчитано {c+s+q+b}, на листе {t} ({c+s+q+b-t:+})")
    print(f"  листов: {len(D)}, расхождений: {bad}")

    PERIODS = [
        ("ИЮНЬ, терминала нет", "2026-06-01", "2026-06-30"),
        ("ИЮЛЬ до терминала (1–19)", "2026-07-01", "2026-07-19"),
        ("ИЮЛЬ после (20–31)", "2026-07-20", "2026-07-31"),
        ("АВГУСТ (1–17)", "2026-08-01", "2026-08-17"),
        ("АВГУСТ (18–31)", "2026-08-18", "2026-08-31"),
        ("СЕНТЯБРЬ (1–6)", "2026-09-01", "2026-09-06"),
    ]

    print()
    print(f"{'период':28}{'дней':>6}{'чаевые/день':>14}{'наличные':>12}{'безнал':>12}"
          f"{'сбор/день':>12}{'доля нала':>11}")
    res = {}
    for name, lo, hi in PERIODS:
        days = [d for d in D if lo <= d <= hi]
        n = len(days)
        cash = sum(D[d][0] for d in days)
        svc = sum(D[d][1] for d in days)
        card = sum(D[d][2] + D[d][3] for d in days)
        tips = cash + card                      # чистые чаевые: сбор исключён
        res[name] = dict(n=n, cash=cash / n, card=card / n, tips=tips / n, svc=svc / n)
        print(f"{name:28}{n:6}{f(tips/n):>14}{f(cash/n):>12}{f(card/n):>12}"
              f"{f(svc/n):>12}{cash/tips*100:10.1f} %")

    print()
    print("=== ЭФФЕКТ ТЕРМИНАЛА НА ЧИСТЫХ ЧАЕВЫХ (сбор исключён) ===")
    base_jul = res["ИЮЛЬ до терминала (1–19)"]["tips"]
    base_jun = res["ИЮНЬ, терминала нет"]["tips"]
    for name in ["ИЮЛЬ после (20–31)", "АВГУСТ (1–17)"]:
        t = res[name]["tips"]
        print(f"  {name:22} {f(t):>9} ₽/день   к июлю-до {t/base_jul*100-100:+6.0f} %"
              f"   к июню {t/base_jun*100-100:+6.0f} %")

    print()
    print("=== ЧТО СЛУЧИЛОСЬ С НАЛИЧНЫМИ ===")
    for name in [p[0] for p in PERIODS]:
        r = res[name]
        print(f"  {name:28} наличных {f(r['cash']):>8} ₽/день   безнал {f(r['card']):>8} ₽/день")

    print()
    print("=== СЕРВИСНЫЙ СБОР: сколько его вычли из прежних цифр ===")
    for name in [p[0] for p in PERIODS]:
        r = res[name]
        print(f"  {name:28} сбор {f(r['svc']):>7} ₽/день = {r['svc']/(r['tips']+r['svc'])*100:4.1f} % от «ВСЕГО»")

    print()
    печать_сверки()
