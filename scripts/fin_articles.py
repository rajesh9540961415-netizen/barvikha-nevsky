# Поставщики, которые возят и алкоголь, и воду. Статью здесь берём ТОЛЬКО из скобок:
# справочник по названию тут врёт — он знает поставщика, но не знает, что именно привезли.
# Владелец подтвердил 08.08.2026: пометка есть в назначении платежа.
MIXED = ("симпл", "аст")
# Если у смешанного поставщика пометки нет — это алкоголь. Решение владельца 08.08.2026.
MIXED_DEFAULT = "Алкоголь"

# Контрагенты, у которых название слишком короткое для справочника («ФМ», «ТД СПБ»)
# или которых нет в исторической разметке. Статью назвал владелец 08.08.2026.
BY_NAME = {
    "сергеев павел": "Прочие закупки на бар",
    "тд спб": "Прочие закупки на бар",
    "\"фм\"": "ПО/Услуги",
}
STOP = {"ооо", "ип", "ао", "зао", "пао", "оао", "компания", "россии",
        "банк", "москва", "спб"}
CARD = re.compile(r"PURCHASE|по карте MIR", re.I)


def tokens(name):
    s = name.lower().replace("ё", "е")
    s = re.sub(r"\([^)]*\)", " ", s)
    s = re.sub(r"[^а-яa-z0-9 ]", " ", s)
    return [t for t in s.split() if len(t) > 2 and t not in STOP]


def build_dictionary():
    """Ключевое слово контрагента → статья, по историческому ДДС."""
    agg = defaultdict(Counter)
    for r in csv.DictReader((DATA / "transactions.csv").open(encoding="utf-8")):
        if not r["counterparty"] or not r["category"]:
            continue
        ts = tokens(r["counterparty"])
        if ts:
            agg[max(ts, key=len)][r["category"]] += 1
    d = {k: v.most_common(1)[0][0] for k, v in agg.items() if len(k) > 3}
    for a, b in (("коффи", "кофи"),):          # один поставщик, две записи имени
        if b in d: d.setdefault(a, d[b])
    return d


def brackets(purpose):
    """Подсказки в скобках, кроме шума про НДС и номера документов."""
    out = []
    for h in re.findall(r"\(([^()]{2,40})\)", purpose):
        h = h.strip().lower().replace("ё", "е")
        if re.search(r"ндс|^\d[\d\s.,]*$|кредитн|банк россии|депозит", h):
            continue
        out.append(h)
    return out


def article(row, keydict):
    """Возвращает (статья, откуда взята). Статья None — не опознано."""
    p = row["purpose"]
    why = row.get("why", "")

    # 0. «Завершение расчетов с ТСТ по операциям Возврат покупки» — банк забирает
    # деньги, которые гость вернул по карте. В расход это НЕ идёт: выручка из кассы
    # приходит уже за вычетом возвратов (qr_sales.py: card = totalCard −
    # totalReturnCard). Учли бы здесь — посчитали бы одну и ту же сумму дважды.
    # Проверка должна стоять ПЕРЕД правилом о комиссиях банка: платёж идёт в пользу
    # банка, и то правило перехватило бы его раньше.
    if "с ТСТ" in p or "возврат покупки" in p.lower():
        return None, "возврат гостю — уже вычтен из выручки, в расход не идёт"

    # 1. Особые правила: статья следует из природы платежа
    if why == "налоги":
        return "Налоги/Страхования", "правило: налоговый платёж"
    if why == "зарплата":
        return "Зарплата/аванс/мотивация", "правило: зарплатный реестр"
    if CARD.search(p):
        u = p.upper()
        if "YANDEX*4121" in u or "YANDEX*4215" in u:
            return "Такси", "правило: такси по карте"
        # Остальные покупки по карте — маркетплейсы (Wildberries, ОЗОН, Яндекс Маркет)
        # и мелочь. Владелец подтвердил 10.08.2026: это «Прочие расходы», потому что
        # закупки там делятся между баром и административными нуждами, и разнести их
        # по одной статье нельзя. Правило нужно явно — иначе справочник цепляется за
        # слово «Сбербанк» в названии контрагента и ставит что попало.
        return "Прочие расходы", "правило: покупка по карте, кроме такси"
    if row.get("inn") == "7707083893" and not CARD.search(p):
        low = p.lower()
        if "заработная плата" not in low and "расчет при увольнении" not in low:
            return "Комиссия", "правило: комиссия банка"

    low = p.lower()
    if "взносы на обязательное страхование" in low:
        return "Налоги/Страхования", "правило: страховые взносы"

    # 2. Подсказка в скобках
    for h in brackets(p):
        if h in BRACKET:
            return BRACKET[h], f"скобки: ({h})"

    # 3. Справочник по историческому ДДС.
    # Для смешанных поставщиков справочник не спрашиваем: без скобок непонятно,
    # алкоголь это или вода, а угадывать нельзя.
    name = row["counterparty"].lower().replace("ё", "е")
    if any(m in name for m in MIXED):
        return MIXED_DEFAULT, "смешанный поставщик без пометки — по умолчанию алкоголь"
    for frag, art in BY_NAME.items():
        if frag in name:
            return art, f"по названию: {frag}"
    for t in tokens(row["counterparty"]):
        if t in keydict:
            return keydict[t], f"справочник: {t}"
    return None, ""


