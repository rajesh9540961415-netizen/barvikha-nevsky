def cash_articles(month):
    a = defaultdict(float)
    f = DATA / "cash_expenses.csv"
    if not f.exists():
        return a, []
    unknown = []
    for r in csv.DictReader(f.open(encoding="utf-8")):
        if r["date"][:7] != month:
            continue
        amt = float(r["amount"])
        detail = CASH_DETAIL.get((r["date"], r["column"]))
        if detail:
            if abs(sum(v for _, v in detail) - amt) > 0.01:
                unknown.append((amt, f"{r['column']} {r['date']}: расшифровка не сходится", "наличные"))
                continue
            for art, v in detail:
                a[art] += v
            continue
        art = CASH_MAP.get(r["column"])
        if art:
            a[art] += amt
        else:
            unknown.append((amt, r["column"], "наличные"))
    return a, unknown


def acquiring(month):
    """Эквайринг банк удерживает из зачисления — отдельным платежом он не приходит,
    поэтому в расходах его нет и статью «Комиссия» надо пополнить отдельно."""
    t = 0.0
    for r in csv.DictReader((DATA / "bank_transactions.csv").open(encoding="utf-8")):
        if r["date"][:7] != month or r["direction"] != "in": continue
        if "эквайринг" not in r["purpose"].lower(): continue
        for m in re.finditer(r"Комиссия\s+([\d\s\u00a0]+[.,]\d+|[\d\s\u00a0]+)", r["purpose"]):
            t += float(m.group(1).replace(" ", "").replace("\u00a0", "").replace(",", "."))
    return t


def main():
    months = sys.argv[1:] or ["2026-04", "2026-05", "2026-06"]
    keydict = build_dictionary()
    rows = list(csv.DictReader((DATA / "bank_classified.csv").open(encoding="utf-8")))
    M = lambda v: f"{v:,.2f}".replace(",", " ")

    for month in months:
        agg = defaultdict(float)
        src = Counter()
        unknown = []
        for r in rows:
            if (r["date"][:7] != month or r["direction"] != "out"
                    or r["class"] != "external"):
                continue
            art, how = article(r, keydict)
            amount = float(r["amount"])
            if art:
                agg[art] += amount
                src[how.split(":")[0]] += 1
            else:
                unknown.append((amount, r["counterparty"], r["purpose"][:60]))

        # Возврат покупки по карте — не расход. Уменьшаем ту же статью, иначе
        # расходы завышены: за 2026 год возвратов набралось около 15 тыс. ₽.
        for r in rows:
            if (r["date"][:7] != month or r["direction"] != "in"
                    or not CARD.search(r["purpose"])): continue
            a, _ = article(r, keydict)
            if a: agg[a] -= float(r["amount"])

        ca, cu = cash_articles(month)
        for k, v in ca.items():
            agg[k] += v
        unknown += cu
        agg["Комиссия"] += acquiring(month)

        print(f"\n{'═' * 66}\n  СТАТЬИ РАСХОДОВ — {month}   (банк + наличные + эквайринг)\n{'═' * 66}")
        for a in ARTICLES:
            print(f"   {a:<28} {M(agg.get(a, 0)):>18}")
        print(f"   {'─' * 46}")
        for a in EXTRA:
            print(f"   {a:<28} {M(agg.get(a, 0)):>18}   ← в апрельской сводке такой строки нет")
        total = sum(agg.values())
        print(f"   {'РАЗМЕЧЕНО ВСЕГО':<28} {M(total):>18}")

        if unknown:
            s = sum(a for a, _, _ in unknown)
            print(f"\n   ⚠️  НЕ ОПОЗНАНО: {len(unknown)} оп. на {M(s)} — статья не проставлена")
            for a, c, p in sorted(unknown, key=lambda x: -x[0])[:10]:
                print(f"      {M(a):>14}  {c[:34]:<34} {p[:44]}")
        else:
            print("\n   ✅ не опознанных операций нет")
        print(f"\n   откуда брались статьи: " +
              ", ".join(f"{k} — {v}" for k, v in src.most_common()))


