"""Разметка расходов по статьям «Фин. свода».

Статью не угадываем. Берём её из трёх источников, в порядке надёжности:

  1. Особые правила — налоги, зарплата, комиссии банка, такси по карте.
     Здесь статья следует из самой природы платежа, а не из названия.
  2. Подсказка в скобках внутри назначения платежа. Сотрудники при заведении
     платежа пишут категорию: «Счёт от 13.03.26 №06572 (табак)». Есть у 53%
     внешних платежей — самый прямой сигнал.
  3. Справочник «контрагент → статья», построенный по историческому ДДС:
     3 162 платежа с проставленными вручную статьями за май 2024 — апрель 2026.
     Сопоставление по ключевому слову, а не по полному имени: одного и того же
     поставщика пишут по-разному («ИП МОСКОВКИНА Е.В.» и «МОСКОВКИНА ЕКАТЕРИНА
     ВАЛЕРЬЕВНА»), и точное сравнение теряет две трети совпадений.

Что не опознано — остаётся БЕЗ статьи и попадает в отдельный список. Молча
сваливать такое в «Прочие расходы» нельзя: там утонет всё, чего мы не поняли.

Запуск:  python3 scripts/fin_articles.py [ГГГГ-ММ ...]
Читает:  data/dds/bank_classified.csv, data/dds/transactions.csv,
         data/dds/cash_expenses.csv
"""
