"""Где лежат отчёты по чаевым.

Одно место на два скрипта: `report_new.py` их создаёт, `report_fill.py`
находит и заполняет. Разъехаться эти два адреса не должны никогда — иначе
скрипт создаст отчёт в одной папке, а заполнять будет копию в другой,
и в конце месяца окажется два файла с разными цифрами.

Порядок поиска:

1. Переменная `CHAEVYE_REPORT_DIR`, если задана. Ручное управление на случай,
   когда папка нестандартная.
2. Папка Google Диска, если на компьютере стоит клиент «Google Drive для
   компьютера». Тогда отчёт сразу оказывается на Диске, без ручной возни.
3. Корень проекта — как было до 08.08.2026.

⚠️ Если адрес задан явно, а папки нет — останавливаемся с ошибкой, а не
пишем куда придётся. Молча уехавший в другое место отчёт — это разошедшиеся
цифры через месяц, и найти причину будет уже некому.
"""

# Аннотации не вычисляются на ходу: системному Python на этом Маке 3.9,
# а запись «Path | None» появилась только в 3.10.
from __future__ import annotations

import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Имя папки на Диске. Отдельная, а не рядом с рабочей таблицей «Чаевые Таблица
# учёта Невский»: перепутать выгрузку приложения с таблицей, которую ведут
# руками, — ошибка, которую никто не заметит до сверки.
DRIVE_FOLDER = "Чаевые — отчёты приложения"

# 🔴 Финансовые документы живут ОТДЕЛЬНО от отчётов по чаевым, и это решение
# 14.09.2026, принятое при подключении второго участника. В папке отчётов
# по чаевым лежат ежемесячные отчёты с фамилиями и заработком каждого;
# финансисту, который считает выручку, они не нужны, а открыть папку можно
# только целиком. Разделение папок — единственный способ отдать одно,
# не отдав другого.
FINANCE_FOLDER = "Финансы — Барвиха Невский"


def _google_drive_dir() -> Path | None:
    """Папка «Мой диск» клиента Google Диска, если он установлен И работает.

    Клиент монтирует диск в ~/Library/CloudStorage под именем вида
    GoogleDrive-почта@gmail.com. Название папки внутри зависит от языка
    системы, поэтому проверяем оба варианта.

    ⚠️ Проверять существование папки недостаточно. Диск монтируется через
    механизм macOS «file provider»: пока клиент не достроил подключение
    (не завершена настройка, не выдано разрешение системы), папка уже видна
    и `is_dir()` честно отвечает «да», а первая же настоящая операция
    падает с таймаутом. Поймано 08.08.2026 при подключении: `is_dir()`
    отвечал мгновенно, `mkdir` — «Operation timed out» через секунду.

    Поэтому мерилом считаем не существование папки, а удавшуюся запись.

    ⚠️ Точек подключения может быть НЕСКОЛЬКО, и мёртвая среди них — обычное
    дело. 11.08.2026 клиент на ходу переименовал свою папку из
    «GoogleDrive-почта@gmail.com» в «GoogleDrive-почта@gmail.com (11.08.2026
    10:14)» — просто потому, что владелец меняла настройки синхронизации.
    Прежний адрес перестал существовать в ту же секунду.

    Поэтому перебираем ВСЕ подходящие папки и берём первую, куда удалось
    записать. Раньше на первой же неудаче делался вывод «Диска нет» — и живая
    точка подключения, лежащая второй по списку, не проверялась вовсе.
    """
    base = Path.home() / "Library" / "CloudStorage"
    if not base.is_dir():
        return None

    беды: list[str] = []
    for mount in sorted(base.glob("GoogleDrive-*")):
        for name in ("Мой диск", "My Drive"):
            root = mount / name
            try:
                if not root.is_dir():
                    continue
                target = root / DRIVE_FOLDER
                target.mkdir(parents=True, exist_ok=True)
                # Диск может быть смонтирован «только на чтение», пока клиент
                # думает. Пробуем ровно то, что будем делать по-настоящему.
                probe = target / ".проверка-записи"
                probe.write_text("", encoding="utf-8")
                probe.unlink()
                return root
            except OSError as e:
                # Не сдаёмся: следующая точка подключения может быть живой.
                беды.append(f"{mount.name}: {e.strerror}")

    if беды:
        перечень = "\n".join(f"    {b}" for b in беды)
        print(
            "⚠ Google Диск подключён, но не отвечает:\n"
            f"{перечень}\n"
            "  Отчёт кладу в папку проекта. Проверьте значок Google Диска\n"
            "  в строке меню: чаще всего синхронизация стоит на паузе —\n"
            "  именно это было причиной 08–11.08.2026.",
            file=sys.stderr,
        )
    return None


def report_dir() -> Path:
    """Куда класть и где искать отчёты. Папку создаём, если её ещё нет."""
    manual = os.environ.get("CHAEVYE_REPORT_DIR")
    if manual:
        path = Path(manual).expanduser()
        if not path.is_dir():
            sys.exit(
                f"Папка из CHAEVYE_REPORT_DIR не найдена: {path}\n"
                "  Проверьте адрес или уберите переменную, чтобы вернуться "
                "к папке проекта."
            )
        return path

    drive = _google_drive_dir()
    if drive is not None:
        # Папку уже создала и проверила на запись сама _google_drive_dir().
        return drive / DRIVE_FOLDER

    return ROOT


def фин_dir() -> Path:
    """Куда класть финансовые документы: своды, P&L, разборы, возвраты.

    Та же логика, что у `report_dir`, и намеренно та же: один способ найти
    Диск на оба случая. Разъедутся способы — разъедутся и папки, а искать
    потом будут глазами.

    ⚠️ Переменная `CHAEVYE_FINANCE_DIR` перекрывает адрес — она понадобится
    на Windows, где клиент Диска монтируется буквой, а не папкой внутри дома.
    """
    manual = os.environ.get("CHAEVYE_FINANCE_DIR")
    if manual:
        path = Path(manual).expanduser()
        if not path.is_dir():
            sys.exit(
                f"Папка из CHAEVYE_FINANCE_DIR не найдена: {path}\n"
                "  Проверьте адрес или уберите переменную, чтобы вернуться "
                "к папке проекта."
            )
        return path

    drive = _google_drive_dir()
    if drive is not None:
        папка = drive / FINANCE_FOLDER
        папка.mkdir(exist_ok=True)
        return папка

    return ROOT


def describe(path: Path) -> str:
    """Куда именно легло — словами, для вывода в конце работы скрипта."""
    if "CloudStorage" in str(path):
        return f"{path}  (Google Диск — синхронизируется сам)"
    return str(path)
