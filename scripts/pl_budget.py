def тыс(v):
    """До целых тысяч. Решение владельца 26.08.2026: копейки и сотни в бюджете
    только мешают читать."""
    return int(round(v / 1000.0)) * 1000

ПРОЦЕНТ = '0,0%'


def перестроить(ws, б, заголовок):
    """Форма владельца плюс две строки (аренда VIP, сервисный сбор) и колонка «Факт».

    Колонки: D — план, E — факт, F — отклонение, G — доля в итоге, H — доля наличных.
    Факт заполняется руками по итогам месяца; отклонение и итоги считаются сами.
    """
    # Объединённые ячейки снимаем ДО вставки строк: после неё диапазоны
    # съезжают, и openpyxl уже не находит ячейку, которую надо разъединить.
    for rng in list(ws.merged_cells.ranges):
        ws.unmerge_cells(str(rng))
    ws.insert_rows(17, 3)     # выручка «Аренда VIP» с наличными и безналичными
    ws.insert_rows(33, 1)     # валовая прибыль по аренде
    ws.insert_rows(44, 1)     # сервисный сбор отдельной строкой в ФОТ

    ws["B4"] = "Локация:"; ws["C4"] = "Барвиха Лаунж Невский"
    ws["D6"] = заголовок
    for кол, имя in ((4, "План, ₽"), (5, "Факт, ₽"), (6, "Отклонение"),
                     (7, "Доля"), (8, "Доля нал.")):
        ws.cell(7, кол, имя).font = Font(bold=True)

    def пара(строка, формула_d, формула_e=None):
        """Одна и та же формула в план и в факт — колонки D и E живут одинаково."""
        ws.cell(строка, 4, формула_d)
        ws.cell(строка, 5, формула_e or формула_d.replace("D", "E"))

    план, себест, opex_ = б["план"], б["себест"], б["opex"]
    доход = [(8,  "Выручка Кухня",      план["кухня"],   нал_доля["кухня"]),
             (11, "Выручка Бар",        план["бар"],     нал_доля["бар"]),
             (14, "Выручка Кальяны",    план["кальяны"], нал_доля["кальяны"]),
             (17, "Выручка Аренда VIP", план["аренда"],  нал_доля["аренда"])]
    for строка, имя, сумма, доля in доход:
        # Наличные округляем сами, а безналичные считаем остатком: иначе две
        # округлённые половины перестанут складываться в округлённое целое.
        всего, налом = тыс(сумма), тыс(сумма * доля)
        ws.cell(строка, 2, имя); ws.cell(строка, 4, всего)
        ws.cell(строка + 1, 3, "Наличные");    ws.cell(строка + 1, 4, налом)
        ws.cell(строка + 2, 3, "Безналичные"); ws.cell(строка + 2, 4, всего - налом)
        for i in range(3):
            ws.cell(строка + i, 7, f"=D{строка+i}/D$20")

    ws["B20"] = "ИТОГО выручка"; пара(20, "=D8+D11+D14+D17")
    ws["C21"] = "Наличные";      пара(21, "=D9+D12+D15+D18")
    ws["C22"] = "Безналичные";   пара(22, "=D10+D13+D16+D19")
    for строка in (20, 21, 22):
        ws.cell(строка, 7, f"=D{строка}/D$20")

    ws["B23"] = "РАСХОДЫ"
    ws["B24"] = "Себестоимость (руб.)"
    for строка, имя, знач, ключ in ((25, "Кухня", себест["кухня"], "Кухня"),
                                    (26, "Бар", себест["бар"], "Бар"),
                                    (27, "Кальяны (табак, уголь и т.д.)", себест["кальяны"], "Кальяны")):
        ws.cell(строка, 3, имя); ws.cell(строка, 4, тыс(знач))
        ws.cell(строка, 7, f"=D{строка}/D$28")
        ws.cell(строка, 8, round(НАЛ_СТРОКИ[ключ], 4))
    ws["B28"] = "ИТОГО Себестоимость (руб.)"; пара(28, "=SUM(D25:D27)")
    ws["G28"] = "=D28/D$28"

    ws["B29"] = "Валовая прибыль (руб.)"
    for строка, имя, форм in ((30, "Кухня", "=D8-D25"), (31, "Бар", "=D11-D26"),
                              (32, "Кальяны", "=D14-D27"), (33, "Аренда VIP", "=D17")):
        ws.cell(строка, 3, имя); пара(строка, форм)
        ws.cell(строка, 7, f"=D{строка}/D$34")
    ws["B34"] = "ИТОГО Валовая прибыль (руб.)"; пара(34, "=SUM(D30:D33)")
    ws["G34"] = "=D34/D$34"

    ws["B35"] = "Валовая прибыль %"
    for строка, имя, форм in ((36, "Кухня", "=1-D25/D8"), (37, "Бар", "=1-D26/D11"),
                              (38, "Кальяны", "=1-D27/D14")):
        ws.cell(строка, 3, имя); пара(строка, форм)
        ws.cell(строка, 4).number_format = ПРОЦЕНТ
        ws.cell(строка, 5).number_format = ПРОЦЕНТ
    ws["B39"] = "ИТОГО Валовая прибыль % (маржа)"; пара(39, "=D34/D20")
    ws["D39"].number_format = ПРОЦЕНТ; ws["E39"].number_format = ПРОЦЕНТ

    ws["B40"] = "OPEX"
    for i, (имя, знач) in enumerate(opex_):
        строка = 41 + i
        ws.cell(строка, 3, имя.replace("в т.ч. ", ""))
        ws.cell(строка, 4, тыс(знач))
        ws.cell(строка, 7, f"=D{строка}/D$57")
        ws.cell(строка, 8, round(НАЛ_СТРОКИ[имя], 4))
    ws["B57"] = "ИТОГО OPEX"; пара(57, "=SUM(D41:D56)")
    ws["G57"] = "=D57/D$57"

    # Раскладка считается по колонке H — доле наличных, посчитанной по фактическим
    # платежам января–июля. Прежняя формула перечисляла строки: маркетинг стоял
    # в безналичных, хотя он весь наличный, а ФОТ целиком в наличных, хотя
    # наличными идёт 83 %.
    налом = ("=ROUND((SUMPRODUCT(D25:D27,H25:H27)"
             "+SUMPRODUCT(D41:D56,H41:H56))/1000,0)*1000")
    ws["B58"] = "Расходы р/с"; пара(58, "=D60-D59")
    ws["B59"] = "Расходы нал"; ws["D59"] = налом
    ws["E59"] = налом.replace("D25", "E25").replace("D27", "E27").replace("D41", "E41").replace("D56", "E56")
    ws["B60"] = "ИТОГО Расходы"; пара(60, "=D28+D57")
    ws["B61"] = "EBITDA";        пара(61, "=D20-D60")
    for строка in (58, 59, 60):
        ws.cell(строка, 7, f"=D{строка}/D$60")
    ws["G61"] = "=D61/D20"

    # Отклонение показываем только там, где факт уже заполнен.
    for строка in list(range(8, 23)) + list(range(25, 35)) + list(range(41, 62)):
        if ws.cell(строка, 4).value is not None and строка not in (36, 37, 38, 39):
            ws.cell(строка, 6, f'=IF(N(E{строка})=0,"",E{строка}-D{строка})')

    for строка in range(6, 62):
        for кол in (4, 5, 6):
            if ws.cell(строка, кол).number_format != ПРОЦЕНТ:
                ws.cell(строка, кол).number_format = ДЕНЬГИ
        ws.cell(строка, 7).number_format = ПРОЦЕНТ
        if ws.cell(строка, 8).value is not None:
            ws.cell(строка, 8).number_format = ПРОЦЕНТ
    for жирная in (20, 28, 34, 39, 57, 60, 61):
        for кол in range(2, 8):
            ws.cell(жирная, кол).font = Font(bold=True)
    for заголовок_ in (7, 23, 24, 29, 35, 40):
        ws.cell(заголовок_, 2).font = Font(bold=True)
    for кол, ширина in (("B", 28), ("C", 30), ("D", 15), ("E", 15),
                        ("F", 14), ("G", 9), ("H", 10)):
        ws.column_dimensions[кол].width = ширина


# Цифры в пояснениях не набиваются руками: иначе после пересборки текст будет
# врать про таблицу, лежащую рядом.
Ц = lambda v: f"{round(v):,.0f} ₽".replace(",", "\u00a0")
Д = lambda v: f"{v*100:.1f} %".replace(".", ",")
rост = lambda: f"{рост_год:.2f}".replace(".", ",")


