def лист_пояснений(wb):
    ws = wb.create_sheet("Как читать", 0)
    шапка = PatternFill("solid", fgColor="1F3864")
    раздел = PatternFill("solid", fgColor="D9E2F3")
    ws["A1"] = "Бюджет сентября 2026 — откуда взялась каждая цифра"
    ws["A1"].font = Font(bold=True, size=14)
    ws["A2"] = (f"Собран {datetime.now():%d.%m.%Y}. Файл пересобирается заново командой "
                "python3 scripts/pl_budget.py — руками его не правьте, правки затрутся.")
    ws["A2"].font = Font(italic=True, color="666666")
    for кол, имя in enumerate(["Строка бюджета", "Цифра", "Откуда взята", "Почему именно так"], 1):
        c = ws.cell(4, кол, имя)
        c.font = Font(bold=True, color="FFFFFF"); c.fill = шапка
    строка = 5
    for имя, цифра, откуда, почему in ПОЯСНЕНИЯ:
        if not цифра and not откуда:
            c = ws.cell(строка, 1, имя)
            c.font = Font(bold=True); c.fill = раздел
            for кол in range(2, 5):
                ws.cell(строка, кол).fill = раздел
        else:
            ws.cell(строка, 1, имя).font = Font(bold=True)
            ws.cell(строка, 2, цифра)
            ws.cell(строка, 3, откуда)
            ws.cell(строка, 4, почему)
        for кол in range(1, 5):
            ws.cell(строка, кол).alignment = Alignment(vertical="top", wrap_text=True)
        строка += 1
    for кол, ширина in (("A", 34), ("B", 16), ("C", 46), ("D", 78)):
        ws.column_dimensions[кол].width = ширина
    ws.freeze_panes = "A5"
    return ws


def main():
    if not ОБРАЗЕЦ.exists():
        sys.exit(f"Нет образца формы: {ОБРАЗЕЦ}")
    if ДИСК.exists():
        КОПИИ.mkdir(exist_ok=True)
        shutil.copy2(ДИСК, КОПИИ / f"{ДИСК.stem} (до пересборки {datetime.now():%Y-%m-%d}){ДИСК.suffix}")
    wb = openpyxl.load_workbook(ОБРАЗЕЦ)
    основа = wb[ЛИСТ]
    # Копии делаем ДО того, как трогать образец: copy_worksheet умеет копировать
    # только внутри одной книги, и копировать надо ещё пустую форму.
    листы = [основа] + [wb.copy_worksheet(основа) for _ in МЕСЯЦЫ[1:]]
    итоги = []
    for ws, (месяц, имя) in zip(листы, МЕСЯЦЫ):
        б = бюджет(месяц)
        перестроить(ws, б, имя)
        ws.title = имя
        c = sum(б["себест"].values()); o = sum(v for _, v in б["opex"])
        итоги.append((имя, б["выручка"], c, o, б["выручка"] - c - o))
    лист_пояснений(wb)
    wb.active = 1
    ДИСК.parent.mkdir(parents=True, exist_ok=True)
    wb.save(ДИСК)
    ЗАГРУЗКИ = Path.home() / "Downloads" / ДИСК.name
    shutil.copy2(ДИСК, ЗАГРУЗКИ)
    print(f"✓ {ДИСК}")
    print(f"✓ {ЗАГРУЗКИ}")
    M = lambda v: f"{v:,.0f}".replace(",", " ")
    for имя, в, c, o, e in итоги:
        print(f"  {имя:<16} выручка {M(в):>12}  себест {M(c):>10}  OPEX {M(o):>10}  "
              f"EBITDA {M(e):>11} ({e/в*100:.1f}%)")


if __name__ == "__main__":
    main()
