#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Короткое сообщение в группу Telegram «ЧАЕВЫЕ ОФ».

Просьба владельца 06.09.2026: каждое утро писать в группу — сошлись
бумажный лист смены и приложение или нет, и если нет, то у кого именно.
Группа та же, откуда приходят фотографии листов.

⚠️ **Текст сообщения складывает НЕ этот скрипт.** Лист рукописный, машина
его не разбирает: сверяет глазами утренняя задача и передаёт сюда готовую
строку. Скрипт только отправляет.

⚠️ **Сообщение уходит людям, отменить его нельзя.** Поэтому по умолчанию
скрипт лишь показывает текст; отправка — отдельным ключом `--отправить`.
Неудобство осознанное.

⚠️ **Сессия отдельная, «маковская».** Общий ключ делит с роботом на Amvera,
и Telegram рвёт тот, что работает с двух адресов сразу.

⚠️ **Поимённые суммы в группу не пишем.** Называем только того, у кого
расхождение, и сами суммы расхождения — сколько человек заработал,
соседу знать незачем.

Запуск:
    python3 scripts/tips_telegram.py --текст "Лист и приложение сошлись."
    python3 scripts/tips_telegram.py --текст "…" --отправить
    echo "…" | python3 scripts/tips_telegram.py --отправить
"""
from __future__ import annotations

import argparse
import asyncio
import sys
from datetime import datetime, timedelta
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
СЕССИЯ = ROOT / "scripts" / ".tg-mac-session"
ГРУППА = -4244984520  # «ЧАЕВЫЕ ОФ» — та же, откуда приходят фотографии листов
ПРЕДЕЛ = 900  # длиннее короткого сообщения быть не должно


def из_env(имя: str) -> str:
    for строка in (ROOT / ".env").read_text(encoding="utf-8").splitlines():
        if строка.startswith(f"{имя}="):
            return строка.split("=", 1)[1].strip().strip('"').strip("'")
    sys.exit(f"✗ В .env нет {имя}")


async def отправить(текст: str) -> None:
    try:
        from telethon import TelegramClient
    except ImportError:
        sys.exit("✗ Нет telethon: pip3 install telethon")
    if not Path(f"{СЕССИЯ}.session").exists():
        sys.exit(
            f"✗ Нет файла сессии {СЕССИЯ.name}.session.\n"
            "  Создать её должна владелец: python3 scripts/tg_login.py --мак"
        )
    клиент = TelegramClient(str(СЕССИЯ), int(из_env("TG_API_ID")), из_env("TG_API_HASH"))
    await клиент.start()
    await клиент.send_message(ГРУППА, текст)
    await клиент.disconnect()


# ─────────────────────────────────────────────────────────────────────────
# Вердикт складывает ПРОГРАММА, а не модель. Причин две.
#
# 1. Разрешение утренней задачи хранится текстом команды целиком. Команда
#    с текстом внутри («--текст "…"») каждый день новая и не совпадёт
#    с одобренной НИКОГДА — задача повиснет. Так каждое утро вставала
#    финансовая сводка 27–29.08.2026. Ключ `--вердикт` не меняется, значит
#    команда одна и та же изо дня в день.
# 2. Сообщение уходит людям и не отменяется. Пусть в группу идут четыре
#    заранее одобренные фразы, а не то, что модель сочинила этим утром.
#
# Владелец 07.09.2026: «мне не нравится отправлять руками, давай
# что-нибудь придумаем». Это и есть придуманное.
# ─────────────────────────────────────────────────────────────────────────

class НечегоСлать(Exception):
    """Случай, когда молчание правильнее сообщения."""


ОТПРАВЛЕНО = ROOT / "data" / ".вердикт-отправлен"
МЕСЯЦЫ = ("января", "февраля", "марта", "апреля", "мая", "июня", "июля",
          "августа", "сентября", "октября", "ноября", "декабря")


def по_русски(день: str) -> str:
    """2026-09-06 → «6 сентября»."""
    г, м, д = (int(ч) for ч in день.split("-"))
    return f"{д} {МЕСЯЦЫ[м - 1]}"


def сложить_вердикт(день: str) -> str:
    """Короткая фраза для группы. Складывается из данных, не из головы."""
    sys.path.insert(0, str(ROOT / "scripts"))
    from tips_paper import D, ВЫГРУЗКИ, ПОРОГ_РУБЛЕЙ, сверка_с_приложением

    когда = по_русски(день)
    if день not in D:
        # Развилка, которую нельзя путать: не приехала ФОТОГРАФИЯ — вина
        # смены, и просить надо их. Фотография есть, а в своде дня нет —
        # вина наша: утренняя задача её не прочитала или не вписала.
        # Свалить второе на смену значит отчитать людей за нашу поломку,
        # поэтому во втором случае в группу НЕ ПИШЕМ ВОВСЕ.
        фото = list((ROOT / "data" / "листы-смен").glob(f"лист-{день}*"))
        if фото:
            raise НечегоСлать(
                f"Фотография листа за {когда} на месте ({фото[0].name}), "
                "а в своде дня нет — значит его не вписали. Это наша недоделка, "
                "а не вина смены: в группу ничего не отправляю."
            )
        return (f"Лист за {когда} в группу не приехал — сверить не с чем. "
                "Пришлите, пожалуйста, фотографию таблицы.")
    if not (ВЫГРУЗКИ / f"смена-{день}.json").exists():
        return (f"Лист за {когда} получили. Выгрузка смены ещё не пришла, "
                "сверим позже.")
    расхождение = next((р for р in сверка_с_приложением() if р["день"] == день), None)
    if расхождение is None:
        return f"Лист за {когда} и приложение сошлись. Спасибо, смена."
    разница = abs(расхождение["разница"])
    куда = "в приложении больше" if расхождение["разница"] > 0 else "в приложении меньше"
    # Пробел между тысячами ставим ТОЛЬКО в числе. Замена по всей фразе
    # съедала запятую в «Посмотрим, кого не внесли» — проверено 07.09.2026.
    сумма = f"{разница:,.0f}".replace(",", " ")
    return (f"Лист за {когда} и приложение разошлись на {сумма} ₽ — {куда}. "
            "Посмотрим, кого не внесли в состав смены.")


def main() -> None:
    разбор = argparse.ArgumentParser(description="Короткое сообщение в «ЧАЕВЫЕ ОФ».")
    разбор.add_argument("--текст", help="что отправить; без него читается со входа")
    разбор.add_argument("--вердикт", action="store_true",
                        help="сложить вердикт за вчера самому, текст не нужен")
    разбор.add_argument("--отправить", action="store_true",
                        help="отправить (без ключа — только показать)")
    разбор.add_argument("--снова", action="store_true",
                        help="отправить вердикт за тот же день второй раз")
    аргументы = разбор.parse_args()

    if аргументы.вердикт:
        вчера = (datetime.now() - timedelta(days=1)).strftime("%Y-%m-%d")
        try:
            текст = сложить_вердикт(вчера)
        except НечегоСлать as почему:
            print(f"Молчу: {почему}")
            return
        # Второй запуск за то же утро не должен слать в группу второе
        # сообщение: отчёт пересобирают по нескольку раз в день нарочно,
        # и люди не должны это видеть.
        уже = ОТПРАВЛЕНО.read_text(encoding="utf-8").strip() if ОТПРАВЛЕНО.exists() else ""
        if аргументы.отправить and уже == вчера and not аргументы.снова:
            print(f"Вердикт за {по_русски(вчера)} уже отправлен сегодня — молчу.")
            print("Если всё-таки надо второй раз, добавьте --снова")
            return
    else:
        текст = (аргументы.текст or sys.stdin.read()).strip()
    if not текст:
        sys.exit("✗ Нечего отправлять: текст пустой")
    if len(текст) > ПРЕДЕЛ:
        sys.exit(
            f"✗ Сообщение длиннее {ПРЕДЕЛ} знаков ({len(текст)}).\n"
            "  В группу идёт короткий вердикт, а не отчёт: сошлось или нет,\n"
            "  и если нет — у кого. Подробности живут в отчёте на Диске."
        )

    print("─" * 46)
    print(текст)
    print("─" * 46)
    if not аргументы.отправить:
        print("\nЭто был показ. Чтобы отправить — добавьте --отправить")
        return
    asyncio.run(отправить(текст))
    if аргументы.вердикт:
        ОТПРАВЛЕНО.write_text(
            (datetime.now() - timedelta(days=1)).strftime("%Y-%m-%d"), encoding="utf-8")
    print("\n✓ Отправлено в группу «ЧАЕВЫЕ ОФ»")


if __name__ == "__main__":
    main()
