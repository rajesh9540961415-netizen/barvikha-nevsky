#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""Финансовая рамка банкета — одна страница для того, кто готовит предложение.

Задача владельца 14.09.2026: второй участник делает презентацию для банкетов,
и ему нужны цифры, которых он сам не найдёт.

🔴 **Цель банкетов — ДОГРУЗИТЬ слабые слоты, а не продавать пик.** Решение
владельца 14.09.2026. От этого зависит вся конструкция ценника: считаем
от упущенной выручки конкретного слота, а не от «сколько не жалко отдать».

💡 Главное, что показал разбор: **до 18:00 заведение зарабатывает 9,8 %
выручки**. Дневной банкет почти ничего не отнимает у обычной работы —
и потому может стоить втрое дешевле вечернего, оставаясь выгодным.

⚠️ В документ не идут ни фамилии, ни заработки: он уходит человеку,
которому положены только агрегаты.

Запуск:  python3 scripts/bankety_ramka.py
"""
from __future__ import annotations

import json
import sys
from collections import defaultdict
from datetime import datetime
from pathlib import Path

from docx import Document
from docx.enum.text import WD_ALIGN_PARAGRAPH
from docx.shared import Pt, RGBColor

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / "scripts"))
from report_path import фин_dir  # noqa: E402

НАЧАЛО, КОНЕЦ = "2026-06-01", "2026-08-31"
ЗАЛЫ = ["Малый", "Большой", "Невский"]
ИМЕНА = ["понедельник", "вторник", "среда", "четверг", "пятница", "суббота", "воскресенье"]
# Запас к упущенной выручке: банкет — это хлопоты, риск отмены и отказ
# от верхней половины разброса. 20 % — не расчёт, а осознанная надбавка.
ЗАПАС = 1.2


def зал(код) -> str:
    код = str(код)
    return "Большой" if код.startswith("Б") else "Невский" if код.startswith("Н") else "Малый"


def собрать():
    заказы = json.loads((ROOT / "data/qr/заказы-зал-2026.json").read_text(encoding="utf-8"))
    ключи = [к for к in заказы if НАЧАЛО <= к[:10] <= КОНЕЦ]
    дни = sorted({к[:10] for к in ключи})

    весь, днём = defaultdict(float), defaultdict(float)
    по_часам = defaultdict(float)
    for к in ключи:
        з = заказы[к]
        if з.get("возврат"):
            continue
        д, с, час = к[:10], float(з["сумма"]), int(з["время"][:2])
        весь[(д, зал(з["стол"]))] += с
        по_часам[час] += с
        # ⚠️ Ночные часы 0–7 — это хвост ПРЕДЫДУЩЕГО вечера, а не утро.
        # Сложи их с дневными — и «день» окажется прибыльнее вечера.
        if 11 <= час < 18:
            днём[(д, зал(з["стол"]))] += с

    def среднее(источник):
        итог = {}
        for н in range(7):
            дни_н = [д for д in дни if datetime.fromisoformat(д).weekday() == н]
            итог[ИМЕНА[н]] = [
                sum(источник.get((д, з), 0) for д in дни_н) / len(дни_н) if дни_н else 0
                for з in ЗАЛЫ
            ]
        return итог

    всего = sum(по_часам.values())
    доля_дня = sum(v for ч, v in по_часам.items() if 11 <= ч < 18) / всего
    return среднее(весь), среднее(днём), len(дни), доля_дня


def деньги(v) -> str:
    return f"{round(v):,}".replace(",", " ") + " ₽"


def круглые(v) -> str:
    """Депозит — переговорная цифра, и дробей в ней быть не должно."""
    шаг = 10_000 if v < 200_000 else 25_000
    return деньги(round(v / шаг) * шаг)


def таблица(док, заголовки, строки):
    т = док.add_table(rows=1, cols=len(заголовки))
    т.style = "Table Grid"
    for я, текст in zip(т.rows[0].cells, заголовки):
        я.text = ""
        п = я.paragraphs[0].add_run(текст)
        п.bold = True
        п.font.size = Pt(9)
    for строка in строки:
        ячейки = т.add_row().cells
        for я, значение in zip(ячейки, строка):
            я.text = ""
            п = я.paragraphs[0].add_run(str(значение))
            п.font.size = Pt(9)
            if я is not ячейки[0]:
                я.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.RIGHT
    док.add_paragraph()


def main() -> None:
    вечер, днём, дней, доля_дня = собрать()

    док = Document()
    обычный = док.styles["Normal"]
    обычный.font.name = "Calibri"
    обычный.font.size = Pt(10)

    з = док.add_heading("Финансовая рамка банкета", level=0)
    з.runs[0].font.color.rgb = RGBColor(0x1F, 0x1F, 0x1F)
    п = док.add_paragraph()
    п.add_run("Барвиха Lounge, Невский проспект, 26. ").bold = True
    п.add_run(f"Считано по чекам кассы за {дней} дней, июнь–август 2026. "
              "Документ служебный: цифры внутри — коммерческая тайна.")

    док.add_heading("Зачем нужны банкеты", level=1)
    док.add_paragraph(
        "Догрузить слабые слоты, а не продавать пик. Это решение владельца, "
        "и от него зависит весь ценник: минимальная сумма банкета считается "
        "от того, сколько зал заработал бы сам в это же время, а не от общих "
        "представлений о том, сколько «нормально» взять за вечер.")

    док.add_heading("Где на самом деле пусто", level=1)
    док.add_paragraph(
        f"До 18:00 заведение зарабатывает {доля_дня*100:.1f} % своей выручки. "
        "Пик приходится на 22:00–02:00. Это и есть главный довод банкетного "
        "предложения: дневное мероприятие почти ничего не отнимает у обычной "
        "работы, поэтому может стоить заметно дешевле вечернего и всё равно "
        "приносить заведению больше, чем этот день принёс бы сам.")

    док.add_heading("Сколько стоит слот: вечер", level=1)
    док.add_paragraph(
        "Средняя выручка зала за вечер. Столько заведение теряет, отдавая зал "
        "под банкет целиком.")
    таблица(док, ["День недели"] + ЗАЛЫ + ["Все три зала"],
            [[д] + [деньги(v) for v in вечер[д]] + [деньги(sum(вечер[д]))] for д in ИМЕНА])

    док.add_heading("Сколько стоит слот: день, 11:00–18:00", level=1)
    таблица(док, ["День недели"] + ЗАЛЫ + ["Все три зала"],
            [[д] + [деньги(v) for v in днём[д]] + [деньги(sum(днём[д]))] for д in ИМЕНА])

    док.add_heading("Минимальный депозит", level=1)
    док.add_paragraph(
        "Упущенная выручка слота плюс 20 % — за хлопоты, риск отмены и отказ "
        "от удачного вечера. Ниже этих сумм банкет заведению невыгоден: "
        "проще работать как обычно.")
    строки = []
    for д in ИМЕНА:
        строки.append([д]
                      + [круглые(v * ЗАПАС) for v in вечер[д]]
                      + [круглые(sum(вечер[д]) * ЗАПАС)])
    таблица(док, ["Вечер целиком"] + ЗАЛЫ + ["Все три зала"], строки)
    строки = []
    for д in ИМЕНА:
        строки.append([д]
                      + [круглые(v * ЗАПАС) for v in днём[д]]
                      + [круглые(sum(днём[д]) * ЗАПАС)])
    таблица(док, ["День, 11:00–18:00"] + ЗАЛЫ + ["Все три зала"], строки)
    док.add_paragraph(
        "Суммы округлены: депозит — переговорная цифра, а не результат деления.")
    п = док.add_paragraph()
    п.add_run("Важно про дневные суммы. ").bold = True
    п.add_run(
        "Они показывают только упущенную выручку, а днём заведение почти "
        "пустое — терять нечего. Но дневной банкет означает лишние часы "
        "персонала и кухни, которых в обычный день не было бы. Поэтому "
        "к дневному депозиту надо прибавить стоимость смены: официанты, "
        "кальянщики, кухня, администратор. Пока это число не посчитано, "
        "дневные цифры в таблице — нижняя граница убытка, а не цена.")

    док.add_heading("Маржа и потолок скидки", level=1)
    док.add_paragraph(
        "Себестоимость от выручки направления: бар 22,7 %, кальяны 10,6 %. "
        "То есть каждая тысяча, потраченная гостем на бар, оставляет "
        "заведению около 773 ₽, на кальяны — около 894 ₽. Чем больше доля "
        "кальянов и бара в пакете, тем дешевле можно продать сам вход.")
    док.add_paragraph(
        "Потолок скидки — сумма из таблицы выше. Это не «жёсткая позиция "
        "в переговорах», а граница, ниже которой банкет приносит меньше, "
        "чем обычная работа зала.")

    док.add_heading("Что уточнить, прежде чем печатать предложение", level=1)
    for пункт in [
        "Посадка каждого зала — сколько гостей помещается. В кассе этих чисел "
        "нет, взять их надо у управляющего.",
        "Себестоимость кухни модель показывает 73,6 % — это втрое выше обычного "
        "для ресторана. Пока цифра не разобрана, строить на ней банкетный "
        "ценник нельзя: пакет с большой едой может оказаться убыточным.",
        "Действующий прайс на аренду VIP-зоны. Заведение уже продаёт выкуп "
        "зоны, и банкетное предложение не должно ему противоречить.",
        "Средние цифры не гарантия: в слабый вторник зал делал и 140 тысяч, "
        "и 976 тысяч. Бронь закрывает и плохой вечер, и удачный.",
    ]:
        док.add_paragraph(пункт, style="List Bullet")

    путь = фин_dir() / "Финансовая рамка банкета.docx"
    док.save(путь)
    print(f"✓ {путь}")


if __name__ == "__main__":
    main()
