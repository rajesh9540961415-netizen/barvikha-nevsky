for k in КАТ:
    д = [итого(m, k) / sum(итого(m, c) for c in КАТ) for m in ("2026-07", "2026-08")]
    доли[k] = sum(д) / 2
норм = sum(доли.values())
план = {k: выручка_сен * доли[k] / норм for k in КАТ}
