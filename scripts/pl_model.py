def бюджет(месяц):
    """Полный бюджет месяца одной механикой — чтобы месяцы были сравнимы.

    Возвращает словарь: выручка, план по направлениям, себестоимость, OPEX.
    Всё, что зависит от выручки (себестоимость, эквайринг), пересчитывается;
    всё остальное — среднемесячный факт января–июля и потому одинаково.
    """
    год_назад, в_день, всего = прогноз(месяц)
    п = {k: всего * доли[k] / норм for k in КАТ}
    с = {"кухня": п["кухня"] * доля_кухня,
         "бар": п["бар"] * доля_бар,
         "кальяны": п["кальяны"] * доля_кальян}
    безнал = sum(п[k] * (1 - нал_доля[k]) for k in КАТ)
    строки = []
    for имя, знач in opex:
        строки.append((имя, безнал * ставка_экв if имя == "Эквайринг" else знач))
    return {"месяц": месяц, "дней": ДНЕЙ[месяц],
            "год_назад_в_день": год_назад, "в_день": в_день,
            "выручка": всего, "план": п, "себест": с, "opex": строки}
