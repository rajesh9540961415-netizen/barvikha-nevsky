нал_доля = {k: факт[("2026-08", k)]["нал"] / итого("2026-08", k) for k in КАТ}

# ---------- 3. Статьи расходов ----------
ст = {m: articles_for_month(m)[0] for m in БАЗА}
нал_ст = {m: cash_articles(m)[0] for m in БАЗА}
сред = lambda a: sum(ст[m].get(a, 0) for m in БАЗА) / len(БАЗА)
сред_нал = lambda a: sum(нал_ст[m].get(a, 0) for m in БАЗА) / len(БАЗА)
эквайринг_ср = sum(acquiring(m) for m in БАЗА) / len(БАЗА)

# себестоимость — долей от выручки своего направления
