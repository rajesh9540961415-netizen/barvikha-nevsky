"""Бюджет на месяц вперёд. Все числа считаются здесь, чтобы их можно было пересчитать.

Механика одна на все месяцы, чтобы не было разночтений:
  выручка  = тот же месяц прошлого года (₽/день) × годовой рост × дней в месяце
  доли направлений и доля наличных — по июлю и августу 2026
  себестоимость — процентом от выручки своего направления, по январю–июлю
  OPEX — среднемесячный факт января–июля, кроме маркетинга и эквайринга
  эквайринг — процентом от безналичной выручки плана
"""
import sys, csv, glob, collections
sys.path.insert(0, "scripts")
sys.path.insert(0, str(__import__("pathlib").Path(__file__).resolve().parent))
from fin_articles import articles_for_month, acquiring, cash_articles
from pl_revenue import собрать

БАЗА = [f"2026-{i:02d}" for i in range(1, 8)]        # январь–июль: полные месяцы
КАТ = ["кухня", "бар", "кальяны", "аренда"]

# ---------- 1. Выручка: факт ----------
зал = собрать(sorted(glob.glob("data/ofd/чеки-2026-0[1-8].json")))
бар = собрать(sorted(glob.glob("data/ofd/чеки-бар-2026-0[78].json")))
факт = collections.defaultdict(lambda: {"нал": 0.0, "безнал": 0.0})
for src in (зал, бар):
    for k, v in src.items():
        факт[k]["нал"] += v["нал"]; факт[k]["безнал"] += v["безнал"]
итого = lambda m, k: факт[(m, k)]["нал"] + факт[(m, k)]["безнал"]

# ---------- 2. Прогноз выручки ----------
ДНЕЙ_АВГ, ДНЕЙ_СЕН = 25, 30
авг = sum(итого("2026-08", k) for k in КАТ) / ДНЕЙ_АВГ


def в_день_2025():
    """Выручка в день по месяцам 2025 года — из ежедневных данных владельца."""
    сумма = collections.Counter(); дни = collections.defaultdict(set)
    for x in csv.DictReader(open("data/dds/daily_metrics.csv", encoding="utf-8")):
        if x["metric"] != "revenue_total":
            continue
        try:
            сумма[x["date"][:7]] += float(x["value"])
        except ValueError:
            continue
        дни[x["date"][:7]].add(x["date"])
    return {m: сумма[m] / len(дни[m]) for m in сумма if дни[m]}


# Считаем НЕ от августа вниз по сезонности, а от сентября прошлого года вверх
# по годовому росту. Решение владельца 26.08.2026: первый способ давал 22,1 млн,
# то есть рост +55 % к сентябрю 2025 — больше, чем фактические +36…+45 %
# за три последних месяца. Второй способ опирается на тот же месяц года,
# и сезонность в нём уже сидит.
_2025 = в_день_2025()
_ОПОРА = ("06", "07", "08")                   # месяцы, по которым меряем годовой рост
рост_год = sum((sum(итого(f"2026-{м}", k) for k in КАТ)
                / (30 if м in ("06", "09") else 31 if м != "08" else ДНЕЙ_АВГ))
               / _2025[f"2025-{м}"] for м in _ОПОРА) / len(_ОПОРА)
ДНЕЙ = {"2026-09": 30, "2026-10": 31, "2026-11": 30, "2026-12": 31}


def прогноз(месяц):
    """(₽ в день прошлого года, ₽ в день плана, выручка месяца)."""
    год_назад = f"2025-{месяц[5:]}"
    если_нет = f"нет данных за {год_назад} в daily_metrics.csv"
    if год_назад not in _2025:
        raise SystemExit(если_нет)
    в_день = _2025[год_назад] * рост_год
    return _2025[год_назад], в_день, в_день * ДНЕЙ[месяц]


МЕСЯЦ = "2026-09"
сен_2025, день_сен, выручка_сен = прогноз(МЕСЯЦ)

# доли направлений — среднее июля и августа
