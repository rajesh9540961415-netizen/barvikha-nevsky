def полиграфия():
    """Листовки и визитки — рекламная полиграфия, лежала в «Прочих расходах».
    Решение владельца 26.08.2026: перенести в маркетинг. Меню сюда НЕ берём —
    его печать это операционный расход, а не продвижение."""
    сумма = 0.0
    for x in csv.DictReader(open("data/dds/bank_classified.csv", encoding="utf-8")):
        if x["direction"] != "out" or x["class"] != "external" or x["date"][:7] not in БАЗА:
            continue
        ц = x["purpose"].lower()
        if any(w in ц for w in ("листовк", "визитк")):
            сумма += float(x["amount"])
    return сумма / len(БАЗА)


