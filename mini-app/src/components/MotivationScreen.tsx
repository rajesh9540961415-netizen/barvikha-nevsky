import { useEffect, useState } from "react";
import { formatBusinessDay, formatMoney } from "@/lib/businessDay";
import { посчитать } from "@/lib/hookahMotivation";
import type { МотивацияСмены } from "@/lib/hookahMotivation";
import { getHookahCrew } from "@/lib/people";
import { hookahMotivation } from "@/lib/storage";

/**
 * Мотивация кальянного бара за смену.
 *
 * Кальянщики продают разные типы кальянов, и за каждый тип положена доплата
 * рублями за штуку. Это не чаевые: доплату платит заведение, в отчёт по
 * чаевым она не идёт, и делится она не так — котлом на всю смену поровну
 * между теми, кто вышел (формат владельца 08.09.2026).
 *
 * 🔴 **Вид экрана назвала владелец 08.09.2026, и он нарочно простой:**
 * «упрости, оставь только заголовки, общее количество проданных позиций,
 * стоимость одной позиции и общую сумму». Ровно четыре столбца и итог.
 * Раскладка по конкретным кальянам внутри типа и по дням есть в бэк-офисе,
 * на странице `/motivaciya`, — здесь её быть не должно.
 *
 * 🔴 **Выручки на этом экране нет и не будет** (владелец 06.09.2026). Она
 * даже не приезжает на телефон: `readHookahMotivation` не спрашивает у базы
 * столбец с деньгами.
 *
 * 🔴 **Цифры живые.** Владелец 08.09.2026: экран нужен, «чтобы администратор
 * в оперативном режиме видел объём продаж и к концу смены мог дать цифру
 * по мотивации кальянному бару». Первая версия показывала посчитанное утром,
 * то есть вчерашнюю смену, и цели не решала вовсе. Теперь продажи идут прямо
 * из кассы бара и обновляются сами раз в минуту, пока экран открыт.
 *
 * ⚠️ **Экран ничего не считает сам, кроме сложения.** Что чем считается
 * и за что положена доплата, решено один раз на Маке, в `hookah_push.py`:
 * доплата за «ЧМ» полагается лишь в комплекте с электронной чашей, а комплект
 * виден по составу чека. 08.09.2026 три ошибки счёта выросли из того, что
 * одно правило жило в двух местах, — здесь третьего места нет.
 */

type Props = {
  /** Смена, открытая в приложении. */
  day: string;
  onClose: () => void;
};

type Состояние =
  | { вид: "грузим" }
  | { вид: "не вышло" }
  | { вид: "готово"; данные: МотивацияСмены };

export default function MotivationScreen({ day, onClose }: Props) {
  const [состояние, setСостояние] = useState<Состояние>({ вид: "грузим" });
  const [попытка, setПопытка] = useState(0);

  useEffect(() => {
    let живо = true;
    // «Считаю…» показываем только пока показывать больше нечего. На повторном
    // чтении цифры на экране остаются: моргать числами, за которыми следят,
    // нельзя — администратор решит, что смена обнулилась.
    setСостояние((было) => (было.вид === "готово" ? было : { вид: "грузим" }));
    hookahMotivation(day)
      .then((данные) => {
        if (живо) setСостояние({ вид: "готово", данные });
      })
      .catch(() => {
        if (живо) {
          setСостояние((было) => (было.вид === "готово" ? было : { вид: "не вышло" }));
        }
      });
    return () => {
      живо = false;
    };
  }, [day, попытка]);

  /**
   * Пока экран открыт, перечитываем сами.
   *
   * Экран для того и заведён, чтобы смотреть на растущую цифру, а не жать
   * «обновить». Минуты хватает: кальян готовится дольше, а лишний запрос
   * в кассу ничего не стоит.
   */
  useEffect(() => {
    const часы = setInterval(() => setПопытка((n) => n + 1), 60_000);
    return () => clearInterval(часы);
  }, []);

  return (
    <div className="flex min-h-dvh flex-col">
      <header className="flex items-center gap-3 border-b border-line px-4 py-2.5">
        <button
          onClick={onClose}
          aria-label="Назад"
          className="-ml-1 rounded-lg px-2 py-1 text-2xl leading-none text-fg-muted active:bg-surface"
        >
          ‹
        </button>
        <div className="text-base">Мотивация бара</div>
      </header>

      {состояние.вид === "грузим" && (
        <p className="px-4 py-8 text-sm text-fg-muted">Считаю…</p>
      )}

      {состояние.вид === "не вышло" && (
        <div className="px-4 py-8">
          <p className="text-sm text-fg-muted">
            Не удалось загрузить — проверьте связь.
          </p>
          <button
            onClick={() => setПопытка((n) => n + 1)}
            className="mt-4 rounded-xl bg-sand px-6 py-3 text-base text-ink"
          >
            Повторить
          </button>
        </div>
      )}

      {состояние.вид === "готово" && (
        <Таблица данные={состояние.данные} сегодня={day} />
      )}
    </div>
  );
}

function Таблица({
  данные,
  сегодня,
}: {
  данные: МотивацияСмены;
  сегодня: string;
}) {
  if (данные.день === null) {
    return (
      <p className="px-4 py-8 text-sm text-fg-muted">
        Продаж пока нет. Их привозит команда с компьютера владельца.
      </p>
    );
  }

  const { поКатегориям, всего, штукВсего } = посчитать(
    данные.продажи,
    данные.ставки,
  );
  // Типы, которых в эту смену не продали, не показываем: пустая строка
  // с нулём ничего не сообщает, а экран просили упростить.
  const строки = поКатегориям.filter((к) => к.штук > 0);

  return (
    <>
      <p className="px-4 pb-1 pt-3 text-sm text-fg">
        смена · {formatBusinessDay(данные.день)}
        {данные.живое && " · сейчас"}
      </p>
      {/* Живые цифры или вчерашние — разница для администратора
          принципиальная, и молчать о ней нельзя. Живые растут весь вечер
          и отвечают на «сколько нам сегодня»; запасные — это закрытая
          смена, которую можно прочитать как сегодняшнюю и ошибиться. */}
      {данные.живое ? (
        <p className="px-4 pb-2 text-xs text-fg-muted">
          прямо из кассы — цифры растут по ходу вечера; утром их пересчитают
          по чекам, и они могут немного измениться
        </p>
      ) : (
        <p className="px-4 pb-2 text-xs text-alert">
          касса сейчас не отвечает — это последняя посчитанная смена
          {данные.день === сегодня ? "" : ", а не сегодняшняя"}
        </p>
      )}

      {строки.length === 0 ? (
        <p className="px-4 py-8 text-sm text-fg-muted">
          {данные.живое
            ? "Пока ни одного кальяна с доплатой."
            : "В эту смену кальянов с доплатой не было."}
        </p>
      ) : (
        <div className="px-4 pt-2">
          <table className="w-full border-collapse text-right text-sm">
            <thead className="text-fg-muted">
              <tr className="border-b border-line">
                <th className="py-2 pr-2 text-left font-normal">тип кальяна</th>
                <th className="px-1 py-2 font-normal">продано</th>
                <th className="px-1 py-2 font-normal">за штуку</th>
                <th className="py-2 pl-1 font-normal">к доплате</th>
              </tr>
            </thead>
            <tbody>
              {строки.map((к) => (
                <tr key={к.категория} className="border-b border-line/60">
                  <td className="py-2.5 pr-2 text-left">{к.категория}</td>
                  <td className="px-1 py-2.5 tabular-nums">
                    {к.штук.toLocaleString("ru-RU")}
                  </td>
                  <td className="px-1 py-2.5 tabular-nums text-fg-muted">
                    {formatMoney(к.ставка)}
                  </td>
                  <td className="py-2.5 pl-1 tabular-nums">
                    {formatMoney(к.мотивация)}
                  </td>
                </tr>
              ))}
            </tbody>
            <tfoot>
              <tr className="border-t border-line">
                <td className="py-3 pr-2 text-left">Итого</td>
                <td className="px-1 py-3 tabular-nums">
                  {штукВсего.toLocaleString("ru-RU")}
                </td>
                <td />
                <td className="py-3 pl-1 tabular-nums">{formatMoney(всего)}</td>
              </tr>
            </tfoot>
          </table>

          <НаЧеловека всего={всего} данные={данные} />
        </div>
      )}
    </>
  );
}

/**
 * Сколько выходит каждому.
 *
 * Мотивация бара — котёл на смену, и владелец делит его ПОРОВНУ между теми,
 * кто в неё работал (формат листа УК, 08.09.2026): 13 600 ÷ 6 = 2 266,7.
 *
 * 🔴 **Округляем до десятых рубля, и про округление НИЧЕГО не пишем** —
 * решение владельца 08.09.2026: 13 600 на шестерых это «по 2 266,7 ₽».
 *
 * История у этой строки короткая и поучительная. Сначала здесь округляли
 * вниз до целого рубля, а сдачу — сперва отдавали старшему по смене, потом
 * раздавали жребием, и экран честно объяснял, кому достался каждый лишний
 * рубль. Владелец на это посмотрела и сказала: «а что мы так заморочились?
 * Если не хватает, мы просто додаём из кассы, это решается локально». Три
 * рубля не стоили ни правила, ни строки на экране, ни жребия в коде.
 *
 * 💡 **Правило на будущее: спрашивайте про цену вопроса раньше, чем строите
 * механику.** Копейки в долях ЗАЛА беречь надо — там из них складывается
 * выплата, и расхождение видно в отчёте. Здесь тот же инстинкт увёл в сторону
 * от того, что владелец делает руками за две секунды.
 *
 * 💡 Имена показываем нарочно, мелкой строкой. Число, на которое делят,
 * проверить больше нечем.
 *
 * ⚠️ Ошибка от нехватки имени идёт В ПЛЮС, и потому не бросается в глаза:
 * котёл считается от проданных кальянов и не зависит от того, сколько людей
 * отметили. Забыли одного — делят на меньшее число, и доля выходит БОЛЬШЕ
 * настоящей, а забытый остаётся ни с чем. 9 400 ₽ на четверых это 2 350 ₽,
 * а на отмеченных троих — 3 133,3 ₽, и цифра выглядит так же правдоподобно.
 * Увидеть подмену можно только глазами, узнав в списке всех, кто вышел.
 */
function НаЧеловека({
  всего,
  данные,
}: {
  всего: number;
  данные: МотивацияСмены;
}) {
  if (данные.бар.length === 0) {
    return (
      <p className="pt-4 text-sm text-fg-muted">
        Состав бара в ту смену не отмечен — делить не на кого. Кальянщиков
        отмечают в составе смены, там же, где официантов.
      </p>
    );
  }

  const справочник = getHookahCrew();
  const имя = (id: number) =>
    справочник.find((p) => p.id === id)?.short ??
    данные.имена[String(id)] ??
    `№${id}`;

  return (
    <div className="pt-4">
      <p className="text-base">
        Поровну на {данные.бар.length}{" "}
        {plural(данные.бар.length, "человека", "человека", "человек")} — по{" "}
        <span className="tabular-nums">
          {доДесятых(всего / данные.бар.length)}
        </span>
      </p>
      <p className="pt-1 text-xs text-fg-muted">
        {данные.бар.map(имя).join(", ")}
      </p>
    </div>
  );
}

/**
 * «2 266,7 ₽» — доля, округлённая до десятых рубля.
 *
 * Отдельно от `formatMoney`: тот показывает копейки, то есть две цифры после
 * запятой, и правильно делает — там, где считаются чаевые, копейка это деньги.
 * Здесь владелец попросила десятые, а недостачу в пару рублей закрывает
 * из кассы на месте.
 *
 * Нолик после запятой не рисуем: 10 400 на четверых это «2 600 ₽», а не
 * «2 600,0 ₽». Пробелы неразрывные — чтобы сумма не разорвалась по строкам.
 */
function доДесятых(сумма: number): string {
  const текст = (Math.round(сумма * 10) / 10).toLocaleString("ru-RU", {
    maximumFractionDigits: 1,
  });
  return `${текст.replace(/\s/g, " ")} ₽`;
}

/** «на 1 человека», «на 2 человек» — в строке про долю. */
function plural(n: number, one: string, few: string, many: string): string {
  const mod10 = n % 10;
  const mod100 = n % 100;
  if (mod10 === 1 && mod100 !== 11) return one;
  if (mod10 >= 2 && mod10 <= 4 && (mod100 < 12 || mod100 > 14)) return few;
  return many;
}
