import { request } from "node:https";
import { request as requestHttp } from "node:http";
import правила from "@/data/hookah-motivation.json";
import type { СтрокаСчёта } from "./hookahMotivation";

/**
 * Продажи кальянов ПРЯМО СЕЙЧАС — из кассы бара, а не из вчерашней выгрузки.
 *
 * 🔴 **Зачем.** Владелец 08.09.2026: «вся эта задача затевалась для того, чтобы
 * администратор в оперативном режиме видел объём продаж и к концу смены мог
 * дать цифру по мотивации кальянному бару». Первая версия экрана показывала
 * посчитанное утром, то есть ВЧЕРАШНЮЮ смену, и цели не решала вовсе.
 *
 * Касса отвечает про идущую смену: проверено 08.09.2026 в 17:40 — пять
 * кальянов, 1 000 ₽, ровно то, что было продано к той минуте.
 *
 * ⚠️ **Это ВТОРОЕ место, где решается «за что положена доплата».** Первое —
 * `scripts/hookah_push.py` на Маке, и оно остаётся главным: утренний пересчёт
 * по фискальным чекам поправит цифру, если она разойдётся. Второго места
 * не хотелось (08.09.2026 три ошибки счёта выросли ровно из такого), но
 * без него живой цифры не бывает: чеки ОФД доезжают на следующий день.
 *
 * Чтобы места не разъехались, оба читают ОДИН файл правил —
 * `hookah-motivation.json`. Здесь нет ни одного числа и ни одного названия
 * категории, вписанного руками.
 *
 * ✅ **Сверено с проверенным счётом** (08.09.2026):
 *   07.09 — 43 кальяна и 9 000 ₽, совпало и по типам (20 перфюм-чаш);
 *   01–07.09 — 67 500 ₽, совпало с эталоном;
 *   август — 358 800 ₽ против 359 000 выплаченных, разница 0,06 %.
 */

type ПравилоКатегории = {
  наша: string;
  ставка: number;
  только_в_комплекте?: boolean;
};

const КАТЕГОРИИ_МЕНЮ = Object.fromEntries(
  Object.entries(правила.категории_меню as Record<string, unknown>).filter(
    ([ключ]) => !ключ.startsWith("_"),
  ),
) as Record<string, ПравилоКатегории>;

/** Название позиции, которая идёт в комплекте с «ЧМ». */
const ПАРА = правила.комплект.пара;

/**
 * ⚠️ Облако баровой кассы ОБЩЕЕ НА СЕТЬ: рядом с нашим залом в отчёте лежат
 * Митино, Красная площадь и Москва-Сити. За 05.09.2026 наш Невский дал
 * 102 кальяна, чужие — ещё 102. Отбор по залу обязателен всегда.
 */
const НАШ_ЗАЛ = "Невский";

/** Номер отчёта продаж в кабинете кассы — тот же `vid`, что в адресной строке. */
const ОТЧЁТ = 808;

/** Торговые сутки начинаются в 11:00, как и во всём проекте. */
const СМЕНА_НАЧИНАЕТСЯ = 11;

/**
 * Сколько ждём кассу. Экран смены открывают между гостями, и лучше честное
 * «не дозвонились» через восемь секунд, чем крутящаяся надпись полминуты.
 */
const ЖДЁМ_МС = 8_000;

type СтрокаОтчёта = {
  storeItem?: { title?: string } | null;
  productCategory?: { title?: string } | null;
  tableScheme?: { title?: string } | null;
  saleAmount?: number | null;
  totalSum?: number | null;
};

/** Есть ли чем спрашивать кассу. Нет — живой цифры не будет, и это не поломка. */
export function кассаДоступна(): boolean {
  return Boolean(
    (process.env.QR_SHALAEVA_URL || process.env.QR_URL) &&
      (process.env.QR_SHALAEVA_LOGIN || process.env.QR_LOGIN) &&
      (process.env.QR_SHALAEVA_PASSWORD || process.env.QR_PASSWORD),
  );
}

/**
 * Продажи торговых суток из кассы, уже разобранные по нашим категориям.
 *
 * Бросает исключение, если касса не ответила: наверху это ловится и экран
 * показывает посчитанное утром.
 */
export async function продажиИзКассы(
  businessDay: string,
): Promise<СтрокаСчёта[]> {
  const строки = await спроситьКассу(businessDay);
  return разобрать(строки);
}

/**
 * Разбор ответа кассы в строки счёта.
 *
 * Вынесен отдельно от запроса нарочно: так правила можно проверить на
 * сохранённом ответе, не трогая кассу.
 */
export function разобрать(строки: СтрокаОтчёта[]): СтрокаСчёта[] {
  const наши = строки.filter((с) =>
    (с.tableScheme?.title ?? "").includes(НАШ_ЗАЛ),
  );

  const считаем: { позиция: string; наша: string; штук: number; пара: boolean }[] =
    [];
  let вКомплекте = 0;

  for (const с of наши) {
    const позиция = с.storeItem?.title ?? "";
    const категория = с.productCategory?.title ?? "";
    const штук = с.saleAmount ?? 0;
    if (!позиция || !штук) continue;

    // ⚠️ Нулёвки доплаты не дают. Перезабивка, прокур, чашка главного стоят
    // 0 ₽, и по названию их не отличить: «Перезабивка МИКС PERFUME
    // Электронная чаша» лежит в той же категории меню, что и обычный перфюм.
    // 08.09.2026 такие 12 штук за месяц брали по 200 ₽ каждая.
    if ((с.totalSum ?? 0) === 0) continue;

    const правило = КАТЕГОРИИ_МЕНЮ[категория];

    // Категории нет в правилах — значит меню изменилось, а файл нет. Строку
    // всё равно показываем: со ставкой 0 она бросится в глаза, а промолчать
    // значило бы недоплатить и не сказать об этом никому.
    const наша = правило ? правило.наша : категория;
    if (наша === "без мотивации") continue;

    if (правило?.только_в_комплекте) вКомплекте += штук;
    считаем.push({ позиция, наша, штук, пара: позиция.includes(ПАРА) });
  }

  // 🔴 Правило комплекта. Владелец 08.09.2026: «400 рублей мы платим
  // за комплект, который стоит 6500». Комплект — это «ЧМ» плюс электронная
  // чаша, и чаша внутри него своих 200 ₽ не приносит: её оплатили через «ЧМ».
  //
  // Состава чека в отчёте нет, поэтому снимаем ровно столько чаш, сколько
  // продано позиций с пометкой «только в комплекте». Остальные чаши —
  // обычная продажа, и доплата за них положена.
  //
  // ⚠️ Снимать ВСЕ чаши подряд нельзя: за 01–07.09.2026 это дало бы 67 300 ₽
  // вместо проверенных 67 500. Проверено на живых данных 08.09.2026.
  let снять = Math.min(
    вКомплекте,
    считаем.filter((с) => с.пара).reduce((с_, п) => с_ + п.штук, 0),
  );

  const итог: СтрокаСчёта[] = [];
  for (const с of считаем) {
    let штук = с.штук;
    if (с.пара && снять > 0) {
      const убрать = Math.min(снять, штук);
      штук -= убрать;
      снять -= убрать;
    }
    if (штук > 0) итог.push({ position: с.позиция, category: с.наша, qty: штук });
  }
  return итог;
}

/**
 * Запрос к кассе.
 *
 * ⚠️ Это GET **с телом** — так устроен их API, это не опечатка. Обычный
 * `fetch` так не умеет и бросает «Request with GET method cannot have body»,
 * поэтому здесь голый `node:https`.
 *
 * ⚠️ Даты в теле идут СПИСКАМИ: `[мс]`, а не `мс`. Голое число даёт
 * 400 Bad Request — на этом 08.09.2026 потерян первый заход.
 *
 * 💡 Границы считаем с явным московским временем, а не по часам сервера:
 * контейнер живёт по Гринвичу, и «11:00» на нём — это 14:00 в зале.
 */
function спроситьКассу(businessDay: string): Promise<СтрокаОтчёта[]> {
  const база = (process.env.QR_SHALAEVA_URL || process.env.QR_URL || "").replace(
    /\/+$/,
    "",
  );
  const логин = process.env.QR_SHALAEVA_LOGIN || process.env.QR_LOGIN || "";
  const пароль = process.env.QR_SHALAEVA_PASSWORD || process.env.QR_PASSWORD || "";
  if (!база || !логин || !пароль) {
    throw new Error("Нет доступа к кассе бара: не заданы QR_SHALAEVA_*");
  }

  const час = String(СМЕНА_НАЧИНАЕТСЯ).padStart(2, "0");
  const с = new Date(`${businessDay}T${час}:00:00+03:00`);
  const по = new Date(с.getTime() + 24 * 60 * 60 * 1000);

  const тело = JSON.stringify({
    mode: "dateFilter",
    extParams: { dateFrom: [с.getTime()], dateTo: [по.getTime()] },
  });

  const адрес = new URL(
    `${база}/platform/online/api/list` +
      `?moduleName=report.datasources.sales&ownerContextId=${ОТЧЁТ}`,
  );
  const запросить = адрес.protocol === "http:" ? requestHttp : request;

  return new Promise((готово, беда) => {
    const req = запросить(
      адрес,
      {
        method: "GET",
        headers: {
          Authorization:
            "Basic " + Buffer.from(`${логин}:${пароль}`).toString("base64"),
          "Content-Type": "application/json",
          "Content-Length": Buffer.byteLength(тело),
        },
        timeout: ЖДЁМ_МС,
      },
      (ответ) => {
        const куски: Buffer[] = [];
        ответ.on("data", (к) => куски.push(к));
        ответ.on("end", () => {
          if ((ответ.statusCode ?? 0) !== 200) {
            беда(new Error(`Касса ответила ${ответ.statusCode}`));
            return;
          }
          try {
            готово(JSON.parse(Buffer.concat(куски).toString("utf-8")));
          } catch {
            беда(new Error("Касса ответила не разбираемым текстом"));
          }
        });
      },
    );
    req.on("timeout", () => req.destroy(new Error("Касса не ответила вовремя")));
    req.on("error", беда);
    req.end(тело);
  });
}
