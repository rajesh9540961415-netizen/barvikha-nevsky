export type Table = {
  id: number;
  title: string;
  seats: number | null;
  x: number;
  y: number;
  width: number;
  height: number;
  shape: string;
};

export type Hall = {
  id: number;
  title: string;
  tables: Table[];
};

export type Scheme = {
  scheme: string;
  halls: Hall[];
};

export type Employee = {
  id: number;
  /** Полное имя из Quick Resto. */
  name: string;
  /** Короткое имя для кнопки: «Анна К.» */
  short: string;
};

/**
 * Что именно записали.
 *
 * cash и terminal — чаевые от гостя, добровольные.
 * service — сервисный сбор: 10 % от чека, начисляется автоматически
 * большим компаниям. Выдаётся официантам в тот же день, как и чаевые,
 * но делится иначе — кассир от него доли не получает.
 */
/**
 * Что именно записали.
 *
 * Первые четыре — деньги, полученные официантом. `staff` стоит особняком:
 * это не доход, а **вычет** — сколько человек проел за смену. Расходы
 * на питание пробиваются в Quick Resto на столе STAFF, и администратор
 * в конце смены вычитает их из причитающейся выплаты.
 */
export type Kind = "cash" | "terminal" | "service" | "qr" | "staff";

/**
 * Поступление по персональному QR — пришло, но ещё не разнесено по людям.
 *
 * Приходит не из зала: гость платит по QR на чеке, кассир этих денег не видит.
 * Сбер сообщает о них уведомлением в Telegram и называет не человека,
 * а котёл — «Официант 5». Кто обслуживал, знает только смена, поэтому
 * сумму разносит кассир.
 */
export type QrTip = {
  /** Идентификатор сообщения в Telegram — он же защита от повторов. */
  messageId: number;
  /** Когда пришло, ISO. */
  receivedAt: string;
  businessDay: string;
  amount: number;
  /** Котёл Сбера: «Официант 5», «Хостес». */
  team: string;
};

/**
 * Состав смены и роли.
 *
 * Живёт здесь, а не в crew.ts, чтобы серверный слой базы мог ссылаться
 * на этот тип, не втягивая за собой браузерный код.
 */
export type Shift = {
  crew: number[];
  operator: number | null;
  admin: number | null;
  cashier: number | null;
};

/** Одна запись о полученных деньгах. */
export type Entry = {
  id: string;
  /**
   * Зал и стол. Пусто у QR-чаевых: гость платит по чеку, а не за столом,
   * и привязки к месту в зале у такого поступления нет.
   */
  hallId: number | null;
  hallTitle: string | null;
  tableId: number | null;
  tableTitle: string | null;
  waiterId: number;
  waiterName: string;
  /**
   * Сколько **дошло** до официанта — после комиссии Сбера.
   *
   * Именно эта сумма участвует во всём: в пороге 1300 ₽, в доле
   * администратора и кассира, в итогах смены и в отчёте. Брать долю
   * с денег, которых человек не получил, нельзя.
   */
  amount: number;
  /**
   * Сколько **оставил гость** — до комиссии.
   *
   * У наличных и сервисного сбора совпадает с `amount`: они идут мимо Сбера.
   * Хранится отдельно, чтобы было видно, куда делась разница, и чтобы
   * сходилось с выгрузкой Сбера, когда дойдём до склейки.
   */
  gross: number;
  /**
   * Ставка комиссии, применённая **в момент записи**: 0.08 у терминала.
   *
   * Хранится в самой записи, а не берётся из настроек при чтении: если Сбер
   * поменяет тариф, прошлые смены должны остаться такими, какими были.
   */
  commissionRate: number;
  kind: Kind;
  /** Кто внёс запись — администратор или кассир на смене. */
  operatorId: number;
  operatorName: string;
  /** Момент ввода, ISO. */
  createdAt: string;
  /** Бизнес-день, к которому относится запись: YYYY-MM-DD. */
  businessDay: string;
  /**
   * Когда запись отменили, ISO. Пусто у живых записей.
   *
   * Отменённые не входят ни в суммы, ни в отчёт — они видны только
   * в истории. Отмена не стирает строку: иначе проверить себя нельзя.
   */
  deletedAt?: string | null;
  /** Кто отменил. */
  deletedByName?: string | null;
  /**
   * Метка «эти строки — одни чаевые, поделённые между официантами».
   *
   * Большой стол обслуживают вдвоём, гость оставляет чаевые за стол целиком,
   * и запись ложится в базу по строке на каждого — каждому своя доля.
   * Общая метка связывает их: история показывает такие строки одним событием,
   * а отмена убирает группу целиком.
   *
   * Пусто у обычной записи одному официанту.
   */
  splitGroup?: string | null;
};
