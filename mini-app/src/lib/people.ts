import employees from "@/data/employees.json";
import hookah from "@/data/hookah.json";
import { addManual, deleteManual, listManual, unhideManual } from "./db/actions";
import type { Удаление } from "./db/actions";
import { HOOKAH_POT_ID, HOOKAH_POT_NAME } from "./split";
import type { Employee } from "./types";

/**
 * Кого можно поставить в смену.
 *
 * Основной список — из Quick Resto, лежит файлом в самой сборке и читается
 * мгновенно. Но в смену выходят и те, кого в кассе не завели: стажёры,
 * подработчики. Их администратор дописывает руками прямо на экране смены,
 * и вот они уже в общей базе — их должен видеть и сменщик.
 *
 * У дописанных вручную идентификатор отрицательный — так они никогда
 * не столкнутся с настоящими из Quick Resto.
 */

const FROM_QUICK_RESTO = employees as Employee[];

/**
 * Кальянщики — из второй кассы, ИП Шалаевой.
 *
 * Касса у бара своя, и номера обе кассы выдают из одного ряда: сегодня они
 * не пересекаются случайно, завтра новый кальянщик получил бы номер
 * работающего официанта. Поэтому здесь номера сдвинуты на миллион —
 * их так и кладёт scripts/qr_employees.py.
 */
const FROM_SHALAEVA = hookah as Employee[];

/**
 * Общий котёл бара — «Весь бар».
 *
 * Не человек, а получатель: администратор не всегда знает, кто из
 * кальянщиков обслуживал стол, и тогда деньги пишутся на бар целиком,
 * а делят их между собой сами. Стоит первым в списке, чтобы до него
 * не приходилось листать.
 */
export const HOOKAH_POT: Employee = {
  id: HOOKAH_POT_ID,
  name: HOOKAH_POT_NAME,
  short: HOOKAH_POT_NAME,
};

export function isManual(id: number): boolean {
  return id < 0;
}

export function getQuickRestoPeople(): Employee[] {
  return FROM_QUICK_RESTO;
}

/**
 * Из кого выбирают получателя в баре. Сейчас — только общий котёл.
 *
 * 🔴 **Имена кальянщиков сюда НЕ идут. Решение владельца 07.09.2026:
 * «не пересматриваем».**
 *
 * История у этой строки такая. Решение 22.08.2026 — «чаевые бара общий
 * котёл, поимённо не делим, кальянщиков в справочник не заводим» — держалось
 * само собой: облако баровой кассы общее на сеть, привязки к нашему залу
 * не стояло ни у кого, и `qr_employees.py` честно отдавал пустой список.
 * Выбирать было не из кого, и запрет ничего не стоил.
 *
 * Вечером 07.09.2026 УК проставила залы, отбор ожил и отдал троих: Портнов,
 * Черненко, Чуешкова. Владельца спросили, пересматривать ли решение, —
 * ответ «не пересматриваем». Без этой строки первая же выкладка приложения
 * положила бы три имени в список получателей и отменила бы решение молча,
 * никого не спросив.
 *
 * ⚠️ `FROM_SHALAEVA` при этом продолжает собираться и лежать в файле: он
 * нужен бэк-офису, чтобы показывать имена в сменах, и пригодится, если
 * решение когда-нибудь передумают. Тогда правка — вернуть `...FROM_SHALAEVA`
 * в эту строку, и всё.
 */
export function getHookahPeople(): Employee[] {
  return [HOOKAH_POT];
}

/**
 * Кого отмечают в СОСТАВЕ барной смены — все кальянщики, поимённо.
 *
 * ⚠️ **Это другой список, чем `getHookahPeople`, и путать их нельзя.**
 * Там — кому уходят ДЕНЬГИ, и там по-прежнему один общий котёл: решение
 * владельца 07.09.2026 «не пересматриваем». Здесь — кто ВЫШЕЛ РАБОТАТЬ,
 * и здесь нужны имена.
 *
 * Зачем понадобилось. Мотивация бара — котёл на смену, и владелец делит его
 * поровну между теми, кто в неё работал: 13 600 ÷ 6 = 2 266. Делить не на кого,
 * пока состав неизвестен, а известен он ниоткуда: в выгрузке смены на месте
 * кальянщиков стоит «Весь бар» без имён, а касса показывает только того,
 * кто пробивал чеки, — одного-двух за вечер. За 01.09.2026 владелец делила
 * на шестерых, у нас было видно двоих. Решение владельца 08.09.2026: состав
 * отмечает администратор в приложении смены, так же как отмечает официантов.
 *
 * 💡 Четверых из восьми в кассе нет и не будет — «они не оформлены» (владелец
 * 08.09.2026). Они приходят из `data/кальянщики-вне-кассы.json` с номерами
 * от 1 900 001, и `scripts/qr_employees.py` дописывает их в этот справочник
 * сам, поэтому обновление списка из кассы их не стирает.
 *
 * ⚠️ До 08.09.2026 состав брали отсюда же, откуда получателей, — и список
 * получался ПУСТОЙ: раздел «Кальянный бар» в составе смены был на экране,
 * но отмечать в нём было некого. Одно решение про деньги молча погасило
 * совсем другое требование.
 */
export function getHookahCrew(): Employee[] {
  return FROM_SHALAEVA;
}

export async function getManualPeople(): Promise<Employee[]> {
  return listManual();
}

/**
 * Добавляет человека вручную. Возвращает обновлённый список дописанных.
 *
 * Совпадение с Quick Resto проверяется здесь: в базе этого списка нет,
 * он живёт файлом в сборке. Совпадение среди уже дописанных ловит сама
 * база — там на имя стоит запрет повторов.
 */
export async function addManualPerson(
  rawName: string,
): Promise<{ люди: Employee[]; вернулся: string | null }> {
  const name = rawName.trim().replace(/\s+/g, " ");
  if (!name) return { люди: await listManual(), вернулся: null };

  const inQuickResto = FROM_QUICK_RESTO.some(
    (p) => p.name.toLowerCase() === name.toLowerCase(),
  );
  if (inQuickResto) {
    // Человек есть в кассе — вписывать его руками не надо и нельзя: вышел бы
    // двойник с двумя номерами. Раньше здесь просто возвращался прежний
    // список, и на экране это выглядело как «кнопка не сработала».
    return {
      люди: await listManual(),
      вернулся: `${name} уже заведён в кассе — выберите его в общем списке, вписывать руками не нужно.`,
    };
  }

  return addManual(name);
}

/**
 * Убирает дописанного руками человека — если ему больше ничего не должны.
 *
 * Возвращает не только новый список, но и причину отказа: удаление человека,
 * за которым стоят деньги, приложение больше не делает. Почему именно так —
 * в пояснении к `deleteManual`.
 */
export async function removeManualPerson(id: number): Promise<Удаление> {
  return deleteManual(id);
}

/** Возвращает убранного человека в список выбора. */
export async function restoreManualPerson(id: number): Promise<Employee[]> {
  return unhideManual(id);
}
