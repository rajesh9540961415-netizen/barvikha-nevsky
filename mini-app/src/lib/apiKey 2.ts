import { timingSafeEqual } from "node:crypto";

/**
 * Проверка ключа у служебных адресов приложения.
 *
 * Общая на всех, а не по копии в каждом адресе: проверка ключа — это то место,
 * где копия однажды разойдётся молча и тихо ослабнет. Пока адрес был один
 * (`/api/export/<день>`), копия была незаметна; с появлением второго
 * (`/api/qr-tips`) её пришлось бы держать в двух местах.
 *
 * Ключ передаётся заголовком `X-Export-Key`, а не в адресе: адреса оседают
 * в журналах сервера и в истории команд, и ключ утёк бы туда вместе с ними.
 */

/** Сравнение за постоянное время: обычное `===` выдаёт длину совпадения. */
function ключиСовпали(данный: string, нужный: string): boolean {
  const a = Buffer.from(данный);
  const b = Buffer.from(нужный);
  // timingSafeEqual падает на разной длине, поэтому длину проверяем отдельно.
  // Сама по себе она секрета не выдаёт.
  return a.length === b.length && timingSafeEqual(a, b);
}

/**
 * Вернуть готовый отказ, если ключ не подошёл, или `null`, если всё в порядке.
 *
 * Не задан `EXPORT_KEY` — адрес не работает вовсе. Отдавать или принимать
 * деньги смены без защиты нельзя даже разово: адрес угадывается с первой
 * попытки, а данные в нём поимённые.
 */
export function отказПоКлючу(request: Request): Response | null {
  const нужный = process.env.EXPORT_KEY;

  if (!нужный) {
    return Response.json(
      {
        ok: false,
        причина:
          "не задана переменная EXPORT_KEY — служебные адреса выключены. " +
          "Задать её в панели Amvera, тем же значением, что и у скриптов",
      },
      { status: 503 },
    );
  }

  const данный = request.headers.get("X-Export-Key");
  if (!данный || !ключиСовпали(данный, нужный)) {
    return Response.json({ ok: false, причина: "неверный ключ" }, { status: 401 });
  }

  return null;
}
