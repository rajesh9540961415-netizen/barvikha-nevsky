import postgres from "postgres";

/**
 * Подключение к базе.
 *
 * Живёт только на сервере: браузер с PostgreSQL напрямую разговаривать
 * не умеет и не должен — иначе пароль от базы уехал бы на телефон каждому,
 * кто открыл приложение. Экраны обращаются к серверным функциям
 * из actions.ts, а те уже ходят в базу.
 *
 * Строка подключения — в `mini-app/.env.local`, в git не уходит.
 */

let client: ReturnType<typeof postgres> | null = null;

export function db() {
  if (client) return client;

  const url = process.env.DATABASE_URL;
  if (!url) {
    // Мест два, и подсказка должна называть оба: на сервере искать файл
    // бессмысленно, а на компьютере — панель Amvera.
    throw new Error(
      "Не задан DATABASE_URL. На сервере строка подключения задаётся " +
        "в переменных приложения в панели Amvera (имя переменной — ровно " +
        "DATABASE_URL), на этом компьютере — в файле mini-app/.env.local",
    );
  }

  // Тестовые таблицы живут в отдельной схеме той же базы: у пользователя нет
  // прав завести вторую базу, а схема даёт ту же изоляцию — это разные наборы
  // таблиц. На сервере переменная не задана, поэтому там всегда боевая public.
  const schema = process.env.DATABASE_SCHEMA;

  client = postgres(url, {
    ...(schema ? { connection: { search_path: schema } } : {}),
    // «prefer», а не «require»: снаружи Amvera пускает к базе только
    // по шифрованному каналу, и тогда шифрование включится само.
    // Но внутри Amvera приложение и база сидят в одной закрытой сети,
    // где база может отвечать и без шифрования — с «require» такое
    // соединение просто не состоялось бы.
    ssl: "prefer",
    // Больше и не нужно: приложением пользуются несколько человек в смену.
    max: 5,
    // Не держим соединение открытым вечно: связь в зале может пропасть,
    // и мёртвое соединение молча съело бы первую же запись.
    idle_timeout: 20,
    connect_timeout: 10,
  });

  return client;
}
