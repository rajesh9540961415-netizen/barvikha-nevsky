import { readLastShift, readShift } from "./db/actions";
import { enqueueAndSend } from "./offline";
import type { Shift } from "./types";

/**
 * Состав смены.
 *
 * Quick Resto не хранит должности — там вперемешку официанты, кухня
 * и служебные учётки. Поэтому смену собирает администратор один раз
 * в начале вечера, а дальше при вводе видит только этих людей.
 *
 * Кроме официантов нужны ещё три роли:
 *   — кто вносит записи: попадает в каждую запись, видно, кто отвечает;
 *   — администратор смены: ему уходят 20 % от заработка официантов;
 *   — кассир смены: ему уходит доля от 750 ₽, а в пятницу и субботу — от 1000 ₽.
 * Последние две нужны отчёту: там у каждого своя строка.
 *
 * Хостес и кальянщики стоят в смене отдельными списками, а не в `crew`:
 * их деньги не делятся ни с кем, и в знаменатель доли кассира они
 * не входят (решение владельца 18.08.2026).
 *
 * Состав лежит в общей базе, а не только на одном телефоне: иначе
 * администратор собрал бы смену у себя, а сменщик открыл бы приложение
 * и увидел пустой экран.
 */

// Тип объявлен в types.ts, чтобы на него мог ссылаться серверный слой базы.
// Здесь оставлен для экранов: они берут его отсюда с самого начала.
export type { Shift } from "./types";

export const EMPTY_SHIFT: Shift = {
  crew: [],
  operator: null,
  admin: null,
  admin2: null,
  cashier: null,
  hostess: [],
  hookah: [],
  halfShift: [],
  names: {},
};

export async function getShift(businessDay: string): Promise<Shift> {
  return (await readShift(businessDay)) ?? EMPTY_SHIFT;
}

/**
 * Сохраняет состав смены. Тоже через очередь отправки.
 *
 * Смена собирается в начале вечера, и если сети в этот момент нет, без
 * очереди администратор не смог бы даже начать: без состава экран ввода
 * не открывается. Состав хранится строкой на бизнес-день и переписывается
 * целиком, поэтому повторная отправка того же состава ничего не портит.
 */
export async function setShift(
  businessDay: string,
  shift: Shift,
): Promise<void> {
  return enqueueAndSend({ type: "shift", businessDay, shift });
}

/**
 * Прошлая смена — чтобы не собирать состав заново каждый вечер.
 *
 * 🔴 **Состав бара при этом НЕ подставляется: раздел начинается пустым.**
 * Решение владельца 09.09.2026, после того как узнали цену вопроса —
 * «внезапная подмена в баре получится раз в неделю».
 *
 * Почему именно так. Подстановка экономит нажатия, но в баре она молча
 * переносит в новый вечер вчерашних людей. Не вышел один, вместо него
 * пришёл другой — администратору надо и вписать пришедшего, и заметить,
 * что не пришедший стоит отмеченным. Первое он делает: человек рядом
 * и просит. Второе делать нечего — тот уже отмечен, и экран выглядит
 * правильно. Ошибки на нём не видно ни одной.
 *
 * ⚠️ Разница с залом принципиальная, и она не про внимательность.
 * Лишний человек в зале меняет долю кассира и всплывает в отчёте деньгами.
 * Лишний человек в баре не виден НИГДЕ: котёл делится на отмеченных,
 * и завышенная доля выглядит так же правдоподобно, как верная. Такое
 * закрывают устройством, а не памяткой.
 *
 * Цена — четыре нажатия в начале вечера. Отмеченные смены это не трогает:
 * там состав лежит в самой смене.
 *
 * 💡 До 09.09.2026 состав бара подставлялся, но просеивался: 07.09 касса
 * завела кальянщикам новые карточки, и старые номера, подставленные
 * в новую смену, кнопкой не рисовались — снять их администратор не мог,
 * а в делителе мотивации они стояли. Пустой раздел закрывает и этот случай
 * заодно: подставлять нечего, значит и просеивать нечего.
 */
export async function getLastShift(): Promise<Shift> {
  const прошлая = await readLastShift();
  if (!прошлая) return EMPTY_SHIFT;
  // Отметка «полсмены» вчерашняя и к новому вечеру отношения не имеет:
  // человек выходит на часть смены не каждый раз, а подставленная отметка
  // молча лишила бы кассира его доли. Пусть ставят заново, как и состав бара.
  return { ...прошлая, hookah: [], halfShift: [] };
}

/** Смена собрана, можно вводить. Проверка чистая, база для неё не нужна. */
export function isReady(shift: Shift): boolean {
  return shift.crew.length > 0 && shift.operator !== null;
}
