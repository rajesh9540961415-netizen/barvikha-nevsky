import hookah from "@/data/hookah.json";

/**
 * Опознание людей кальянного бара по строкам «РАСПРЕДЕЛЕНИЯ» из Telegram.
 *
 * Заведено 20.10.2026. Строки приносит варшавский робот (`tg-reader/bar_reader.py`)
 * как есть: «VIP: Айнур», «КМ - Тамаз Ш». Опознаём здесь, потому что
 * справочник бара лежит здесь (`src/data/hookah.json`) — вторая его копия
 * в роботе однажды разошлась бы с этой.
 *
 * Как пишут в чате, неизвестно до конца: образца на 20.10.2026 нет. Знаем
 * по 1–8.09.2026 (`scripts/uk_push.py`): по имени, иногда с фамилией,
 * с опечатками — «Даникеев» вместо «Деникеев». Отсюда правила:
 *
 *   — слово сверяется с именем и фамилией каждого из справочника;
 *   — сначала точно, потом по началу («Влад» → Владислав), потом с одной
 *     опечаткой (для слов от пяти букв);
 *   — подходит больше одного человека — не угадываем, а пишем в неопознанные.
 *     Угадавший однажды угадает неверно в другой раз, и доля уйдёт не тому.
 *
 * ⚠️ Один человек на нескольких зонах считается ОДИН раз (владелец 10.09.2026).
 */

export type СтрокаЧата = { зона: string; текст: string };

export type Опознание = {
  crew: number[];
  names: Record<string, string>;
  unknown: string[];
};

type Человек = { id: number; name: string; имя: string; фамилия: string };

function норм(s: string): string {
  return s
    .toLowerCase()
    .replace(/ё/g, "е")
    .replace(/[^a-zа-я0-9\s-]/g, " ")
    .replace(/\s+/g, " ")
    .trim();
}

/** Расстояние правки, но не дальше `предел`: дальше нам не интересно. */
function расстояние(a: string, b: string, предел: number): number {
  if (Math.abs(a.length - b.length) > предел) return предел + 1;
  let прошлая = Array.from({ length: b.length + 1 }, (_, j) => j);
  for (let i = 1; i <= a.length; i++) {
    const эта = [i];
    let лучшая = i;
    for (let j = 1; j <= b.length; j++) {
      const з = Math.min(
        прошлая[j] + 1,
        эта[j - 1] + 1,
        прошлая[j - 1] + (a[i - 1] === b[j - 1] ? 0 : 1),
      );
      эта.push(з);
      лучшая = Math.min(лучшая, з);
    }
    if (лучшая > предел) return предел + 1;
    прошлая = эта;
  }
  return прошлая[b.length];
}

function справочник(список: { id: number; name: string }[]): Человек[] {
  return список.map((ч) => {
    const части = норм(ч.name).split(" ");
    return { id: ч.id, name: ч.name, имя: части[0] ?? "", фамилия: части.at(-1) ?? "" };
  });
}

/** Кто подходит под одно слово: точно, по началу, с одной опечаткой. */
function кандидаты(слово: string, люди: Человек[]): Человек[] {
  const точно = люди.filter((ч) => ч.имя === слово || ч.фамилия === слово);
  if (точно.length > 0) return точно;
  if (слово.length >= 4) {
    const начало = люди.filter((ч) => ч.имя.startsWith(слово) || ч.фамилия.startsWith(слово));
    if (начало.length > 0) return начало;
  }
  if (слово.length >= 5) {
    return люди.filter(
      (ч) => расстояние(слово, ч.имя, 1) <= 1 || расстояние(слово, ч.фамилия, 1) <= 1,
    );
  }
  return [];
}

// Пустая зона в чате бывает словом: опознавать там некого, и в неопознанные
// это не идёт.
const ПУСТО = new Set(["нет", "никого", "пусто", "свободно", "закрыто", "закрыта"]);

/** Строки раздела → номера и имена людей из справочника бара. */
export function опознатьБар(
  строки: СтрокаЧата[],
  список: { id: number; name: string }[] = hookah,
): Опознание {
  const люди = справочник(список);
  const найдены = new Map<number, string>();
  const неопознанные: string[] = [];

  for (const строка of строки) {
    // Несколько человек в одной зоне: «Айнур, Тамаз», «Айнур / Тамаз», «Айнур и Тамаз».
    const куски = строка.текст.split(/[,;/+&\n]|\s+и\s+/i);
    for (const кусок of куски) {
      const слова = норм(кусок).split(" ").filter(Boolean);
      if (слова.length === 0 || слова.every((с) => ПУСТО.has(с) || !/[a-zа-я]/.test(с))) continue;

      // Однобуквенные — инициалы: «Тамаз Ш». Сами никого не опознают,
      // но помогают выбрать из двух одноимённых.
      const инициалы = слова.filter((с) => с.length === 1);
      let опознан = false;
      for (const слово of слова.filter((с) => с.length >= 2)) {
        let подходят = кандидаты(слово, люди);
        if (подходят.length > 1 && инициалы.length > 0) {
          подходят = подходят.filter((ч) =>
            инициалы.some((и) => ч.фамилия.startsWith(и) || ч.имя.startsWith(и)),
          );
        }
        if (подходят.length === 1) {
          найдены.set(подходят[0].id, подходят[0].name);
          опознан = true;
        }
      }
      if (!опознан) {
        const как = кусок.trim();
        if (!неопознанные.includes(как)) неопознанные.push(как);
      }
    }
  }

  const crew = [...найдены.keys()].sort((a, b) => a - b);
  return {
    crew,
    names: Object.fromEntries(crew.map((id) => [String(id), найдены.get(id)!])),
    unknown: неопознанные,
  };
}
