"""Разбор двух сообщений администратора про кальянный бар.

Запускается сам собой и проверяет себя: `python3 bar_parse.py`.

1. **«РАСПРЕДЕЛЕНИЕ ДД.ММ.ГГ»** из группы «НЕВСКИЙ | ОБЩИЙ ЧАТ» — кто
   на какой зоне работает вечером. Из него берём раздел «КАЛЬЯННЫЙ БАР»
   (пять зон) и отдельную строку «КМ»: КМ работает тот же вечер и в мотивации
   участвует (решение владельца 10.09.2026, см. `scripts/uk_push.py`).

2. **«Мотивация кальянного бара»** из группы «НЕВСКИЙ | АДМИН» — продажи бара
   по типам кальянов за смену. Тот же разбор, что у `scripts/motivaciya_sverka.py`:
   скрипт берёт его отсюда, второй копии нет.

⚠️ **Имена здесь НЕ опознаются.** Робот отдаёт строки раздела как есть,
а сопоставляет их со справочником бара приложение смены
(`mini-app/src/lib/barChat.ts`): справочник лежит там, и вторая его копия
в роботе однажды разошлась бы с первой.

⚠️ **Образца «РАСПРЕДЕЛЕНИЯ» на 20.10.2026 в проекте нет** — формат известен
только по описанию. Поэтому разбор терпимый, а вместе с разобранным уходит
«скелет» сообщения: строки без имён, только подписи зон и разделов. По нему
видно, где разбор ошибся, не вывозя никуда сам текст.
"""

from __future__ import annotations

import re
from dataclasses import dataclass, field

# «08.10.26», «8.10.2026», «08/10/26».
ДАТА = re.compile(r"(?<!\d)(\d{1,2})[./](\d{1,2})[./](\d{4}|\d{2})(?!\d)")

# ─── Распределение ──────────────────────────────────────────────────────

РАСПРЕДЕЛЕНИЕ = "распределение"
РАЗДЕЛ_БАРА = "кальянный бар"
КМ = "км"

# Подпись зоны и имена делит двоеточие или тире. Дефис — только с пробелом
# хотя бы с одной стороны: «Анна-Мария» — одно имя, а не зона «Анна».
ЗОНА_И_ИМЕНА = re.compile(r"^(.*?)\s*(?::|—|–|\s-\s?|-\s)\s*(.*)$")
НУМЕРАЦИЯ = re.compile(r"^\s*(\d{1,2})\s*[.)]\s*(.*)$")
БУКВЫ = re.compile(r"[A-Za-zА-Яа-яЁё]")


@dataclass
class Строка:
    зона: str
    текст: str


@dataclass
class Распределение:
    день: str | None
    строки: list[Строка] = field(default_factory=list)
    # Сколько строк нашлось в самом разделе «КАЛЬЯННЫЙ БАР», без «КМ».
    # Зон пять — другое число значит, что формат поехал.
    зон_в_разделе: int = 0
    раздел_найден: bool = False
    скелет: str = ""


def _день(текст: str) -> str | None:
    м = ДАТА.search(текст)
    if not м:
        return None
    д, мес, г = м.groups()
    г = г if len(г) == 4 else f"20{г}"
    return f"{г}-{int(мес):02d}-{int(д):02d}"


def _чисто(строка: str) -> str:
    """Без смайликов и украшений по краям: «🔥КАЛЬЯННЫЙ БАР🔥» → «КАЛЬЯННЫЙ БАР»."""
    return re.sub(r"^[^\wА-Яа-яЁё]+|[^\wА-Яа-яЁё.)]+$", "", строка.strip())


def _заголовок(строка: str) -> bool:
    """Строка-раздел: одни заглавные буквы, без имён после двоеточия.

    «ЗАЛ», «КАЛЬЯННЫЙ БАР:», «ХОСТЕС» — разделы. «VIP: Айнур» — зона.
    """
    с = _чисто(строка).rstrip(":").strip()
    м = ЗОНА_И_ИМЕНА.match(с)
    if м and м.group(2).strip():
        return False
    буквы = БУКВЫ.findall(с)
    return len(буквы) >= 2 and all(б.isupper() for б in буквы)


def _разбить(строка: str) -> Строка:
    с = _чисто(строка)
    м = ЗОНА_И_ИМЕНА.match(с)
    if м and м.group(2).strip():
        return Строка(зона=м.group(1).strip(), текст=м.group(2).strip())
    н = НУМЕРАЦИЯ.match(с)
    if н and н.group(2).strip():
        return Строка(зона=н.group(1), текст=н.group(2).strip())
    return Строка(зона="", текст=с)


def _скелет(строки: list[str]) -> str:
    """Сообщение без имён: подписи зон и разделов остаются, имена — нет.

    «VIP: Айнур, Тамаз» → «VIP: ‹2 сл.›». Строка без подписи — целиком
    «‹N сл.›». Разделы (заглавными) остаются как есть.
    """
    вышло = []
    for с in строки:
        if not с.strip():
            вышло.append("")
            continue
        if _заголовок(с) or РАСПРЕДЕЛЕНИЕ in с.lower():
            вышло.append(_чисто(с) or с.strip())
            continue
        р = _разбить(с)
        слов = len(р.текст.split())
        вышло.append(f"{р.зона}: ‹{слов} сл.›" if р.зона else f"‹{слов} сл.›")
    return "\n".join(вышло).strip()


def разобрать_распределение(текст: str) -> Распределение | None:
    """«РАСПРЕДЕЛЕНИЕ» → строки кальянного бара и «КМ». Чужое сообщение → None."""
    строки = (текст or "").splitlines()
    первые = " ".join(строки[:3]).lower()
    if РАСПРЕДЕЛЕНИЕ not in первые:
        return None

    итог = Распределение(день=_день(" ".join(строки[:3])), скелет=_скелет(строки))
    в_разделе = False
    for с in строки:
        if not с.strip():
            continue
        чистая = _чисто(с).lower().rstrip(":").strip()
        # Заголовок бара узнаём и не заглавными: «Кальянный бар:» — тоже он.
        if чистая.startswith(РАЗДЕЛ_БАРА) and not _разбить(с).зона:
            в_разделе, итог.раздел_найден = True, True
            continue
        # «КМ» берём, где бы он ни стоял: внутри раздела бара или отдельно.
        р = _разбить(с)
        if р.зона.lower().strip(" .") == КМ:
            итог.строки.append(Строка(зона="КМ", текст=р.текст))
            continue
        if в_разделе:
            if _заголовок(с):
                в_разделе = False
                continue
            итог.строки.append(р)
            итог.зон_в_разделе += 1
    return итог


# ─── Мотивация ──────────────────────────────────────────────────────────

НАЧАЛО_МОТИВАЦИИ = "мотивация кальянного бара"

# Как администратор называет типы и как называем их мы.
ИМЕНА = {
    "perfume чаша": "Perfume чаша",
    "perfume фрукт": "Perfume фрукт",
    "кальян на фрукте": "Кальян на фрукте",
    "авторское предложение": "Авторское предложение",
    "арт-кальян": "Арт-кальян",
    "фирменный кальян барвиха": "Фирменный Барвиха",
    "чемпионат мира": "Чемпионат мира",
}

# «18*200=3600₽» — штук, ставка, сумма. Пробелы и «х» вместо звёздочки бывают.
ШТУК = re.compile(r"(\d+)\s*[*хx×]\s*(\d+)\s*₽?\s*=\s*(\d[\d\s]*)", re.IGNORECASE)
ИТОГО = re.compile(r"Итого\s*:?\s*(\d[\d\s]*)", re.IGNORECASE)


@dataclass
class Позиция:
    тип: str  # наше имя типа; неизвестный тип — как у администратора
    штук: int
    ставка: int
    сумма: int


@dataclass
class Мотивация:
    день: str | None
    позиции: list[Позиция] = field(default_factory=list)
    итог: int | None = None
    # Где арифметика самого отчёта не сходится. Это НЕ сверка с нами —
    # сверка идёт по типам с продажами из чеков; это только опечатки отчёта.
    замечания: list[str] = field(default_factory=list)


def _тип(подпись: str) -> str:
    п = re.sub(r"^\d+\s*[.)]\s*", "", подпись).strip().rstrip(":").strip()
    return ИМЕНА.get(п.lower(), п)


def разобрать_мотивацию(текст: str) -> Мотивация | None:
    """Отчёт администратора → день, штуки по типам, его итог. Чужое → None.

    Формат из группы «НЕВСКИЙ | АДМИН», снимок владельца 08.09.2026:

        Мотивация кальянного бара:
        31.08.26

        1. Perfume чаша
        18*200=3600₽
        ...
        Итого: 8600₽

    ⚠️ Тип, которого нет в списке, НЕ пропускается, а уходит под своим
    именем. Молча выброшенный тип — это ровно та ошибка, которую сверка
    по типам и должна ловить.
    """
    текст = текст or ""
    if not текст.strip().lower().startswith(НАЧАЛО_МОТИВАЦИИ):
        return None

    итог = Мотивация(день=_день(текст))
    подпись = None
    for с in (с.strip() for с in текст.splitlines()):
        if not с or с.lower().startswith(НАЧАЛО_МОТИВАЦИИ):
            continue
        if ИТОГО.match(с):
            итог.итог = int(ИТОГО.match(с).group(1).replace(" ", ""))
            подпись = None
            continue
        ч = ШТУК.search(с)
        if ч:
            перед = с[: ч.start()].strip()
            тип = _тип(перед) if БУКВЫ.search(перед) else (подпись and _тип(подпись))
            if not тип:
                итог.замечания.append(f"строка «{с}» без названия типа")
                continue
            штук, ставка = int(ч.group(1)), int(ч.group(2))
            сумма = int(ч.group(3).replace(" ", ""))
            if штук * ставка != сумма:
                итог.замечания.append(f"{тип}: {штук}×{ставка} = {штук * ставка}, а написано {сумма}")
            итог.позиции.append(Позиция(тип, штук, ставка, сумма))
            подпись = None
            continue
        if ДАТА.fullmatch(с.strip(" .")) or (ДАТА.search(с) and not БУКВЫ.search(с)):
            continue
        if БУКВЫ.search(с):
            подпись = с

    if итог.итог is not None and итог.позиции:
        всего = sum(п.сумма for п in итог.позиции)
        if всего != итог.итог:
            итог.замечания.append(f"сумма строк {всего}, а «Итого» {итог.итог}")
    return итог


# ─── Самопроверка ───────────────────────────────────────────────────────

if __name__ == "__main__":
    мотивация = разобрать_мотивацию(
        "Мотивация кальянного бара:\n31.08.26\n\n1. Perfume чаша\n18*200=3600₽\n"
        "2. Арт-кальян\n5*300=1500₽\n3. Новый тип\n2 * 100 = 200 ₽\n"
        "4. Кальян на фрукте 3х150=450₽\nИтого: 5 750₽"
    )
    assert мотивация and мотивация.день == "2026-08-31", мотивация
    assert [(п.тип, п.штук) for п in мотивация.позиции] == [
        ("Perfume чаша", 18), ("Арт-кальян", 5), ("Новый тип", 2), ("Кальян на фрукте", 3),
    ], мотивация.позиции
    assert мотивация.итог == 5750 and not мотивация.замечания, мотивация
    плохая = разобрать_мотивацию("Мотивация кальянного бара\n01.09.26\nPerfume чаша\n2*200=500\nИтого: 400")
    assert плохая and len(плохая.замечания) == 2, плохая.замечания
    assert разобрать_мотивацию("Получены чаевые") is None

    р = разобрать_распределение(
        "РАСПРЕДЕЛЕНИЕ 08.10.26\n\nЗАЛ\n1 зона: Яна\n2 зона - Даша\n\n"
        "🔥КАЛЬЯННЫЙ БАР🔥\nVIP: Айнур\nЗона 2 — Тамаз, Антон\n3) Айнур\nТерраса – Акмаль\n"
        "Веранда: Милинтина\n\nХОСТЕС\nМаша\n\nКМ - Даниил"
    )
    assert р and р.день == "2026-10-08" and р.раздел_найден, р
    assert [(с.зона, с.текст) for с in р.строки] == [
        ("VIP", "Айнур"), ("Зона 2", "Тамаз, Антон"), ("3", "Айнур"),
        ("Терраса", "Акмаль"), ("Веранда", "Милинтина"), ("КМ", "Даниил"),
    ], р.строки
    assert р.зон_в_разделе == 5
    assert "Айнур" not in р.скелет and "VIP: ‹1 сл.›" in р.скелет, р.скелет
    assert разобрать_распределение("Добрый вечер всем") is None
    print("bar_parse: самопроверка прошла")
